# прошёл бы их молча.
#
# Замер на 29 точках: как надо — 0.810…0.9999; слой съехал на два
# пикселя — 0.614…0.869; на восемь — 0.158…0.505; субтитра нет вовсе —
# −0.074…0.470. Порог 0.65 стоит между «съехал на восемь» и «как надо».
#
# Происхождение: то же эссе, тот профиль субтитров — С ПЛАШКОЙ.
SUBS_MIN = 0.65

# ТО ЖЕ, НО КОГДА ПОДЛОЖКИ НЕТ ВОВСЕ.
#
# Заслон сравнивает пиксели там, где у слоя сплошная краска. С плашкой,
# обводкой или тенью в этих пикселях лежат два сильно разных уровня —
# светлая подложка и тёмные буквы, — и сравнивать есть что. При
# подложке «без» краска только в самих буквах, и уровня там два близких:
# сказанное слово и ещё не сказанное. Сигнал слабее, и связь на верном
# файле падает.
#
# ЗАМЕР на том же ролике, третья сессия, восемь точек на каждый режим:
#
#             как надо      слой съехал на 8   запас
#   плашка    0.999…1.000   0.295…0.406        0.59…0.70
#   обводка   0.999…1.000   0.169…0.369        0.63…0.83
#   тень      0.999…1.000   0.148…0.375        0.63…0.85
#   БЕЗ       0.572…0.999   −0.018…0.417       0.58…0.84
#
# То есть заслон при «без» НЕ СЛЕП — сломанный файл он по-прежнему
# отличает с запасом, — но его верхняя планка ниже, и порог 0.65
# отвергал бы исправные ролики. 0.5 стоит между худшим верным (0.572)
# и худшим сломанным (0.417).
#
# ОДНИМ ЧИСЛОМ ЭТО НЕ ЗАКРЫТЬ, и это сказано вслух: у плашки «слой
# съехал на два пикселя» даёт 0.614…0.869, что ВЫШЕ, чем худший верный
# случай у «без». Порог, который ловит сдвиг на два пикселя с плашкой,
# отвергает исправное без неё. Поэтому порогов два, каждый замерен.
SUBS_MIN_БЕЗ = 0.5

# На сколько пикселей нарочно сдвигается слой в контрольном замере
# четвёртого заслона.
#
# Восемь: замерено, что при таком сдвиге связь падает у всех четырёх
# подложек до 0.42 и ниже, а на исправном файле остаётся 0.57 и выше.
# Разница между ними — ЗАПАС, и печатается он числом: на короткой
# однословной фразе заслон слабее, и человек должен это видеть, а не
# догадываться.
SUBS_CONTROL_SHIFT = 8

# ПОРОГ ПЯТОГО ЗАСЛОНА: плашка в конце есть, и стоит она с той секунды.
#
# Первые три заслона под плашку не смотрят вовсе, и это не поблажка:
# под ней картинки исходника нет — там картинка плашки, — и требовать
# её значит требовать того, чего в файле не должно быть. Планы под
# плашкой погашены ещё в `plans`. Поэтому `VERIFY_MIN` выше НЕ ТРОНУТ
# ни на сотую: он отвечает за те же секунды, что и раньше.
#
# А секунды плашки сверяются своей парой: кадр готового файла против
# самой картинки плашки, той, что ушла входом в цепочку.
#
# ЗАМЕР на живом ролике (44.52 с, плашка с 41.52, фон + обложка +
# надпись), кадр сравнивается ЦЕЛИКОМ:
#
#   как надо (5 кадров под плашкой)        0.9993…0.9994
#   кадры ДО плашки против неё (5 кадров)  −0.1695…−0.0188
