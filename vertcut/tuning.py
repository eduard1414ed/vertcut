from __future__ import annotations

# ─────────────────────────────────────────────────────────────────────────
# Уменьшенная копия
# ─────────────────────────────────────────────────────────────────────────

# Ширина копии, по которой ищутся склейки и собирается контактный лист.
#
# Зачем копия. Исходник может быть 23 мегабитами HEVC, и детектор читает
