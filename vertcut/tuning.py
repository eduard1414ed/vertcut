# Короче этого ролик не собирается.
#
# ВНИМАНИЕ: у этого числа здесь ДРУГАЯ причина, чем в Нарезаторе.
#
# Там пятнадцать секунд раскладывались как «три секунды заберёт плашка
# хвоста плюс двенадцать живой картинки», и число было связано с длиной
# плашки. По спеке этого проекта плашки по умолчанию нет вовсе — у чужого
# человека нет ни обложки выпуска, ни канала, ни фона, — и та половина
# причины отпала.
#
# Осталась вторая: сколько нужно на самодостаточную мысль. На эссе она
# раскладывалась так — медиана предложения 7.42 с, два предложения
# по медиане это 14.8 с. Одного предложения мало не по вкусу: первая
# фраза работает крючком, и если после крючка ничего не осталось, ролик
# состоит из одного крючка.
#
# ВТОРАЯ СЕССИЯ ЭТУ ВЫКЛАДКУ ПРОВЕРИЛА, И ОНА НЕ ПЕРЕНОСИТСЯ.
#
#   медиана длины предложения:
#   эссе (начитка по сценарию)      7.42 с
#   интервью (живой разговор)       1.68 с
#   английское видео (один спикер)  3.72 с
#
# В отложенном стояло ожидание: «у разговорного видео предложения
# длиннее и рванее». Замер говорит обратное — они ВЧЕТВЕРО короче.
# В разговоре много коротких предложений: «Да.», «Конечно.», «Третья.».
# Пятнадцать секунд разговора — это не два предложения, а около девяти.
#
# ЧИСЛО ОСТАВЛЕНО, НО ПРИЧИНА У НЕГО ТЕПЕРЬ ЧЕСТНЕЕ. Выкладка «два
# предложения» верна только для начитки по сценарию. Держится число
# на другом, и это НЕ ЗАМЕР, а суждение о площадках: вертикальный ролик
# короче пятнадцати секунд состоит из крючка и ничего больше. Мерить
# это здесь нечем — нужен отклик зрителей, а его у сервиса нет.
#
# Так и записано вслух: единственное число проекта, которое не мерялось
# ни разу и меряться пока нечем. На своём материале его двигают первым.
#
