#
# **Связь двух ровных картинок — монетка.** После вычитания среднего
# в них остаётся один шум пересжатия, а связь двух шумов ложится куда
# угодно. Сверка при этом не «слегка ошибается» — она объявляет
# исправный файл битым.
#
# ПОЙМАНО НА ЖИВОМ МАТЕРИАЛЕ, и не проверками: сквозной прогон пяти
# вертикалок этого видео уронил одну со связью 0.5666 при пороге 0.9.
# Глазами: на том стыке стоит БЕЛАЯ ВСПЫШКА — переход, каких в этом
# эссе много. Кадр в ней почти ровный.
#
# ЗАМЕР на 88 кадрах сверки трёх вертикалок:
#
#   разброс 0.00  — чёрный кадр (проходил и раньше: там разброс
#                   РОВНО ноль, и для него ветка была)
#   разброс 0.03  — та самая белая вспышка, 0.5666
#   разброс 6.75  — самый ровный кадр С СОДЕРЖАНИЕМ
#   медиана 56.0, самый пёстрый 102.6
#
