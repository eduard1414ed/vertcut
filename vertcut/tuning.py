# минут по исходнику, и каждая переподборка порога стоила бы этих минут.
#
# 640 выбрано не «чтобы поменьше»: детектор всё равно ужимает кадр своим
# внутренним множителем, а контактный лист на 300 пикселей в ширину
# из 640 собирается без потерь.
#
# ВАЖНО: порог склеек ниже подобран НА ЭТОЙ ШИРИНЕ. Поменяете её —
