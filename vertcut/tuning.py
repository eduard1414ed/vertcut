PROXY_WIDTH = 640

# Качество копии. 20 — заметно чище, чем нужно глазу, и это нарочно:
# артефакты сжатия детектор видит как движение, и на crf 28 порог
# пришлось бы поднимать ради мусора, а не ради материала.
#
# Происхождение: то же эссе.
PROXY_CRF = 20


# ─────────────────────────────────────────────────────────────────────────
# Детектор склеек
# ─────────────────────────────────────────────────────────────────────────

# Порог, выше которого разница между соседними кадрами считается склейкой.
#
# ПЕРЕМЕРЕНО ВО ВТОРОЙ СЕССИИ НА СЪЁМКЕ КАМЕРОЙ, И ЧИСЛО ИЗМЕНЕНО.
# Было 45, снятое с анимационного эссе. Стало 35.
#
# Как мерялось. На русском интервью (16.5 минуты, монтаж двух камер
# с перебивками) детектор гонялся порогами 27, 35, 45, 55, 70.
# Границы, которые есть при низком пороге и пропадают при высоком,
# вынимались парами кадров «за 0.12 с до / через 0.12 с после»
# и смотрелись ГЛАЗАМИ — тем же способом, каким это мерял предок.
#
# Из шестнадцати просмотренных спорных границ зоны 27–45 пятнадцать
# оказались настоящими склейками: другой план, другая крупность,
# другой человек в кадре. Одна спорная — трамвай, проезжающий перед
# неподвижной камерой.
#
# То есть порог 45 на съёмке камерой ПРОПУСКАЛ примерно четверть
# склеек: 162 плана вместо 212.
#
# Почему именно 35, а не 27. Распределение самой метрики говорит, где
# что лежит:
#
#   метрика   | интервью (камера) | эссе (анимация)
#   27–35     |   3 срабатывания  |  47
#   35–45     |  49               |  36
#   45–55     | 106               |  55
#   55+       |  54               | 297
#
# У камеры склейки собраны в зоне 35–55, ниже 35 почти ничего нет:
# опускать порог до 27 значит взять три границы и заплатить за них
# сорока семью ложными на анимации. У анимации медиана 63 — там
# склейки резче, и зона 30–45 у предка замерена как 40% настоящих.
#
# ЧЕМ ПЛАТИМ. На анимационном материале 35 даёт 425 планов вместо 382,
# и по замеру предка примерно шесть из десяти новых — движение внутри
# плана, а не склейка. Это ложное деление плана надвое.
#
# ПОЧЕМУ ВСЁ РАВНО 35. Правило, записанное здесь же первой сессией:
# наклон в сторону лишних склеек намеренный. Лишняя склейка делит план
# надвое; пропущенная склеивает две разные сцены под одну рамку кадра.
# И второе: раздаётся сервис людям с подкастами и разговорами, а
# не с анимационными эссе, — материал предка здесь редкий случай,
# а не обычный.
#
# КАК ВЕРНУТЬ. Одна строка. На анимации и клиповом монтаже 45 лучше,
# и это замерено.
SCENE_THRESHOLD = 35.0

# До скольких точек в ширину ужимается кадр, прежде чем считать метрику.
#
# Число НЕ наше и подбору не подлежит: ровно с ним считала библиотека
# `scenedetect`, чьей метрикой замерен порог выше. Поменяете — поедет
# метрика, а вместе с ней и смысл порога 35, замеренного глазами
# по шестнадцати спорным границам во второй сессии.
#
# Стоит здесь, а не в коде, ровно затем, чтобы это было видно: оно
# выглядит мелочью исполнения, а на деле держит замеренный порог.
ШИРИНА_СЧЁТА_СКЛЕЕК = 256

# Ближе этого две склейки не ставятся.
#
# Как мерялось. При пороге 45 детектор срабатывает 494 раза, а промежутков
# короче 0.2 с между срабатываниями — 92: это одна склейка, пойманная
# на нескольких кадрах подряд (смаз и сжатие размазывают её на 2–4 кадра).
# Самый короткий настоящий план, найденный глазами на ленте через 0.2 с,
# — 0.6 с. 0.5 стоит между этими двумя числами.
#
# Происхождение: то же эссе. На клиповом монтаже с планами по четверти
# секунды это число будет склеивать настоящие планы.
MIN_SHOT = 0.5

# Принудительной резки длинных планов НЕТ, и это решение, а не пропуск.
#
# В соседней библиотеке план длиннее 8 секунд рубится пополам: там это
# обычно неотловленный медленный наплыв в трейлере. Здесь длинный
# статичный план — норма: за границей фразы лежит тот же самый план,
# а не следующий, и резать там нечего.
#
# Происхождение: замер на том же эссе — при пороге 45 планов длиннее
# 8 секунд восемь штук на весь ролик, длиннее 15 секунд один.
# Для разговорного видео с одной камерой это тем более верно.
#
# Ради этого числа константы нет: её отсутствие и есть решение.

# С краёв видео НИЧЕГО не отбрасывается.
#
# В соседней библиотеке отбрасывается по 1.5 секунды с начала и с конца:
# там на этих местах логотипы студий в трейлере. Здесь на первых
# секундах стоит вступление — самый ценный материал для крючка.
#
# Происхождение: решение, а не замер. Верно для любого материала, где
# начало содержательное; для видео с заставкой канала человек отрежет
# её сам, выбрав кусок позже.
TRIM_HEAD = 0.0
TRIM_TAIL = 0.0


# ─────────────────────────────────────────────────────────────────────────
# Распознавание речи
# ─────────────────────────────────────────────────────────────────────────

# Модель распознавания.
#
# Замер на анимешном эссе (19 мин 28 с сведённого звука, процессор
# Apple, int8):
#
#   large-v3  не кончилась за 78 минут и была оборвана
#   small     5.3 минуты
#
# Видеоядро Apple движок распознавания не умеет, так что большая модель
# считается только процессором, и двадцать минут для неё — часы. Это
# не «медленно», это неприменимо: разбор перестаёт быть однократной
# ценой и становится препятствием.
#
# Качество мерялось не на слух, а долей слов сценария, которые модель
# услышала дословно, — это и есть опоры, по которым расставляется время:
#
#   дословных совпадений             89.2%
#   конец фразы на измеренном слове  88.4%
#   начало фразы на измеренном слове 90.7%
#
# ПРОИСХОЖДЕНИЕ. Русская закадровая начитка, чистая запись, один голос.
# На громком стриме, на двух голосах вперебой, на английском — доля
# будет другой, и `small` может оказаться мала. Поэтому выбор модели
# по спеке показывается человеку вместе с ценой во времени: угадать
# за него нельзя. Здесь это значение по умолчанию, а не приговор.
WHISPER_MODEL = "small"

# Сколько весит скачанная модель распознавания.
#
# Число нужно ДО скачивания: человеку говорят, на что он подписывается,
# а установка проверяет, хватит ли места. Спросить у поставщика заранее
# нельзя — размер известен только после обращения к сети, а сказать
# надо раньше.
#
# ЗАМЕР 2 сентября 2026 года: папка кэша `models--Systran--faster-
# whisper-small` на этой машине — 486 МБ. В сообщении стадии стояло
# «около 460»; это ПЯТЫЙ раз в проекте, когда записанное однажды число
# не сошлось с пересчётом, и цена у ошибки здесь маленькая, но своя:
# на диске надо на четверть гигабайта больше, чем обещано.
#
# Наклонено в большую сторону нарочно: обещать меньше места, чем нужно,
# — худшая из двух ошибок. Меняете модель на `medium` или `large-v3` —
# меняйте и это число: у `large-v3` в том же кэше лежит 2.9 ГБ.
ВЕС_МОДЕЛИ_МБ = 486

# Язык. Пустое значение — «определи сам».
#
# Происхождение: у Нарезатора здесь наглухо стоял русский, потому что
# автор один и говорит по-русски. Здесь язык неизвестен, и «определи
# сам» — единственное честное значение по умолчанию.
WHISPER_LANGUAGE = ""

# int8 на процессоре: видеоядро движок не умеет, а по точности времён
# int8 не хуже.
#
# Происхождение: замер на той же машине. На машине с видеокартой NVIDIA
# правильный ответ другой, и это отдельная работа (см. TODO.md).
WHISPER_COMPUTE = "int8"

# Перебор вариантов слова.
#
# История, чтобы её не повторяли: сначала виноватым в медленности сочли
# перебор и поставили 1 — не помогло, прогон шёл 78 минут. Дело было
# в размере модели. Менять это число «ради скорости» бессмысленно.
#
# Происхождение: замер на том же эссе, с моделью `small`.
WHISPER_BEAM = 5

# Доля слов сценария, совпавших со слышимым дословно, ниже которой
# укладка считается несостоявшейся.
#
# Зачем порог вообще: выдуманные времена хуже отсутствующих — по ним
# нарежут и промахнутся молча.
#
# Происхождение: 0.60 при замеренных 0.89 — то есть запас в полтора
# раза. Число выбрано как «явно сломалось», а не как граница качества:
# на чужом материале доля будет ниже, и порог обязан пропускать
# нормальную работу на плохом звуке.
MIN_MATCH = 0.60

# То же самое, но когда сценария нет и текстом стала расшифровка.
#
# Это НЕ порог качества. Текст и слова приходят из одного прогона
# распознавания, и совпасть они обязаны полностью: времена раздаются
# словам самого текста.
#
# ЗАМЕР, И ОН НАШЁЛ ОШИБКУ. Первый прогон дал 0.976 на русском
# интервью и 0.998 на английском видео — то есть НЕ полностью.
# Разбор показал причину: распознавание отдаёт «какая» и «-то» двумя
# кусками, а текст и весь остальной проект считают это одним словом.
# Такое слово не совпадало само с собой и получало прикинутое время
# вместо измеренного. Починено раздачей времён словам текста, а не
# кускам распознавания; после починки обе цифры равны 1.000.
#
# Порог оставлен с запасом, а не подтянут к единице: он ловит поломку
# разбора, а не плохой звук. На плохом звуке расшифровка будет
# неверной, но сама с собой сойдётся всё равно.
SELF_MATCH = 0.95


# ─────────────────────────────────────────────────────────────────────────
# Кадр и детектор лиц
# ─────────────────────────────────────────────────────────────────────────

# Отношение сторон вертикального кадра. Не калибровка, а геометрия
# площадки: 9:16 — это то, во что публикуется вертикальный ролик.
VERTICAL = 9 / 16

# Размер кадра готового ролика. Тоже геометрия, а не замер.
VERTICAL_W = 1080
VERTICAL_H = 1920

# Сколько кадров на план смотрит детектор лиц и в каких долях длины.
# Один кадр обманывает на движении, больше трёх не окупается.
#
# Происхождение: выбор, проверенный на том же эссе.
FRAMES_AT = (0.15, 0.5, 0.85)

# Ширина кадра, на которой работает детектор лиц.
#
# Кадры вынимаются ИЗ ИСХОДНИКА, а не из уменьшенной копии, и это замер,
# а не рассуждение. На всех 382 планах эссе сравнивались рамки, взятые
# с исходника и с копии 640:
#
#   рамка разошлась больше чем на 96 пикселей   13%
#   разошлась на целое полуокно (304 пикселя)    8%
#   решение «лицо или центр» перевернулось      14 планов
#
# То есть у каждого двенадцатого плана копия ставит колонку туда, где
# от задуманной не остаётся ничего общего. Копия при этом НЕ врёт
# детектору склеек (связь метрик 0.995): это разные задачи. Склейка —
# «насколько кадр непохож на предыдущий», и мелочь на неё не влияет;
# лицо — это мелочь и есть.
#
# Происхождение: замер сделан со старым детектором (аниме-лица поверх
# ultralytics). Для нового детектора вывод перепроверен в первой сессии
# этого проекта — см. private/docs/sessions.md.
CROP_FRAME_WIDTH = 1280

# Порог уверенности детектора лиц.
#
# Подобран замером на 382 планах анимешного эссе — тех же самых, что
# считал старый детектор (аниме-лица поверх ultralytics). Сравнивались
# решения: где лицо, где центр, и насколько разошлись окна.
#
#   порог   нашли лицо   мы нашли, он нет   он нашёл, мы нет
#    0.4        215             50                 47
#    0.5        180             29                 61
#    0.6        148             12                 76
#    0.7        123              3                 92
#    0.8         95              1                118
#
# Выбрано 0.6, и выбор наклонён в сторону осторожности намеренно.
# Цены у двух ошибок разные:
#
#   лишнее лицо  — окно уезжает на текстуру, толпу или блик, и человек
#                  получает кадр мимо того, что происходит;
#   пропущенное  — окно встаёт по центру, то есть туда же, куда ставит
#                  его любой кроп без всякого детектора. Не идеально,
#                  но и не брак.
#
# Поэтому лучше пропустить, чем поставить не туда, и порог стоит там,
# где лишние срабатывания почти кончились (12 из 382), а пропуски ещё
# не разрослись.
#
# ПРОИСХОЖДЕНИЕ. Подбирался на РИСОВАННЫХ лицах, потому что другого
# материала в первой сессии под рукой не было.
#
# ЗАМЕР НА ЖИВЫХ ЛИЦАХ СДЕЛАН ВО ВТОРОЙ СЕССИИ, И ОЖИДАНИЕ ПОДТВЕРДИЛОСЬ.
# Порог не изменился — изменилось то, что про него известно:
#
#   материал                        планов   рамка по лицу
#   интервью, две живые головы        212     191  (90%)
#   английское видео, один спикер      46      33  (72%)
#   анимационное эссе                 382     148  (39%)
#
# На живых лицах детектор находит лицо втрое чаще, чем на рисованных,
# и это ровно то, ради чего он выбирался вместо аниме-детектора.
#
