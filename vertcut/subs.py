def цвет(значение: str, альфа: int = 255):
    текст = str(значение).lstrip("#")
    if len(текст) != 6:
        raise VertcutError(
            f"A color in the subtitle style must look like #RRGGBB, "
            f"not {значение!r}")
    try:
        r, g, b = (int(текст[i:i + 2], 16) for i in (0, 2, 4))
    except ValueError as bad:
        raise VertcutError(
            f"{значение!r} in the subtitle style isn't a color "
            "(it should look like #RRGGBB)") from bad
    return r, g, b, альфа


def _яркость(какой: str) -> float:
    """Относительная яркость цвета — та, что в мере контраста."""
    r, g, b, _ = цвет(какой)

    def ровно(доля: float) -> float:
        доля /= 255
        if доля <= 0.03928:
            return доля / 12.92
        return ((доля + 0.055) / 1.055) ** 2.4

    return 0.2126 * ровно(r) + 0.7152 * ровно(g) + 0.0722 * ровно(b)


def контраст(один: str, другой: str) -> float:
    """Во сколько раз один цвет светлее другого. От 1 до 21."""
    a, b = _яркость(один), _яркость(другой)
    светлее, темнее = max(a, b), min(a, b)
    return (светлее + 0.05) / (темнее + 0.05)


def жалоба_на_контраст(prof: dict) -> str | None:
    """Сливается ли сказанное слово со своей подложкой.

    Способ подложки и цвет краски связаны: под плашку берут тёмный
    текст, под обводку и тень — светлый. Поменял человек одно и не
    поменял второе — получит чёрное на чёрном и узнает об этом
    из собранного файла.

    **При подложке «без» не считается ничего, и это честно:** там
    подложка — сама картинка видео, она меняется каждый кадр, и
    сказать про неё нечего.
    """
    под = prof["подложка"]
    если = {ПЛАШКА: ("цвет", "the box"),
            ОБВОДКА: ("обводка_цвет", "the outline"),
            ТЕНЬ: ("тень_цвет", "the shadow")}.get(под)
    if если is None:
        return None
    ключ, чем = если
    мера = контраст(prof["сказанное"], prof[ключ])
    if мера >= tuning.CONTRAST_MIN:
        return None
    return (f"the spoken word blends into {чем}: colors "
            f"{prof['сказанное']} and {prof[ключ]}, contrast {мера:.1f}, "
            f"needs {tuning.CONTRAST_MIN}. Use dark text on a box, light "
            "text with an outline or shadow")


def нарисовать(страница: list, сказано: int, низ: int, prof: dict, font):
    """Одно состояние субтитра картинкой с прозрачностью.

    Блок растёт ВВЕРХ от своего низа: нижняя строка всегда на одном
    месте, сколько бы их ни было. Так строка не прыгает при
    перелистывании.

    Плашки рисуются все сразу, а текст поверх них. Иначе нижняя плашка
    закрыла бы свесы верхней строки: плашки соседних строк нарочно
    перекрываются.
    """
    from PIL import Image, ImageDraw

    слой = Image.new("RGBA", (prof["width"], prof["height"]), (0, 0, 0, 0))
    if not страница:
        return слой
    перо = ImageDraw.Draw(слой)
    высота, шаг = prof["высота_плашки"], prof["шаг"]
    места = разложить_строки(страница, низ, prof)

    if prof["рисует_плашку"]:
        # Плашки рисуются ВСЕ СРАЗУ, а текст поверх них. Иначе нижняя
        # плашка закрыла бы свесы верхней строки: плашки соседних строк
        # нарочно перекрываются.
        фон = цвет(prof["цвет"])
        for _, лев, ширина, свой_низ in места:
            перо.rounded_rectangle(
                [лев, свой_низ - высота, лев + ширина, свой_низ],
                radius=prof["радиус"], fill=фон)

    # Плашки подсветки — ПОД текстом и над плашкой строки. Порядок
    # здесь часть смысла: плашка строки, плашка слова, подложка, текст.
    было = 0
    for строка, лев, _, свой_низ in места:
        свои = подсвеченные(строка, сказано - было, prof)
        было += len(строка.words)
        if свои and prof["подсветка_чем"] == ПЛАШКОЙ:
            x = лев + prof["запас_сбоку"]
            слова = font.места_слов(x, строка.text, строка.words)
            поле = prof["поле_сбоку"] if prof["рисует_плашку"] else 0
            for n in свои:
                a, b = слова[n]
                перо.rounded_rectangle(
                    [a - поле / 2, свой_низ - высота, b + поле / 2, свой_низ],
                    radius=prof["радиус"], fill=цвет(prof["подсветка_цвет"]))

    видно, было = сказано, 0
    for строка, лев, _, свой_низ in места:
        база = свой_низ - prof["базовая_от_низа"]
        # Ставим по КРАСКЕ, а не по габариту: поля эталона мерялись
        # от края плашки до первого пикселя буквы.
        x = лев + prof["запас_сбоку"]
        свои = подсвеченные(строка, сказано - было, prof)
        чем = prof["подсветка_чем"]
        крупные = set(свои) if чем == КЕГЛЕМ else set()
        сколько = max(0, min(видно, len(строка.words)))

        def какого_цвета(n: int, сколько=сколько, свои=свои, чем=чем):
            if свои and n in свои and чем == ЦВЕТОМ:
                return цвет(prof["подсветка_цвет"])
            готово = prof["сказанное"] if n < сколько else prof["несказанное"]
            return цвет(готово)

        # Подложка кладётся ПОД текст отдельным проходом — и до того,
        # как строка разделится на сказанное и ещё нет. Иначе обводка
        # сказанного слова легла бы поверх соседнего.
        if prof["подложка"] == ТЕНЬ:
            сдвиг = prof["тень_сдвиг"]
            _нарисовать_строку(перо, font, x + сдвиг, база + сдвиг, строка,
                               цвет(prof["тень_цвет"]), крупные=крупные)
        elif prof["подложка"] == ОБВОДКА:
            _нарисовать_строку(перо, font, x, база, строка,
                               цвет(prof["обводка_цвет"]),
                               толщина=prof["обводка_толщина"],
                               крупные=крупные)
        if not свои and not font.мерить_крупно:
            # Прежний путь, слово в слово: приглушённая строка целиком,
            # поверх — сказанный кусок. Он остаётся главным — на нём
            # собран весь материал, по которому замерены пороги
            # заслонов, и трогать его без нужды нельзя.
            font.рисовать(перо, x, база, строка.text,
                          цвет(prof["несказанное"]))
            if сколько:
                font.рисовать(перо, x, база, segmentation.join_words(
                    w["w"] for w in строка.words[:сколько]),
                    цвет(prof["сказанное"]))
        else:
            _нарисовать_строку(перо, font, x, база, строка, какого_цвета,
                               крупные=крупные)
        видно -= len(строка.words)
        было += len(строка.words)
    return слой


def _нарисовать_строку(перо, font: Набор, x: float, база: float, строка,
                       краска, толщина: int = 0, крупные=()) -> None:
    """Строка: целиком одним куском или по словам.

    **По словам рисуется тогда, когда у слов свои места** — когда они
    зарезервированы крупным кеглем или когда одно слово подсвечено.
    Тогда каждое слово рисуется РОВНО ОДИН РАЗ, своим цветом и своим
    кеглем.

    Раньше это делалось наложением: вся строка приглушённой, поверх —
    сказанный кусок, поверх — подсвеченное слово. При подсветке кеглем
    такое наложение видно глазами: под крупной буквой торчит её же
    обычная копия, и слово выглядит смазанным. Поймано на первом же
    листе.

    `краска` — либо один цвет на всю строку (проходы подложки), либо
    функция «номер слова → цвет».
    """
    один = краска if not callable(краска) else None
    if один is not None and not font.мерить_крупно and not крупные:
        # Прежний путь, слово в слово: строка одним куском. Он остаётся
        # главным — на нём собран весь материал, по которому замерены
        # пороги заслонов, и трогать его без нужды нельзя.
        font.рисовать(перо, x, база, строка.text, один, толщина)
        return
    места = font.места_слов(x, строка.text, строка.words)
    for n, слово in enumerate(строка.words):
        слева, справа = места[n]
        крупно = n in крупные
        # Слово встаёт ПО ЦЕНТРУ своего места. Когда места посчитаны
        # обычным кеглем, оно ровно в него и попадает — буквы встают
        # туда же, куда встали бы у строки, нарисованной одним куском.
        # Когда крупным (подсветка кеглем), обычные слова стоят
        # с одинаковым просветом с обеих сторон, а крупное занимает
        # своё место целиком и никуда не вылезает.
        ширина = font.продвижение(слово["w"], крупно=крупно)
        перо_x = слева + (справа - слева - ширина) / 2
        font.рисовать(перо, перо_x, база, слово["w"],
                      один if один is not None else краска(n),
                      толщина, крупно=крупно, от_краски=False)


def подсвеченные(строка, сказано: int, prof: dict) -> list[int]:
    """Номера слов строки, которые сейчас подсвечены.

    `сказано` — сколько слов страницы прозвучало к этому мгновению,
    считая от начала ЭТОЙ строки.

    **Подсвечивается ТЕКУЩЕЕ слово, а не весь сказанный кусок.**
    «Сказано или ещё нет» уже показано краской и работает всегда;
    подсветка отвечает на другой вопрос — что звучит прямо сейчас.
    """
    if prof["подсветка"] == НЕТ_ПОДСВЕТКИ:
        return []
    n = сказано - 1
    if not (0 <= n < len(строка.words)):
        return []
    if prof["подсветка"] == ПО_СТРОКЕ:
        return list(range(len(строка.words)))
    return [n]


def разложить_строки(страница: list, низ: int, prof: dict) -> list[tuple]:
    """Где стоит каждая строка страницы: (строка, левый край, ширина, низ).

    Одно место на всех: рисование ставит по этим числам краску, заслон
    по ним же считает, какие пиксели субтитр занял. Разойдись они —
    заслон начнёт спрашивать не те пиксели, и поймать это будет нечем.
    """
    запас, шаг = prof["запас_сбоку"], prof["шаг"]
    вышло = []
    for n, строка in enumerate(страница):
        свой_низ = низ - (len(страница) - 1 - n) * шаг
        ширина = строка.ink + 2 * запас + prof["тень_сдвиг"]
        лев = (prof["width"] - ширина) / 2
        вышло.append((строка, лев, ширина, свой_низ))
    return вышло


# ─────────────────────────────────────────────────────────────────────
# Что занято субтитром: для сверки готового файла
# ─────────────────────────────────────────────────────────────────────
#
# Заслоны сверяют кадр готового файла с кадром исходника. Поверх кадра
# лежит субтитр, и связь падает — на первом же прогоне с 0.999 до 0.66.
#
# Выбрано: сверка перестаёт спрашивать те пиксели, которые заняты
# субтитром. Не «сверять до наложения» — до наложения файла
# не существует, кодирование одно. Не «понизить порог» — порог стоит
# посреди пропасти между исправным и сломанным.
#
# А исключить субтитр можно ТОЧНО, до пикселя: слой рисуем мы сами
# и на любой секунде знаем, где у него краска.

# Сколько пикселей прибавить к прямоугольнику плашки с каждой стороны.
# Не запас «на всякий случай», а цена сжатия: h264 размазывает резкую
# границу плашки на несколько пикселей вокруг неё, и эти пиксели уже
# не кадр исходника.
РАЗМАЗ = 2


def занято(раскл: dict, prof: dict, при: float) -> tuple | None:
    """Прямоугольник, занятый субтитром на этой секунде ролика."""
    показ = None
    for p in раскл["показы"]:
        if p["at"] - 1e-6 <= при < p["till"] + 1e-6:
            показ = p
            break
    if показ is None or not показ["страница"]:
        return None
    места = разложить_строки(показ["страница"], показ["низ"], prof)
    # Считается ПО ТЕМ ЖЕ числам, по которым субтитр нарисован. Своей
    # арифметики здесь нет: разойдись она с рисованием — заслон начнёт
    # спрашивать не те пиксели, и поймать это будет нечем.
    x0 = min(лев for _, лев, _, _ in места)
    x1 = max(лев + ширина for _, лев, ширина, _ in места)
    верх = min(свой_низ for *_, свой_низ in места) - prof["высота_плашки"]
    низ = max(свой_низ for *_, свой_низ in места) + prof["тень_сдвиг"]
    return (max(0, int(x0) - РАЗМАЗ), max(0, int(верх) - РАЗМАЗ),
            min(prof["width"], int(x1) + РАЗМАЗ),
            min(prof["height"], int(низ) + РАЗМАЗ))


def занято_когда_нибудь(раскл: dict, prof: dict) -> tuple | None:
    """Прямоугольник, который субтитр занимает хоть когда-нибудь.

    Нужен там, где секунда неизвестна или сравниваются два кадра
    из разных мест — например, на проверке стыков.
    """
    куски = [занято(раскл, prof, p["at"]) for p in раскл["показы"]]
    куски = [k for k in куски if k]
    if not куски:
        return None
    return (min(k[0] for k in куски), min(k[1] for k in куски),
            max(k[2] for k in куски), max(k[3] for k in куски))


# ─────────────────────────────────────────────────────────────────────
# Лист раскладки: посмотреть глазами до сборки
# ─────────────────────────────────────────────────────────────────────

def выбрать_показы(раскл: dict, сколько: int = 5) -> list[dict]:
    """Какие состояния показать на листе.

    Не подряд и не наугад: берётся по одному представителю каждой
    породы — первое, двухстрочное, нижнее, последнее. Лист нужен
    затем, чтобы увидеть РЕДКОЕ, а не частое.
    """
    показы = раскл["показы"]
    if not показы:
        return []
    взято: list[dict] = []

    def добавить(что):
        if что is not None and все_разные(взято, что):
            взято.append(что)

    def все_разные(куда, что):
        return all(x is not что for x in куда)

    добавить(показы[0])
    добавить(next((p for p in показы if len(p["страница"]) > 1), None))
    добавить(next((p for p in показы if p["где"] == НИЗ), None))
    # Перелистывание: первое состояние второй страницы фразы.
    for ф in раскл["фразы"]:
        if len(ф["страницы"]) > 1:
            вторая = ф["страницы"][1]
            добавить(next((p for p in показы if p["страница"] is вторая), None))
            break
    добавить(показы[-1])
    return взято[:сколько]


def лист(раскл: dict, prof: dict, font, куда: Path) -> Path:
    """Картинка: несколько состояний субтитра на сером фоне.

    Фон серый нарочно, а не чёрный и не белый: на чёрном не видно
    светлой плашки, на белом — её краёв. Серый показывает и плашку,
    и границы кадра.

    Показаны и полосы безопасной зоны: справа и слева по 140 пикселей
    занимает столбик иконок соцсети, и строка, вылезшая под него,
    видна на листе сразу.
    """
    from PIL import Image, ImageDraw

    выбранные = выбрать_показы(раскл)
    if not выбранные:
        raise VertcutError("Nothing to show: this clip has no subtitles")

    ширина, высота = prof["width"], prof["height"]
    # Поле берётся у ЗОНЫ, а не считается из предельной ширины строки:
    # со снятым флажком предел равен всему кадру, и полосы пропали бы
    # ровно тогда, когда смотреть на них важнее всего.
    поле_площадки = prof["зона_сбоку"]
    полотна = []
    for показ in выбранные:
        кадр = Image.new("RGBA", (ширина, высота), (70, 70, 80, 255))
        перо = ImageDraw.Draw(кадр)
        перо.rectangle([0, 0, поле_площадки, высота], fill=(90, 60, 60, 255))
        перо.rectangle([ширина - поле_площадки, 0, ширина, высота],
                       fill=(90, 60, 60, 255))
        кадр = Image.alpha_composite(
            кадр, нарисовать(показ["страница"], показ["сказано"],
                             показ["низ"], prof, font))
        верх = max(0, показ["низ"] - 320)
        полотна.append(кадр.convert("RGB").crop((0, верх, ширина, показ["низ"] + 60)))

    ш = max(p.width for p in полотна)
    итог = Image.new("RGB", (ш, sum(p.height + 8 for p in полотна)), (20, 20, 24))
    y = 0
    for p in полотна:
        итог.paste(p, (0, y))
        y += p.height + 8
    куда.parent.mkdir(parents=True, exist_ok=True)
    итог.save(куда, quality=90)
    return куда


# ─────────────────────────────────────────────────────────────────────
# Выгрузка .srt
# ─────────────────────────────────────────────────────────────────────

def srt(раскл: dict) -> str:
    """Субтитры ролика файлом `.srt`.

    **Собирается из ПОКАЗОВ, а не из фраз, и это не мелочь.** Фраза,
    которая не влезает в кадр, показывается страницами — сперва одна
    половина, потом другая. В `.srt` это две разные реплики с разными
    временами, и взять их можно только из показов: только там записано,
    какая страница когда стояла.

    Соседние показы одной и той же страницы сливаются в одну реплику:
    показов у фразы бывает до полусотни — по одному на слово, — а
    в `.srt` слова не подсвечиваются, и полсотни одинаковых реплик
    подряд были бы мусором.

    Времена — В ШКАЛЕ РОЛИКА, а не видео: файл `.srt` кладут рядом
    с готовым роликом, и отсчёт у него от первого кадра этого ролика.
    """
    куски = []
    for показ in раскл["показы"]:
        текст = "\n".join(строка.text for строка in показ["страница"])
        if куски and куски[-1]["текст"] == текст:
            куски[-1]["till"] = показ["till"]
            continue
        куски.append({"at": показ["at"], "till": показ["till"],
                      "текст": текст})

    вышло = []
    for n, кусок in enumerate(куски, 1):
        вышло.append(f"{n}\n{_время_srt(кусок['at'])} --> "
                     f"{_время_srt(кусок['till'])}\n{кусок['текст']}\n")
    return "\n".join(вышло)


def _время_srt(секунд: float) -> str:
    """Часы:минуты:секунды,миллисекунды — как велит формат."""
    всего = max(float(секунд), 0.0)
    часы, остаток = divmod(всего, 3600)
    минуты, секунды = divmod(остаток, 60)
    целых = int(секунды)
    мс = int(round((секунды - целых) * 1000))
    if мс == 1000:          # округление вверх не должно давать «,1000»
        целых, мс = целых + 1, 0
    return f"{int(часы):02d}:{int(минуты):02d}:{целых:02d},{мс:03d}"
