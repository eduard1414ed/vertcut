def фразы_куска(laid: dict, куски: list[dict]) -> list[dict]:
    """Фразы, попавшие в ролик, со временами в шкале ролика.

    `куски` — список кусков видео: у каждого номера первого
    и последнего слова и `сдвиг` (сколько вычесть из времени видео,
    чтобы получить время ролика).

    **Краевая фраза берётся половиной.** Начать ролик с середины фразы
    человек вправе, и тогда сюда приходит не вся фраза, а её кусок.
    Берётся по номерам СЛОВ: номера — это то, из чего сам кусок
    посчитан.
    """
    from . import speech

    места = speech.spans(laid)
    вышло = []
    for кусок in куски:
        первое, последнее = int(кусок["first"]), int(кусок["last"])
        сдвиг = float(кусок["сдвиг"])
        for n, (w0, w1) in enumerate(места):
            с, по = max(w0, первое), min(w1, последнее)
            if с > по:
                continue
            фраза = laid["phrases"][n]
            слова = фраза["words"][с - w0:по - w0 + 1]
            if not слова:
                continue
            вышло.append({
                "idx": фраза["idx"],
                # Номера слов фразы в ролике. По ним ложатся правки
                # рукой: номера фраз переезжают, номера слов — нет.
                "с": с, "по": по,
                "кусок": кусок.get("n", 1),
                "сдвиг": сдвиг,
                "at": round(float(слова[0]["s"]) - сдвиг, 3),
                "till": round(float(слова[-1]["e"]) - сдвиг, 3),
                # То же самое ДО правки по звуку — чтобы было видно,
                # что правка сделала.
                "по_словам": (round(float(слова[0]["s"]) - сдвиг, 3),
                              round(float(слова[-1]["e"]) - сдвиг, 3)),
                "words": [{"w": w["w"],
                           "s": round(float(w["s"]) - сдвиг, 3),
                           "e": round(float(w["e"]) - сдвиг, 3)}
                          for w in слова],
                "целая": (с, по) == (w0, w1),
                "снаружи_слева": " ".join(
                    w["w"] for w in фраза["words"][:с - w0]),
                "снаружи_справа": " ".join(
                    w["w"] for w in фраза["words"][по - w0 + 1:]),
            })
    вышло.sort(key=lambda ф: ф["at"])
    if not вышло:
        raise VertcutError(
            "This clip has no phrases, so there are no subtitles to make")
    return вышло


def раскладка_ролика(project: Path, meta: dict, laid: dict, cut: dict,
                     ряды: list[dict], prof: dict, шрифт) -> dict:
    """Вся раскладка субтитров ролика — от папки и ролика, а не от кусков.

    Одно место, где куски ролика превращаются в места для раскладки.
    Раньше эта дюжина строк лежала в трёх: у сборки, у команды `subs`
    и у предпросмотра. Три копии арифметики времени — это ровно то,
    на чём предок терял кадр на каждой склейке.
    """
    from . import edits, pick, plans

    таблица = plans.карта(cut, float(meta["duration"]),
                          float(meta.get("fps") or 25))
    места = [{"first": к["words"]["first"], "last": к["words"]["last"],
              "n": к["n"],
              "сдвиг": round(с["звук"]["essay0"] - с["звук"]["at"], 4)}
             for к, с in zip(pick.pieces(cut), таблица["куски"])]
    from . import plate
    return раскладка(project, laid, meta, места, ряды, prof, шрифт,
                     таблица["всего"], edits.список(cut),
                     plate.начало(таблица["всего"],
                                  plate.сырые(project, cut["id"])))


# ─────────────────────────────────────────────────────────────────────
# Субтитры в файле: есть или нет
# ─────────────────────────────────────────────────────────────────────
#
# **Решение лежит у вертикалки и у видео, а не в стиле.** Положи его
# в профиль — и выключить субтитры у одного ролика значило бы завести
# ему свой стиль: шапка редактора сказала бы «only this clip uses it»,
# а правки стиля видео до него больше не доходили бы. Выключить
# субтитры — это не про то, как они выглядят.
#
# Уровня два: видео (`meta.json`, запоминается при первом разборе
# по галочке настроек) и вертикалка (`cut.json`, только если человек
# решил иначе, чем видео).

БЕЗ_СУБТИТРОВ = "без_субтитров"          # meta.json: видео без субтитров
СУБТИТРЫ_В_ФАЙЛЕ = "субтитры_в_файле"    # cut.json: своё решение ролика


def у_видео(project: Path) -> bool:
    """Будут ли субтитры у роликов видео, если ролик не решил иначе."""
    import json

    файл = layout.meta(project)
    meta = json.loads(файл.read_text(encoding="utf-8")) if файл.exists() else {}
    return not meta.get(БЕЗ_СУБТИТРОВ)


def в_файле(project: Path, cut: dict) -> bool:
    """Будут ли субтитры в готовом файле ЭТОЙ вертикалки.

    Одно место на всех, кто спрашивает: сборка, заслоны, обложка,
    экран и команда. Ответь двое по-разному — и на экране кадр без
    субтитра, а в файле с ним.
    """
    своё = cut.get(СУБТИТРЫ_В_ФАЙЛЕ)
    if своё is not None:
        return bool(своё)
    return у_видео(project)


def задать_в_файле(project: Path, cut: dict, да: bool) -> None:
    """Включить или выключить субтитры у вертикалки.

    Совпало с видео — ключа нет: ролик снова идёт за видео, и в файле
    не остаётся решения, которое ничего не решает.
    """
    if bool(да) == у_видео(project):
        cut.pop(СУБТИТРЫ_В_ФАЙЛЕ, None)
    else:
        cut[СУБТИТРЫ_В_ФАЙЛЕ] = bool(да)


def фразы_с_правками(laid: dict, куски: list, правки=None) -> list[dict]:
    """Фразы ролика с наложенными правками рукой, во времени ВИДЕО.

    `куски` — пары номеров слов, как `pick.ranges`. Без шрифта и без
    звука: это ответ на вопрос «какой текст у субтитров ролика».
    Его же читают штамп сборки и вычитка моделью — одно место, иначе
    модель правила бы не тот текст, что стоит в кадре.
    """
    from . import edits

    ряд = [{"first": int(a), "last": int(b), "сдвиг": 0.0, "n": n}
           for n, (a, b) in enumerate(куски, 1)]
    return edits.наложить(фразы_куска(laid, ряд), правки)


def отпечаток_фраз(laid: dict, куски: list, правки=None) -> str:
    """Отпечаток фраз, попавших в ролик: их номера, слова и времена.

    Зачем. Штамп сборки помнил профиль субтитров и монтаж кадра, но
    не помнил САМИ ФРАЗЫ. А фразы меняются: перенарезали видео другими
    правилами, поправили сценарий, поправили текст фразы рукой —
    и субтитры в готовом файле стали чужими. Файл при этом целый,
    нужной длины и с субтитрами на месте; понять, что они старые,
    можно было только глазами.

    **Правки рукой входят сюда наравне с разбором.** Иначе поправленный
    текст не считался бы поводом пересобрать — а он самый частый повод
    из всех.

    Считается по голому `align.json`, без шрифта и без звука: это
    ответ на вопрос «из какого текста собрано», а не «как он выглядел».
    Сдвиг времени нулевой: сравниваются времена ВИДЕО, и от того,
    в какой ролик они попали, не зависят.
    """
    import hashlib
    import json

    фразы = фразы_с_правками(laid, куски, правки)
    что = [[ф["idx"], [[w["w"], w["s"], w["e"]] for w in ф["words"]]]
           for ф in фразы]
    строка = json.dumps(что, ensure_ascii=False, sort_keys=True)
    return hashlib.sha1(строка.encode("utf-8")).hexdigest()[:16]


def подрезать_по_голосу(project: Path, laid: dict,
                        фразы: list[dict]) -> list[str]:
    """Подрезать фразы там, где голоса нет. Меняет фразы на месте.

    Возвращает список того, что подрезано, — для печати. **Молча такое
    делать нельзя:** субтитр, исчезнувший на четыре секунды раньше, чем
    сказано в разборе, человек обязан увидеть числом.

    Подрезаем только внутрь: наружу укладку не двигаем никогда. Слово
    может звучать тише порога — например, в конце вздоха, — и тогда
    лучше оставить как есть.
    """
    if not фразы:
        return []
    сказано = []
    по_кускам: dict[int, list[dict]] = {}
    for ф in фразы:
        по_кускам.setdefault(int(ф.get("кусок", 1)), []).append(ф)
    for номер in sorted(по_кускам):
        сказано += _подрезать_кусок(project, laid, по_кускам[номер])
    return сказано


def _подрезать_кусок(project: Path, laid: dict,
                     фразы: list[dict]) -> list[str]:
    начало_куска = фразы[0]["сдвиг"]
    a = min(ф["at"] for ф in фразы) + начало_куска
    b = max(ф["till"] for ф in фразы) + начало_куска
    гр, начало = громкость(project, a - 0.5, b + 0.5)
    темп = темп_речи(laid)
    # Прижат ли край фразы к соседке — считается по ИСХОДНОЙ укладке
    # всего видео, а не по уже подрезанным соседкам: иначе правка
    # поехала бы по цепочке.
    номера = {int(ф["idx"]): n for n, ф in enumerate(laid["phrases"])}
    сказано = []
    for ф in фразы:
        было_at, было_till = ф["at"], ф["till"]
        n = номера.get(int(ф["idx"]))
        соседи = laid["phrases"]
        слева = (float(соседи[n]["start"]) - float(соседи[n - 1]["end"])
                 if n else 99.0)
        справа = (float(соседи[n + 1]["start"]) - float(соседи[n]["end"])
                  if n + 1 < len(соседи) else 99.0)
        s, e = границы_речи(гр, начало, было_at + начало_куска,
                            было_till + начало_куска, ф["words"], темп,
                            слева >= tuning.SPEECH_GAP,
                            справа >= tuning.SPEECH_GAP)
        стало_at = max(было_at, round(s - начало_куска, 3))
        стало_till = min(было_till, round(e - начало_куска, 3))
        if стало_till - стало_at < tuning.SPEECH_STEP * 3:
            continue
        ф["at"], ф["till"] = стало_at, стало_till
        разложены = разложить_заново(ф, темп)
        позже = round(стало_at - было_at, 2)
        раньше = round(было_till - стало_till, 2)
        if позже > 0.05 or раньше > 0.05:
            части = []
            if позже > 0.05:
                части.append(f"starts {позже:.2f} s later")
            if раньше > 0.05:
                части.append(f"ends {раньше:.2f} s earlier")
            хвост = " — there's no voice there"
            if разложены:
                хвост += "; its words were re-timed to fit"
            сказано.append(f"phrase {ф['idx']}: " + " and ".join(части)
                           + хвост)
    return сказано


def где_стоит(фраза: dict, ряды: list[dict],
              плашка_с: float | None = None) -> str:
    """Где стоит субтитр этой фразы. Одно решение на всю фразу.

    `ряды` — отрезки монтажа кадра: у каждого `at`, `till`
    и `полный_кадр`. Пусто значит «весь ролик обрезан в вертикаль»,
    и тогда всё стоит по центру.

    **Плашка в конце сильнее горизонтального плана.** Фраза, заходящая
    под неё, встаёт по центру, даже если до плашки задела полный кадр:
    под плашкой горизонтального плана нет вовсе — там картинка плашки,
    и полоса в её середине держится пустой ровно затем, чтобы субтитр
    был виден. Уехав вниз, он лёг бы на надпись.

    **Пересечение считается не любое, а заметное глазу.** Мера взята
    готовая — `tuning.STUB`, полсекунды: она и заведена ровно под этот
    вопрос. Своего числа здесь нет и заводить его незачем — два числа
    на один вопрос однажды разъедутся.

    Заслон не теоретический: без него фраза уезжала вниз целиком из-за
    ОДНОГО кадра горизонтального плана, попавшего под её начало. Этого
    кадра зритель не видит вовсе, а разнобой в положении субтитра
    видит.
    """
    if плашка_с is not None and фраза["till"] > плашка_с - 1e-6:
        return ЦЕНТР
    for ряд in ряды:
        if not ряд.get("полный_кадр"):
            continue
        вместе = (min(ряд["till"], фраза["till"])
                  - max(ряд["at"], фраза["at"]))
        if вместе >= tuning.STUB - 1e-6:
            return НИЗ
    return ЦЕНТР


def раскладка(project: Path, laid: dict, meta: dict, куски: list[dict],
              ряды: list[dict], prof: dict, font, всего: float,
              правки=None, плашка_с: float | None = None) -> dict:
    """Вся раскладка субтитров ролика: фразы, страницы, места, показы.

    Одна дорога и для команды, и для сборки слоя, и для будущего
    экрана. Двух быть не должно: тогда напечатанное и собранное
    разойдутся, и увидит это только зритель.
    """
    from . import edits

    низ_снизу = низ_под_планом(meta, prof)
    # Правки рукой ложатся ДО подрезки по голосу: подрезка смотрит
    # на слова фразы, а правка их меняет.
    фразы = edits.наложить(фразы_куска(laid, куски), правки)
    жалобы: list[str] = []
    # Субтитр стоит, пока звучит голос, а не пока длится фраза
    # по разбору.
    подрезано = подрезать_по_голосу(project, laid, фразы)
    показы: list[dict] = []

    for фраза in фразы:
        стр = страницы(фраза["words"], prof, font)
        фраза["страницы"] = стр
        фраза["где"] = где_стоит(фраза, ряды, плашка_с)
        фраза["низ"] = (низ_снизу["низ"] if фраза["где"] == НИЗ
                        else prof["низ_центра"])
        # «Влезает» считается ЗДЕСЬ, а не при нарезке фраз: только здесь
        # известен стиль и померена настоящая ширина краски. Фраза,
        # не влезшая в одну страницу, показывается двумя — то есть
        # перелистывается посреди себя.
        фраза["строк"] = sum(len(с) for с in стр)
        фраза["влезает"] = len(стр) == 1
        for текст in слишком_широкие(стр, prof):
            жалобы.append(
                f"phrase {фраза['idx']}: the line “{текст}” is wider "
                "than the box allows")

        # Страница живёт от первого своего слова до первого слова
        # следующей. Последняя гаснет вместе с голосом, а не тянется
        # до следующей фразы: субтитр не должен висеть в паузе.
        for n, страница in enumerate(стр):
            слова = [w for строка in страница for w in строка.words]
            начало = фраза["at"] if n == 0 else float(слова[0]["s"])
            конец = (фраза["till"] if n == len(стр) - 1
                     else float(стр[n + 1][0].words[0]["s"]))
            # Строка стоит целиком, но сказанное чёрное, а ещё
            # не сказанное серое. Каждое слово — своё состояние.
            for k, слово in enumerate(слова):
                показы.append({
                    "at": round(max(начало, float(слово["s"])), 3),
                    "till": конец,
                    "страница": страница,
                    "сказано": k + 1,
                    "низ": фраза["низ"],
                    "где": фраза["где"],
                    "фраза": фраза["idx"],
                })

    показы.sort(key=lambda p: p["at"])
    for n, показ in enumerate(показы[:-1]):
        показ["till"] = min(показ["till"], показы[n + 1]["at"])
    показы = [p for p in показы if p["till"] - p["at"] > 1e-6]

    # Знаки, которых шрифт не знает.
    #
    # **Считается по тому тексту, который БУДЕТ НАРИСОВАН**, а не
    # по тексту фразы: при регистре «прописные» рисуются другие буквы,
    # и шрифт, знающий строчные, может не знать прописных.
    #
    # Молчать про это нельзя: сборка пройдёт, все четыре заслона
    # пройдут — квадратик тоже краска, — и человек узнает о беде
    # из комментариев под роликом.
    беда_с_цветом = жалоба_на_контраст(prof)
    if беда_с_цветом:
        жалобы.append(беда_с_цветом)

    нет_знаков = _чего_нет_в_шрифте(фразы, prof, font)
    if нет_знаков:
        жалобы.append(перечислить_знаки(нет_знаков, prof)
                      + ". Choose another font or change the text")

    # Про «не влезло» говорится ОДНОЙ строкой, а не строкой на фразу:
    # сорок жалоб подряд человек не читает, он их пролистывает. Кто
    # именно не влез — видно в списке фраз ролика (`vertcut subs`).
    #
    # **И это не жалоба, а сведение — своим полем, не в `жалобы`.**
    # Жалобы экран красит жёлтым, и первые люди читали жёлтое
    # «doesn't fit» как «субтитр обрежется». Не обрежется: все слова
    # в кадре, просто страницами.
    не_влезли = [ф["idx"] for ф in фразы if not ф["влезает"]]
    частями = (
        f"{len(не_влезли)} of {report.счёт(len(фразы), 'phrase', 'phrases')} "
        "take more than one page: they're too long to show at once, so "
        "the subtitle turns the page partway through. No words are lost. "
        "To choose where it turns, split the phrase or shorten the text"
    ) if не_влезли else None

    if низ_снизу["упёрся"]:
        жалобы.append(
            f"the subtitle under the shot hit the apps' bottom margin: "
            f"wanted its bottom at {низ_снизу['хотели']}, sits at "
            f"{низ_снизу['низ']}")
    # Про безопасные зоны говорится ЗДЕСЬ, а не при чтении профиля:
    # упереться можно только зная кадр и число строк.
    if prof.get("упёрся_вниз"):
        жалобы.append(
            f"the subtitle hit the apps' bottom margin: asked for its "
            f"bottom at {prof['низ_хотели']}, sits at {prof['низ_центра']} "
            "— below that the app shows its own caption")
    if prof.get("упёрся_вверх"):
        жалобы.append(
            f"the subtitle hit the apps' top margin: two lines don't fit "
            f"between the safe zones, so it was moved down to "
            f"{prof['низ_центра']}")

    return {"фразы": фразы, "показы": показы, "total": всего,
            "низ_под_планом": низ_снизу, "подрезано": подрезано,
            "не_влезли": не_влезли, "частями": частями,
            "нет_знаков": нет_знаков,
            "жалобы": жалобы, "полоса": полоса(prof),
            # Длина ролика и начало плашки — оба уже посчитаны здесь.
            # Отдаются наверх нарочно: второй счёт того же числа — это
            # ровно то, на чём предок терял кадр на каждой склейке.
            "всего": всего, "плашка_с": плашка_с}


# Сколько незнакомых знаков перечислять поимённо. Шрифт, не знающий
# кириллицы вовсе, даёт их четыре десятка, и список во всю строку
# человек не читает — он его пролистывает. Первого десятка хватает,
# чтобы понять беду; остальные считаются числом.
ЗНАКОВ_В_СТРОКУ = 10


def перечислить_знаки(нет: list[str], prof: dict) -> str:
    """Незнакомые шрифту знаки — строкой для человека."""
    видно = " ".join(f"«{з}»" for з in нет[:ЗНАКОВ_В_СТРОКУ])
    ещё = len(нет) - ЗНАКОВ_В_СТРОКУ
    хвост = f" and {ещё} more" if ещё > 0 else ""
    return (f"{Path(prof['шрифт']).name} is missing "
            f"{report.счёт(len(нет), 'character', 'characters')} "
            f"from the text: {видно}{хвост}")


