# ─────────────────────────────────────────────────────────────────────
# Три уровня профиля
# ─────────────────────────────────────────────────────────────────────
#
# 1. ПОСТАВЛЯЕМЫЙ образец — в репозитории, работает сразу, не правится;
# 2. ЛИЧНЫЙ образец — то, что человек сохранил однажды. Снаружи
#    репозитория, иначе обновление сервиса его снесёт;
# 3. КОПИЯ В ВИДЕО — начинается с личного и дальше живёт своей жизнью.
#
# Уровней три, потому что двух мало: настроил на первом видео, загрузил
# второе — и всё сначала; на третьем человек начнёт злиться,
# и справедливо.
#
# **Копия заводится СРАЗУ, а не при первой правке.** Это не мелочь
# исполнения, а то, ради чего уровней три. Отпечаток профиля входит
# в штамп сборки: правка профиля устаревает собранные ролики. Пока
# копии нет, видео читало бы личный образец — и правка «моего стиля»
# устаревала бы ролики ЧУЖИХ видео, которых она не касается вовсе.
# Копия отвечает на это раз и навсегда: у каждого видео свой файл,
# и чужая правка до него не дотягивается.

# Чей стиль — словами экрана: их печатает разбор («copy (my style)»).
ПОСТАВЛЯЕМЫЙ, ЛИЧНЫЙ, СВОЙ = "default style", "my style", "this video's style"


def _прочитать(путь: Path) -> dict:
    """Один файл профиля с диска. Разбор yaml и отказы словами."""
    try:
        import yaml
    except ImportError as bad:
        raise VertcutError(
            "PyYAML isn't installed, so the subtitle style can't be read",
            hint="install the dependencies: pip install -e . -c constraints.txt") from bad
    try:
        данные = yaml.safe_load(путь.read_text(encoding="utf-8"))
    except Exception as bad:
        # Где сломано — строкой и столбцом, а не пересказом разборщика:
        # «while parsing a flow sequence… expected ',' or ']'» человеку
        # не говорит ничего, а номер строки — говорит.
        где = getattr(bad, "problem_mark", None) or getattr(bad, "context_mark", None)
        место = (f" — the file is broken at line {где.line + 1}, "
                 f"column {где.column + 1}" if где is not None else "")
        raise VertcutError(
            f"{_чей_файл(путь)} can't be read{место}.\n  File: {путь}",
            hint="fix that line in the file, or reset the style to the "
                 "default (Fix the style → Reset to default style)") from bad
    if not isinstance(данные, dict):
        raise VertcutError(
            f"{_чей_файл(путь)} is empty.\n  File: {путь}",
            hint="reset the style to the default (Fix the style → Reset "
                 "to default style)")
    return данные


def образец() -> dict:
    """Поставляемый профиль. Он же образец формы для двух остальных."""
    путь = layout.subs_yaml()
    if not путь.exists():
        raise VertcutError(
            f"The default subtitle style is missing: {путь}\n"
            "  It holds every subtitle setting — font, size, box, "
            "position.",
            hint="it comes with Vertcut — the install looks incomplete; "
                 "install it again")
    return _прочитать(путь)


def _слить(свой: dict, эталон: dict) -> dict:
    """Достроить недостающее из поставляемого образца.

    Личный образец лежит на диске у человека. Заведётся в профиле новый
    ключ — его файл не должен от этого сломаться, и человек не должен
    дописывать в него руками то, чего он в глаза не видел.

    Достраивается ТОЛЬКО отсутствующее. Всё, что человек написал,
    остаётся как написано, даже если оно совпадает со значением
    по умолчанию.
    """
    вышло = dict(свой)
    for ключ, значение in эталон.items():
        if ключ not in вышло:
            вышло[ключ] = значение
        elif isinstance(значение, dict) and isinstance(вышло[ключ], dict):
            вышло[ключ] = _слить(вышло[ключ], значение)
    return вышло


def _чужие(свой: dict, эталон: dict, путь: str = "") -> list[str]:
    """Ключи, которых в образце нет вовсе.

    Молчать про них нельзя. Опечатка в имени ключа — «кегл» вместо
    «кегль» — иначе прошла бы тихо: файл читается, сервис работает,
    а число не доехало. Человек при этом уверен, что настроил.
    """
    лишние = []
    for ключ, значение in свой.items():
        где = f"{путь}{ключ}"
        if ключ not in эталон:
            лишние.append(где)
        elif isinstance(значение, dict) and isinstance(эталон[ключ], dict):
            лишние += _чужие(значение, эталон[ключ], f"{где}.")
    return лишние


def виды() -> dict:
    """Готовые виды из поставки: имя → {зовут, зачем, цена, числа}.

    **Вид — это несколько чисел поверх профиля, а не профиль.** Заведи
    вид полным профилем — и каждый новый ключ субтитров пришлось бы
    дописывать в каждый вид, а забытый молча оставался бы старым.

    В файле поля вида английские (`name`, `about`, `cost`, `settings`):
    их читает человек. Наружу они уходят прежними русскими именами —
    это ключи json между сервером и страницей.
    """
    путь = layout.looks()
    if not путь.exists():
        raise VertcutError(
            f"The presets file is missing: {путь}",
            hint="it comes with Vertcut — the install looks incomplete; "
                 "install it again")
    данные = _прочитать(путь)
    эталон = плоско(образец())
    эталон.pop(ВЕРСИЯ, None)
    вышло = {}
    for имя, вид in данные.items():
        if not isinstance(вид, dict) or "settings" not in вид:
            raise VertcutError(
                f"The preset «{имя}» in {путь.name} is written wrong: "
                "a preset needs «name», «about», «cost» and «settings»")
        числа = вид["settings"] or {}
        нет = [к for к in числа if к not in эталон]
        if нет:
            raise VertcutError(
                f"The preset «{имя}» has settings Vertcut doesn't know: "
                f"{', '.join(нет)}\n  File: {путь}",
                hint=f"compare with the default style: {layout.subs_yaml()}")
        цена = вид.get("cost") or {}
        if not isinstance(цена, dict) or not цена:
            raise VertcutError(
                f"The preset «{имя}» has no cost — the share of phrases "
                "that need two pages.\n"
                f"  File: {путь}",
                hint="measure it (vertcut looks VIDEO_ID) and write it "
                     "down: otherwise people find out on their first video")
        вышло[имя] = {"зовут": str(вид.get("name") or имя),
                      "зачем": str(вид.get("about", "")),
                      "цена": {к: float(з) for к, з in цена.items()},
                      "числа": числа}
    return вышло


def взять_вид(имя: str) -> dict:
    """Числа одного вида. Нет такого — отказ со списком того, что есть."""
    все = виды()
    if имя not in все:
        raise VertcutError(
            f"There's no preset called «{имя}»",
            hint="see the presets: vertcut looks")
    return все[имя]["числа"]


def перелистывания(laid: dict, prof: dict, шрифт) -> dict:
    """Сколько фраз видео не влезает в одну страницу при этом стиле.

    **Это замер, и он живёт в сервисе, а не в черновом скрипте.**
    Второй раз подряд записанное однажды число не сошлось с пересчётом
    — сперва у предка, потом у нас. Число, которое нельзя перемерить
    одной командой, через полгода становится преданием.
    """
    всего = не_влезли = страниц = 0
    for фраза in laid["phrases"]:
        стр = страницы(фраза["words"], prof, шрифт)
        всего += 1
        страниц += len(стр)
        не_влезли += len(стр) > 1
    return {"фраз": всего, "не_влезли": не_влезли, "страниц": страниц,
            "доля": (не_влезли / всего) if всего else 0.0}


def завести(project: Path) -> tuple[Path, str]:
    """Профиль этого видео: путь и откуда он взялся.

    Нет копии — делается, из личного образца или из поставляемого.
    Копируется ФАЙЛОМ, со всеми примечаниями: числа в этом файле
    подписаны тем, как они мерялись, и копия без подписей — это
    двадцать голых чисел, которые человек боится трогать.
    """
    import shutil

    куда = layout.project_subs(project)
    if куда.exists():
        return куда, СВОЙ
    личный = layout.my_subs()
    откуда = личный if личный.exists() else layout.subs_yaml()
    если_нет = ЛИЧНЫЙ if личный.exists() else ПОСТАВЛЯЕМЫЙ
    if not откуда.exists():
        raise VertcutError(
            f"The default subtitle style is missing: {откуда}",
            hint="it comes with Vertcut — the install looks incomplete; "
                 "install it again")
    куда.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(откуда, куда)
    _ПРОФИЛИ.pop(str(куда), None)
    return куда, если_нет


def записать(куда: Path, данные: dict) -> None:
    """Профиль на диск. Кэш сбрасывается здесь же.

    Не сбросишь — правка и лист «после» разойдутся внутри одной
    команды: числа на диске новые, в памяти старые.
    """
    import yaml

    куда.parent.mkdir(parents=True, exist_ok=True)
    куда.write_text(
        yaml.safe_dump(данные, allow_unicode=True, sort_keys=False,
                       default_flow_style=False),
        encoding="utf-8")
    _ПРОФИЛИ.pop(str(куда), None)


def сбросить_кэш() -> None:
    """Забыть прочитанное. Нужен там, где файл правят из-под сервиса."""
    _ПРОФИЛИ.clear()


def файл(project: Path | None = None, ident: str | None = None) -> Path:
    """Какой файл профиля читается. Без видео — поставляемый.

    **Без видео берётся поставляемый, а не личный, и это решение.**
    Личный образец — то, во что человек превращает стиль КОНКРЕТНОГО
    видео; там, где видео нет вовсе (подписи на контактных листах,
    проверки), спрашивать «а какой у него личный вкус» не о чем.

    **Уровней теперь четыре, и четвёртый заводится не всегда.** Пока
    у вертикалки нет своего файла, она читает профиль видео — и пачка
    из одного видео выходит единообразной, как и записано в спеке.
    Файл появляется ровно тогда, когда человек поправил стиль ЭТОЙ
    вертикалки.
    """
    if project is None:
        return layout.subs_yaml()
    if ident:
        свой = layout.cut_subs(project, ident)
        if свой.exists():
            return свой
    return завести(project)[0]


def починить(project: Path, ident: str, откуда: Path) -> list[str]:
    """Заменить файлом `откуда` те файлы стиля вертикалки, что
    не читаются. Возвращает, чьи стили заменены, — словами экрана.

    **Нужна затем, что «вернуть стиль» на экране отказа чинила
    не тот файл.** Кнопка заводила вертикалке свой стиль из образца —
    а не читался стиль ВИДЕО, и он оставался прежним: следующий же
    показ экрана падал на нём снова, и выхода не было. Файлов на пути
    у вертикалки два — свой и копия видео, — и чинится каждый, который
    не читается. Читается — не трогается.
    """
    import shutil

    вышло = []
    свой = layout.cut_subs(project, ident)
    for путь, чей_ in ((свой, "this clip's style"),
                       (layout.project_subs(project), СВОЙ)):
        if not путь.exists():
            continue
        try:
            разобрать(путь)
        except VertcutError:
            shutil.copyfile(откуда, путь)
            вышло.append(чей_)
    сбросить_кэш()
    return вышло


def свой_ли(project: Path, ident: str) -> bool:
    """Есть ли у этой вертикалки свой стиль, отдельный от видео."""
    return layout.cut_subs(project, ident).exists()


def завести_свой(project: Path, ident: str) -> Path:
    """Отделить стиль вертикалки от стиля видео.

    Копией того, что у неё сейчас, а не пустым файлом: человек правит
    ОДНО число, а остальные обязаны остаться теми же, что были минуту
    назад. Копируется файл целиком, с примечаниями, — по той же
    причине, по которой так копируется профиль видео.
    """
    import shutil

    свой = layout.cut_subs(project, ident)
    if not свой.exists():
        свой.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(завести(project)[0], свой)
        сбросить_кэш()
    return свой


def применить_ко_всем(project: Path, ident: str) -> int:
    """Сделать стиль этой вертикалки стилем ВСЕГО видео.

    Кладёт её профиль профилем видео и убирает все четвёртые уровни,
    включая её собственный: пачка возвращается к единообразию, но уже
    по новому образцу. Возвращает, сколько своих стилей убрано.

    **Собранные ролики после этого устареют, и это правильно:**
    отпечаток профиля входит в штамп сборки, и у тех, чей стиль
    поменялся, он разойдётся сам.
    """
    import shutil

    from . import pick

    откуда = файл(project, ident)
    куда = завести(project)[0]
    # Своего стиля у вертикалки нет — она и так читает стиль видео,
    # копировать нечего. До 24-й сессии это падало: файл копировался
    # сам в себя (поймано прочёсом, `tools/cyrillic-sweep.py`).
    if откуда.resolve() != куда.resolve():
        shutil.copyfile(откуда, куда)
    убрано = 0
    for cut in pick.listing(project):
        свой = layout.cut_subs(project, cut["id"])
        if свой.exists():
            свой.unlink()
            убрано += 1
    сбросить_кэш()
    return убрано


def settings(project: Path | None = None, ident: str | None = None) -> dict:
    """Числа субтитров. Нет ключа — берётся из поставляемого образца."""
    путь = файл(project, ident)
    # В памяти профиль лежит вместе с ОТМЕТКОЙ файла, а не сам по себе.
    #
    # **Это не ускорение, а починка.** Раньше прочитанное помнилось
    # навсегда, и работало это, пока сервис был командой: команда
    # живёт секунду. Экран живёт часами — и профиль, поправленный
    # из терминала или из другой вкладки, он показывал бы старым,
    # а собирал бы новым. Поймано на живом сервере: испорченный файл
    # ручка проглотила, потому что у неё в памяти лежал прежний.
    сейчас = _отметка(путь)
    было_ = _ПРОФИЛИ.get(str(путь))
    if было_ is not None and было_[0] == сейчас:
        return было_[1]

    try:
        данные = разобрать(путь)
    except VertcutError as беда:
        if project is not None:
            беда.вид = ОТКАЗ_СТИЛЯ
            беда.слаг, беда.ключ = project.name, ident
        raise
    _ПРОФИЛИ[str(путь)] = (сейчас, данные)
    return данные


def разобрать(путь: Path) -> dict:
    """Один файл профиля целиком: прочитан, проверен, достроен.

    Отдельно от `settings` затем, чтобы спросить про КОНКРЕТНЫЙ файл:
    «вернуть стиль» на экране чинит тот файл, который не читается, —
    а их на пути у вертикалки два (свой и копия видео).
    """
    эталон = образец()
    данные = эталон if путь == layout.subs_yaml() else _прочитать(путь)

    _версия(данные, путь)
    лишние = _чужие(данные, эталон)
    if лишние:
        raise VertcutError(
            f"The subtitle style has settings Vertcut doesn't know: "
            f"{', '.join(лишние)}\n  File: {путь}",
            hint="check the spelling against the default style: "
                 f"{layout.subs_yaml()}")
    данные = _слить(данные, эталон)

    for ключ, вид in НУЖНО:
        значение = _достать(данные, ключ)
        if вид is str:
            подходит, каким = isinstance(значение, str), "text"
        elif вид is bool:
            подходит, каким = isinstance(значение, bool), "true or false"
        else:
            подходит = (isinstance(значение, (int, float))
                        and not isinstance(значение, bool))
            каким = "a number"
        if not подходит:
            raise VertcutError(
                f"In the subtitle style, «{ключ}» must be {каким}, "
                f"but it's {значение!r}\n  File: {путь}")
    return данные


def _версия(данные: dict, путь: Path) -> None:
    """Файл старого образца — отказ словами, что делать.

    **Переезда внутри программы нет, и это решение автора.** Ключи
    профиля стали английскими в двадцатой сессии; файл, сохранённый
    раньше, — это русские имена и ни одного знакомого ключа. Разобрать
    его как обычный значило бы вывалить человеку тридцать «незнакомых
    ключей» — честно и бесполезно. Узнаётся он по отсутствию `version`.

    Что делать, говорится разное: личный образец чинится тем, что стиль
    сохраняют своим заново, а копия в видео и стиль вертикалки — кнопкой
    «вернуть стиль по умолчанию», которая рисуется под этим отказом.
    """
    версия = данные.get(ВЕРСИЯ)
    if версия == ВЕРСИЯ_СЕЙЧАС:
        return
    if версия is None:
        if путь == layout.my_subs():
            raise VertcutError(
                "Your saved style (my style) is from an older version of "
                f"Vertcut, and this version can't read it.\n  File: {путь}",
                hint="open any clip's subtitles, set the style up and click "
                     "Save as my style — or delete the file")
        raise VertcutError(
            f"{_чей_файл(путь)} was saved by an older version of Vertcut, "
            f"and this version can't read it.\n  File: {путь}",
            hint="reset it to the default style, then change what you need "
                 "again. On screen: Fix the style → Reset to default style. "
                 "In the terminal: vertcut style VIDEO_ID --default-style")
    raise VertcutError(
        f"{_чей_файл(путь)} is version {версия!r}, but this Vertcut "
        f"only knows version {ВЕРСИЯ_СЕЙЧАС}.\n  File: {путь}",
        hint="update Vertcut, or reset this style to the default")


def _чей_файл(путь: Path) -> str:
    """Чей это файл стиля — словами экрана. Спрашивается у `layout`,
    а не угадывается по именам папок: пути собираются только там."""
    if путь == layout.my_subs():
        return "Your saved style (my style)"
    # Вертикалка — первой: путь её стиля похож и на путь стиля видео
    # (тот же файл в своей папке), и спроси видео первым — назовётся
    # видео.
    ролик = путь.parent
    if путь == layout.cut_subs(ролик.parent.parent, ролик.name):
        return "This clip's subtitle style"
    if путь == layout.project_subs(путь.parent):
        return "This video's subtitle style"
    return "This subtitle style"


def _отметка(путь: Path) -> tuple:
    """Время правки и размер файла. Их же спрашивает экран у роликов:
    времени мало (у файловых систем оно бывает грубым), размера мало
    (правка цифры на цифру его не меняет), вместе — почти всегда хватает.
    """
    try:
        с = путь.stat()
    except OSError:
        return ()
    return (с.st_mtime_ns, с.st_size)


def _достать(данные: dict, ключ: str):
    где = данные
    for часть in ключ.split("."):
        if not isinstance(где, dict) or часть not in где:
            return None
        где = где[часть]
    return где


def из_файла(путь: Path) -> dict:
    """Профиль из любого файла, достроенный поставляемым образцом.

    Тем же способом, что и профиль видео: недостающее берётся
    из образца. Иначе личный образец, сохранённый до появления
    нового ключа, читался бы неполным и сравнивался бы с полным.
    """
    данные = _прочитать(путь)
    _версия(данные, путь)
    return _слить(данные, образец())


def плоско(данные: dict, путь: str = "") -> dict:
    """Профиль плоским списком: «плашка.цвет» → «#E8E5E9».

    Так его показывают человеку и так же его правят числом из команды:
    вложенность в файле — для чтения глазами, а не для разговора.
    """
    вышло = {}
    for ключ, значение in данные.items():
        где = f"{путь}{ключ}"
        if isinstance(значение, dict):
            вышло.update(плоско(значение, f"{где}."))
        else:
            вышло[где] = значение
    return вышло


def разница(было: dict, стало: dict) -> list[str]:
    """Чем один профиль отличается от другого — словами, по строке
    на число. Молча подменённый стиль человек заметит только на
    собранном ролике."""
    a, b = плоско(было), плоско(стало)
    вышло = []
    for ключ in sorted(set(a) | set(b)):
        if a.get(ключ) != b.get(ключ):
            вышло.append(f"{ключ}: {a.get(ключ, '—')} → {b.get(ключ, '—')}")
    return вышло


# ─────────────────────────────────────────────────────────────────────
# Правка профиля числами
# ─────────────────────────────────────────────────────────────────────
#
# **Правится ТЕКСТ файла, а не разобранный словарь.** Соблазн велик:
# прочитать yaml, поменять число, записать обратно — три строки.
# Так делать нельзя: разбор не помнит примечаний, а в этом файле
# у каждого числа написано, как оно мерялось и чего от него ждать.
# Записать словарём значит стереть их все и оставить человеку
# двадцать голых чисел, которые он побоится трогать.

_КЛЮЧ = re.compile(r"^(\s*)([^\s#][^:]*):(.*)$")


def _как_записать(значение) -> str:
    if isinstance(значение, bool):
        return "true" if значение else "false"
    if isinstance(значение, (int, float)):
        return repr(значение)
    текст = str(значение)
    if re.fullmatch(r"[\w.\-/]+", текст):
        return текст
    # Перевод строки записывается как \n, а не как настоящий перенос.
    # Профиль правится ПОСТРОЧНО — по номеру строки, — и значение
    # в две строки разорвало бы файл: вторая половина стала бы
    # неизвестным ключом, а следующая правка легла бы поверх неё.
    # Единственное такое значение сегодня — надпись плашки в конце.
    без_переносов = (текст.replace("\\", "\\\\").replace('"', '\\"')
                     .replace("\n", "\\n").replace("\r", ""))
    return '"' + без_переносов + '"'


def _разобрать_строки(строки: list[str]) -> dict[str, int]:
    """Где в файле лежит каждый ключ: «плашка.цвет» → номер строки.

    Разбор простой нарочно: профиль — это только вложенные словари
    и скаляры. Списков и многострочных значений в нём нет, и заводить
    их не надо: настройка, которую нельзя показать одной строкой,
    человеку всё равно ничего не скажет.
    """
    где, стопка = {}, []
    for n, строка in enumerate(строки):
        совпало = _КЛЮЧ.match(строка)
        if not совпало:
            continue
        отступ, имя = совпало.group(1), совпало.group(2).strip()
        хвост = совпало.group(3)
        while стопка and стопка[-1][0] >= len(отступ):
            стопка.pop()
        путь = ".".join([имя_ for _, имя_ in стопка] + [имя])
        if хвост.strip():
            где[путь] = n
        else:
            стопка.append((len(отступ), имя))
    return где


def _вписать(строки: list[str], где: int, значение) -> None:
    совпало = _КЛЮЧ.match(строки[где])
    отступ, имя = совпало.group(1), совпало.group(2)
    строки[где] = f"{отступ}{имя}: {_как_записать(значение)}"


def _с_примечаниями(строки: list[str], конец: int) -> int:
    """Номер первой строки примечаний перед этой."""
    начало = конец
    while начало > 0 and (строки[начало - 1].strip().startswith("#")
                          or not строки[начало - 1].strip()):
        начало -= 1
    return начало


def _занять_из_образца(ключ: str) -> list[str]:
    """Строки поставляемого образца про этот ключ — вместе с его
    примечаниями. Нужны, когда ключа в файле человека нет вовсе:
    вписать голую строку значит отдать ему число без причины.
    """
    свои = layout.subs_yaml().read_text(encoding="utf-8").split("\n")
    где = _разобрать_строки(свои)
    if ключ not in где:
        return []
    конец = где[ключ]
    return свои[_с_примечаниями(свои, конец):конец + 1]


def _занять_блок(имя: str) -> list[str]:
    """Целый блок поставляемого образца — заголовок и всё, что внутри.

    Нужен, когда в файле человека нет БЛОКА, а не одного числа: его
    профиль сохранён до того, как блок завёлся. Вписать туда одну
    вложенную строку нельзя — по отступу она станет ребёнком
    последнего блока файла и уедет в чужие настройки. Поймано живьём:
    «подсветка.режим» лёг в «положение».
    """
    свои = layout.subs_yaml().read_text(encoding="utf-8").split("\n")
    начало = None
    for n, строка in enumerate(свои):
        совпало = _КЛЮЧ.match(строка)
        if совпало and совпало.group(1) == "" \
                and совпало.group(2).strip() == имя:
            начало = n
            break
    if начало is None:
        return []
    конец = начало + 1
    while конец < len(свои) and (not свои[конец].strip()
                                 or свои[конец].startswith((" ", "#"))):
        конец += 1
    # Хвостовые пустые строки и примечания следующего блока — не наши.
    while конец > начало + 1 and (not свои[конец - 1].strip()
                                  or свои[конец - 1].strip().startswith("#")):
        конец -= 1
    return свои[_с_примечаниями(свои, начало):конец]


def задать(путь: Path, правки: dict) -> list[str]:
    """Поставить числа в профиль на диске. Возвращает сказанное словами.

    Ключ пишется точками: «size», «box.color», «lines.spacing».
    Незнакомый ключ — отказ, а не тихая запись: опечатка иначе легла бы
    в файл и осталась там навсегда, ничего не делая. Версия файла
    не правится вовсе: её пишет программа, а не человек.
    """
    эталон = плоско(образец())
    for ключ in правки:
        if ключ == ВЕРСИЯ:
            raise VertcutError(
                "The style file's version isn't a setting — Vertcut "
                "writes it itself")
        if ключ not in эталон:
            raise VertcutError(
                f"The subtitle style has no setting «{ключ}»",
                hint=f"all settings are listed in: {layout.subs_yaml()}")

    строки = путь.read_text(encoding="utf-8").split("\n")
    сказано = []
    for ключ, сырое in правки.items():
        значение = _привести(ключ, сырое, эталон[ключ])
        где = _разобрать_строки(строки)
        if ключ in где:
            было = _достать(_прочитать(путь), ключ)
            _вписать(строки, где[ключ], значение)
        else:
            # Ключа в файле человека нет — он приехал из образца
            # достройкой. Кладём его вместе с примечаниями образца:
            # число без причины через месяц выглядит произволом.
            было = эталон[ключ]
            родитель = ключ.rsplit(".", 1)[0] if "." in ключ else None
            строки = _вставить(строки, ключ, родитель, значение)
        сказано.append(f"{ключ}: {было} → {значение}")

    путь.write_text("\n".join(строки), encoding="utf-8")
    _ПРОФИЛИ.pop(str(путь), None)
    return сказано


def _вставить(строки: list[str], ключ: str, родитель: str | None,
              значение) -> list[str]:
    """Вписать недостающий ключ в его блок, а не в конец файла."""
    имя = ключ.rsplit(".", 1)[-1]
    отступ = "  " * ключ.count(".")
    кусок = list(_занять_из_образца(ключ))
    if кусок:
        _вписать(кусок, len(кусок) - 1, значение)
    else:
        кусок = [f"{отступ}{имя}: {_как_записать(значение)}"]

    где = _разобрать_строки(строки)
    если_есть = [n for путь_, n in где.items()
                 if родитель and путь_.startswith(родитель + ".")]
    if если_есть:
        куда = max(если_есть) + 1
        return строки[:куда] + кусок + строки[куда:]
    if родитель is not None:
        # Блока нет вовсе — профиль сохранён до того, как он завёлся.
        # Кладём весь блок из образца, а не одну вложенную строку:
        # по отступу она стала бы ребёнком последнего блока файла
        # и уехала бы в чужие настройки.
        блок = list(_занять_блок(родитель))
        if блок:
            свои = _разобрать_строки(блок)
            if имя in свои or ключ in свои:
                _вписать(блок, свои.get(ключ, свои.get(имя)), значение)
            return строки + ["", *блок]
    return строки + ["", *кусок]


def _привести(ключ: str, сырое, каким):
    """Значение к тому же виду, какой стоит в поставляемом образце.

    Вид берётся у образца, а не угадывается по написанию: «700» — это
    вес шрифта числом, а «#000000» — цвет текстом, и отличить их
    по виду написанного нельзя.
    """
    if not isinstance(сырое, str):
        return сырое
    текст = сырое.strip()
    if isinstance(каким, bool):
        if текст.lower() in ("true", "yes", "1"):
            return True
        if текст.lower() in ("false", "no", "0"):
            return False
        raise VertcutError(
            f"«{ключ}» is true or false, but it's {сырое!r}")
    if isinstance(каким, int):
        try:
            return int(текст)
        except ValueError:
            raise VertcutError(
                f"«{ключ}» is a whole number, but it's {сырое!r}") from None
    if isinstance(каким, float):
        try:
            return float(текст.replace(",", "."))
        except ValueError:
            raise VertcutError(
                f"«{ключ}» is a number, but it's {сырое!r}") from None
    return текст


def чей(project: Path) -> dict:
    """Чей стиль стоит у этого видео — для печати человеку.

    Считается СРАВНЕНИЕМ чисел, а не пометкой в файле. Пометка врёт
    через месяц: человек поправил личный образец, а в копии видео
    по-прежнему написано «взят из личного».
    """
    мой = layout.my_subs()
    свой = settings(project)
    вышло = {"файл": layout.project_subs(project),
             "личный_есть": мой.exists(),
             "как_поставляемый": свой == образец()}
    if мой.exists():
        вышло["как_личный"] = свой == _слить(_прочитать(мой), образец())
    else:
        вышло["как_личный"] = None
    return вышло


def profile(project: Path | None = None,
            width: int = tuning.VERTICAL_W,
            height: int = tuning.VERTICAL_H,
            ident: str | None = None) -> dict:
    """Профиль этого ВИДЕО, приведённый к пикселям этого кадра.

    Долями он лежит затем, чтобы кадр однажды приехал не 1080×1920
    и ничего не поехало. Приведение — здесь, одно на весь сервис.

    Видео стоит первым доводом, а не последним, потому что оно теперь
    главный вопрос: чей стиль берём. Размер кадра меняется раз в год,
    видео — каждую команду.
    """
    return к_пикселям(settings(project, ident), width, height, project)


def к_пикселям(это: dict, width: int = tuning.VERTICAL_W,
               height: int = tuning.VERTICAL_H,
               project: Path | None = None) -> dict:
    """Числа профиля → пиксели этого кадра. Без диска и без видео.

    Отделено от `profile` затем, чтобы можно было посчитать профиль,
    которого на диске уже нет, — тот, что был ДО правки. Иначе лист
    «до и после» показать нечем: «до» лежит только в памяти.
    """
    from . import fonts

    кегль = max(8, round(width * float(это["size"])))
    режим = _одно_из(это.get("case", КАК_ЕСТЬ), РЕГИСТРЫ, "case")
    подложка = _одно_из(это.get("background", ПЛАШКА), ПОДЛОЖКИ,
                        "background")
    подсветка = _одно_из(это["karaoke"]["mode"], ПОДСВЕТКИ, "karaoke.mode")
    чем = _одно_из(это["karaoke"]["by"], ЧЕМ_КРАСИМ, "karaoke.by")
    беречь = да_или_нет(это["safe_zones"]["enabled"], "safe_zones.enabled")
    поле = round(width * float(это["box"]["side_padding"]))
    толщина = (max(1, round(кегль * float(это["outline"]["width"])))
               if подложка == ОБВОДКА else 0)
    сдвиг_тени = (max(1, round(кегль * float(это["shadow"]["offset"])))
                  if подложка == ТЕНЬ else 0)
    # Безопасные зоны площадок. Отсюда — и предельная ширина строки,
    # и предел, ниже которого субтитр не опускается: держать их
    # вторыми числами значит однажды подвинуть зону и забыть предел.
    зона_сбоку = round(width * float(это["safe_zones"]["side"]))
    зона_снизу = round(height * float(это["safe_zones"]["bottom"]))
    зона_сверху = round(height * float(это["safe_zones"]["top"]))
    предел_плашки = width - 2 * зона_сбоку if беречь else width
    предел_низа = height - зона_снизу if беречь else height
    предел_верха = зона_сверху if беречь else 0
    # Сколько краски выходит за буквы с каждой стороны. У плашки это
    # её поле, у обводки — её толщина, у тени — ничего слева и её сдвиг
    # справа. Число одно на всех, потому что вопрос один: где начинается
    # и кончается то, что видно.
    запас = поле if подложка == ПЛАШКА else толщина
    return {
        "width": width, "height": height,
        "шрифт": fonts.найти(это["font"], project),
        "вес": int(это["weight"]),
        "регистр": режим,
        "кегль": кегль,
        "высота_плашки": round(height * float(это["box"]["height"])),
        "поле_сбоку": поле,
        "радиус": max(0, round(width * float(это["box"]["radius"]))),
        "цвет": str(это["box"]["color"]),
        "сказанное": str(это["text_color"]["spoken"]),
        "несказанное": str(это["text_color"]["upcoming"]),
        # Шаг — долями КЕГЛЯ, а не кадра: это типографика, а не разметка.
        "шаг": round(кегль * float(это["lines"]["spacing"])),
        "максимум_строк": max(1, int(это["lines"]["max"])),
        "предел_плашки": предел_плашки,
        # Подложка и её числа. Толщина обводки и сдвиг тени — долями
        # КЕГЛЯ: контур и тень растут вместе с буквой, а не вместе
        # с экраном.
        "подложка": подложка,
        "рисует_плашку": подложка == ПЛАШКА,
        "обводка_цвет": str(это["outline"]["color"]),
        "обводка_толщина": толщина,
        "тень_цвет": str(это["shadow"]["color"]),
        "тень_сдвиг": сдвиг_тени,
        "запас_сбоку": запас,
        "подсветка": подсветка,
        "подсветка_чем": чем,
        "подсветка_цвет": str(это["karaoke"]["color"]),
        "подсветка_крупнее": max(1.0, float(это["karaoke"]["scale"])),
        # Строка МЕРЯЕТСЯ крупным кеглем, когда подсветка кеглем: иначе
        # она перекладывалась бы на каждом слове и дрожала весь ролик,
        # а подсвеченное слово вылезало бы за плашку.
        "мерить_крупно": (подсветка != НЕТ_ПОДСВЕТКИ and чем == КЕГЛЕМ),
        # Сколько места остаётся САМИМ БУКВАМ. Держать это вторым
        # числом нельзя: у каждой подложки свой запас, и разъедутся
        # они молча — строка вылезет под столбик иконок соцсети.
        "предел_текста": max(1, предел_плашки - 2 * запас - сдвиг_тени),
        "базовая_от_низа": round(
            height * float(это["position"]["baseline_from_bottom"])),
        "беречь_зоны": беречь,
        "зона_сбоку": зона_сбоку,
        "зона_снизу": зона_снизу,
        "зона_сверху": зона_сверху,
        # С какой высоты идёт столбик иконок площадки. Спрашивает его
        # сегодня одна плашка в конце: субтитр всегда ниже середины,
        # и для него ответ один и тот же. Лежит здесь, потому что все
        # числа про интерфейс площадки живут в одном месте.
        "столбик_верх": round(height * float(это["safe_zones"]["icons_top"])),
        "предел_низа": предел_низа,
        "предел_верха": предел_верха,
        **_где_блок(это, height, кегль, зона_сверху, предел_низа, беречь),
        "отступ_от_плана": round(
            height * float(это["position"]["below_shot"]["gap"])),
    }


def да_или_нет(значение, ключ: str) -> bool:
    """Да или нет из профиля — в правду или ложь.

    Общий на весь проект: его зовёт и плашка в конце. Второй такой
    разборщик однажды принял бы «True» за имя файла. В файле это
    настоящие `true`/`false` yaml; слова здесь принимаются затем, что
    человек, правящий файл руками, напишет и «yes».
    """
    if isinstance(значение, bool):
        return значение
    текст = str(значение).strip().lower()
    if текст in ("true", "yes", "1"):
        return True
    if текст in ("false", "no", "0"):
        return False
    raise VertcutError(
        f"In the subtitle style, «{ключ}» is true or false, "
        f"but it's {значение!r}")


def _одно_из(значение, можно: tuple, ключ: str) -> str:
    """Слово из профиля, которое обязано быть одним из знакомых."""
    слово = str(значение).strip()
    if слово not in можно:
        raise VertcutError(
            f"In the subtitle style, «{ключ}» is one of "
            f"{', '.join(можно)}, but it's {слово!r}")
    return слово


def _где_блок(это: dict, height: int, кегль: int, зона_сверху: int,
              предел_низа: int, беречь: bool) -> dict:
    """Низ блока субтитра и упёрся ли он в безопасную зону.

    **Считается ОДИН раз и здесь.** По этому числу рисование ставит
    краску, заслон считает занятый прямоугольник, а предпросмотр —
    кадр. Посчитай его в трёх местах — разойдутся в трёх.

    Упёрся — говорится числами, а не двигается молча: человек поставил
    субтитр туда, куда хотел, и обязан узнать, что его подвинули.
    """
    шаг = round(кегль * float(это["lines"]["spacing"]))
    высота = round(height * float(это["box"]["height"]))
    строк = max(1, int(это["lines"]["max"]))
    хотели = height - round(height * float(это["position"]["from_bottom"]))
    низ = min(хотели, предел_низа)
    верх_блока = низ - высота - (строк - 1) * шаг
    поднять = 0
    if беречь and верх_блока < зона_сверху:
        # Блок не влезает между зонами — опускаем его, сколько можно.
        поднять = зона_сверху - верх_блока
        низ = min(низ + поднять, предел_низа)
    return {"низ_центра": низ, "низ_хотели": хотели,
            "упёрся_вниз": хотели > предел_низа,
            "упёрся_вверх": поднять > 0,
            "верх_блока": низ - высота - (строк - 1) * шаг}


def отпечаток(prof: dict | None = None,
              project: Path | None = None,
              ident: str | None = None) -> str:
    """Отпечаток профиля — без раскладки конкретного ролика.

    Нужен очереди сборки: поправят кегль — и все собранные ролики
    обязаны стать устаревшими, иначе новый кегль доедет не до всех
    и молча.

    **Шрифт входит отпечатком ФАЙЛА, а не путём.** Подменят файл под
    тем же именем — по пути этого не видно, а буквы будут другие.

    **И именно НЕ путём.** Путь абсолютный: перенесли папку сервиса
    в другое место — и все собранные ролики объявились бы устаревшими,
    хотя буквы в них те же самые. Содержимое файла отвечает на вопрос
    «те же ли буквы» точно, а имя — на вопрос «тот же ли это шрифт»
    для человека, который читает штамп глазами.
    """
    import hashlib
    import json

    prof = prof if prof is not None else profile(project, ident=ident)
    шрифт = prof.get("шрифт")
    отп_шрифта = ""
    if шрифт is not None and Path(шрифт).exists():
        отп_шрифта = hashlib.sha1(Path(шрифт).read_bytes()).hexdigest()[:16]
    голый = {k: v for k, v in prof.items() if k != "шрифт"}
    что = json.dumps(
        {**{k: (str(v) if isinstance(v, Path) else v)
            for k, v in sorted(голый.items())},
         "шрифт_имя": Path(шрифт).name if шрифт is not None else "",
         "шрифт_файл": отп_шрифта},
        ensure_ascii=False, sort_keys=True)
    return hashlib.sha1(что.encode()).hexdigest()[:16]


# Регистр субтитра. Три вида, и все три меняют не только вид, но
# и ШИРИНУ строки: прописные шире строчных, и фраза, влезавшая в одну
# страницу, может перестать влезать. Считается это само — ширина
# меряется по тому тексту, который будет нарисован.
КАК_ЕСТЬ, ПРОПИСНЫЕ, КАПИТЕЛЬ = "as_typed", "all_caps", "small_caps"
РЕГИСТРЫ = (КАК_ЕСТЬ, ПРОПИСНЫЕ, КАПИТЕЛЬ)

# Чем субтитр отделён от картинки. ЧЕТЫРЕ РИСОВАЛКИ, а не настройки
# одной: плашка, обводка и тень устроены по-разному, и подгонять их
# под общую модель значило бы двигать не те числа.
ПЛАШКА, ОБВОДКА, ТЕНЬ, БЕЗ = "box", "outline", "shadow", "none"
ПОДЛОЖКИ = (ПЛАШКА, ОБВОДКА, ТЕНЬ, БЕЗ)

# Подсветка текущего слова. Это ВТОРОЙ слой поверх «сказано или ещё
# нет», а не замена ему: краска отвечает на вопрос «прозвучало ли»,
# подсветка — «что звучит прямо сейчас».
НЕТ_ПОДСВЕТКИ, ПО_СЛОВУ, ПО_СТРОКЕ = "none", "word", "line"
ПОДСВЕТКИ = (НЕТ_ПОДСВЕТКИ, ПО_СЛОВУ, ПО_СТРОКЕ)
ЦВЕТОМ, ПЛАШКОЙ, КЕГЛЕМ = "color", "box", "size"
ЧЕМ_КРАСИМ = (ЦВЕТОМ, ПЛАШКОЙ, КЕГЛЕМ)


def _ось_веса(шрифт) -> tuple[list, int] | None:
    """Оси переменного шрифта и номер той, что отвечает за вес.

    **Ось ищется ПО ИМЕНИ, а не берётся первой, и это замер.** Сначала
    вес выставлялся списком из одного числа — так работает у любого
    шрифта с единственной осью, и на трёх поставляемых из четырёх это
    было верно. У Literata осей две: сначала оптический размер, потом
    вес. Список из одного числа ставил 700 ОПТИЧЕСКОМУ РАЗМЕРУ (тот
    молча упирался в свой предел 72), а вес оставался тем, что
    по умолчанию, — 400. Видно это было только глазами на листе:
    Literata стояла заметно тоньше трёх остальных при том же весе 700.
    """
    try:
        оси = шрифт.get_variation_axes()
    except Exception:
        return None            # не переменный шрифт — осей нет вовсе
    if not оси:
        return None
    for n, ось in enumerate(оси):
        имя = ось.get("name", b"")
        имя = (имя.decode("utf-8", "replace") if isinstance(имя, bytes)
               else str(имя))
        if имя.strip().lower() == "weight":
            return оси, n
    return оси, -1             # оси есть, а веса среди них нет


def открыть_шрифт(путь: Path, кегль: int, вес) -> tuple:
    """Шрифт с выставленным весом. Возвращает (шрифт, выставился ли).

    **Одно место на весь проект.** Вес выставляется на ось ПО ИМЕНИ,
    а не на первую: у Literata осей две — сначала оптический размер,
    потом вес, — и список из одного числа ставил бы 700 оптическому
    размеру. Это замер, найденный глазами на листе, и второе такое
    место повторило бы ошибку молча. Отсюда же его берёт надпись
    плашки в конце: шрифт у неё из того же набора.
    """
    from PIL import ImageFont

    try:
        шрифт = ImageFont.truetype(str(путь), кегль)
    except OSError as bad:
        raise VertcutError(f"Can't open the subtitle font:\n  {путь}",
                           hint="choose another font in the subtitle "
                                "editor") from bad
    нашлось = _ось_веса(шрифт)
    if нашлось is None or нашлось[1] < 0:
        return шрифт, False
    оси, где = нашлось
    # Остальные оси остаются на своих значениях по умолчанию: трогать
    # их сервис не просили, а список Pillow требует целиком.
    значения = [ось["default"] for ось in оси]
    значения[где] = max(оси[где]["minimum"],
                        min(int(вес), оси[где]["maximum"]))
    try:
        шрифт.set_variation_by_axes(значения)
    except Exception:
        return шрифт, False
    return шрифт, True


def _доля_малых(шрифт) -> float:
    """Во сколько раз мельче стоят малые прописные.

    Считается ПО САМОМУ ШРИФТУ: высота строчной делится на высоту
    прописной. Так малые прописные встают вровень со строчными
    у любого шрифта, и подбирать число не приходится.
    """
    # Вторая пара — кириллица: шрифт без латиницы. не для человека
    for строчная, прописная in (("x", "H"), ("х", "Н")):
        низ = шрифт.getbbox(строчная)
        верх = шрифт.getbbox(прописная)
        малая, большая = низ[3] - низ[1], верх[3] - верх[1]
        if малая > 0 and большая > 0:
            return малая / большая
    return tuning.SMALLCAPS_RATIO


class Набор:
    """Шрифт вместе с режимом регистра.

    Заведён затем, чтобы «какими буквами это нарисуется» знало ОДНО
    место. Ширину строки меряет разбивка на страницы, рисует —
    рисование, занятый прямоугольник считает заслон; разойдись они
    хоть на пиксель, субтитр вылезет за плашку или заслон заругается
    на исправное.
    """

    def __init__(self, шрифт, мелкий, режим: str, крупный=None,
                 мелкий_крупного=None, мерить_крупно: bool = False):
        self.шрифт = шрифт
        self.мелкий = мелкий
        self.режим = режим
        # Крупная пара — для подсветки кеглем. Её же строка меряется,
        # чтобы не перекладываться на каждом слове.
        self.крупный = крупный if крупный is not None else шрифт
        self.мелкий_крупного = (мелкий_крупного if мелкий_крупного is not None
                                else self.крупный)
        self.мерить_крупно = мерить_крупно

    def _пара(self, крупно: bool) -> tuple:
        if крупно:
            return self.крупный, self.мелкий_крупного
        return self.шрифт, self.мелкий

    def куски(self, текст: str, крупно: bool = False) -> list[tuple]:
        """Текст, разбитый на куски одного начертания."""
        if not текст:
            return []
        большой, малый = self._пара(крупно)
        if self.режим == ПРОПИСНЫЕ:
            return [(текст.upper(), большой)]
        if self.режим != КАПИТЕЛЬ:
            return [(текст, большой)]
        вышло: list[tuple[str, object]] = []
        накоплено, малым = "", текст[0].islower()
        for знак in текст:
            свой = знак.islower()
            if свой != малым and накоплено:
                вышло.append((накоплено.upper() if малым else накоплено,
                              малый if малым else большой))
                накоплено = ""
            малым = свой
            накоплено += знак
        вышло.append((накоплено.upper() if малым else накоплено,
                      малый if малым else большой))
        return вышло

    def слева(self, текст: str, крупно: bool | None = None) -> float:
        """Левый вынос первого знака: от пера до первого пикселя краски."""
        крупно = self.мерить_крупно if крупно is None else крупно
        куски = self.куски(текст, крупно)
        return куски[0][1].getbbox(куски[0][0])[0] if куски else 0.0

    def продвижение(self, текст: str, крупно: bool | None = None) -> float:
        """На сколько перо уедет вправо, нарисовав этот текст."""
        крупно = self.мерить_крупно if крупно is None else крупно
        return sum(шрифт.getlength(кусок)
                   for кусок, шрифт in self.куски(текст, крупно))

    def ширина(self, текст: str, крупно: bool | None = None) -> int:
        """Ширина КРАСКИ, а не габарита.

        Именно по краске мерялись поля эталона: от края плашки
        до первого пикселя буквы.
        """
        крупно = self.мерить_крупно if крупно is None else крупно
        куски = self.куски(текст, крупно)
        if not куски:
            return 0
        всего = self.продвижение(текст, крупно)
        последний, шрифт = куски[-1]
        справа = шрифт.getlength(последний) - шрифт.getbbox(последний)[2]
        return int(round(всего - self.слева(текст, крупно) - справа))

    def места_слов(self, x: float, текст: str,
                   слова: list[dict]) -> list[tuple[float, float]]:
        """Где в строке стоит каждое слово: (левый край, правый край).

        Считается ТЕМ ЖЕ продвижением, каким строка рисуется, — по
        нарастающим кускам текста. Своей арифметики нет: подсветка,
        вставшая не на то слово, — это ролик, который надо переснять.
        """
        начало = x - self.слева(текст)
        места, было = [], []
        for слово in слова:
            было = [*было, слово["w"]]
            # Правый край слова — это конец всего, что до него написано.
            # Левый — правый минус продвижение самого слова. Считать
            # левый край «концом предыдущего куска» нельзя: между ними
            # стоит пробел, и слова слиплись бы. Поймано глазами.
            справа = начало + self.продвижение(
                segmentation.join_words(было))
            места.append((справа - self.продвижение(слово["w"]), справа))
        return места

    def рисовать(self, перо, x: float, база: float, текст: str, цвет,
                 толщина: int = 0, крупно: bool = False,
                 от_краски: bool = True) -> None:
        """Нарисовать строку от `x` — там, где начинается КРАСКА.

        `толщина` — обводка вокруг букв. Она рисуется тем же цветом,
        что и сами буквы, и это не небрежность: обводку кладут ОТДЕЛЬНЫМ
        проходом под текст. Рисуй её вместе с буквами — на стыке двух
        кусков разного кегля контур одного лёг бы поверх другого,
        и в капители это видно.
        """
        перо_x = x - (self.слева(текст, крупно) if от_краски else 0)
        for кусок, шрифт in self.куски(текст, крупно):
            перо.text((перо_x, база), кусок, font=шрифт, fill=цвет,
                      anchor="ls", stroke_width=толщина, stroke_fill=цвет)
            перо_x += шрифт.getlength(кусок)


def font_of(prof: dict) -> Набор:
    """Шрифт профиля с выставленной осью веса и режимом регистра.

    Ось выставляется явно: без неё Pillow берёт начертание по умолчанию
    (400), и субтитр выйдет заметно тоньше при той же ширине — поломка,
    которую замечают через неделю.

    Шрифт без оси веса — не беда: у обычного, не переменного шрифта
    её нет вовсе, а человек вправе подключить свой. Тогда вес задаёт
    само начертание, и сервис говорит об этом в `vertcut style`,
    а не молчит.
    """
    try:
        from PIL import ImageFont  # noqa: F401
    except ImportError as bad:
        raise VertcutError(
            "Pillow isn't installed, so subtitles can't be drawn",
            hint="install the dependencies: pip install -e . -c constraints.txt") from bad
    путь = Path(prof["шрифт"])
    if not путь.exists():
        raise VertcutError(
            f"The subtitle font file isn't there:\n  {путь}",
            hint="choose a font again in the subtitle editor")
    шрифт, _ = открыть_шрифт(путь, prof["кегль"], prof["вес"])
    режим = prof.get("регистр", КАК_ЕСТЬ)
    доля = _доля_малых(шрифт)
    мелкий = шрифт
    if режим == КАПИТЕЛЬ:
        мелкий, _ = открыть_шрифт(
            путь, max(6, round(prof["кегль"] * доля)), prof["вес"])
    крупнее = float(prof.get("подсветка_крупнее", 1.0))
    крупный, мелкий_крупного = шрифт, мелкий
    if крупнее > 1.0:
        крупный_кегль = max(8, round(prof["кегль"] * крупнее))
        крупный, _ = открыть_шрифт(путь, крупный_кегль, prof["вес"])
        мелкий_крупного = крупный
        if режим == КАПИТЕЛЬ:
            мелкий_крупного, _ = открыть_шрифт(
                путь, max(6, round(крупный_кегль * доля)), prof["вес"])
    return Набор(шрифт, мелкий, режим, крупный, мелкий_крупного,
                 bool(prof.get("мерить_крупно")))


def про_шрифт(prof: dict) -> dict:
    """Что сервис знает про шрифт этого профиля — для печати человеку.

    **Вес, который не выставился, называется вслух.** У обычного,
    не переменного шрифта оси веса нет: профиль говорит 700, а буквы
    выйдут те, какие в файле. Молчать про это нельзя — человек будет
    двигать число и не понимать, почему ничего не меняется.
    """
    from . import fonts

    путь = Path(prof["шрифт"])
    св = fonts.сведения(путь)
    _, выставлен = открыть_шрифт(путь, prof["кегль"], prof["вес"])
    return {**св, "вес_выставлен": выставлен, "вес": prof["вес"],
            "регистр": prof.get("регистр", КАК_ЕСТЬ)}


def полоса(prof: dict) -> dict:
    """Полоса, которую субтитр занимает в центральном положении.

    Считается ОТ профиля — от высоты плашки, шага и предела строк.
    Держать её отдельным числом значит однажды подвинуть кегль
    и забыть полосу.

    Принимает ГОТОВЫЙ профиль, а не размер кадра: пока она читала
    его сама, у неё был шанс прочитать не тот — профиль теперь у
    каждого видео свой.
    """
    низ = prof["низ_центра"]
    верх = prof["верх_блока"]
    return {"верх": верх, "низ": низ, "строк": prof["максимум_строк"],
            "высота_плашки": prof["высота_плашки"], "шаг": prof["шаг"]}


def низ_плана(meta: dict, width: int, height: int) -> int:
    """Нижний край плана, оставленного горизонтальным.

    Считается тем же способом, каким сборка вписывает кадр целиком:
    самый большой размер, влезающий в вертикаль, по центру. Своей
    арифметики тут нет — есть повторение чужой, и потому она в одном
    месте.
    """
    ш, в = int(meta["width"]), int(meta["height"])
    k = min(width / ш, height / в)
    нв = max(2, 2 * round(в * k / 2))
    return (height - нв) // 2 + нв


def низ_под_планом(meta: dict, prof: dict) -> dict:
    """Низ блока субтитра в нижнем положении.

    Упирается в нижнее поле площадок — тогда садится на предел
    и говорит об этом, а не лезет под интерфейс молча.
    """
    план = низ_плана(meta, prof["width"], prof["height"])
    хочу = план + prof["отступ_от_плана"] + prof["высота_плашки"]
    низ = min(хочу, prof["предел_низа"])
    return {"низ": низ, "план_низ": план, "хотели": хочу,
            "упёрся": хочу > prof["предел_низа"]}


