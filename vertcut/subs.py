"""Субтитры: профиль, раскладка по строкам, подрезка по голосу, рисование.

Здесь нет ни ffmpeg, ни видео — только числа, строки и картинки. Слой
для сборки делает `layer.py`; сюда он приходит за тем, что рисовать
и когда.

## Откуда числа

**Все из `assets/subtitles.yaml`, долями кадра.** В коде нет ни одного
подобранного числа. Профиль снят замером с настоящего ролика — и это
не «правильные числа», а отправная точка одного канала; так и написано
в самом файле.

## Что здесь своё, а что перенесено

Перенесена **разбивка на строки и страницы**: она делит слова не жадно,
а на равные строки, и меряет НЕ ЗНАКИ, а настоящую ширину краски. Это
содержательная часть, и своей ей быть незачем.

**Рисование написано своё, двадцать строк.** Готовое рисовало плашку
по своей модели — высота равна высоте строки шрифта плюс одинаковые
поля сверху и снизу. Замер говорит другое: плашка постоянной высоты
при любых буквах, а базовая линия стоит на замеренном расстоянии
от её низа. Подгонять чужую модель под замер значило бы двигать
не то число.

## Где стоит субтитр

Два места, и выбирает их фраза ЦЕЛИКОМ:

* **центр** — на планах, обрезанных в вертикаль;
* **низ, под планом** — на планах, оставленных горизонтальными.

**Правило: есть в фразе горизонтальный план дольше порога заметности —
вся фраза уходит вниз.** Не «по первому плану» и не «по
преобладающему»: цены у ошибок разные. Субтитр по центру поверх
горизонтального плана закрывает сам план целиком — это брак. Субтитр
внизу поверх обрезанного плана просто стоит ниже обычного, читается
так же. Выбирать надо в сторону второй ошибки.
"""

