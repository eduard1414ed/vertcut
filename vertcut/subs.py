@dataclass
class Строка:
    """Строка страницы: слова, их текст и ширина краски."""
    words: list[dict] = field(default_factory=list)
    text: str = ""
    ink: int = 0


def ширина_краски(набор: Набор, text: str) -> int:
    """Ширина КРАСКИ строки, а не габарита. Считает сам набор."""
    return набор.ширина(text)


def _строка(words: list[dict], font) -> Строка:
    текст = segmentation.join_words(w["w"] for w in words)
    return Строка(list(words), текст, ширина_краски(font, текст))


def поровну(words: list[dict], предел: int, строк: int, font) -> list[Строка]:
    """Слова страницы → строки поровну.

    Жадная набивка даёт «длинная строка плюс огрызок из одного слова»,
    и в вертикальном кадре это смотрится плохо. Делим так, чтобы самая
    широкая строка была как можно уже; не вышло уложиться в предел —
    значит слово длиннее плашки, и остаётся жадная набивка.
    """
    if строк <= 1 or len(words) < 2:
        return [_строка(words, font)]
    лучшее: tuple[int, list[Строка]] | None = None
    for где in range(1, len(words)):
        слева = _строка(words[:где], font)
        справа = поровну(words[где:], предел, строк - 1, font)
        if слева.ink > предел or any(r.ink > предел for r in справа):
            continue
        цена = max(слева.ink, *(r.ink for r in справа))
        if лучшее is None or цена < лучшее[0]:
            лучшее = (цена, [слева, *справа])
    return лучшее[1] if лучшее else [_строка(words, font)]


def страницы(words: list[dict], prof: dict, font) -> list[list[Строка]]:
    """Слова фразы → страницы по одной-две строки.

    Меряются НЕ ЗНАКИ, а настоящая ширина краски: «Violet Evergarden»
    шире, чем столько же букв кириллицей, и предел в знаках тут врёт.

    Жадная набивка нужна только затем, чтобы узнать, СКОЛЬКО страниц
    нужно: меньше не даёт никто. А слова между этими страницами
    делятся поровну — как строки внутри страницы. Жадно набранная
    доверху страница оставляет следующей огрызок: «лучших.» одним
    словом на весь кадр. Первые отзывы были ровно про это место.
    """
    if not words:
        return []
    предел = prof["предел_текста"]
    больше_нет = prof["максимум_строк"]
    ширины: dict[tuple[int, int], int] = {}
    строк: dict[tuple[int, int], int] = {}

    def ширина(с: int, по: int) -> int:
        """Краска слов `с..по` одной строкой. Меряется один раз."""
        if (с, по) not in ширины:
            ширины[с, по] = ширина_краски(font, segmentation.join_words(
                w["w"] for w in words[с:по]))
        return ширины[с, по]

    def жадно(с: int, по: int) -> int:
        """Сколько строк займут слова `с..по`, набранные жадно."""
        if (с, по) not in строк:
            занято, начало = 1, с
            for i in range(с + 1, по):
                if ширина(начало, i + 1) > предел:
                    занято, начало = занято + 1, i
            строк[с, по] = занято
        return строк[с, по]

    # Сколько страниц нужно: жадно, страница за страницей.
    швы_жадно: list[int] = []
    с = 0
    while с < len(words):
        по = с + 1
        while по < len(words) and жадно(с, по + 1) <= больше_нет:
            по += 1
        швы_жадно.append(по)
        с = по

    # Столько же страниц, но поровну: самая длинная — как можно короче.
    лучшее: dict[tuple[int, int], tuple[int, list[int]] | None] = {}

    def поделить(с: int, осталось: int) -> tuple[int, list[int]] | None:
        if (с, осталось) in лучшее:
            return лучшее[с, осталось]
        вышло = None
        if осталось == 1:
            if жадно(с, len(words)) <= больше_нет:
                вышло = (ширина(с, len(words)), [len(words)])
        else:
            # Самая длинная первая страница, какая влезает. От лишнего
            # слова строк меньше не становится, поэтому дальше смотреть
            # нечего.
            верх = с + 1
            while (верх < len(words) - осталось + 1
                   and жадно(с, верх + 1) <= больше_нет):
                верх += 1
            # Дальше первая страница только короче, а остаток длиннее.
            # Каждое измерение — это шрифт, а экран зовёт раскладку
            # на каждый кадр предпросмотра; поэтому перебор кончается,
            # как только лучше стать не может.
            for по in range(верх, с, -1):
                хвост = поделить(по, осталось - 1)
                if хвост is None:
                    break
                первая = ширина(с, по)
                цена = max(первая, хвост[0])
                if вышло is None or цена < вышло[0]:
                    вышло = (цена, [по, *хвост[1]])
                if хвост[0] >= первая:
                    break
        лучшее[с, осталось] = вышло
        return вышло

    найдено = поделить(0, len(швы_жадно))
    # Не найтись не может: жадная раскладка сама из таких. Но если
    # однажды не нашлось — остаётся она, и страниц не больше, чем было.
    швы = найдено[1] if найдено else швы_жадно
    вышло: list[list[Строка]] = []
    с = 0
    for по in швы:
        вышло.append(поровну(words[с:по], предел, жадно(с, по), font))
        с = по
    return вышло


def слишком_широкие(стр: list[list[Строка]], prof: dict) -> list[str]:
    """Строки, которые всё равно не влезли в предельную ширину.

    Бывает от одного длинного слова: делить его разбивка не умеет
    и не должна. Молчать про это нельзя — строка вылезет под столбик
    иконок соцсети, и увидит это только зритель.
    """
    предел = prof["предел_текста"]
    return [строка.text for страница in стр for строка in страница
            if строка.ink > предел]


# ─────────────────────────────────────────────────────────────────────
# Где кончается речь: замер по звуку
# ─────────────────────────────────────────────────────────────────────
#
# Укладка иногда растягивает последнее слово фразы на всю тишину после
# неё, и субтитр висит, когда голос уже замолчал. На настоящем эссе
# слово «года» получило время с 70.56 по 75.34 — почти пять секунд
# на два слога.
#
# Чинится ЗАМЕРОМ ЗВУКА, а не догадкой о правдоподобной длине слова:
# звук лежит рядом и знает точно. Числа и почему порог относительный —
# в `tuning.py`.

_БУКВЫ = re.compile(r"[^\W\d_]", re.UNICODE)


def букв(слово: str) -> int:
    return max(1, len(_БУКВЫ.findall(слово)))


def громкость(project: Path, при: float, до: float) -> tuple:
    """Громкость снятой дорожки по окнам. Возвращает (массив, начало).

    Меряется КУСОК звука вокруг ролика, а не вся дорожка: фраз в ролике
    десяток, а видео бывает двухчасовым.
    """
    import numpy as np

    from .run import FFMPEG, run_bytes

    путь = layout.audio(project)
    if not путь.exists():
        raise VertcutError(
            f"The analysis folder has no audio track: {путь.name}\n"
            "  Vertcut uses it to measure where each phrase's speech ends.",
            hint="analyze again: vertcut ingest … --again")
    ставка = 16000
    # Через общий вход, а не своим `subprocess`. Это не порядок ради
    # порядка: имя программы превращается в путь ровно там, и своя
    # копия ffmpeg, скачанная установкой, лежит рядом с сервисом,
    # а не в PATH. Поймано сквозным прогоном на чистой учётной записи:
    # разбор проходил целиком, а сборка падала здесь.
    сырое = run_bytes(
        [FFMPEG, "-v", "error", "-ss", f"{max(0.0, при):.3f}",
         "-to", f"{до:.3f}", "-i", str(путь),
         "-f", "s16le", "-ac", "1", "-ar", str(ставка), "-"])
    x = np.frombuffer(сырое, dtype=np.int16).astype(np.float32) / 32768
    окно = int(tuning.SPEECH_STEP * ставка)
    n = len(x) // окно
    if n < 3:
        raise VertcutError(
            f"Got no sound from the audio track at {при:.2f}–{до:.2f} s: "
            f"{путь.name}",
            hint="analyze again: vertcut ingest … --again")
    гр = np.sqrt((x[:n * окно].reshape(n, окно) ** 2).mean(axis=1))
    return гр, max(0.0, при)


def темп_речи(laid: dict) -> tuple:
    """Сколько секунд речи приходится на слово: связь «буквы → время».

    Считается по САМОМУ ЭТОМУ ВИДЕО, а не берётся числом: у другого
    человека другой темп. Берутся слова обычной длины — между пятым
    и девяносто пятым процентилем, — чтобы растянутые укладкой выбросы
    не тянули связь вверх.

    Зачем: чтобы отличить кусок звука, в который помещаются слова
    фразы, от куска, в который не помещаются. Без такой проверки
    подрезка принимает за фразу случайный громкий звук — и это
    не выдумка, а поймано на настоящем материале.
    """
    import numpy as np

    длины = np.array([w["e"] - w["s"] for w in laid["words"]], dtype=float)
    if len(длины) < 20:
        return 0.04, 0.2
    низ, верх = np.percentile(длины, 5), np.percentile(длины, 95)
    свои = [(букв(w["w"]), w["e"] - w["s"]) for w in laid["words"]
            if низ <= w["e"] - w["s"] <= верх]
    if len(свои) < 20:
        return 0.04, 0.2
    A = np.array([[b, 1.0] for b, _ in свои])
    y = np.array([t for _, t in свои])
    k, c = np.linalg.lstsq(A, y, rcond=None)[0]
    return float(k), float(c)


def куски_речи(гр, порог: float) -> list:
    """Куски звука, в которых слышен голос. Тишина короче паузы не рвёт."""
    речь = гр >= порог
    сырые, i = [], 0
    while i < len(речь):
        if речь[i]:
            j = i
            while j + 1 < len(речь) and речь[j + 1]:
                j += 1
            сырые.append([i, j])
            i = j + 1
        else:
            i += 1
    склеено = []
    for s, e in сырые:
        if склеено and (s - склеено[-1][1] - 1) * tuning.SPEECH_STEP \
                < tuning.SPEECH_GAP:
            склеено[-1][1] = e
        else:
            склеено.append([s, e])
    return склеено


def границы_речи(гр, начало: float, a: float, b: float, слова: list,
                 темп: tuple, слева_свободно: bool,
                 справа_свободно: bool) -> tuple:
    """Где во фразе слышен голос: (начало речи, конец речи).

    ## Как выбирается кусок

    Укладка пакует соседние фразы встык, и краю, который упирается
    в соседку, верить можно: там речь и правда продолжается. А край,
    перед которым зияет пауза, укладка ставила свободно — и иногда
    ставит не туда.

    Отсюда правило: **идём от прижатого края и набираем куски звука,
    пока их не хватит на слова фразы.** Прижаты оба края — не трогаем
    ничего. Свободны оба — начинаем с самого длинного куска и добираем
    соседей.

    ## Почему не «ближайший кусок»

    Так и было сделано сначала, и сломалось на настоящем материале
    дважды. Фраза «Три года» лежит в окне 69.6–75.34, а внутри окна
    два звука: одинокий громкий всплеск на 70.3–70.95 и настоящая речь
    на 74.3–75.34. Ближайший к началу — всплеск, и субтитр вставал
    на него: слова показывались за четыре секунды до того, как их
    произносят.

    А правило «бери кусок у прижатого края» без проверки по словам
    ломает другие фразы: у фразы из двенадцати слов последний кусок
    длится 0.68 с, и субтитр съёжился бы до него.
    """
    import numpy as np

    шаг = tuning.SPEECH_STEP
    i0 = max(0, int(round((a - начало) / шаг)))
    i1 = min(len(гр), int(round((b - начало) / шаг)))
    окно = гр[i0:i1]
    if len(окно) < 3 or (слева_свободно is False and справа_свободно is False):
        return a, b
    порог = float(np.percentile(окно, 95)) * tuning.SPEECH_LEVEL
    if порог <= 0:
        return a, b
    куски = куски_речи(окно, порог)
    if not куски:
        return a, b

    k, c = темп
    надо = sum(k * букв(x["w"]) + c for x in слова)

    def длина(n: int) -> float:
        return (куски[n][1] + 1 - куски[n][0]) * шаг

    if not слева_свободно:
        лев = прав = 0
    elif not справа_свободно:
        лев = прав = len(куски) - 1
    else:
        лев = прав = max(range(len(куски)), key=длина)
    взято = длина(лев)
    while взято < надо and (лев > 0 or прав < len(куски) - 1):
        # Добираем соседа — того, что больше: он вероятнее речь,
        # а не случайный звук.
        слева_есть, справа_есть = лев > 0, прав < len(куски) - 1
        if слева_есть and (not справа_есть or длина(лев - 1) >= длина(прав + 1)):
            лев -= 1
            взято += длина(лев)
        else:
            прав += 1
            взято += длина(прав)

    s = max(a, a + куски[лев][0] * шаг)
    e = min(b, a + (куски[прав][1] + 1) * шаг)
    return (a, b) if e - s < шаг * 3 else (s, e)


def разложить_заново(фраза: dict, темп: tuple) -> bool:
    """Разложить слова фразы заново, если они вылезли из её окна.

    Подрезка двигает границы фразы, а времена отдельных слов остаются
    от укладки — и после большой подрезки все они могут оказаться
    снаружи. Тогда состояния схлопываются в одно: вся строка чернеет
    разом, и показ по словам пропадает.

    Слова, оставшиеся внутри окна, не трогаются вовсе.
    """
    слова = фраза["words"]
    if not слова:
        return False
    if all(фраза["at"] - 1e-6 <= w["s"] < фраза["till"] + 1e-6 for w in слова):
        return False
    k, c = темп
    вес = [k * букв(w["w"]) + c for w in слова]
    всего = sum(вес) or 1.0
    длина = фраза["till"] - фраза["at"]
    t = фраза["at"]
    for w, доля in zip(слова, вес):
        w["s"] = round(t, 3)
        t += длина * доля / всего
        w["e"] = round(min(t, фраза["till"]), 3)
    return True


