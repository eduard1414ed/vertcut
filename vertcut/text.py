"""Слово — одно определение на весь проект.

Здесь ровно одна вещь, и это не бедность файла, а решение. Пять разных
мест могут считать словами разное — и в проекте, откуда механика
перенесена, так и было, НАРОЧНО:

- укладка на звук складывает `ё` и `е`: распознавание `ё` не пишет
  никогда;
- поиск авторской цитаты складывать не имеет права — там `ё` буква;
- разбивка на строки считает знаки, а рисование субтитра меряет
  настоящую ширину краски, потому что у него есть шрифт.

Дублировалась там ровно одна вещь — вот эта регулярка, побайтово
одинаковая в двух файлах. Здесь она одна, и все, кому нужно «что такое
слово», берут её отсюда.
"""

from __future__ import annotations

import re

# Слова так, как их считает человек: дефисные за одно («какой-то»),
# числа за одно («1,5»), апостроф внутри слова не рвёт его.
WORD_RE = re.compile(
    r"[^\W\d_]+(?:[-'’][^\W\d_]+)*|\d+(?:[.,]\d+)*", re.UNICODE)


def азбука(текст: str) -> str | None:
    """Какими буквами это написано: «кириллица», «латиница» или обе.

    **Счёт, а не суждение.** Заведено ради одной механической проверки:
    ответ модели должен приехать на том же языке, на каком уехал
    запрос. Определять ЯЗЫК сервису нечем и не нужно — а отличить
    кириллицу от латиницы можно счётом букв, и этого хватает, чтобы
    поймать настоящую беду: русское видео, описанное по-английски.

    Языки с одной азбукой (испанский против английского) так
    не различаются, и обещать этого нельзя. Здесь и не обещается:
    вопрос ровно один — той ли азбукой.

    Меньше трети букв в меньшинстве — считается, что азбука одна:
    имя или название на другом языке есть почти в любом тексте
    («Смотрите новое видео про Kubernetes» — это четверть букв
    латиницей), и жаловаться на них значило бы жаловаться всегда.

    **Треть — суждение, а не замер, и точность тут почти не важна.**
    Тот, кто этим пользуется, жалуется ТОЛЬКО когда обе стороны
    однозначны и противоположны: русский запрос, английский ответ.
    Ответ, вышедший «обеими», не жалоба ни в какую сторону — то есть
    ошибка порога стоит молчания, а не ложной тревоги.
    """
    кир = сум_лат = 0
    for знак in текст:
        if not знак.isalpha():
            continue
        if "Ѐ" <= знак <= "ӿ":
            кир += 1
        elif знак.isascii():
            сум_лат += 1
    всего = кир + сум_лат
    if not всего:
        return None
    доля = min(кир, сум_лат) / всего
    if доля > 1 / 3:
        return "обе"
    return "кириллица" if кир > сум_лат else "латиница"


def азбуки_разошлись(свои: str, их: str) -> bool:
    """Приехал ли ответ модели не той азбукой, что уехал запрос.

    Жалоба только тогда, когда обе стороны однозначны
    и противоположны: ответ «обеими» — не жалоба ни в какую сторону.
    Одно правило на кандидатов, описания и вычитку.
    """
    было, стало = азбука(свои), азбука(их)
    return bool(было and стало and было != стало
                and "обе" not in (было, стало))
