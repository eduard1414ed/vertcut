"""Деньги: дневник расходов, порог подтверждения, суточный стоп.

## Зачем это вообще

До этой сессии все ошибки в проекте были бесплатны. Неверное число,
кривая рамка, испорченный профиль — всё чинилось временем. Кнопка,
которая обращается к модели, стоит денег, и платит их чужой человек.

Отсюда три работы, и все три здесь:

1. **сказать цену ДО нажатия.** Дорога проторена: экран уже говорит
   цену копирования файла, цену вида в перелистываниях и оценку
   времени сборки;
2. **спросить, если дорого** — порог из дизайна;
3. **остановиться, если за сутки ушло слишком много** — суточный стоп
   оттуда же.

## Три числа, и все три разные

**Оценка** — до нажатия, по размеру запроса. Она всегда приблизительна
и честно называет себя оценкой.

**Факт** — после ответа, из самого ответа поставщика. Сколько токенов
он посчитал, столько и записано. Своей арифметики тут нет.

**Деньги** — факт, помноженный на цену. Цены модели не знаем — денег
не записываем вовсе, а записываем токены. Дневник, в котором лежит
выдуманное число, хуже пустого.

## Почему оценка умеет ошибаться и что с этим сделано

Нынешние модели думают, прежде чем ответить, и думанье оплачивается
по цене ответа, а увидеть его до нажатия нельзя. Значит оценка,
посчитанная по одному размеру ответа, занижена всегда.

Поэтому множитель не выдуман, а **меряется на ходу**: после каждого
ответа сюда ложится, сколько токенов ушло на самом деле, и следующая
оценка считается по прошлым запросам к ЭТОЙ модели. Отправная точка
из `tuning.py` работает ровно один раз — до первого ответа.

Это и есть то единственное, что здесь можно мерить честно. Качество
предложений моделью мерить нечем, и оно не мерится; цена, время и
размер — меряются.
"""

from __future__ import annotations

import json
from datetime import date

from . import config, layout, tuning
from .errors import VertcutError


def _прочитать() -> dict:
    файл = layout.spend_file()
    if not файл.exists():
        return {}
    try:
        это = json.loads(файл.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, UnicodeDecodeError):
        # Дневник — не настройка: человек его не правит и потерять
        # его не страшно. Падать здесь значило бы не дать спросить
        # модель из-за испорченного счётчика.
        return {}
    return это if isinstance(это, dict) else {}


def _записать(это: dict) -> None:
    from . import works

    works.записать(layout.spend_file(), это)


def сегодня() -> str:
    return date.today().isoformat()


def день(какой: str | None = None) -> dict:
    """Что ушло за день: запросов, токенов, денег."""
    дни = _прочитать().get("дни") or {}
    это = дни.get(какой or сегодня()) or {}
    return {
        "запросов": int(это.get("запросов") or 0),
        "вошло": int(это.get("вошло") or 0),
        "вышло": int(это.get("вышло") or 0),
        "деньги": float(это.get("деньги") or 0.0),
        "без_цены": int(это.get("без_цены") or 0),
    }


# Задачи, ради которых сервис вообще спрашивает модель. Замер ведётся
# по КАЖДОЙ отдельно, а не по модели целиком.
#
# **ЗАМЕР пятой сессии, и он поймал дыру в суточном стопе.** Кандидаты
# и описания отвечают совершенно по-разному:
#
#     кандидаты  4765 и 2802 токена ответа
#     описания    305 и  212
#
# Среднее по модели занижало оценку кандидатов впятеро — и суточный
# стоп, поставленный на пять центов, пропустил запрос на шесть.
# То есть страховка, которая не сработала бы у чужого человека ровно
# тогда, когда она нужна.
КАНДИДАТЫ, ОПИСАНИЯ = "кандидаты", "описания"
# Вычитка субтитров — своя задача по той же причине: ответ у неё —
# только исправленные строки, то есть короче кандидатов и длиннее
# описаний, и общий замер занижал бы одно или завышал другое.
ВЫЧИТКА = "вычитка"


def записать(модель: str, вошло: int, вышло: int,
             деньги: float | None, секунд: float,
             знаков_ушло: int = 0, азбука_: str = "кир",
             задача: str = КАНДИДАТЫ) -> dict:
    """Положить в дневник то, что ответил поставщик.

    **Записывается сразу, как ответ пришёл, — до того, как его начнут
    разбирать.** Разбор может не удаться, а деньги уже потрачены:
    дневник, который узнаёт о запросе только при удачном разборе,
    показывал бы меньше, чем в счёте.
    """
    это = _прочитать()
    дни = это.setdefault("дни", {})
    сейчас = дни.setdefault(сегодня(), {})
    сейчас["запросов"] = int(сейчас.get("запросов") or 0) + 1
    сейчас["вошло"] = int(сейчас.get("вошло") or 0) + int(вошло)
    сейчас["вышло"] = int(сейчас.get("вышло") or 0) + int(вышло)
    if деньги is None:
        сейчас["без_цены"] = int(сейчас.get("без_цены") or 0) + 1
    else:
        сейчас["деньги"] = round(float(сейчас.get("деньги") or 0.0)
                                 + float(деньги), 6)

    # Замер множителя: сколько токенов модель отдала на самом деле.
    # Складывается по моделям, а не в кучу: у разных моделей думанье
    # разное, и общее среднее не отвечает ни за одну из них.
    замеры = это.setdefault("замеры", {}).setdefault(f"{модель}·{задача}", {})
    замеры["ответов"] = int(замеры.get("ответов") or 0) + 1
    замеры["вышло"] = int(замеры.get("вышло") or 0) + int(вышло)
    замеры["вошло"] = int(замеры.get("вошло") or 0) + int(вошло)
    замеры["секунд"] = round(float(замеры.get("секунд") or 0.0)
                             + float(секунд), 2)
    # Отношение знаков к токенам — по каждой азбуке отдельно: у кириллицы
    # токен вдвое короче, и общее среднее не отвечало бы ни за одну.
    if знаков_ушло:
        замеры["знаки_" + азбука_] = (int(замеры.get("знаки_" + азбука_) or 0)
                                      + int(знаков_ушло))
        замеры["вошло_" + азбука_] = (int(замеры.get("вошло_" + азбука_) or 0)
                                      + int(вошло))

    _подрезать(дни)
    _записать(это)
    return день()


def _подрезать(дни: dict) -> None:
    """Оставить последние дни. Файл не должен расти вечно."""
    лишние = sorted(дни)[:-tuning.ДНЕЙ_РАСХОДОВ]
    for какой in лишние:
        дни.pop(какой, None)


def замер(модель: str, задача: str = КАНДИДАТЫ) -> dict | None:
    """Что известно про эту модель на этой задаче по прошлым запросам."""
    это = (_прочитать().get("замеры") or {}).get(f"{модель}·{задача}")
    if not это or not int(это.get("ответов") or 0):
        return None
    ответов = int(это["ответов"])
    return {
        "ответов": ответов,
        "вышло_в_среднем": int(это.get("вышло") or 0) / ответов,
        "секунд_в_среднем": float(это.get("секунд") or 0.0) / ответов,
    }


# ─────────────────────────────────────────────────────────────────────
# Оценка до нажатия
# ─────────────────────────────────────────────────────────────────────

def азбукой(текст: str) -> str:
    """Какой азбукой считать этот текст: «кир» или «лат».

    Смешанный берёт кириллическое число — оно осторожнее, а занижать
    цену хуже, чем завышать.
    """
    from .text import азбука

    return "лат" if азбука(текст) == "латиница" else "кир"


def знаков_на_токен(текст: str, модель: str | None = None,
                    задача: str = КАНДИДАТЫ) -> float:
    """Отношение знаков к токенам для ЭТОГО текста.

    Меряется на ходу и по каждой модели с азбукой отдельно: у чужого
    поставщика токенизатор другой, а у кириллицы токен вдвое короче,
    чем у латиницы. Замера ещё нет — берётся поставляемое число,
    и у него написано, на чём оно мерялось.
    """
    какая = азбукой(текст)
    поставляемое = (tuning.ЗНАКОВ_НА_ТОКЕН_ЛАТИНИЦЕЙ if какая == "лат"
                    else tuning.ЗНАКОВ_НА_ТОКЕН_КИРИЛЛИЦЕЙ)
    было = (_прочитать().get("замеры") or {}).get(
        f"{модель or config.модель()}·{задача}")
    свой = (было or {}).get("знаки_" + какая)
    вошло = (было or {}).get("вошло_" + какая)
    if not (свой and вошло):
        return поставляемое

    # **Замер двигает оценку только в осторожную сторону.**
    #
    # Он честнее поставляемого числа, но не всегда безопаснее: у двух
    # РУССКИХ текстов отношение вышло разным — 1.51 у списка фраз
    # и 2.15 у сплошной прозы. Токенизатор считает не только буквы,
    # но и форму текста, и замер, снятый на одном виде просьбы,
    # занизил бы цену другому.
    #
    # А занизить цену — худшая из двух ошибок: человек, увидевший вдвое
    # меньше настоящего, нажмёт не думая. Поэтому берётся меньшее
    # из двух отношений, то есть большее из двух количеств токенов.
    return min(свой / вошло, поставляемое)


def токенов(текст: str, задача: str = КАНДИДАТЫ) -> int:
    """Сколько примерно токенов в этом тексте.

    **Своя прикидка, а не ручка поставщика.** У Anthropic есть отдельная
    дешёвая ручка для подсчёта, у произвольного адреса на протоколе
    OpenAI её может не быть вовсе — и две дороги к одному числу
    разошлись бы молча. Расхождение прикидки с фактом печатается
    человеку после каждого ответа, так что число не остаётся
    непроверенным.
    """
    return max(1, round(len(текст) / знаков_на_токен(текст, задача=задача)))


def оценить(текст: str, потолок_ответа: int,
            задача: str = КАНДИДАТЫ) -> dict:
    """Во что обойдётся этот запрос. Всё, что нужно сказать до нажатия.

    Ответ считается не по потолку, а по замеру: потолок — это предел,
    а не ожидание, и считать по нему значило бы пугать человека суммой
    впятеро больше настоящей.
    """
    модель = config.модель()
    цена_ = config.цена(модель)
    вошло = токенов(текст, задача)

    было = замер(модель, задача)
    if было:
        выйдет = round(было["вышло_в_среднем"])
        from . import report
        откуда = ("based on " + report.счёт(было["ответов"], "past request",
                                            "past requests"))
    else:
        выйдет = round(потолок_ответа / tuning.ДУМАНЬЕ_СВЕРХ_ОТВЕТА)
        откуда = "no requests to this model yet"
    выйдет = min(выйдет, потолок_ответа)

    деньги = None
    if цена_:
        деньги = round(вошло / 1e6 * цена_[0] + выйдет / 1e6 * цена_[1], 4)

    порог_ = config.порог()
    прошло = день()
    стоп_ = config.стоп()
    return {
        "модель": модель,
        "знаков": len(текст),
        "вошло": вошло,
        "выйдет": выйдет,
        "откуда_оценка": откуда,
        "цена_модели": цена_,
        "цены_сверены": tuning.ЦЕНЫ_СВЕРЕНЫ,
        "деньги": деньги,
        "порог": порог_,
        # Сравнение с порогом делает ОДНО место, и оно здесь. В веб-слое
        # его быть не может: порог — это число, а числа живут там, где
        # написано их происхождение.
        "спросить_разрешения": bool(деньги is not None and деньги > порог_),
        "стоп": стоп_,
        "за_сегодня": прошло,
        "стоп_близко": bool(деньги is not None
                            and прошло["деньги"] + деньги > стоп_),
    }


def проверить_стоп(будет: float | None) -> None:
    """Суточный стоп. Упёрлись — отказ словами, а не тихий пропуск.

    **Стоп не работает, когда цена неизвестна, и об этом говорится.**
    Считать неизвестную цену нулём значило бы обещать защиту, которой
    нет: человек с моделью не из прейскуранта уверен, что его стережёт
    стоп, а тот пропустит любое количество запросов.
    """
    предел = config.стоп()
    if предел <= 0:
        return
    ушло = день()["деньги"]
    if ушло >= предел:
        raise VertcutError(
            f"Daily limit reached: ${ушло:.2f} of ${предел:.2f} spent today",
            hint="raise the daily limit in Settings or wait until tomorrow — "
                 "the day follows this computer's calendar",
        )
    if будет is not None and ушло + будет > предел:
        raise VertcutError(
            f"Daily limit: ${ушло:.2f} spent today, this request adds "
            f"about ${будет:.2f} — together more than ${предел:.2f}",
            hint="raise the daily limit in Settings or wait until tomorrow",
        )


def проверить_порог(будет: float | None, разрешено: bool) -> None:
    """Порог подтверждения: дорогой запрос не уходит молча."""
    предел = config.порог()
    if разрешено or будет is None or предел <= 0 or будет <= предел:
        return
    raise ДорогоError(
        f"This request will cost about ${будет:.2f} — "
        f"more than your ${предел:.2f} limit for asking first",
        hint="press again to go ahead, or raise the limit in Settings",
        сколько=будет, порог=предел,
    )


class ДорогоError(VertcutError):
    """Не поломка, а вопрос: платить ли столько.

    Своим типом, а не общим отказом: экран должен показать это полосой
    с кнопкой «да, спросить», а не красной бедой. Отличить одно
    от другого по тексту сообщения нельзя — по типу можно.
    """

    # Слово, по которому экран отличает вопрос от поломки. Едет
    # в json отдельным полем: разбирать для этого текст сообщения
    # значило бы завести в браузере знание о том, как оно написано.
    вид = "дорого"

    def __init__(self, message: str, hint: str, сколько: float,
                 порог: float):
        super().__init__(message, hint)
        self.сколько = сколько
        self.порог = порог
