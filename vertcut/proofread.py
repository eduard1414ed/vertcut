"""Вычитка субтитров моделью: правки списком, решает человек.

## Зачем

Распознавание пишет то, что услышало, слово за словом, и ошибается так,
как человек не ошибся бы никогда: «антология истории, связанных лишь
главным героям», «мангоюки у Русибары» вместо «манга Юки Урусибары».
Падежи, имена и названия правятся рукой по одной фразе — это и есть
работа, которую можно отдать модели.

## Модель предлагает, а не правит

**Ни одна правка не ложится в субтитр сама.** Модель уверенно
«исправляет» и то, что было сказано верно: в устной речи бывают
и неправильные падежи, и оборванные фразы, а субтитр обязан говорить
то, что сказано. Поэтому ответ — список «было → стало, почему», и
у каждой правки три кнопки: принять, поправить самому, отклонить.

Принятая правка — **обычная правка текста рукой** (`edits`): та же
метка «edited», тот же «Reset text edits», тот же штамп сборки. Своего
второго механизма правок не заводится.

## Один ролик, а не всё видео

Ролик — это полсотни слов, и проверка стоит центы. А правки ложатся
на фразы РОЛИКА, с его правками рукой: всё видео пришлось бы потом
разносить по роликам, и у двух роликов с общей фразой правки бы
разошлись. Модели уезжает ровно тот текст, что стоит в кадре, плюс
несколько фраз вокруг и начало видео — для смысла, а не на правку.

## «Было» пишет сервис, а не модель

Модель называет строку и присылает, какой она должна стать. Что
в строке стоит СЕЙЧАС, сервис берёт у себя: модель могла переписать
исходник с ошибкой, и тогда «было» на экране было бы неправдой.
Отсюда и свежесть: правка показывается, пока текст фразы равен её
«было». Поправили фразу рукой, разделили, склеили — правка пропадает
сама, без отдельного учёта.

## Ответ ложится файлом до разбора

Та же причина, что у кандидатов: разбор может не удаться, а деньги
уже заплачены.
"""

from __future__ import annotations

import json
from datetime import datetime
from pathlib import Path

from . import describe, edits, layout, pick, prompts, speech, subs, tuning, works
from .errors import VertcutError


def спросить(project: Path, ключ: str, *, разрешено_дорого: bool = False,
             на_ходу=None) -> dict:
    """Попросить модель вычитать субтитры этой вертикалки.

    Хозяин тот же, что у кандидатов и описаний: обращение платное,
    и два нажатия подряд стоили бы вдвое.
    """
    from . import ai
    from . import spend as spend_

    cut = pick.load(project, ключ)
    laid = speech.read(project)
    фразы = _фразы(laid, cut)

    файл_работы = layout.ai_work(project)
    works.взять(файл_работы, "AI check")
    try:
        if на_ходу:
            на_ходу("asking AI to check the subtitles…")
        ответ = ai.спросить(
            prompts.собрать(prompts.ВЫЧИТКА),
            _что_показать_модели(project, laid, cut, фразы),
            потолок=tuning.ПОТОЛОК_ВЫЧИТКИ,
            разрешено_дорого=разрешено_дорого,
            задача=spend_.ВЫЧИТКА)
        layout.proofread_raw(project, ключ).write_text(ответ.текст,
                                                       encoding="utf-8")
        это = _разобрать(project, ключ, фразы, ответ)
        _записать(project, ключ, это)
        return это
    finally:
        works.отпустить(файл_работы)


def оценить(project: Path, cut: dict) -> dict:
    """Во что обойдётся. Считается ЗДЕСЬ: цена складывается из размера
    запроса и прейскуранта, а это числа."""
    from . import spend

    laid = speech.read(project)
    текст = (prompts.собрать(prompts.ВЫЧИТКА)
             + _что_показать_модели(project, laid, cut, _фразы(laid, cut)))
    return spend.оценить(текст, tuning.ПОТОЛОК_ВЫЧИТКИ, spend.ВЫЧИТКА)


def для_экрана(project: Path, cut: dict) -> dict:
    """Что показать у списка фраз: живые правки и цена.

    Цена приезжает всегда, а показывается только дорогая: решает это
    `spend.оценить` (`спросить_разрешения`), а не экран.
    """
    from . import config

    было = прочитать(project, cut["id"])
    return {
        "правки": [{**п, "разница": разница(п["было"], п["стало"])}
                   for п in свежие(project, cut, было)],
        "спрошено": было is not None,
        "подключён": config.подключён(),
        "оценка": оценить(project, cut) if config.подключён() else None,
    }


def разница(было: str, стало: str) -> dict:
    """Слово к слову: какие слова ушли и какие пришли.

    Считается здесь, а не в браузере: экран только рисует — зачёркнутое
    и подсвеченное приезжают готовыми, парами «слово, изменено ли».
    """
    import difflib

    а, б = было.split(), стало.split()
    слева, справа = [], []
    for тег, i1, i2, j1, j2 in difflib.SequenceMatcher(
            a=а, b=б, autojunk=False).get_opcodes():
        слева += [[с, тег != "equal"] for с in а[i1:i2]]
        справа += [[с, тег != "equal"] for с in б[j1:j2]]
    return {"было": слева, "стало": справа}


def прочитать(project: Path, ключ: str) -> dict | None:
    файл = layout.proofread(project, ключ)
    if not файл.exists():
        return None
    return json.loads(файл.read_text(encoding="utf-8"))


def свежие(project: Path, cut: dict, было: dict | None = None) -> list[dict]:
    """Правки, которые ещё ложатся: текст фразы равен их «было».

    Остальные не стираются с диска — они просто больше ни к чему
    не относятся, и показывать их значило бы предлагать править то,
    чего на экране уже нет.
    """
    if было is None:
        было = прочитать(project, cut["id"])
    if not было:
        return []
    сейчас = {(ф["с"], ф["по"]): ф["текст"]
              for ф in _фразы(speech.read(project), cut)}
    return [п for п in было.get("правки") or []
            if сейчас.get((п["с"], п["по"])) == п["было"]]


def принять(project: Path, cut: dict, с: int | None = None,
            по: int | None = None, текст: str | None = None) -> int:
    """Принять правку — или все. Своим текстом — если человек поправил.

    Принятая правка записывается обычной правкой текста рукой и уходит
    из списка. Возвращает, сколько принято.
    """
    if текст is not None and с is None:
        raise VertcutError(
            "Your own text can replace only one AI fix at a time",
            hint="name the phrase the text is for")
    выбраны = _выбрать(project, cut, с, по)
    for п in выбраны:
        edits.поправить_текст(cut, п["с"], п["по"],
                              п["стало"] if текст is None else текст)
    _убрать(project, cut["id"], выбраны)
    return len(выбраны)


def отклонить(project: Path, cut: dict, с: int | None = None,
              по: int | None = None) -> int:
    """Убрать правку — или все. Субтитр не меняется."""
    выбраны = _выбрать(project, cut, с, по)
    _убрать(project, cut["id"], выбраны)
    return len(выбраны)


# ─────────────────────────────────────────────────────────────────────
# Что уезжает модели
# ─────────────────────────────────────────────────────────────────────

def _фразы(laid: dict, cut: dict) -> list[dict]:
    """Фразы ролика так, как они стоят в кадре: с правками рукой."""
    return [{"с": ф["с"], "по": ф["по"], "строка": f'{ф["с"]}-{ф["по"]}',
             "текст": " ".join(w["w"] for w in ф["words"])}
            for ф in subs.фразы_с_правками(laid, pick.ranges(cut),
                                           edits.список(cut))]


def _что_показать_модели(project: Path, laid: dict, cut: dict,
                         фразы: list[dict]) -> str:
    """Начало видео, фразы перед роликом, строки ролика, фразы после.

    **Вокруг — только для смысла.** Строка ролика часто продолжает
    предложение, начатое раньше, и без него не понять ни падежа,
    ни большой буквы. Но правка на контекст не ложится: его нет
    в кадре, и форма ответа говорит модели это прямо.
    """
    до, после = _вокруг(laid, cut)
    # Часть запроса к модели, а не экрана: переводится вместе
    # с инструкциями модели (`prompt-*.txt`).
    куски = describe.про_видео(project)
    if до:
        куски += ["Context just before the clip — not part of it, "
                  "don't fix it:", " ".join(до), ""]
    куски += ["The clip's subtitle lines, each with its id in brackets:", ""]
    куски += [f'[{ф["строка"]}] {ф["текст"]}' for ф in фразы]
    куски.append("")
    if после:
        куски += ["Context just after the clip — not part of it, "
                  "don't fix it:", " ".join(после), ""]
    куски.append("List only the lines that need a fix.")
    куски.append(prompts.ПРО_ЯЗЫК)
    return "\n".join(куски)


def _вокруг(laid: dict, cut: dict) -> tuple[list[str], list[str]]:
    """Тексты нескольких фраз видео до первого и после последнего слова."""
    куски = pick.ranges(cut)
    первое, последнее = куски[0][0], куски[-1][1]
    места = speech.spans(laid)
    до = [n for n, (_, w1) in enumerate(места) if w1 < первое]
    после = [n for n, (w0, _) in enumerate(места) if w0 > последнее]
    n = tuning.ФРАЗ_ВОКРУГ_ДЛЯ_ВЫЧИТКИ

    def текст(k: int) -> str:
        return " ".join(w["w"] for w in laid["phrases"][k]["words"])

    return ([текст(k) for k in до[max(0, len(до) - n):]],
            [текст(k) for k in после[:n]])


# ─────────────────────────────────────────────────────────────────────
# Что приезжает обратно
# ─────────────────────────────────────────────────────────────────────

def _разобрать(project: Path, ключ: str, фразы: list[dict], ответ) -> dict:
    from . import suggest
    from .text import азбуки_разошлись

    сырое = suggest._вынуть_json(ответ.текст)
    ряд = сырое.get("правки") if isinstance(сырое, dict) else None
    if not isinstance(ряд, list):
        raise VertcutError(
            "Could not read the AI answer: it has no list of fixes",
            hint=f"the full answer is saved here: "
                 f"{layout.proofread_raw(project, ключ)}. The request is "
                 "paid for — look at what came back before asking again")

    по_строкам = {ф["строка"]: ф for ф in фразы}
    правки, чужие, не_та_азбука = [], [], 0
    for это in ряд:
        if not isinstance(это, dict):
            continue
        строка = _строка(это.get("строка"))
        стало = " ".join(str(это.get("стало") or "").split())
        ф = по_строкам.get(строка)
        if ф is None:
            # Строки, которой в ролике нет: модель правила контекст или
            # выдумала номер. Молча положить нельзя — некуда.
            чужие.append(строка)
            continue
        if not стало or стало == ф["текст"]:
            continue
        if азбуки_разошлись(ф["текст"], стало):
            # Русская строка, ставшая латиницей, — это перевод,
            # а не правка распознавания.
            не_та_азбука += 1
            continue
        if any((п["с"], п["по"]) == (ф["с"], ф["по"]) for п in правки):
            continue
        правки.append({"с": ф["с"], "по": ф["по"], "было": ф["текст"],
                       "стало": стало,
                       "почему": " ".join(str(это.get("почему") or "").split())})

    return {
        "когда": datetime.now().astimezone().isoformat(timespec="seconds"),
        "модель": ответ.модель,
        "вошло": ответ.вошло, "вышло": ответ.вышло,
        "деньги": ответ.деньги, "секунд": ответ.секунд,
        "оборвался": ответ.оборвался,
        "правки": правки,
        "чужие_строки": чужие,
        "не_та_азбука": не_та_азбука,
    }


def _строка(значение) -> str:
    """Номер строки так, как его пишет сервис: «508-515».

    Модель любит типографское тире и квадратные скобки вокруг —
    это не повод потерять правку.
    """
    голая = str(значение or "").strip().strip("[]").strip()
    for тире in ("–", "—", "‒", " "):
        голая = голая.replace(тире, "-" if тире != " " else "")
    return голая


def _выбрать(project: Path, cut: dict, с: int | None,
             по: int | None) -> list[dict]:
    живые = свежие(project, cut)
    if с is None:
        return живые
    выбраны = [п for п in живые if (п["с"], п["по"]) == (int(с), int(по))]
    if not выбраны:
        raise VertcutError(
            "This AI fix is no longer there",
            hint="it was accepted or dismissed, or the phrase changed "
                 "since — check with AI again")
    return выбраны


def _убрать(project: Path, ключ: str, ушли: list[dict]) -> None:
    было = прочитать(project, ключ)
    if not было:
        return
    уходят = {(п["с"], п["по"]) for п in ушли}
    было["правки"] = [п for п in было.get("правки") or []
                      if (п["с"], п["по"]) not in уходят]
    _записать(project, ключ, было)


def _записать(project: Path, ключ: str, это: dict) -> None:
    layout.proofread(project, ключ).write_text(
        json.dumps(это, ensure_ascii=False, indent=1) + "\n",
        encoding="utf-8")
