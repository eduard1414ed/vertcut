def прочитать(какая: str) -> str:
    """Инструкция человека, а нет своей — поставляемая."""
    своя = layout.prompt(какая)
    if своя.exists():
        текст = своя.read_text(encoding="utf-8").strip()
        if текст:
            return текст
    return поставляемая(какая)


def поставляемая(какая: str) -> str:
    return layout.shipped_prompt(какая).read_text(encoding="utf-8").strip()


def своя_ли(какая: str) -> bool:
    return layout.prompt(какая).exists()


def записать(какая: str, текст: str) -> None:
    """Положить свою. Пустая — вернуть базовую, то есть стереть свою.

    Пустое поле и отсутствующий файл должны значить одно и то же:
    иначе «стёр инструкцию» и «инструкции не было» — два разных
    состояния там, где смысл один.
    """
    файл = layout.prompt(какая)
    чистый = (текст or "").strip()
    if not чистый:
        файл.unlink(missing_ok=True)
        return
    файл.parent.mkdir(parents=True, exist_ok=True)
    файл.write_text(чистый + "\n", encoding="utf-8")


def эталоны() -> list[str]:
    """Настоящие подписи человека, по которым модель пишет его голосом.

    **Их может не быть вовсе, и это законный случай.** У предка
    инструкция снималась с десятка настоящих подписей автора; у чужого
    человека эталона нет, и требовать его значило бы закрыть кнопку
    тому, кто ещё ничего не публиковал. Нет эталонов — модель пишет
    по одной инструкции, и сервис об этом говорит.
    """
    файл = layout.samples()
    if not файл.exists():
        return []
    строки = файл.read_text(encoding="utf-8").splitlines()
    return [с.strip() for с in строки if с.strip()]


def записать_эталоны(текст: str) -> list[str]:
    файл = layout.samples()
    чистый = (текст or "").strip()
    if not чистый:
        файл.unlink(missing_ok=True)
        return []
    файл.parent.mkdir(parents=True, exist_ok=True)
    файл.write_text(чистый + "\n", encoding="utf-8")
    return эталоны()


def собрать(какая: str, эталонов: list[str] | None = None) -> str:
    """Инструкция целиком: правленая часть, эталоны, форма ответа."""
    куски = [прочитать(какая)]
    if эталонов:
        куски.append(
            # «Манеру, а не язык» — с 21-й сессии: русские образцы
            # тянули бы на русский описания английского видео.
            "HERE IS HOW THE CREATOR WRITES. Match this length, tone "
            "and manner — it matters more than anything above. Take "
            "the manner, not the language: the language comes from "
            "the transcript.\n\n"
            + "\n".join(f"- {э}" for э in эталонов))
    куски.append(ФОРМА[какая].strip())
    return "\n\n".join(куски)
