"""Инструкции модели: поставляемая и своя.

## Уровня два, а не три

У профиля субтитров их четыре, и каждый заслужен: стиль попадает
в готовый файл, и копия в видео нужна, чтобы правка «моего стиля»
не устаревала чужие ролики.

**Инструкция не попадает в файл ни одним пикселем.** Ролик от её правки
не устаревает и в штамп сборки она не входит — как и само описание.
Значит копии в видео заводить не за чем: двадцать копий одного текста,
расходящихся молча, это не гибкость, а беда.

Уровня два: поставляемая в репозитории и своя в `~/.vertcut/`.
Как со стилем — «вернуть базовую» на экране это просто стереть свою.

## Форму ответа задаёт сервис, и она не правится

Дизайн говорит это прямо, и правило дорогое: инструкцию человек правит
руками, а от формы ответа зависит, разберётся ли ответ вообще. Пусти
форму в правку — и первая же вольность («пиши просто списком»)
превратилась бы в «сервис перестал понимать модель», а виноватым
выглядел бы сервис.

Поэтому склейка: **сверху то, что человек правит, снизу то, что
не правится никогда.**

## Язык — из самого текста, и определителя нет

**Решение сессии, и оно короче, чем кажется.** Расшифровка уже лежит
в запросе; ниже стоит строка «отвечай на языке расшифровки». Заводить
отдельное поле «язык видео» значило бы завести вторую правду: у старых
разборов его нет вовсе, а у новых он мог бы разойтись с текстом —
и тогда сервис знал бы про видео две разные вещи, а какая из них верна,
проверить было бы нечем.

Механическая проверка у этого есть, и она честная: азбука ответа
сверяется с азбукой запроса — счётом букв, а не суждением. Разошлись
— сервис говорит об этом словами. Это `text.азбука`.
"""

from __future__ import annotations

from . import layout

ФРАГМЕНТЫ, ОПИСАНИЯ, ВЫЧИТКА = "фрагменты", "описания", "вычитка"
