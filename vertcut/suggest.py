"""Кандидаты во фрагменты: спросить модель, разобрать, отсеять негодное.

## Это ярлык к существующей дороге, а не третий способ

Главная дорога выбора куска — ручная, и остаётся такой. Кандидат
не создаёт ничего: он превращается в ту же пару номеров фраз, которую
человек назвал бы щелчками по списку, и дальше всё идёт по дороге,
которой четыре сессии. **Автор подтверждает всегда.**

Отсюда и то, чего здесь нет: кандидат не становится вертикалкой сам,
даже если он хорош, и десять кандидатов не создают десяти вертикалок
одной кнопкой.

## Что сервис проверяет, а что нет

**Проверяет механическое:**

- номера фраз существуют и идут по порядку;
- кусок не короче порога — того самого единственного порога сервиса;
- кандидаты не пересекаются между собой ни одной фразой;
- кандидат не повторяет уже созданную вертикалку.

**Не проверяет ничего про качество.** Ни связности, ни силы крючка,
ни оценки моделью самой себя. Число, которое выглядит замером, но им
не является, — худший вид самообмана: оно выглядит как знание,
и по нему начинают принимать решения.

## Негодные не прячутся

Правило дизайна, и оно верное: причина часто интереснее самого
предложения. «Не годится: 12 с — короче порога 15 с» говорит человеку
про его материал больше, чем ещё один годный кусок.

## Непересечение — работа СЕРВИСА, а не просьба к модели

Просьба в инструкции есть, но верить ей нельзя: два ролика с общей
серединой — брак, видный только на публикации, а модель просьбу
может и не выполнить. Поэтому пересечение ловится счётом, и первый
кандидат побеждает: он назван моделью раньше, а другого основания
предпочесть один другому у сервиса нет.

## Ответ ложится файлом ДО разбора

Разбор может не удаться — модель обернула json в разметку, назвала
поле иначе, оборвалась на потолке, — а деньги уже заплачены. Без
сырого файла человек видит «не разобралось» и не может даже
посмотреть, что именно он купил.
"""

from __future__ import annotations

import json
import re
from datetime import datetime
from pathlib import Path

from . import layout, pick, plate, prompts, speech, subs, tuning, works
from .errors import VertcutError


def спросить(project: Path, laid: dict, meta: dict, *,
             разрешено_дорого: bool = False, на_ходу=None) -> dict:
    """Попросить модель предложить фрагменты. Пишет два файла и отдаёт разбор.

    **Хозяин берётся ЗДЕСЬ, внутри работы, а не снаружи.** Поставь его
    в веб-слое — и между «проверили» и «начали» поместится целая чужая
    команда. Работа тут не долгая, а платная: два нажатия подряд стоили
    бы вдвое.
    """
    from . import ai
    from . import spend as spend_

    файл_работы = layout.ai_work(project)
    works.взять(файл_работы, "AI suggestions")
    try:
        текст = _что_показать_модели(laid, meta,
                                     plate.секунд_у(project))
        if на_ходу:
            from . import report
            на_ходу("asking about "
                    + report.счёт(len(laid["phrases"]), "phrase", "phrases")
                    + "…")
        ответ = ai.спросить(prompts.собрать(prompts.ФРАГМЕНТЫ), текст,
                            потолок=tuning.ПОТОЛОК_КАНДИДАТОВ,
                            разрешено_дорого=разрешено_дорого,
                            задача=spend_.КАНДИДАТЫ)
        layout.suggestions_raw(project).write_text(ответ.текст,
                                                   encoding="utf-8")
        это = _разобрать(project, laid, ответ)
        _записать(project, это)
        return это
    finally:
        works.отпустить(файл_работы)


def прочитать(project: Path) -> dict | None:
    """Что предложено в прошлый раз. Нет файла — None, это не ошибка."""
    файл = layout.suggestions(project)
    if not файл.exists():
        return None
    try:
        это = json.loads(файл.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        raise VertcutError(
            f"The AI suggestions file is damaged: {файл}",
            hint="delete it and ask again") from None
    return это if isinstance(это, dict) else None


def свежие_ли(project: Path, laid: dict, это: dict | None) -> bool:
    """Не перенарезаны ли фразы с тех пор, как это спрашивали.

    **Та же беда, что со штампом сборки, и решается так же.** Номера
    фраз переезжают: поменяли правило нарезки — и кандидат «фразы
    247–269» показывает на другое место видео. Отпечаток фраз считает
    то же место, что и штамп сборки.
    """
    if not это:
        return False
    было = это.get("отпечаток_фраз")
    return bool(было) and было == _отпечаток(laid)


def убрать(project: Path) -> None:
    """Стереть предложения. Кнопка «убрать все» из дизайна."""
    layout.suggestions(project).unlink(missing_ok=True)
    layout.suggestions_raw(project).unlink(missing_ok=True)


# ─────────────────────────────────────────────────────────────────────
# Что уезжает модели
# ─────────────────────────────────────────────────────────────────────

def _что_показать_модели(laid: dict, meta: dict,
                         хвост: float = 0.0) -> str:
    """Расшифровка фразами: номер, длительность, текст.

    **Длительность каждой фразы даётся нарочно.** Порог длины сервис
    проверит сам, но модель, не знающая секунд, предложит пять кусков
    по восемь секунд — и все пять окажутся негодными. Дать ей считать
    самой дешевле, чем показать человеку пять отказов.
    """
    # Часть запроса к модели, а не экрана: переводится вместе
    # с инструкциями модели (`prompt-*.txt`).
    строки = [
        f"The video is {_минуты(float(meta.get('duration') or 0))} long "
        f"and has {len(laid['phrases'])} phrases.",
        f"Vertcut won't take segments {pick.короче_порога(хвост)} — "
        "they won't even be shown.",
        "",
        "Transcript: phrase number, its length, text.",
        "",
    ]
    for фраза in laid["phrases"]:
        длина = фраза["end"] - фраза["start"]
        строки.append(f'{фраза["idx"]}\t{длина:.1f}s\t{фраза["text"]}')
    строки.append(prompts.ПРО_ЯЗЫК)
    return "\n".join(строки)


def _минуты(секунд: float) -> str:
    return f"{int(секунд // 60)}:{int(секунд % 60):02d}"


# ─────────────────────────────────────────────────────────────────────
# Что приезжает обратно
# ─────────────────────────────────────────────────────────────────────

def _разобрать(project: Path, laid: dict, ответ) -> dict:
    сырое = _вынуть_json(ответ.текст)
    ряд = сырое.get("фрагменты") if isinstance(сырое, dict) else None
    if not isinstance(ряд, list):
        raise VertcutError(
            "Could not read the AI answer: it has no list of segments",
            hint=f"the full answer is saved here: "
                 f"{layout.suggestions_raw(project)}. The request is paid "
                 "for — look at what came back before asking again")

    вышло = _проверить_все(project, laid, ряд)

    return {
        "когда": datetime.now().astimezone().isoformat(timespec="seconds"),
        "модель": ответ.модель,
        "вошло": ответ.вошло, "вышло": ответ.вышло,
        "деньги": ответ.деньги, "секунд": ответ.секунд,
        "оборвался": ответ.оборвался,
        "отпечаток_фраз": _отпечаток(laid),
        # Язык считается, а не оценивается: азбука ответа против азбуки
        # расшифровки. Испанский от английского так не отличить, и это
        # сказано вслух там, где считается.
        "язык_разошёлся": _язык_разошёлся(laid, вышло),
        "предложения": вышло,
        "годных": sum(1 for э in вышло if э["годен"]),
    }


def _проверить_все(project: Path, laid: dict, ряд: list) -> list[dict]:
    """Проверить весь список сразу — и при разборе, и при удалении.

    **Одно место, и это важнее, чем кажется.** Убрали кандидата рукой
    — и тот, что был негоден «пересекается с предложением выше»,
    может стать годным: пересекаться больше не с чем. Проверь удаление
    отдельным кодом — и причина осталась бы висеть, указывая на то,
    чего уже нет.
    """
    всего_фраз = len(laid["phrases"])
    уже = _что_уже_есть(project, laid)
    # Порог длины растёт вместе с плашкой в конце. Спрашивается один
    # раз на весь список: он один на всё видео.
    хвост = plate.секунд_у(project)
    вышло, занято = [], []
    for это in ряд:
        # Номер СВОЙ, если он уже есть: он назван моделью, и человек
        # видел его на экране. Перенумеровать после удаления значило бы
        # переименовать всё, на что он только что смотрел.
        n = это.get("н") if isinstance(это, dict) and это.get("н") \
            else len(вышло) + 1
        разбор = _один(это, n, всего_фраз, laid, занято, уже, хвост)
        if разбор["годен"]:
            занято.append((разбор["с"], разбор["по"]))
        вышло.append(разбор)
    return вышло


def убрать_одно(project: Path, laid: dict, н: int) -> dict:
    """Убрать одно предложение. Остальные проверяются заново.

    Заново — потому что негодность бывает относительной: «пересекается
    с предложением выше» перестаёт быть правдой, как только того
    предложения не стало.
    """
    это = прочитать(project)
    if not это:
        raise VertcutError("There are no AI suggestions to remove")
    осталось = [э for э in это["предложения"] if э["н"] != н]
    if len(осталось) == len(это["предложения"]):
        raise VertcutError(f"Suggestion #{н} is not in the list")
    это["предложения"] = _проверить_все(project, laid, осталось)
    это["годных"] = sum(1 for э in это["предложения"] if э["годен"])
    _записать(project, это)
    return это


def _один(это, n: int, всего_фраз: int, laid: dict,
          занято: list, уже: dict, хвост: float = 0.0) -> dict:
    """Один кандидат: годен ли, а если нет — почему словами."""
    разбор = {"н": n, "название": _строкой(это, "название"),
              "о_чём": _строкой(это, "о_чём"),
              "с": None, "по": None, "duration": None,
              "годен": False, "почему": None, "есть_ключ": None}
    if not isinstance(это, dict):
        разбор["почему"] = "the model sent something that is not a suggestion"
        return разбор

    с, по = _цел(это.get("с")), _цел(это.get("по"))
    if с is None or по is None:
        разбор["почему"] = "the model did not give phrase numbers"
        return разбор
    разбор["с"], разбор["по"] = с, по
    if с < 1 or по > всего_фраз or с > по:
        разбор["почему"] = (f"there are no phrases {с}–{по}: "
                            f"the video has {всего_фраз}")
        return разбор

    первое, _ = speech.слова_фразы(laid, с)
    _, последнее = speech.слова_фразы(laid, по)
    разбор["duration"] = round(
        laid["phrases"][по - 1]["end"] - laid["phrases"][с - 1]["start"], 1)

    ключ = уже.get((первое, последнее))
    if ключ:
        разбор["есть_ключ"] = ключ

    пересёкся = next((а for а, б in занято if not (по < а or с > б)), None)
    if пересёкся is not None:
        разбор["почему"] = (f"overlaps the suggestion above that starts "
                            f"at phrase {пересёкся}")
        return разбор

    # Сравнение с порогом делает `pick`, а не мы: это единственное
    # число проекта, которое не мерялось ни разу, и второе место,
    # где с ним сравнивают, разъедется с первым. Есть автотест.
    коротко = pick.коротко_словами(разбор["duration"], хвост)
    if коротко:
        разбор["почему"] = коротко
        return разбор

    разбор["годен"] = True
    return разбор


def _что_уже_есть(project: Path, laid: dict) -> dict:
    """Пары слов уже созданных вертикалок.

    Кандидат, повторяющий готовую вертикалку, не отсеивается: он
    помечается «есть» — так его рисует дизайн. Отсеять значило бы
    спрятать то, что модель как раз угадала.
    """
    вышло = {}
    for cut in pick.listing(project):
        куски = pick.ranges(cut)
        if len(куски) == 1:
            вышло[(куски[0][0], куски[0][1])] = cut["id"]
    return вышло


def _вынуть_json(текст: str):
    """Голый json, а не «то, что вокруг него».

    Просим прямо, но надеяться на просьбу нельзя: модели любят обернуть
    ответ в разметку или предварить его строкой «Вот предложения:».
    Берётся первая же скобка и последняя — этого хватает на оба случая
    и не превращается в разбор чужого языка.
    """
    голый = текст.strip()
    голый = re.sub(r"^```(?:json)?\s*|\s*```$", "", голый).strip()
    try:
        return json.loads(голый)
    except json.JSONDecodeError:
        pass
    начало, конец = голый.find("{"), голый.rfind("}")
    if начало >= 0 and конец > начало:
        try:
            return json.loads(голый[начало:конец + 1])
        except json.JSONDecodeError:
            pass
    return None


def _язык_разошёлся(laid: dict, предложения: list) -> bool:
    """Приехал ли ответ на языке видео. Счёт букв, а не суждение."""
    from .text import азбуки_разошлись

    свои = " ".join(ф["text"] for ф in laid["phrases"][:200])
    их = " ".join(f'{э["название"]} {э["о_чём"]}' for э in предложения)
    return азбуки_разошлись(свои, их)


def _отпечаток(laid: dict) -> str:
    """Тот же отпечаток фраз, что и в штампе сборки, — на всё видео."""
    все = [[1, len(laid["words"])]]
    return subs.отпечаток_фраз(laid, все)


def _записать(project: Path, это: dict) -> None:
    layout.suggestions(project).write_text(
        json.dumps(это, ensure_ascii=False, indent=1) + "\n",
        encoding="utf-8")


def _строкой(это, имя: str) -> str:
    if not isinstance(это, dict):
        return ""
    return str(это.get(имя) or "").strip()


def _цел(значение) -> int | None:
    try:
        return int(значение)
    except (TypeError, ValueError):
        return None


def для_экрана(project: Path, laid: dict, meta: dict) -> dict:
    """Всё про предложения одним ответом — и то, во что обойдётся спросить.

    **Цена считается ЗДЕСЬ, а не в веб-слое.** Она складывается
    из размера запроса и прейскуранта, а это числа; их место там, где
    написано их происхождение. Ручка только переводит ответ в json.
    """
    from . import config, spend

    это = прочитать(project)
    свежо = свежие_ли(project, laid, это)
    if свежо:
        _пометить_готовые(project, laid, это)
    оценка = spend.оценить(_что_показать_модели(laid, meta),
                           tuning.ПОТОЛОК_КАНДИДАТОВ, spend.КАНДИДАТЫ)
    return {
        "подключён": config.подключён(),
        "модель": оценка["модель"],
        "оценка": оценка,
        "было": это,
        # Свежесть — про то, не переехали ли номера фраз. Спрашивается
        # рядом с самими предложениями, а не считается на экране:
        # отпечаток фраз считает то же место, что и штамп сборки.
        # Свежесть — про то, не переехали ли номера фраз.
        "свежие": свежо,
    }


def _пометить_готовые(project: Path, laid: dict, это: dict) -> dict:
    """Пересчитать метку «вертикалка уже есть» — в момент ПОКАЗА.

    **Считалась она раньше один раз, при разборе ответа, и лежала
    в файле.** А вертикалку человек создаёт ПОСЛЕ: щёлкнул
    по предложению, нажал «Создать» — и то самое предложение
    по-прежнему выглядит так, будто по нему ничего не сделано. Человек
    видит пятнадцать одинаковых карточек и не помнит, какие из них
    уже отработаны.

    Поэтому метка считается на каждый показ и на диск не ложится:
    вертикалку могли и удалить, и тогда предложение снова свободно.
    Само сравнение то же самое — пары номеров СЛОВ, а не фраз: номера
    фраз переезжают при перенарезке, номера слов нет.

    Зовётся только у свежих предложений. У несвежих номера фраз
    показывают уже на другое место видео, и метка «есть» соврала бы
    про совпадение, которого нет.
    """
    уже = _что_уже_есть(project, laid)
    всего = len(laid["phrases"])
    for э in это.get("предложения", []):
        с, по = э.get("с"), э.get("по")
        э["есть_ключ"] = None
        if not с or not по or с < 1 or по > всего or с > по:
            continue
        первое, _ = speech.слова_фразы(laid, с)
        _, последнее = speech.слова_фразы(laid, по)
        э["есть_ключ"] = уже.get((первое, последнее))
    return это
