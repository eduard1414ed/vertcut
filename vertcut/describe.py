"""Описания моделью: та же кнопка, то же поле, другая метка авторства.

## Здесь не заводится ничего нового

Место для описаний готово с четвёртой сессии: поле в `cut.json`, метка
авторства рядом с ним и экран, на котором их правят руками. Модели
остаётся заполнять **то же самое поле** и ставить метку «AI».

Отсюда всё остальное. Описание, написанное моделью, ничем не отличается
от написанного рукой: правится там же, стирается так же, в штамп сборки
не входит (оно не попадает в файл ни одним пикселем), и человек может
поправить его немедленно — метка тогда сменится на «правится», а потом
на «ваше».

## Одна просьба на все вертикалки, а не по одной

Дизайн рисует и то и другое: кнопку у каждой карточки и общую внизу.
Обе идут сюда, и обе — ОДНА просьба к модели: список ключей на входе,
список подписей на выходе.

Причина не в экономии. **Описания одного видео должны отличаться друг
от друга**, и это единственное, что сервис вообще может про них
проверить, — он и проверяет, механически, счётом одинаковых начал.
Модель, которая видит все подписи сразу, не начнёт три из них словами
«Как жить…»; модель, которую спрашивают по одной, не знает про
остальные ничего.

## Эталонные подписи — необязательная настройка

У предка инструкция снималась с десятка настоящих подписей автора.
У чужого человека эталона нет, и требовать его значило бы закрыть
кнопку тому, кто ещё ничего не публиковал. Нет эталонов — модель пишет
по одной инструкции, и сервис об этом говорит.

## Модель видит начало всего видео, а не только ролик

Первый заход отдавал ей одну речь ролика, и на живом видео это дало
подпись в 330 знаков — пересказ первых двух предложений ролика. Модель
не знала, о чём видео и как зовётся то, что в нём разбирают, и честно
пересказывала единственное, что ей дали. Теперь вместе с роликами
уезжают имя файла видео и его первые фразы: так же было у предка,
и там подписи называли произведение, а не пересказывали кусок.

## Ответ ложится файлом до разбора

Та же причина, что у кандидатов: разбор может не удаться, а деньги
уже заплачены.
"""

from __future__ import annotations

import json
from datetime import datetime
from pathlib import Path

from . import ingest, layout, notes, pick, prompts, speech, suggest, tuning, works
from .errors import VertcutError


def написать(project: Path, ключи: list[str], *,
             разрешено_дорого: bool = False, на_ходу=None) -> dict:
    """Попросить модель написать подписи этим вертикалкам.

    Хозяин тот же, что у кандидатов: обращение платное, и два нажатия
    подряд стоили бы вдвое.
    """
    from . import ai
    from . import spend as spend_

    ролики = [pick.load(project, ключ) for ключ in ключи]
    if not ролики:
        raise VertcutError(
            "No clips were named to write descriptions for",
            hint="to write them for every clip that has none, use the "
                 "button at the bottom of the Descriptions screen")

    файл_работы = layout.ai_work(project)
    works.взять(файл_работы, "AI descriptions")
    try:
        if на_ходу:
            from . import report
            на_ходу("asking about "
                    + report.счёт(len(ролики), "clip", "clips") + "…")
        ответ = ai.спросить(
            prompts.собрать(prompts.ОПИСАНИЯ, prompts.эталоны()),
            _что_показать_модели(project, ролики),
            потолок=tuning.ПОТОЛОК_ОПИСАНИЯ,
            разрешено_дорого=разрешено_дорого,
            задача=spend_.ОПИСАНИЯ)
        layout.notes_raw(project).write_text(ответ.текст, encoding="utf-8")
        return _разобрать(project, ролики, ответ)
    finally:
        works.отпустить(файл_работы)


def без_описания(project: Path) -> list[str]:
    """Ключи вертикалок, у которых подписи нет. Кнопка «написать тому,
    у кого нет» спрашивает именно это."""
    return [о["id"] for о in notes.список(project) if not о["текст"]]


def все_ключи(project: Path) -> list[str]:
    return [о["id"] for о in notes.список(project)]


def оценить(project: Path, ключи: list[str]) -> dict:
    """Во что обойдётся. Считается ЗДЕСЬ: цена складывается из размера
    запроса и прейскуранта, а это числа."""
    from . import spend

    ролики = [pick.load(project, ключ) for ключ in ключи]
    текст = (prompts.собрать(prompts.ОПИСАНИЯ, prompts.эталоны())
             + _что_показать_модели(project, ролики) if ролики else "")
    оценка = spend.оценить(текст or " ", tuning.ПОТОЛОК_ОПИСАНИЯ,
                           spend.ОПИСАНИЯ)
    return {**оценка, "вертикалок": len(ролики)}


# ─────────────────────────────────────────────────────────────────────
# Что уезжает модели
# ─────────────────────────────────────────────────────────────────────

def _что_показать_модели(project: Path, ролики: list[dict]) -> str:
    """О чём всё видео, а потом ключ, длина и сама речь каждого ролика.

    **Речь целиком, а не название.** Название — это первые слова
    ролика, и подпись, написанная по одному названию, пересказывала бы
    его же. Ролик идёт полминуты; его текст — это полсотни слов,
    и дешевле отдать их, чем получить двадцать подписей ни о чём.

    **И начало всего видео рядом.** Без него модель не знает, о чём
    видео, и пересказывает ролик — см. шапку модуля.
    """
    куски = про_видео(project)
    # Часть запроса к модели, а не экрана: переводится вместе
    # с инструкциями модели (`prompt-*.txt`).
    куски += ["Here are the clips. Each has a key, a length and its "
              "transcript.", ""]
    for это in ролики:
        куски.append(f'KEY {это["id"]} · {это["duration"]:.0f} s')
        куски.append(это.get("text") or "(no speech recognized)")
        куски.append("")
    куски.append("Write a description for each. A description is a hook, "
                 "not a summary: don't rephrase the clip's first sentence. "
                 "Descriptions from one video must differ from each "
                 "other — don't start them the same way.")
    куски.append(prompts.ПРО_ЯЗЫК)
    return "\n".join(куски)


def про_видео(project: Path) -> list[str]:
    """Имя файла видео и его первые фразы.

    Его же берёт вычитка субтитров (`proofread`): в начале видео чаще
    всего названы произведение и имена, и по нему модель пишет их так,
    как их пишет видео.

    **Имя файла — подсказка, а не правда,** и модели это сказано: у
    скачанного видео оно бывает набором букв и цифр. Но чаще в нём
    стоит название, и это дешевле всего остального.
    """
    имя = Path(str(ingest.read_meta(project).get("source") or "")).stem
    фразы = speech.read(project)["phrases"][:tuning.ФРАЗ_НАЧАЛА_ДЛЯ_ОПИСАНИЙ]
    куски = []
    if имя:
        куски += [f'The video file is named "{имя}" — it may be the '
                  "title, or it may mean nothing.", ""]
    if фразы:
        куски += ["This is how the whole video begins — not part of any "
                  "clip, just so you know what it's about:",
                  " ".join(ф["text"] for ф in фразы), ""]
    return куски


# ─────────────────────────────────────────────────────────────────────
# Что приезжает обратно
# ─────────────────────────────────────────────────────────────────────

def _разобрать(project: Path, ролики: list[dict], ответ) -> dict:
    сырое = suggest._вынуть_json(ответ.текст)
    ряд = сырое.get("описания") if isinstance(сырое, dict) else None
    if not isinstance(ряд, list):
        raise VertcutError(
            "Could not read the AI answer: it has no list of descriptions",
            hint=f"the full answer is saved here: "
                 f"{layout.notes_raw(project)}. The request is paid "
                 "for — look at what came back before asking again")

    свои = {это["id"] for это in ролики}
    записано, чужие = [], []
    for это in ряд:
        if not isinstance(это, dict):
            continue
        ключ = str(это.get("ключ") or "").strip()
        текст = str(это.get("текст") or "").strip()
        if not ключ or not текст:
            continue
        if ключ not in свои:
            # Модель назвала ключ, которого не спрашивали. Молча
            # записать его нельзя: он может быть чужой вертикалкой,
            # у которой человек уже написал подпись рукой.
            чужие.append(ключ)
            continue
        notes.записать(project, ключ, текст, кто=notes.МОДЕЛЬЮ)
        записано.append(ключ)

    все = notes.список(project)
    return {
        "когда": datetime.now().astimezone().isoformat(timespec="seconds"),
        "модель": ответ.модель,
        "вошло": ответ.вошло, "вышло": ответ.вышло,
        "деньги": ответ.деньги, "секунд": ответ.секунд,
        "оборвался": ответ.оборвался,
        "записано": записано,
        "не_ответила": sorted(свои - set(записано)),
        "чужие_ключи": чужие,
        "язык_разошёлся": _язык_разошёлся(ролики, записано, все),
        # Единственное, что сервис может проверить про качество подписей,
        # — что они не начинаются одинаково. Это счёт, а не суждение.
        "одинаковые": notes.одинаковые_начала(все),
    }


def _язык_разошёлся(ролики: list[dict], записано: list[str],
                    все: list[dict]) -> bool:
    """Приехали ли подписи на языке видео. Счёт букв, а не суждение."""
    from .text import азбуки_разошлись

    свои = " ".join(это.get("text") or "" for это in ролики)
    их = " ".join(о["текст"] for о in все if о["id"] in записано)
    return азбуки_разошлись(свои, их)
