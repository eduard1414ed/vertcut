# в итогах; первая не прошедшая проверка называется своим именем.
_БЕДЫ = {
    ИМЕНА["картинка"]: "Picture — the picture doesn't match your edit",
    ИМЕНА["стыки"]: "Cuts — a cut landed on the wrong frame",
    ИМЕНА["субтитры"]: "Subtitles — they aren't where they should be",
}


def что_не_сошлось(штамп: dict) -> str:
    for итог in итоги(штамп):
        if итог["как"] != "failed":
            continue
        if итог["имя"] == ИМЕНА["плашка"]:
            return f"End card — {итог['подробно']}"
        return _БЕДЫ.get(итог["имя"], итог["имя"])
    return "unknown check"
