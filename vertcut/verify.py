"""Заслоны: готовый файл сверяется с монтажом.

**Зачем их четыре.** Ролик не той длины открывается и выглядит целым,
а внутри чужие минуты — это первый заслон. Файл правильной длины,
со звуком слово в слово, а на седьмом плане чужая колонка — второй.
То же самое, но подмена или склейка уехала на две десятых — третий.
И четвёртый: всё то же самое, но субтитров нет вовсе или они съехали.

**Первые три заслона субтитра не видят вовсе** — сверка кадра как раз
выбрасывает занятые им пиксели. Поэтому пустой или съехавший слой
прошёл бы их молча, и четвёртый заслон не украшение.

**Сверка не всесильна, и она об этом говорит.** На статичном тёмном
плане она подтвердит что угодно, поэтому рядом с каждой связью
считается КОНТРОЛЬ: тот же кадр, но с нарочно сдвинутой колонкой.
Не заметно лучше контрольного — у проверки нет силы, и она печатает
свой запас числом.

**Чего сверка не ловит, названо вслух:** она сверяет файл с монтажом,
а не монтаж с замыслом человека. Поставили рамку не туда — промолчит,
потому что файл собран точно как записано.
"""

from __future__ import annotations

import shutil
import tempfile
from pathlib import Path

from . import chain, layout, media, subs, tuning
from .errors import VertcutError

# Размер, до которого ужимаются оба кадра перед сравнением.
#
# Сравнивать 1080×1920 напрямую нельзя: между исходником и готовым
# файлом лежат два сжатия и одно масштабирование, и на полном размере
# они дают заметную рябь даже там, где картинка та же самая. Ужатие
# до 135 пикселей эту рябь стирает, а промах колонки — нет: он сдвигает
# картинку на треть кадра, и в ужатом виде это треть кадра.
СРАВНИВАТЬ_ШИРИНОЙ = 135

# Насколько сдвигается колонка в контрольном замере, долями ширины.
# Половина окна: контроль показывает картинку, которая пересекается
# с настоящей ровно наполовину.
КОНТРОЛЬ_СДВИГ = 0.079

# Сколько кадров смотреть вокруг заказанной секунды.
#
# Кадр из готового файла и кадр из исходника на той же секунде ложатся
# на соседние кадры: поиск по сжатому видео встаёт на ближайший,
# а «ближайший» у HEVC и у H.264 разный. На плане с быстрым движением
# соседние кадры непохожи — замер: свой кадр 0.848, соседний 0.9996.
ЛЕНТА = 2

# Стыки: два кадра по обе стороны склейки — насколько они непохожи.
# Отступ в два кадра, а не в один: на самой склейке иногда стоит
# смазанный кадр перехода, похожий на обе стороны сразу.
СТЫК_ОТСТУП = 2

# Сколько точек берётся на четвёртый заслон. Больше не нужно: он
# отвечает на вопрос «есть ли субтитр и там ли он», а не «правильный
# ли в нём текст».
СУБТИТР_ТОЧЕК = 8

# Отступ от краёв плашки, в кадрах. Тот же, что у стыков, и по той же
# причине: на самой границе стоит кадр, который может оказаться
# по любую её сторону.
ПЛАШКА_ОТСТУП = 2


def связь(a, b, мимо=None) -> float:
    """Связь двух картинок: от −1 до 1. Единица — одно и то же.

    Не разность яркостей: между исходником и готовым файлом стоит
    пересжатие, и оно двигает яркость целиком. Связь на такой сдвиг
    не реагирует, а на «другое место кадра» реагирует сразу.

    `мимо` — маска пикселей, которые не спрашиваем. Ими закрыт субтитр.
    Пиксели именно ВЫБРАСЫВАЮТСЯ, а не заливаются ровным цветом:
    заливка сдвинула бы среднее и подкрутила бы связь на всём
    остальном кадре.
    """
    import numpy

    if мимо is not None:
        оставить = ~мимо.ravel()
        if оставить.sum() < 64:
            # От кадра ничего не осталось. Такого быть не должно, но
            # молча возвращать «сошлось» на пустом сравнении нельзя.
            return 0.0
        a, b = a.ravel()[оставить], b.ravel()[оставить]
    x, y = a.ravel() - a.mean(), b.ravel() - b.mean()
    низ = float(numpy.sqrt((x * x).sum() * (y * y).sum()))
    # РОВНЫЙ КАДР НЕ КОРРЕЛИРУЕТСЯ ВОВСЕ, и черта тут не «ровно ноль».
    #
    # Раньше здесь стояло `низ == 0` — то есть ветка ловила только
    # идеально одноцветный кадр, чёрное затемнение. А беда приходит
    # с почти ровным: белая вспышка на стыке даёт разброс 0.03, после
    # вычитания среднего в ней остаётся шум пересжатия, и связь двух
    # шумов — монетка. Монетка легла 0.5666 при пороге 0.9, и сверка
    # объявила исправный файл битым.
    #
    # Поймано сквозным прогоном на живом видео; замер и черта —
    # в `tuning.FLAT_SPREAD`. Ровные сравниваются средней яркостью:
    # белая вспышка вместо чёрного затемнения — это всё ещё поломка.
    if (низ == 0 or float(numpy.std(x)) < tuning.FLAT_SPREAD
            or float(numpy.std(y)) < tuning.FLAT_SPREAD):
        return (1.0 if abs(float(a.mean()) - float(b.mean()))
                < tuning.FLAT_TOLERANCE else 0.0)
    return round(float((x * y).sum() / низ), 4)


def _маска(рект, высота_ленты: int, out_w: int, out_h: int, w: int, h: int):
    """Где в уменьшенной картинке лежит субтитр.

    `высота_ленты` — высота той картинки, которую сравниваем. У плана
    «полный кадр» сверяется только лента посередине, и субтитр под ней
    в сравнение не попадает вовсе; тогда маска либо съезжает вместе
    с лентой, либо не нужна.
    """
    import numpy

    if рект is None:
        return None
    маска = numpy.zeros((h, w), dtype=bool)
    верх = 0 if высота_ленты == out_h else (out_h - высота_ленты) // 2
    y0, y1 = рект[1] - верх, рект[3] - верх
    y0, y1 = max(0, y0), min(высота_ленты, y1)
    if y1 <= y0:
        return None
    kx, ky = w / out_w, h / высота_ленты
    x0, x1 = max(0, int(рект[0] * kx)), min(w, int(numpy.ceil(рект[2] * kx)))
    маска[max(0, int(y0 * ky)):min(h, int(numpy.ceil(y1 * ky))), x0:x1] = True
    return маска if маска.any() else None


def _вырезать_ленту(кадр, высота_ленты: int):
    """Середина кадра высотой с ленту. Полная высота — кадр как есть."""
    if высота_ленты >= кадр.shape[0]:
        return кадр
    верх = (кадр.shape[0] - высота_ленты) // 2
    return кадр[верх:верх + высота_ленты]


def _картинка(путь: Path):
    import numpy
    from PIL import Image

    with Image.open(путь) as кадр:
        return numpy.asarray(кадр.convert("L"), dtype=float)


def _мелко(картинка, ширина: int = СРАВНИВАТЬ_ШИРИНОЙ):
    import numpy
    from PIL import Image

    высота = max(1, round(картинка.shape[0] * ширина / картинка.shape[1]))
    мелкая = Image.fromarray(картинка.astype("uint8")).resize(
        (ширина, высота), Image.BILINEAR)
    return numpy.asarray(мелкая, dtype=float)


def каким_обязан_быть(кадр: Path, ряд: dict, width: int, height: int,
                      cx: float | None = None):
    """Каким кадр обязан выйти в ролике. ТОЙ ЖЕ геометрией, что сборка.

    Собирается из кадра исходника теми же числами, которыми цепочка
    пишет фильтр. Своей геометрии здесь нет и быть не должно: две
    геометрии разойдутся, и сверка начнёт ругаться на исправное.
    """
    import numpy
    from PIL import Image

    with Image.open(кадр) as картинка:
        полный = картинка.convert("RGB")
        ш, в = полный.size
        k = ш / width
        если_cx = ряд["cx"] if cx is None else cx
        if ряд["mode"] == "full":
            # Полный кадр вписан по ширине; сверяем ЛЕНТУ посередине,
            # а размытые поля не сверяем вовсе — они собраны фильтром,
            # а не взяты из исходника.
            лента = полный.resize((tuning.VERTICAL_W,
                                   max(2, round(в / ш * tuning.VERTICAL_W))),
                                  Image.BILINEAR)
            return numpy.asarray(лента.convert("L"), dtype=float), лента.size[1]
        коробка = chain.коробка_окна(width, height, если_cx, k)
        колонка = полный.crop(коробка).resize(
            (tuning.VERTICAL_W, tuning.VERTICAL_H), Image.BILINEAR)
        return numpy.asarray(колонка.convert("L"), dtype=float), tuning.VERTICAL_H


def внутри(отрезок: dict, at: float, fps: float) -> bool:
    """Ляжет ли вынутый на секунде `at` кадр внутрь этого отрезка.

    Вынимается не тот кадр, чьё время названо, а ПЕРВЫЙ, чьё время
    не меньше названного. Значит проверять надо не точку, а кадр
    целиком: точка в двух сотых от конца отрезка вытащит уже следующий
    кадр — а там другой план.
    """
    кадр = 1.0 / fps
    return отрезок["at"] - 1e-9 <= at and at + кадр <= отрезок["till"] + 1e-9


def точки(отрезки: list[dict], fps: float) -> list[dict]:
    """На каких секундах ролика сверяться: по кадру из середины отрезка.

    У краёв стоит монтажный стык, и промах на кадр туда-сюда дал бы
    ложную тревогу на исправном файле.
    """
    кадр = 1.0 / fps
    вышло = []
    for отрезок in отрезки:
        n = int(round((отрезок["at"] + отрезок["till"]) / 2 * fps))
        at = round((n + 0.5) * кадр, 4)
        if (отрезок["till"] - отрезок["at"] < 2 * кадр
                or not внутри(отрезок, at, fps)):
            вышло.append({"idx": отрезок["idx"], "at": None, "n": None,
                          "отрезок": отрезок})
            continue
        вышло.append({"idx": отрезок["idx"], "n": n, "at": at,
                      "отрезок": отрезок})
    return вышло


def края(отрезки: list[dict], fps: float) -> list[dict]:
    """Точки у краёв отрезков, где надо посмотреть отдельно.

    Сверка по середине отвечает на вопрос «та ли картинка», но не
    на вопрос «с той ли секунды». Проверяются не все стыки, а только
    те, где что-то МЕНЯЕТСЯ: другая колонка или другой режим кадра.
    Там, где по обе стороны одно и то же окно, промах во времени
    ничего не портит — менять нечего.

    По две точки на стык: раньше него и позже. Одна поймала бы только
    опоздание, а уехать можно в обе стороны.
    """
    кадр = 1.0 / fps
    вышло = []
    for левый, правый in zip(отрезки, отрезки[1:]):
        меняется = (левый["cx"] != правый["cx"]
                    or левый["mode"] != правый["mode"])
        if not меняется:
            continue
        где = правый["at"]
        for отрезок, знак in ((левый, -1), (правый, +1)):
            n = int(round(где * fps)) + знак * СТЫК_ОТСТУП
            at = round((n + 0.5) * кадр, 4)
            if not внутри(отрезок, at, fps):
                continue
            вышло.append({"idx": отрезок["idx"], "n": n, "at": at,
                          "отрезок": отрезок, "край": round(где, 3),
                          "сторона": "до" if знак < 0 else "после"})
    return вышло


def по_планам(project: Path, meta: dict, cut: dict, rows: list[dict],
              source: Path, раскл: dict | None = None,
              prof: dict | None = None, ход=None) -> dict:
    """Сверить готовый файл с монтажом кадра. Возвращает отчёт.

    Ничего не чинит и ничего не переписывает: считает числа и отдаёт
    их наверх. Решение «это поломка» принимает сборка — там же, где
    стоит заслон на длину.

    `ход` — кому рассказывать, сколько точек уже посмотрено. Этот
    заслон — треть времени сборки (замер: 8.2 с из 25.25 на ролике
    46 с), и молчать эту треть значит показывать человеку замерший
    экран.
    """
    ход = ход or (lambda *_а, **_к: None)
    from . import plans

    duration = float(meta["duration"])
    fps = float(meta.get("fps") or 25)
    таблица = plans.карта(cut, duration, fps)
    готовый = layout.out(project, cut)
    ширина, высота = int(meta["width"]), int(meta["height"])

    работа = Path(tempfile.mkdtemp(prefix="vertcut-check-"))
    точек, худшая, запасы = [], None, []
    все_точки = точки(rows, fps) + края(rows, fps)
    try:
        for сделано, точка in enumerate(все_точки):
            ход("Checking picture and cuts", сделано, len(все_точки), "frames")
            if точка["at"] is None:
                точек.append({"idx": точка["idx"], "связь": None,
                              "почему": "shorter than two frames"})
                continue
            отрезок = точка["отрезок"]
            # Кадр готового файла — по НОМЕРУ, а не по секунде.
            свой = media.grab_frames(
                готовый, [media.frame_time(точка["n"], fps,
                                           таблица["смещение"])],
                работа / f"file-{точка['n']}", tuning.VERTICAL_W)[0]
            # Та же секунда в исходнике: лента вокруг, потому что сетки
            # кадров у двух файлов разные.
            в_видео = отрезок["essay0"] + (точка["at"] - отрезок["t0"])
            лента = media.grab_run(
                source, media.frame_time(int(round(в_видео * fps)) - ЛЕНТА,
                                         fps),
                2 * ЛЕНТА + 1, работа / f"video-{точка['n']}", ширина)

            рект = (subs.занято(раскл, prof, точка["at"])
                    if раскл is not None and prof is not None else None)
            полный_кадр = _картинка(свой)
            лучшее, лучший_сдвиг = -2.0, 0
            for сдвиг, кадр_видео in enumerate(лента, -ЛЕНТА):
                ждали, высота_ленты = каким_обязан_быть(кадр_видео, отрезок,
                                                        ширина, высота)
                # У плана «полный кадр» сверяется ЛЕНТА посередине:
                # размытые поля собраны фильтром, а не взяты
                # из исходника, и сравнивать их не с чем.
                наш = _вырезать_ленту(полный_кадр, высота_ленты)
                мелкий_наш = _мелко(наш)
                маска = _маска(рект, высота_ленты, tuning.VERTICAL_W,
                               tuning.VERTICAL_H, мелкий_наш.shape[1],
                               мелкий_наш.shape[0])
                если = связь(мелкий_наш, _мелко(ждали), маска)
                if если > лучшее:
                    лучшее, лучший_сдвиг = если, сдвиг
            # Контроль: тот же кадр, но с нарочно сдвинутой колонкой.
            # Не заметно лучше контрольного — у проверки нет силы.
            середина = лента[len(лента) // 2]
            свой_cx = 0.5 if отрезок["cx"] is None else float(отрезок["cx"])
            контроль_cx = свой_cx + КОНТРОЛЬ_СДВИГ
            if контроль_cx > 1 - КОНТРОЛЬ_СДВИГ:
                контроль_cx = свой_cx - КОНТРОЛЬ_СДВИГ
            иначе, высота_ленты = каким_обязан_быть(середина, отрезок,
                                                    ширина, высота,
                                                    cx=контроль_cx)
            мелкий_наш = _мелко(_вырезать_ленту(полный_кадр, высота_ленты))
            маска = _маска(рект, высота_ленты, tuning.VERTICAL_W,
                           tuning.VERTICAL_H, мелкий_наш.shape[1],
                           мелкий_наш.shape[0])
            контроль = связь(мелкий_наш, _мелко(иначе), маска)
            запас = round(лучшее - контроль, 4)
            запасы.append(запас)
            точек.append({"idx": точка["idx"], "at": точка["at"],
                          "связь": лучшее, "контроль": контроль,
                          "запас": запас, "сдвиг_кадра": лучший_сдвиг,
                          "сторона": точка.get("сторона")})
            if худшая is None or лучшее < худшая:
                худшая = лучшее
    finally:
        shutil.rmtree(работа, ignore_errors=True)

    посчитанных = [т for т in точек if т["связь"] is not None]
    return {
        "точек": len(посчитанных),
        "худшая": худшая,
        "порог": tuning.VERIFY_MIN,
        "сошлось": bool(посчитанных) and худшая >= tuning.VERIFY_MIN,
        "запас": min(запасы) if запасы else None,
        "слабая": bool(запасы) and min(запасы) < 0.05,
        # Та же сверка, разложенная на два вопроса: середины планов
        # отвечают «та ли картинка», точки у стыков — «с того ли
        # кадра». Порог один, сошлось всё — только если сошлись оба.
        "середины": _итог([т for т in посчитанных if т["сторона"] is None]),
        "края": _итог([т for т in посчитанных if т["сторона"] is not None]),
        "точки": точек,
    }


def _итог(точки_: list[dict]) -> dict:
    худшая = min((т["связь"] for т in точки_), default=None)
    return {"точек": len(точки_), "худшая": худшая,
            "сошлось": худшая is None or худшая >= tuning.VERIFY_MIN}


def субтитры(project: Path, meta: dict, cut: dict, раскл: dict,
             prof: dict, font) -> dict:
    """Четвёртый заслон: субтитр есть и стоит на месте.

    Плашка строки непрозрачна, значит внутри неё пиксели готового файла
    обязаны совпасть с нарисованными. Сравнивается ТОЛЬКО там, где
    у слоя полная краска.

    **Порогов два, и это замер, а не небрежность.** С плашкой, обводкой
    или тенью в сплошной краске лежат два сильно разных уровня, и связь
    на верном файле — 0.999. При подложке «без» краска только в буквах,
    уровня два близких, и верный файл даёт 0.572…0.999. Порог, который
    ловит сдвиг на два пикселя с плашкой, отверг бы исправное без неё.
    Числа и почему одним не обойтись — в `tuning.py`.

    **Рядом считается КОНТРОЛЬ** — та же сверка, но со слоем, нарочно
    сдвинутым вниз. Заслон обязан говорить о своей силе: на короткой
    однословной фразе краски мало, и запас печатается числом.
    """
    import numpy

    fps = float(meta.get("fps") or 25)
    готовый = layout.out(project, cut)
    показы = раскл["показы"]
    if not показы:
        return {"точек": 0, "худшая": None, "сошлось": False,
                "почему": "the clip has no subtitles"}

    шаг = max(1, len(показы) // СУБТИТР_ТОЧЕК)
    выбранные = показы[::шаг][:СУБТИТР_ТОЧЕК]
    работа = Path(tempfile.mkdtemp(prefix="vertcut-subtitles-"))
    точек, худшая, запасы = [], None, []
    try:
        for показ in выбранные:
            середина = (показ["at"] + показ["till"]) / 2
            n = int(round(середина * fps))
            кадр = media.grab_frames(
                готовый, [media.frame_time(n, fps)],
                работа / f"s-{n}", tuning.VERTICAL_W)[0]
            рект = subs.занято(раскл, prof, середина)
            if рект is None:
                continue
            нарисовано = subs.нарисовать(показ["страница"], показ["сказано"],
                                         показ["низ"], prof, font)
            слой = numpy.asarray(нарисовано)
            альфа = слой[:, :, 3]
            плотно = альфа >= 250
            x0, y0, x1, y1 = рект
            окно_плотно = плотно[y0:y1, x0:x1]
            if окно_плотно.sum() < 200:
                continue
            наш = numpy.asarray(_картинка(кадр))[y0:y1, x0:x1]
            ждали = numpy.asarray(
                нарисовано.convert("L"), dtype=float)[y0:y1, x0:x1]
            если = связь(наш[окно_плотно], ждали[окно_плотно])
            # Контроль: тот же слой, нарочно сдвинутый вниз. Показывает
            # не «правильно ли», а «есть ли у проверки сила».
            иначе = subs.нарисовать(
                показ["страница"], показ["сказано"],
                показ["низ"] + tuning.SUBS_CONTROL_SHIFT, prof, font)
            контроль = связь(
                наш[окно_плотно],
                numpy.asarray(иначе.convert("L"),
                              dtype=float)[y0:y1, x0:x1][окно_плотно])
            запасы.append(round(если - контроль, 4))
            точек.append({"at": round(середина, 3), "связь": если,
                          "контроль": контроль,
                          "запас": round(если - контроль, 4),
                          "фраза": показ["фраза"]})
            if худшая is None or если < худшая:
                худшая = если
    finally:
        shutil.rmtree(работа, ignore_errors=True)

    порог = (tuning.SUBS_MIN if prof.get("подложка", subs.ПЛАШКА) != subs.БЕЗ
             else tuning.SUBS_MIN_БЕЗ)
    return {"точек": len(точек), "худшая": худшая,
            "порог": порог,
            "сошлось": bool(точек) and худшая >= порог,
            "запас": min(запасы) if запасы else None,
            "слабая": bool(запасы) and min(запасы) < 0.3,
            "точки": точек}


def плашка(project: Path, meta: dict, cut: dict, раскл: dict,
           prof: dict, картинка_плашки: Path, плашка_с: float,
           всего: float) -> dict:
    """Пятый заслон: плашка в конце есть, и стоит она с той секунды.

    **Заведён потому, что первые три заслона под плашку не смотрят
    вовсе.** И это не поблажка: под ней картинки исходника нет —
    там картинка плашки, — и требовать её значит требовать того, чего
    в файле не должно быть. Планы под плашкой погашены ещё в `plans`,
    и сверка кадра против кадра туда просто не заглядывает. Порог 0.9
    от этого не двинулся ни на сотую: он по-прежнему отвечает
    за те же секунды, что и раньше.

    Но секунды плашки без присмотра остаться не могут: молча не лёгшая
    плашка — это ролик, который кончается посреди фразы чужой
    картинкой, и увидит это зритель. Поэтому здесь сверяется ДРУГАЯ
    пара: кадр готового файла против САМОЙ КАРТИНКИ ПЛАШКИ, той,
    что лежит рядом и ушла входом в цепочку.

    **Сравнивается кадр ЦЕЛИКОМ, а не ужатый.** Это урок пятой сверки:
    на 135 пикселях связь выходит ровно 1.00000 — то есть проверка
    показывает идеальное совпадение там, где идеального быть не может,
    и красивое число не значит ничего. Плашка вдобавок неподвижна,
    и ужимать её незачем: ряби от движения тут нет.

    **Пиксели субтитра выбрасываются**, как и у первых трёх: субтитр
    ложится ПОВЕРХ плашки, и спрашивать про них надо у четвёртого
    заслона, который на них и смотрит.

    **Границу проверяет отдельная точка — за два кадра ДО плашки.**
    Там обязана быть картинка, а не плашка; связь у неё обязана быть
    заметно НИЖЕ. Без этой точки плашка, вставшая на полсекунды
    раньше, прошла бы: сами её кадры от этого не портятся.

    **И рядом считается КОНТРОЛЬ** — та же плашка, нарочно сдвинутая.
    Он отвечает не на вопрос «правильно ли», а на вопрос «есть ли
    у проверки сила»: плашка сплошного цвета совпадёт со сдвинутой
    собой, и человек обязан увидеть это числом, а не думать, что его
    ролик проверен.
    """
    import numpy

    fps = float(meta.get("fps") or 25)
    готовый = layout.out(project, cut)
    if not картинка_плашки.exists():
        raise VertcutError(
            f"The end card image isn't next to the clip: {картинка_плашки}",
            hint="it's made during export and kept there; export again")
    ждали_полная = _картинка(картинка_плашки)

    # Три точки внутри плашки и одна перед ней. Внутри её больше
    # не нужно: плашка неподвижна, и все её кадры одинаковы — точки
    # отвечают на вопрос «встала ли и с той ли секунды», а не «какая
    # она».
    кадр = 1.0 / fps
    первый = int(round(плашка_с * fps)) + ПЛАШКА_ОТСТУП
    последний = int(round(всего * fps)) - ПЛАШКА_ОТСТУП
    if последний <= первый:
        raise VertcutError(
            f"The end card is shorter than {2 * ПЛАШКА_ОТСТУП} frames, "
            "so there's nothing to check",
            hint="make the end card longer in the subtitle style")
    середина = (первый + последний) // 2
    точки_плашки = sorted({первый, середина, последний})
    до_плашки = int(round(плашка_с * fps)) - ПЛАШКА_ОТСТУП

    работа = Path(tempfile.mkdtemp(prefix="vertcut-end-card-"))
    точек, худшая, запасы = [], None, []
    до = None
    try:
        for n in точки_плашки + [до_плашки]:
            при = round((n + 0.5) * кадр, 4)
            свой = media.grab_frames(готовый, [media.frame_time(n, fps)],
                                     работа / f"e-{n}", tuning.VERTICAL_W)[0]
            наш = _картинка(свой)
            рект = subs.занято(раскл, prof, при)
            мимо = _прямоугольник(рект, наш.shape)
            если = связь(наш, ждали_полная, мимо)
            внутри_плашки = n != до_плашки
            if внутри_плашки:
                # Контроль: та же плашка, сдвинутая. Показывает силу
                # проверки, а не правильность файла.
                сдвинутая = numpy.roll(ждали_полная,
                                       tuning.PLATE_CONTROL_SHIFT, axis=0)
                контроль = связь(наш, сдвинутая, мимо)
                запасы.append(round(если - контроль, 4))
                точек.append({"at": при, "связь": если, "контроль": контроль,
                              "запас": round(если - контроль, 4)})
                if худшая is None or если < худшая:
                    худшая = если
            else:
                до = {"at": при, "связь": если}
    finally:
        shutil.rmtree(работа, ignore_errors=True)

    порог = tuning.PLATE_MIN
    сошлось = bool(точек) and худшая >= порог
    # Кадр ПЕРЕД плашкой обязан быть картинкой, а не плашкой. Если
    # и он похож на неё, плашка встала раньше заказанного.
    рано = до is not None and до["связь"] >= порог
    if рано:
        сошлось = False
    return {"точек": len(точек), "худшая": худшая, "порог": порог,
            "сошлось": сошлось, "рано": рано, "до_плашки": до,
            "запас": min(запасы) if запасы else None,
            "слабая": bool(запасы) and min(запасы) < tuning.PLATE_ЗАПАС,
            "с": плашка_с, "точки": точек}


def _прямоугольник(рект, форма):
    """Маска «сюда не смотреть» по прямоугольнику в пикселях кадра."""
    import numpy

    if рект is None:
        return None
    маска = numpy.zeros(форма, dtype=bool)
    x0, y0, x1, y1 = рект
    маска[max(0, y0):min(форма[0], y1), max(0, x0):min(форма[1], x1)] = True
    return маска if маска.any() else None


# ─────────────────────────────────────────────────────────────────────
# Пятая сверка: экран против файла
# ─────────────────────────────────────────────────────────────────────
#
# Четыре заслона сверяют ФАЙЛ С МОНТАЖОМ. Ни один из них не отвечает
# на вопрос, который завёлся вместе с экраном: то, что человек ВИДЕЛ
# в предпросмотре, — это то, что попало в файл?
#
# Вопрос не выдуманный. Экран показывает картинку, которую нарисовал
# Pillow; в файл кадр режет ffmpeg. Пока браузер не набирает субтитр
# сам, правда одна — но «одна» это утверждение, а не измерение, и его
# надо уметь перемерить. Правило проекта тут прямое: число, которое
# нельзя перемерить командой, через полгода становится преданием.
#
# **Единицы здесь не будет, и обещать её нельзя.** Предпросмотр рисует
# Pillow, файл режет ffmpeg, и на границах букв разница в один-два
# уровня яркости есть — это записано в `docs/decisions.md` с первой сессии.
# Работа сверки не в том, чтобы получить 1.000, а в том, чтобы число
# было измерено, записано и повторяемо.
#
# **Маска здесь НЕ ставится, и это главное отличие от второго
# заслона.** Тот выбрасывает пиксели субтитра, потому что сверяет
# картинку. Здесь субтитр — самое интересное: сверяется всё вместе.

# Сколько точек смотреть. Столько же, сколько показывает лист «до и
# после»: по представителю каждой породы состояний субтитра.
ЭКРАН_ТОЧЕК = 5

# Сравнивать ЦЕЛИКОМ, не ужимая. Это замер, а не осторожность.
#
# Второй заслон сравнивает кадры, ужав их до 135 пикселей ширины, —
# ему так и надо: он ищет сдвиг колонки на десятки пикселей, и мелкая
# картинка ловит его не хуже, зато вчетверо быстрее.
#
# Здесь ужимание врёт. Замер на собранном ролике, три точки:
#
#   ширина сравнения    связь с файлом      контроль (субтитр сдвинут)
#   135                 1.00000            0.891  0.915  0.990
#   270                 0.99990            0.886  0.911  0.988
#   540                 0.99980            0.882  0.908  0.986
#   1080 (целиком)      0.99960…0.99970    0.879  0.905  0.984
#
# На 135 пикселях связь выходит РОВНО 1.00000 — то есть проверка
# показывает «совпало идеально» там, где идеального совпадения быть
# не может: предпросмотр рисует Pillow, а кадр в файле режет ffmpeg.
# Красивое число, за которым ничего не стоит, хуже некрасивого.
# Целиком получается 0.9996 — оно и есть настоящее.
СРАВНИВАТЬ_ЦЕЛИКОМ = True

# Насколько сдвинуть субтитр в контрольной картинке. Доля высоты
# кадра; при 1920 это 77 пикселей — примерно полторы строки.
#
# Контроль нужен по той же причине, что и у четвёртого заслона:
# на статичном плане с коротким субтитром сверка подтвердит почти
# что угодно, и человек должен видеть запас числом, а не верить
# на слово.
ЭКРАН_СДВИГ = 0.04


def экран_против_файла(project, meta: dict, cut: dict, ряды: list[dict],
                       раскл: dict, prof: dict, шрифт, файл,
                       говорить=None) -> dict:
    """Сверить то, что человек видел на экране, с тем, что легло в файл.

    По точке на состояние субтитра: кадр из готового файла против
    кадра, нарисованного предпросмотром. Рядом — контроль: тот же
    предпросмотр с нарочно сдвинутым субтитром.
    """
    import shutil
    import tempfile

    from . import media, preview, report
    from .errors import VertcutError

    говорить = говорить or report.скажи
    файл = Path(файл)
    if not файл.exists():
        raise VertcutError(
            f"Nothing to compare with: {файл.name} doesn't exist",
            hint="export the clip first")

    from . import subs
    if not subs.в_файле(project, cut):
        raise VertcutError(
            "This clip exports without subtitles, so there's nothing on "
            "screen to compare with the file",
            hint=f"turn them on: vertcut subs {project.name} {cut['id']} --on")
    точки = preview.секунды_показов(раскл, ЭКРАН_ТОЧЕК)
    if not точки:
        raise VertcutError("This clip has no subtitles")

    работа = Path(tempfile.mkdtemp(prefix="vertcut-check-screen-"))
    вышло = []
    try:
        из_файла = media.grab_frames(файл, [т["при"] for т in точки], работа,
                                     prof["width"])
        if len(из_файла) != len(точки):
            raise VertcutError(
                f"Got {len(из_файла)} frames from the file for "
                f"{len(точки)} points, so they can't be compared")
        for точка, кадр_файла in zip(точки, из_файла):
            свой = _из_pillow(preview.кадр(project, meta, cut, ряды, раскл,
                                           prof, шрифт, при=точка["при"]))
            сдвинутый = _из_pillow(_сдвинуть_субтитр(
                project, meta, cut, ряды, раскл, prof, шрифт, точка["при"]))
            есть = _картинка(кадр_файла)
            ширина = prof["width"] if СРАВНИВАТЬ_ЦЕЛИКОМ else СРАВНИВАТЬ_ШИРИНОЙ
            вышло.append({
                "при": точка["при"],
                "связь": round(связь(_мелко(есть, ширина),
                                     _мелко(свой, ширина)), 4),
                "контроль": round(связь(_мелко(есть, ширина),
                                        _мелко(сдвинутый, ширина)), 4),
            })
    finally:
        shutil.rmtree(работа, ignore_errors=True)

    худшая = min(т["связь"] for т in вышло)
    запас = min(т["связь"] - т["контроль"] for т in вышло)
    говорить(f"    {len(вышло)} frames, worst match {худшая}, "
             f"margin over control {запас:+.4f}")
    return {"точки": вышло, "худшая": худшая, "запас": round(запас, 4),
            "сдвиг_контроля": ЭКРАН_СДВИГ}


def _из_pillow(картинка):
    """Картинка Pillow — в ту же форму, в какой сюда приходят кадры
    с диска. Серым, числами: сравнивать надо одинаковое."""
    import numpy

    return numpy.asarray(картинка.convert("L"), dtype=float)


def _сдвинуть_субтитр(project, meta, cut, ряды, раскл, prof, шрифт, при):
    """Тот же кадр, но субтитр нарочно уехал вниз. Это контроль."""
    сдвинутый = {**раскл, "показы": [
        {**п, "низ": п["низ"] + round(prof["height"] * ЭКРАН_СДВИГ)}
        for п in раскл["показы"]]}
    from . import preview
    return preview.кадр(project, meta, cut, ряды, сдвинутый, prof, шрифт,
                        при=при)


# ─────────────────────────────────────────────────────────────────────
# Итоги заслонов — словами для человека
# ─────────────────────────────────────────────────────────────────────
#
# Пять заслонов называются по именам из словаря, и называет их ЗДЕСЬ
# одна функция: экран сборки и отказ сборки говорят одно и то же.
#
# **Не прошедший проверку и не проверявший — разные вещи.** «Cuts»
# смотрят только на стыки, где МЕНЯЕТСЯ рамка или режим кадра; где
# по обе стороны одно окно, смотреть нечего, и честно сказать
# «пропущено», а не «прошло». Штамп, собранный до того, как сверка
# разделилась на картинку и стыки, своих стыков отдельно не знает —
# тогда и сказано: проверены вместе с картинкой.

ИМЕНА = {"длина": "Length", "картинка": "Picture", "стыки": "Cuts",
         "субтитры": "Subtitles", "плашка": "End card"}


def _связь(итог: dict) -> str:
    # Четыре знака, а не три: 0.9999 с тремя знаками становится «1.000»,
    # то есть идеальным совпадением, которого не бывает (см. пятую
    # сверку выше — тот же урок).
    return (f"worst match {итог['худшая']:.4f}, needs {итог['порог']:.2f}"
            f" · {итог['точек']} frames")


def итоги(штамп: dict) -> list[dict]:
    """Пять заслонов по штампу сборки: имя, прошёл ли, коротко почему.

    `как` — `passed`, `failed` или `skipped`; это значение договора
    с экраном, а не слово на нём.
    """
    # Штамп пишется только после заслона на длину: есть штамп —
    # длина сошлась.
    длина = штамп.get("duration")
    вышло = [{"имя": ИМЕНА["длина"], "как": "passed",
              "подробно": (f"{длина:.1f} s, as planned" if длина is not None
                           else "as planned")}]

    сверка = штамп.get("сверка") or {}
    порог = сверка.get("порог", tuning.VERIFY_MIN)
    середины, края = сверка.get("середины"), сверка.get("края")
    if середины is None:
        # Штамп старше разделения: картинка и стыки — одним числом.
        if сверка.get("худшая") is not None:
            вышло.append({"имя": ИМЕНА["картинка"],
                          "как": "passed" if сверка.get("сошлось") else "failed",
                          "подробно": _связь({**сверка, "порог": порог})})
        вышло.append({"имя": ИМЕНА["стыки"], "как": "skipped",
                      "подробно": "checked together with Picture"})
    else:
        вышло.append({"имя": ИМЕНА["картинка"],
                      "как": "passed" if середины["сошлось"] else "failed",
                      "подробно": _связь({**середины, "порог": порог})})
        if края["точек"]:
            вышло.append({"имя": ИМЕНА["стыки"],
                          "как": "passed" if края["сошлось"] else "failed",
                          "подробно": _связь({**края, "порог": порог})})
        else:
            вышло.append({"имя": ИМЕНА["стыки"], "как": "skipped",
                          "подробно": "the crop doesn't change at any cut, "
                                      "so there's nothing to check"})

    с = штамп.get("сверка_субтитров") or {}
    if штамп.get("субтитры") is False:
        вышло.append({"имя": ИМЕНА["субтитры"], "как": "skipped",
                      "подробно": "the subtitles are off"})
    elif с.get("худшая") is not None:
        вышло.append({"имя": ИМЕНА["субтитры"],
                      "как": "passed" if с.get("сошлось") else "failed",
                      "подробно": _связь(с)})
    else:
        вышло.append({"имя": ИМЕНА["субтитры"], "как": "failed",
                      "подробно": "no subtitles found in the file"})

    п = штамп.get("сверка_плашки")
    if п is None:
        вышло.append({"имя": ИМЕНА["плашка"], "как": "skipped",
                      "подробно": "the end card is off"})
    else:
        if п.get("сошлось"):
            подробно = _связь(п)
        elif п.get("рано"):
            подробно = "the end card starts too early"
        else:
            подробно = "the end card is missing"
        вышло.append({"имя": ИМЕНА["плашка"],
                      "как": "passed" if п.get("сошлось") else "failed",
                      "подробно": подробно})
    return вышло


