"""Как сервис говорит с человеком.

Здесь одна функция, и заведена она из-за настоящей беды.

**Питон буферизует вывод, когда тот идёт не в терминал, а в файл** —
по восемь килобайт. Разбор идёт минуты и всё это время печатает, куда
дошёл; при запуске с записью в лог человек видел пустой файл
у работающей программы. Ровно на это наступил и сосед, когда завёл
запуск ярлыком: лог был единственным каналом, и он молчал.

Слова про ход работы бессмысленны, если доходят после того, как работа
кончилась. Поэтому весь ход печатается отсюда, и отсюда — со сбросом
буфера.
"""

from __future__ import annotations

import codecs
import sys


def по_русски() -> None:
    """Чтобы русские слова доехали, когда вывод идёт НЕ в консоль.

    **Одиннадцатое место, где не проходят русские буквы, и нашла его
    сборочная машина в первую же минуту.** В настоящей консоли питон
    пишет прямо буквами, и всё цело — поэтому шестьсот проверок этого
    не видели никогда. А когда вывод перенаправлен (ярлык пишет весь
    вывод сервиса в журнал, сборочная машина — в свою трубу), питон
    берёт кодировку системы. На Windows она русских букв не знает
    вовсе, и печать не портит слова, а РОНЯЕТ работу: `UnicodeEncodeError`
    на первом же русском слове.

    Не utf-8 — переключаем. **Проба «умеет ли кодировка букву „я“»
    не устояла:** cp1251 русской Windows букву умеет, а «×» в «1920×1080»
    — нет, и разбор падал на второй строке хода. Какой знак следующим
    не влезет в кодовую страницу, не угадать; в консоли питон и так
    пишет utf-8, а журнал читается как utf-8.

    То же правило, что у остальных десяти мест: русские буквы целы
    там, где их несут байтами, и рассыпаются там, где их отдают
    чужому разборщику с его привычкой.
    """
    for поток in (sys.stdout, sys.stderr):
        менять = getattr(поток, "reconfigure", None)
        if менять is None:
            continue
        try:
            своя = codecs.lookup(поток.encoding or "ascii").name
        except LookupError:
            своя = ""
        if своя != "utf-8":
            менять(encoding="utf-8", errors="replace")


def скажи(*части) -> None:
    print(*части, flush=True)


def беда(сообщение: str, подсказка: str | None = None) -> None:
    """Отказ раскладывается по одному правилу.

    Первая строка — что случилось. Пустая строка. Подсказка — что
    сделать. Отказ, у которого подсказка утонула в потоке слов,
    читается как поломка, и человек начинает чинить не то.
    """
    print(f"\n{сообщение}", file=sys.stderr, flush=True)
    if подсказка:
        print(f"\n{подсказка}", file=sys.stderr, flush=True)


def счёт(сколько: int, одна: str, много: str) -> str:
    """«1 clip», «0 clips», «5 clips».

    **Заведено здесь, а не в каждом месте по отдельности.** Экран это
    уже умеет (`слова.счёт` на странице), и правило у них одно: дважды
    написанное правило склонения однажды разъедется.

    У английского две формы: одна — ровно для единицы, вторая — для
    всего остального, нуля тоже. Множественное подаётся словом, а не
    приставкой «s»: «1 copy, 2 copies» одним правилом не сделать.
    """
    return f"{сколько} {одна if abs(сколько) == 1 else много}"
