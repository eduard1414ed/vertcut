"""Очередь сборки: файл, а не процесс.

**Всё состояние — в `queue.json`.** Отсюда всё остальное:

- закрыли окно, ушли — сборка идёт дальше;
- убили процесс — очередь лежит, и следующий запуск продолжает с того
  места, где встали;
- вернулись через полчаса — команда читает файл голым json, без единой
  тяжёлой библиотеки.

**Один упавший ролик не роняет пачку.** Иначе «поставил и ушёл»
не работает: вернёшься к одному сломанному и девятнадцати нетронутым.

**Недоделанная очередь ПОДХВАТЫВАЕТСЯ, а не считается заново.** Это
дыра, найденная предком на себе: пересчёт плана в момент, когда
устаревших уже нет, терял работу молча. Затереть недоделанное можно
только словом `--again`.
"""

from __future__ import annotations

import time
from datetime import datetime
from pathlib import Path

from . import layout, pick, render, verify, works
from .errors import VertcutError


# Как часто ход сборки ложится на диск.
#
# Читает его другой процесс — экран, — и переспрашивает он раз
# в две секунды. Писать чаще, чем спрашивают, значит трогать диск
# зря; писать реже — показывать полосу, которая стоит.
ХОД_КАЖДЫЕ = 1.0


def _ход(файл: Path, состояние: dict, дело: dict):
    """Отчёт сборки о том, что она делает прямо сейчас.

    **Пишется на диск, потому что читает это другой процесс.** Сборка
    идёт своим процессом ровно затем, чтобы пережить закрытую вкладку;
    держи она ход в памяти — вкладка, открытая заново, показывала бы
    пустоту.

    Числа сюда приходят настоящие, а не прикинутые от времени: сколько
    секунд ролика закодировано, сколько точек сверено. Шаг, у которого
    считать нечего, зовётся словом и полосы не рисует — правило пакета
    дизайна.
    """
    прошлая = [0.0]

    def отметить(шаг, сделано=None, всего=None, единица=None) -> None:
        дело["ход"] = {"шаг": шаг, "сделано": сделано,
                       "всего": всего, "единица": единица}
        сейчас = time.monotonic()
        # Смена шага пишется всегда: она и есть новость. А внутри шага
        # — не чаще, чем экран переспрашивает.
        подробность = сделано is not None and сейчас - прошлая[0] < ХОД_КАЖДЫЕ
        if подробность:
            return
        прошлая[0] = сейчас
        works.записать(файл, состояние)

    return отметить


# Причина в очереди у свежего ролика, который собирают ещё раз: его
# попросили. Видна человеку строкой «почему он здесь» — одиночное
# слово «заново» храповик не видел, и оно жило по-русски.
ПОПРОСИЛИ = "you asked to export it again"


def прочитать(project: Path) -> dict:
    return works.прочитать(layout.queue(project))


def записать(project: Path, очередь: dict) -> None:
    works.записать(layout.queue(project), очередь)


def сложить(project: Path, meta: dict, только: list[str] | None = None,
            заново: bool = False) -> dict:
    """Собрать план пачки: кого собирать и почему.

    Причина у каждого называется словами. «Пересобираю семь» без
    объяснения читается как «сервис делает работу зря»; причина
    превращает это в «поправили рамку — вот эти семь».
    """
    старая = прочитать(project)
    если_есть = [д for д in старая.get("дела", [])
                 if д["состояние"] in (works.ЖДЁТ, works.ИДЁТ)]
    if если_есть and not заново:
        # Недоделанное подхватывается: пересчёт плана потерял бы работу.
        for дело in если_есть:
            if дело["состояние"] == works.ИДЁТ:
                дело["состояние"] = works.ЖДЁТ
        старая["дела"] = [д for д in старая.get("дела", [])]
        return старая

    дела = []
    for cut in pick.listing(project):
        if только is not None and cut["id"] not in set(только):
            continue
        причина = render.почему_устарел(project, cut)
        if причина is None and not заново:
            continue
        дела.append({"id": cut["id"], "зовут": pick.зовут(cut),
                     "почему": причина or ПОПРОСИЛИ,
                     "состояние": works.ЖДЁТ})
    очередь = {"собрана": datetime.now().astimezone().isoformat(
        timespec="seconds"), "дела": дела}
    записать(project, очередь)
    return очередь


def поставить_один(project: Path, ключ: str) -> dict:
    """Поставить в очередь ОДИН ролик, не тронув то, что в ней ждёт.

    Кнопка «Собрать» на экране вертикалки — это просьба собрать
    ЭТУ вертикалку, и ничего больше.

    **Раньше она собирала всё видео, и вот почему.** Один ролик
    складывался в очередь словом `только`, а следом пускалась команда
    `queue --export --again`, — и первым же делом та складывала план
    ЗАНОВО, теперь уже по всем роликам: слово «заново» значит «затереть
    недоделанное и посчитать всё сначала». Человек нажимал «Собрать»
    у одной вертикалки и получал очередь из двадцати.

    Отсюда две половины починки. Здесь — ставить одного, не затирая
    остальных: рядом в очереди могут ждать те, кого человек поставил
    минуту назад с экрана сборки, и терять их нельзя. А пускать эту
    очередь надо БЕЗ слова «заново»: недоделанное подхватывается,
    и подхватится ровно то, что мы сюда положили.

    Ролик, уже стоящий в очереди, переставляется в «ждёт»: нажали
    «Собрать заново» у собранного — значит собрать заново.
    """
    cut = pick.load(project, ключ)          # падает, если такого нет
    состояние = прочитать(project)
    дела = [д for д in состояние.get("дела", []) if д["id"] != ключ]
    дела.append({"id": ключ, "зовут": pick.зовут(cut),
                 "почему": render.почему_устарел(project, cut) or ПОПРОСИЛИ,
                 "состояние": works.ЖДЁТ})
    состояние["дела"] = дела
    состояние["собрана"] = datetime.now().astimezone().isoformat(
        timespec="seconds")
    записать(project, состояние)
    return состояние


def взять(project: Path) -> dict:
    """Стать хозяином очереди. Двое в одну очередь не ходят."""
    состояние = works.взять(layout.queue(project), "export")
    # Дела, оставшиеся в «собирается» от умершего хозяина, возвращаются
    # в «ждёт»: штамп сборки пишется только после сверки, значит
    # оборванный ролик всё равно считается несобранным.
    подобрано = 0
    for дело in состояние.get("дела", []):
        if дело["состояние"] == works.ИДЁТ:
            дело["состояние"] = works.ЖДЁТ
            подобрано += 1
    состояние["подобрано"] = подобрано
    works.записать(layout.queue(project), состояние)
    return состояние


def run(project: Path, meta: dict, говорить=None,
        только: list[str] | None = None) -> dict:
    """Собрать то, что стоит в очереди. `только` — ровно этих.

    **`только` заведён по слову автора, и вот что он видел.** Он нажал
    «Собрать» у ОДНОЙ вертикалки и получил сборку всего видео — пяти
    роликов. Кнопка при этом работала как написано: она ставила
    в очередь одного, не затирая тех, кто в ней ждёт. Ждали там
    остатки прошлой сборки — та, что он оборвал: брошенное дело
    возвращается из «собирается» в «ждёт», и следующий запуск честно
    берёт его вместе со своим.

    Правило «не затирать ждущих» верное и остаётся: человек мог
    поставить их минуту назад с экрана сборки. Неверно было другое —
    что просьба собрать ОДНУ вертикалку запускала всех, кто ждал.
    Теперь ждущие остаются ждать, а собирается тот, кого просили;
    очередь при этом видна целиком на экране сборки, и «Собрать всё»
    там по-прежнему значит всё.
    """
    from . import report, shots as планы

    говорить = говорить or report.скажи
    состояние = взять(project)
    if состояние.get("подобрано"):
        говорить(f"picked up where the last export stopped: "
                 f"{report.счёт(состояние['подобрано'], 'clip', 'clips')}")
    дела = [д for д in состояние.get("дела", [])
            if д["состояние"] == works.ЖДЁТ
            and (только is None or д["id"] in set(только))]
    if not дела:
        works.отпустить(layout.queue(project))
        говорить("nothing to export")
        return состояние

    источник = render.проверить_исходник(meta)
    найдено = планы.read(project)
    try:
        for n, дело in enumerate(дела, 1):
            говорить(f"\n[{n} of {len(дела)}] {дело['зовут']}  "
                     f"— {дело['почему']}")
            # Вертикалку могли удалить после того, как она попала
            # в очередь. Собирать нечего, и падать тут незачем:
            # «упал» читается как поломка сборки, а поломки нет —
            # человек сам её убрал.
            if not layout.cut_json(project, дело["id"]).exists():
                дело["состояние"] = works.ОТМЕНЁН
                дело.pop("ход", None)
                говорить("  — the clip was deleted, nothing to export")
                works.записать(layout.queue(project), состояние)
                continue
            дело["состояние"] = works.ИДЁТ
            works.записать(layout.queue(project), состояние)
            try:
                cut = pick.load(project, дело["id"])
                штамп = render.собрать_один(
                    project, meta, cut, источник, найдено, говорить,
                    _ход(layout.queue(project), состояние, дело))
                дело["состояние"] = works.ГОТОВ
                дело["отчёт"] = {
                    "секунд": штамп["took"], "мегабайт": штамп["megabytes"],
                    "сверка": штамп["сверка"],
                    "субтитры": штамп.get("сверка_субтитров"),
                    # Пять заслонов словами — тот же ответ, что в отказе.
                    "проверки": verify.итоги(штамп)}
            except VertcutError as беда:
                # Один упавший не роняет пачку: помечается вместе
                # с сообщением, остальные собираются.
                дело["состояние"] = works.УПАЛ
                дело["беда"] = беда.message
                дело["подсказка"] = беда.hint
                # Не прошла сверка — у отказа есть итоги всех пяти:
                # человек видит, какая именно и что прошло рядом.
                дело["проверки"] = getattr(беда, "проверки", None)
                говорить(f"  ! failed: {беда.message}")
            # Ход своё отработал: дело кончилось, и висящее «кодирую»
            # у готового ролика читалось бы как «всё ещё идёт».
            дело.pop("ход", None)
            works.записать(layout.queue(project), состояние)
    finally:
        works.отпустить(layout.queue(project))
    return состояние


def показать(project: Path) -> list[dict]:
    """Что в очереди. Читает голый json — без тяжёлых библиотек."""
    return прочитать(project).get("дела", [])


def _без_субтитров(project: Path, cut: dict | None, как: str) -> bool:
    """Без субтитров ли этот ролик — для строки на экране сборки.

    У собранного — по штампу ЛЕЖАЩЕГО файла: галочку могли снять уже
    после сборки, и «without subtitles» у файла с субтитрами было бы
    неправдой. У остальных — по тому, как он соберётся.
    """
    if not cut:
        return False
    if как == works.ГОТОВ:
        return (cut.get("render") or {}).get("субтитры") is False
    from . import subs
    return not subs.в_файле(project, cut)


def обзор(project: Path, meta: dict) -> dict:
    """Вся сборка одним куском: что в очереди, что ждёт, сколько времени.

    **Читает, но НЕ перекладывает.** Разница важная: `сложить` меняет
    очередь на диске, а этот вопрос человек задаёт всякий раз, когда
    открывает экран, — и открытие экрана не должно ничего менять.
    Поэтому «что надо собрать» считается рядом и отдельно от того,
    что уже стоит в очереди.

    Считается ЗДЕСЬ, а не на экране: причина устаревания — это
    `render.почему_устарел`, и второй ответ на тот же вопрос разошёлся
    бы с первым молча.
    """
    from . import layout, subs, tuning

    состояние = прочитать(project)
    хозяин = состояние.get("хозяин") or {}
    работает = works.жив(int(хозяин.get("pid") or 0))

    ролики = {c["id"]: c for c in pick.listing(project)}
    дела = []
    for дело in состояние.get("дела", []):
        cut = ролики.get(дело["id"])
        файл = layout.out(project, cut) if cut else None
        # ВЕРТИКАЛКУ МОГЛИ УДАЛИТЬ, пока она стояла в очереди.
        #
        # Очередь этого не знает: она файл, и никто её при удалении
        # не переписывает — переписывать чужой файл вправе только его
        # хозяин, а хозяином в эту минуту может быть идущая сборка.
        # Поэтому вопрос «а есть ли ещё такая вертикалка» задаётся
        # здесь, в момент показа, — тем же порядком, каким считается
        # метка «есть» у совета AI.
        удалён = cut is None
        как = дело["состояние"]
        # Дело, оставшееся «идёт» от мёртвого хозяина, — это
        # оборванная сборка, а не идущая. Врать про неё нельзя:
        # человек будет ждать файл, которого никто не делает.
        if как == works.ИДЁТ and not работает:
            как = works.ЖДЁТ
        # А ждать удалённую вертикалку нельзя вовсе: собирать нечего.
        # Оставь её в «ждёт» — и она попадёт в счёт работы, в оценку
        # времени и в подпись у кнопки «Собрать всё».
        if удалён and как in (works.ЖДЁТ, works.ИДЁТ):
            как = works.ОТМЕНЁН
        дела.append({
            **дело,
            "удалён": удалён,
            "duration": cut["duration"] if cut else None,
            "оценка": round((cut["duration"] if cut else 0)
                            * tuning.ЦЕНА_СБОРКИ, 1),
            "файл": cut.get("файл") if cut else None,
            "есть_файл": bool(файл and файл.exists()),
            "мегабайт": (round(файл.stat().st_size / 1048576, 1)
                         if файл and файл.exists() else None),
            "байт": (файл.stat().st_size
                     if файл and файл.exists() else None),
            "состояние": как,
            "без_субтитров": _без_субтитров(project, cut, как),
        })

    # Упавшая тоже стоит своей строкой — с причиной и «Try again».
    # Покажи её ещё и среди «не в очереди», и одна вертикалка видна
    # дважды, с двумя разными кнопками на одно дело.
    в_очереди = {д["id"] for д in дела
                 if д["состояние"] in (works.ЖДЁТ, works.ИДЁТ, works.УПАЛ)}
    ждут = []
    for cut in ролики.values():
        if cut["id"] in в_очереди:
            continue
        причина = render.почему_устарел(project, cut)
        if причина is None:
            continue
        ждут.append({"id": cut["id"], "зовут": pick.зовут(cut),
                     "почему": причина, "duration": cut["duration"],
                     "без_субтитров": not subs.в_файле(project, cut),
                     "оценка": round(cut["duration"] * tuning.ЦЕНА_СБОРКИ, 1)})

    осталось = [д for д in дела if д["состояние"] in (works.ЖДЁТ, works.ИДЁТ)]
    return {
        "дела": дела, "ждут": ждут,
        "идёт_сейчас": работает,
        "запускается": not работает and works.запускается(состояние),
        "не_запустилась": not работает and works.не_запустилась(состояние),
        "кто": хозяин.get("что") if работает else None,
        # «Export all» соберёт и упавшие — их время в счёт тоже.
        "оценка": round(sum(д["оценка"] for д in осталось + ждут + [
            д for д in дела
            if д["состояние"] == works.УПАЛ and not д["удалён"]]), 1),
        # Только то, что уже в очереди: «осталось» в заголовке экрана
        # про ту сборку, что идёт, а не про вертикалки вне очереди.
        "оценка_очереди": round(sum(д["оценка"] for д in осталось), 1),
        "вертикалок": len(ролики),
        # Удалённые не считаются ни готовыми, ни упавшими: «готово 5»
        # у человека, который две из них выбросил, — это счёт того,
        # чего у него нет.
        "готово": sum(1 for д in дела
                      if д["состояние"] == works.ГОТОВ and not д["удалён"]),
        "упало": sum(1 for д in дела
                     if д["состояние"] == works.УПАЛ and not д["удалён"]),
        "удалено": sum(1 for д in дела if д["удалён"]),
        "папка": str(layout.cuts(project)),
    }


def идущие() -> list[dict]:
    """Очереди, которые собираются ПРЯМО СЕЙЧАС, по всем видео сразу.

    **Спрашивают это снаружи, а не экран.** Значку в строке меню нужна
    одна строка — «собирает 4 из 9», — и другого способа узнать её
    у него нет: `обзор` считает план на ОДНО видео и трогает диск
    за каждым роликом, а спрашивают здесь часто и про все.

    **Мёртвый хозяин — не очередь.** Недоделанные дела лежат в файле
    и после обрыва: они ждут следующего запуска, но прямо сейчас их
    никто не собирает. Сказать про них «собирает» значило бы соврать
    ровно так же, как врёт «идёт» у мёртвого хозяина в `обзор`.

    **Испорченный файл одного видео не прячет остальные.** Читается
    он тем же `works.прочитать`, который на битом json отказывает
    словами; здесь этот отказ значил бы «сервис не отвечает» для того,
    кто спрашивает снаружи, — то есть одна кривая строчка на диске
    гасила бы значок целиком.
    """
    корень = layout.root()
    if not корень.exists():
        return []
    идут = []
    for папка in sorted(корень.iterdir()):
        if not папка.is_dir():
            continue
        try:
            состояние = прочитать(папка)
        except VertcutError:
            continue
        хозяин = состояние.get("хозяин") or {}
        if not works.жив(int(хозяин.get("pid") or 0)):
            continue
        дела = состояние.get("дела") or []
        осталось = sum(1 for д in дела
                       if д.get("состояние") in (works.ЖДЁТ, works.ИДЁТ))
        if дела and осталось:
            идут.append({"видео": папка.name,
                         "всего": len(дела), "осталось": осталось})
