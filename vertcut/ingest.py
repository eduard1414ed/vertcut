# Стадии по порядку. Список, а не набор вызовов подряд: по нему
# печатается ход, по нему же переступается сделанное, и добавить
# стадию можно в одном месте.
#
# Стадии, которых пока нет, названы в конце вслух: молча делать
# половину и называть это разбором нельзя.
СТАДИИ = ["extract", "hear", "align", "shots", "crop"]

ИМЕНА = {
    "extract": "audio and a smaller copy",
    "hear": "transcribing",
    "align": "syncing text to speech, splitting phrases",
    "shots": "cuts and shot frames",
    "crop": "a crop for every shot",
}

# ПЯТАЯ СТАДИЯ ПРИШЛА ВМЕСТЕ С ЭКРАНОМ, и вот почему.
#
# Рамка кадра была отдельной командой: разбор её не делал, человек звал
# `vertcut crop` сам. В терминале это было честно — работа дорогая
# (около секунды на план), и платить за неё должен тот, кому она нужна.
#
# На экране это ломает главное обещание сессии: «весь путь, ни разу
# не открыв терминал». Без рамок ни один ролик не соберётся правильно
# — окно встанет по центру там, где лицо сбоку, — а сказать человеку
# «а теперь откройте терминал» после четырёх стадий значит не сделать
# экрана вовсе.
#
# Команда `vertcut crop` при этом никуда не делась: перемерить рамки
# на части планов по-прежнему можно ею, и в этом её работа теперь
# и состоит.

# Стадии, у которых мало «сделано»: они пересчитываются, когда меняется
# то, из чего они посчитаны.
#
# **Распознавания здесь нет, и это главное решение разделения.** Оно
# стоит минуты и зависит только от звука; звук стережёт отпечаток
# исходника. Укладка стоит долю секунды и зависит от текста и правил
# нарезки — их и стережёт отпечаток. Пока обе жили одной стадией,
# перемерять числа сегментации было нельзя: каждая попытка стоила
# полного прогона распознавания.
ОТПЕЧАТКИ = {"align": lambda project: _отпечаток_укладки(project)}


def _отпечаток_укладки(project: Path) -> str:
    """Из чего посчитана укладка: текст, правила укладки и нарезки фраз.

    Три слагаемых, и все три обязательны. Текст меняется, когда человек
    принёс сценарий или поправил его. Правила укладки — когда меняется
    то, как слова ложатся на время. Правила нарезки — когда меняется,
    где кончается фраза. Забудь любое, и посчитанное по-старому будет
    считать себя свежим.
    """
    import hashlib

    from . import align, phrases

    текст = ""
    if layout.script(project).exists():
        текст = layout.script(project).read_text(encoding="utf-8")
    elif layout.heard(project).exists():
        текст = str(услышанное(project).get("text", ""))
    return ":".join([hashlib.sha1(текст.encode("utf-8")).hexdigest()[:16],
                     align.отпечаток(), phrases.отпечаток()])


def список() -> list[dict]:
    """Что уже разобрано. Читает голый json.

    **Тяжёлых библиотек не трогает, и это правило.** Ровно тот момент,
    когда окружение может быть развалившимся, а человеку надо
    посмотреть, что у него разобрано, — и команда, и экран.

    Считается ЗДЕСЬ, а не в команде и не в веб-слое. Пока это лежало
    в `cli.py`, у экрана был только один способ показать тот же список
    — написать его во второй раз, и разошлись бы они молча: сначала
    в мелочи вроде «сделано ничего», потом в чём-нибудь, что человек
    примет за поломку.

    Папка без журнала — законный случай, а не сбой: разбор мог
    оборваться на первой секунде. Она возвращается со своим словом,
    а не выбрасывается: молча спрятать папку, которая лежит у человека
    на диске, значит соврать.
    """
    import json

    корень = layout.root()
    if not корень.exists():
        return []
    вышло = []
    for папка in sorted(p for p in корень.iterdir() if p.is_dir()):
        # «Входящие» — не разбор, а прихожая.
        #
        # **И всё, что начинается с точки, — тоже не разбор.** Найдено
        # автором на живом экране: в песочнице настройки лежат ВНУТРИ
        # корня (`{корень}/.настройки`), и папка настроек показывалась
        # видео — с меткой «журнала нет» и предложением её разобрать.
        # Слаг видео с точки не начинается никогда: его считает
        # `slug.py`, и точка там первым знаком не бывает. А вот
        # системного мусора с точкой на диске сколько угодно —
        # `.DS_Store` у macOS, `.git`, `.Trash`.
        if папка == layout.inbox() or папка.name.startswith("."):
            continue
        файл = layout.meta(папка)
        if not файл.exists():
            вышло.append({"слаг": папка.name, "журнал": False})
            continue
        try:
            meta = json.loads(файл.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            вышло.append({"слаг": папка.name, "журнал": False,
                          "беда": "analysis data is damaged"})
            continue
        вышло.append({
            "слаг": папка.name, "журнал": True,
            "источник": Path(meta.get("source", "?")).name,
            "duration": float(meta.get("duration") or 0),
            "width": meta.get("width"), "height": meta.get("height"),
            "стадии": list((meta.get("stages") or {}).keys()),
            "разобрано": все_стадии_сделаны(meta, папка),
            **сколько_роликов(папка),
        })
    return вышло


def сколько_роликов(project: Path) -> dict:
    """Сколько вертикалок выбрано и сколько из них лежит собранными.

    **Про «устарело» здесь НЕ говорится, и это решение.** Ответ на него
    считает `render.почему_устарел`, а тот поднимает профиль субтитров,
    отпечаток фраз и монтаж кадра — то есть половину тяжёлых библиотек
    на каждое видео в списке. Список видео обязан открываться и тогда,
    когда с окружением что-то не так; про устаревшее говорит экран
    сборки, где это и считается.
    """
    from . import pick

    ролики = pick.listing(project)
    собрано = sum(1 for cut in ролики if собран(project, cut))
    return {"вертикалок": len(ролики), "собрано": собрано}


def собран(project: Path, cut: dict) -> bool:
    """Лежит ли собранный файл этой вертикалки. Одно правило на список
    видео и на колонку вертикалок.

    **Не по полю `файл`.** Там с момента выбора лежит БУДУЩЕЕ имя файла,
    и колонка, смотревшая на него, называла собранной вертикалку,
    созданную секунду назад. Поймано глазами на снимке экрана.
    """
    return bool(cut.get("render")) and layout.out(project, cut).exists()


def все_стадии_сделаны(meta: dict, project: Path) -> bool:
    """Разобрано ли видео целиком — все стадии, а не «журнал есть».

    Отпечатки здесь считаются наравне со штампами: стадия, у которой
    разошёлся отпечаток, НЕ сделана, как бы старательно ни стоял её
    штамп. Иначе экран показал бы «разобрано» тому, у кого фразы
    посчитаны по старым правилам.
    """
    return all(сделана(meta, стадия, project) for стадия in СТАДИИ)


def ход_разбора(project: Path) -> dict:
    """Всё про разбор одного видео: что сделано, что идёт, что ждёт.

    Считается ЗДЕСЬ, а не на экране. Стадии, их порядок, их имена
    и то, сделана ли стадия (с отпечатком, а не по одному штампу), —
    это устройство разбора. Посчитай экран это сам — и через месяц
    он назовёт стадию сделанной там, где отпечаток разошёлся.

    Оценка «сколько ещё» — из `tuning`, где у неё написано
    происхождение. Она нужна ровно для одного: сказать человеку,
    уходить ему пить чай или ждать.
    """
    from . import tuning

    meta = read_meta(project)
    длина = float(meta.get("duration") or 0)
    состояние = works.прочитать(layout.work(project))
    хозяин = состояние.get("хозяин") or {}
    работает = works.жив(int(хозяин.get("pid") or 0))
    идёт = состояние.get("идёт") if работает else None

    планов = int((meta.get("shots") or {}).get("count") or 0)
    стадии = []
    for имя in СТАДИИ:
        штамп_ = (meta.get("stages") or {}).get(имя) or {}
        это = {
            "имя": имя,
            "зовут": ИМЕНА[имя],
            "сделана": сделана(meta, имя, project),
            "секунд": штамп_.get("секунд"),
            "когда": штамп_.get("когда"),
            "идёт": имя == идёт,
            "оценка": оценка_стадии(имя, длина, планов),
        }
        if имя == идёт:
            # Ход кладётся В САМУ СТАДИЮ, а не рядом. Иначе экрану
            # пришлось бы догадываться, к которой из пяти он относится,
            # — а догадка однажды нарисует полосу не там.
            это.update(сделано=состояние.get("сделано"),
                       всего=состояние.get("всего"),
                       единица=состояние.get("единица"),
                       начало=состояние.get("начало"))
        стадии.append(это)

    return {
        "слаг": project.name,
        "источник": Path(meta.get("source", "?")).name,
        "duration": длина, "width": meta.get("width"),
        "height": meta.get("height"), "fps": meta.get("fps"),
        "разобрано": все_стадии_сделаны(meta, project),
        "стадии": стадии,
        "идёт_сейчас": работает,
        # Работу пустили, а хозяина у неё ещё нет: процесс поднимается
        # и считает отпечаток исходника. Не сказать про это — значит
        # показать «ничего не происходит» там, где всё уже идёт.
        "запускается": not работает and works.запускается(состояние),
        "не_запустилась": not работает and works.не_запустилась(состояние),
        # Хозяин, который умер, не отпустив работу: её убили или она
        # упала. Притвориться, что ничего не было, значит оставить
        # человека перед списком, который не двигается.
        "брошено": bool(хозяин) and not работает,
        "беда": состояние.get("беда"),
        "подсказка": состояние.get("подсказка"),
        "остановлен": bool(состояние.get("остановлен")) and not работает,
        "числа": {
            "минут": round(длина / 60) if длина else None,
            "слов": meta.get("heard_words"),
            "фраз": (meta.get("align") or {}).get("phrases"),
            "планов": планов or None,
            "с_лицом": (meta.get("crop") or {}).get("by_face"),
            **сколько_роликов(project),
        },
        "текст_откуда": meta.get("text_source"),
    }


def оценка_стадии(имя: str, длина: float, планов: int) -> float | None:
    """Сколько эта стадия обычно занимает на видео такой длины.

    `None` там, где сказать нечего: рамки считаются по планам, а планов
    до стадии склеек не знает никто. Выдумать число тут значило бы
    пообещать человеку срок, взятый из воздуха.
    """
    from . import tuning

    if имя == "crop":
        return round(планов * tuning.ЦЕНА_ПЛАНА, 1) if планов else None
    доля = tuning.ЦЕНА_СТАДИЙ.get(имя)
    return round(длина * доля, 1) if доля is not None else None


def занято(project: Path) -> int:
    """Сколько байт занимает этот разбор со всем, что в нём лежит.

    Считается обходом, а не запоминается: файлы тут появляются
    и исчезают всё время — кадры, слои, готовые ролики, — и любое
    запомненное число разошлось бы с правдой на первой же сборке.

    Нужно это ровно затем, чтобы человек мог посмотреть, куда ушли
    гигабайты, и убрать лишнее руками. Разбор двадцатиминутного видео
    — это дорожка, уменьшенная копия и сотни кадров планов.
    """
    всего = 0
    for файл in project.rglob("*"):
        try:
            if файл.is_file():
                всего += файл.stat().st_size
        except OSError:
            continue          # файл унесли прямо сейчас — не беда
    return всего


def обложка(project: Path) -> Path:
    """Кадр, которым видео показано в списке. Считается один раз.

    Берётся из УМЕНЬШЕННОЙ КОПИИ, а не из исходника. Копия лежит
    рядом и весит мало; исходник бывает на другом диске, который
    человек отключил, — и список видео не должен от этого пустеть.

    Отдельно от кадров планов нарочно: те появляются только после
    стадии склеек, а обложка нужна сразу, как только видео принято.
    """
    from . import tuning

    готовая = layout.cover(project)
    if готовая.exists():
        return готовая

    первый_план = layout.thumb(project, 1)
    if первый_план.exists():
        return первый_план

    proxy = layout.proxy(project)
    if not proxy.exists():
        raise VertcutError(
            f"Video {project.name} has no frames yet",
            hint="frames appear after the first stage of analysis — "
                 "the audio and a smaller copy")
    meta = read_meta(project)
    при = float(meta.get("duration") or 0) * tuning.COVER_AT
    # Своя времянка на вызов — та же причина, что у кадра плана:
    # список видео и список планов просят картинки одновременно,
    # и на общий файл они дрались бы за одно имя.
    return media.кадр_в_файл(proxy, при, готовая, tuning.CROP_FRAME_WIDTH)


def открыть(слаг: str):
    """Папка разбора, её журнал и уложенный текст — одним движением.

    Одно место на команду и на экран: отказ «нет такого разбора»
    обязан быть одним и тем же, с одной и той же подсказкой.
    """
    from . import speech

    папка = папка_разбора(слаг)
    return папка, read_meta(папка), speech.read(папка)


def папка_разбора(слаг: str) -> Path:
    """Папка разбора — и только она, без уложенного текста.

    **Не `открыть`, и это замер, а не вкусовщина.** `открыть` заодно
    читает `align.json` и падает словами «видео ещё не разобрано» —
    ему так и надо, он для тех, кто с этим текстом работает.
    А удалять хотят чаще всего ровно ПОЛОВИНУ разбора: распознавание
    упало, место кончилось, человек передумал на шестой минуте.
    Отказать ему «видео ещё не разобрано» значило бы запереть папку
    именно в том случае, ради которого удаление и заведено.
    """
    папка = layout.project(слаг)
    if not папка.exists():
        raise VertcutError(f"No such video: {слаг}",
                           hint="to see your videos, run: vertcut videos")
    return папка


def что_уйдёт(слаг: str) -> dict:
    """Что именно исчезнет, если этот разбор удалить.

    **Спрашивается ДО нажатия, а не после.** Удаление тут совсем,
    не в корзину, и человек обязан увидеть числами, чего лишится:
    сколько занято, сколько вертикалок пропадёт вместе с папкой
    и лежит ли рядом ЕГО видео или наша копия.
    """
    папка = папка_разбора(слаг)
    meta = read_meta(папка)
    ролики = сколько_роликов(папка)
    копия = наша_копия(meta)
    return {
        "слаг": слаг,
        "папка": str(папка),
        "источник": str(meta.get("source", "?")),
        "занято": занято(папка),
        "вертикалок": ролики.get("вертикалок", 0),
        "собрано": ролики.get("собрано", 0),
        "наша_копия": копия is not None,
        "видео": str(копия) if копия else None,
        "видео_есть": bool(копия and копия.exists()),
        "идёт": идёт_работа(папка),
    }


def наша_копия(meta: dict) -> Path | None:
    """Исходное видео — это КОПИЯ, сделанная сервисом, или файл человека?

    **Разница тут не бухгалтерская.** Видео, брошенное в окно браузера,
    сервис скопировал во «Входящие» — эту копию он вправе унести
    вместе с разбором, она его собственная. Видео, выбранное на диске,
    так и осталось лежать в папке человека: удалить его значило бы
    унести чужой файл, которого сервис не создавал.

    Отсюда правило: удалять исходник можно ТОЛЬКО из «Входящих»,
    и только про него человеку предлагается выбор.
    """
    сырое = str(meta.get("source") or "").strip()
    if not сырое:
        return None
    файл = Path(сырое)
    входящие = layout.inbox()
    try:
        файл.relative_to(входящие)
    except ValueError:
        return None
    return файл


def идёт_работа(project: Path) -> str | None:
    """Идёт ли прямо сейчас разбор или сборка этого видео.

    **Удалить папку под работающим процессом нельзя.** Он пишет в неё
    прямо сейчас: ffmpeg дожёвывает дорожку, сборка кладёт ролик.
    Убери папку из-под него — и он упадёт где-то в середине, а человек
    увидит не «нельзя», а трассировку из чужой библиотеки.
    """
    from . import works

    # Слово уходит человеку: «This video's analysis is running».
    for что, файл in (("analysis", layout.work(project)),
                      ("export", layout.queue(project))):
        хозяин = works.прочитать(файл).get("хозяин") or {}
        if хозяин and works.жив(int(хозяин.get("pid") or 0)):
            return что
    return None


def удалить(слаг: str, *, с_видео: bool = False) -> dict:
    """Убрать разбор целиком. НЕ в корзину.

    Так и говорится человеку до нажатия: переносимой корзины в питоне
    нет, а тащить ради неё библиотеку — решать вместе с упаковкой.
    То же решение и та же формулировка, что у удаления вертикалки.

    **Видео уходит только по отдельной просьбе и только своё.**
    Проверку «своё ли» делает `наша_копия`, а не тот, кто зовёт:
    второе место, знающее это правило, однажды решило бы иначе —
    и унесло бы чужой файл.
    """
    import shutil

    папка = папка_разбора(слаг)
    meta = read_meta(папка)
    идёт = идёт_работа(папка)
    if идёт:
        raise VertcutError(
            f"This video's {идёт} is running — it cannot be deleted now",
            hint="stop it and try again")

    копия = наша_копия(meta) if с_видео else None
    ролики = сколько_роликов(папка)
    место = занято(папка)
    shutil.rmtree(папка)
    убрано_видео = None
    if копия and копия.exists():
        копия.unlink()
        убрано_видео = str(копия)
    return {
        "слаг": слаг,
        "папка": str(папка),
        "занято": место,
        "вертикалок": ролики.get("вертикалок", 0),
        "видео": убрано_видео,
    }


def where(source: Path) -> Path:
    """Путь папки разбора. Считается ОДНИМ местом.

    Посчитай его дважды — и работа пойдёт в одну папку, а искать её
    будут в другой.
    """
    return layout.project(slug.make(source.stem))


def read_meta(project: Path) -> dict:
    файл = layout.meta(project)
    if not файл.exists():
        return {}
    try:
        return json.loads(файл.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise VertcutError(
            f"Analysis data is damaged: {файл}\n  {exc}",
            hint="analyze the video again: vertcut ingest PATH_TO_VIDEO --again",
        ) from None


def write_meta(project: Path, meta: dict) -> None:
    """Запись через времянку с переименованием.

    Прямая запись оставляет обрезанный json, если процесс погас
    посередине, — и тогда разбор выглядит испорченным, хотя всё, что
    он посчитал, лежит рядом целым.
    """
    from . import works

    project.mkdir(parents=True, exist_ok=True)
    works.записать(layout.meta(project), meta, отступ=2)


def сделана(meta: dict, стадия: str, project: Path | None = None) -> bool:
    """Сделана ли стадия — и не устарело ли сделанное.

    Штамп «сделано» отвечает только на первый вопрос. У стадий
    с отпечатком есть второй: посчитано ли оно из того же, из чего
    считалось бы сейчас. Разошёлся отпечаток — стадия не сделана,
    как бы старательно ни стоял её штамп.
    """
    отметка = meta.get("stages", {}).get(стадия)
    if not отметка:
        return False
    считать = ОТПЕЧАТКИ.get(стадия)
    if считать is None or project is None:
        return True
    return отметка.get("отпечаток") == считать(project)


def штамп(meta: dict, стадия: str, секунды: float,
          project: Path | None = None) -> None:
    отметка = {
        "когда": datetime.now().isoformat(timespec="seconds"),
        "секунд": round(секунды, 1),
    }
    считать = ОТПЕЧАТКИ.get(стадия)
    if считать is not None and project is not None:
        отметка["отпечаток"] = считать(project)
    штампы = meta.setdefault("stages", {})
    штампы[стадия] = отметка
    # Штампы держатся В ПОРЯДКЕ СТАДИЙ, а не в порядке появления.
    # `videos` печатает их как есть и читается человеком: «extract,
    # align, hear» выглядит так, будто укладка шла до распознавания.
    # Сортировать при печати нельзя — она нарочно не знает про стадии
    # и читает голый json.
    meta["stages"] = {имя: штампы[имя] for имя in СТАДИИ if имя in штампы}
    meta["stages"].update({имя: штамп for имя, штамп in штампы.items()
                           if имя not in СТАДИИ})


def принять(source: Path, *, script_path: Path | None = None,
            заново: bool = False, говорить=report.скажи) -> tuple[Path, dict]:
    """Опознать видео и завести ему папку разбора. Стадий не трогает.

    **Отделено от самого разбора, и не ради красоты.** У экрана это две
    разные минуты человеческой жизни: сперва он кладёт файл в сервис
    и хочет увидеть, что тот принят, — а потом решает, разбирать ли
    сейчас. Пока это было одним куском, принятый файл нигде не значился:
    папки нет, значит в списке видео его нет, значит человек положил
    файл и не увидел ничего.

    Стоит это дёшево и делается один раз: `ffprobe` мгновенный,
    отпечаток трёхгигабайтного файла — около десяти секунд.

    Возвращает папку разбора и её журнал.
    """
    source = Path(source).expanduser().resolve()
    if not source.exists():
        raise VertcutError(f"No such file: {source}")

    project = where(source)
    было = read_meta(project)
    meta = {} if заново else dict(было)

    говорить(f"Reading the file: {source.name}")
    свойства = media.probe(source)
    отпечаток = media.fingerprint(source)

    прежний = meta.get("fingerprint")
    if прежний and прежний != отпечаток:
        raise VertcutError(
            f"The file has changed since it was analyzed: {source.name}\n"
            f"  was  {прежний[:12]}…\n"
            f"  now  {отпечаток[:12]}…",
            hint=("if it is a different video, rename the file;\n"
                  "if it is the same video exported again, run: "
                  "vertcut ingest ... --again"),
        )

    meta.update({
        "slug": project.name,
        "source": str(source),
        "fingerprint": отпечаток,
        **свойства,
    })
    meta.setdefault("stages", {})
    # «Без субтитров» видео решается ОДИН раз — когда оно разобрано
    # впервые, по галочке настроек. Дальше галочка его не трогает
    # (разбор заново — тоже): иначе, сняв её, человек молча вернул бы
    # субтитры сорока роликам старого видео.
    from . import config, subs
    if было.get(subs.БЕЗ_СУБТИТРОВ):
        meta[subs.БЕЗ_СУБТИТРОВ] = True
    elif not было.get("fingerprint") and config.новые_без_субтитров():
        meta[subs.БЕЗ_СУБТИТРОВ] = True
    write_meta(project, meta)          # сразу, чтобы разбор было видно

    говорить(f"  {свойства['width']}×{свойства['height']}, "
             f"{свойства['fps']:g} fps, {свойства['codec']}, "
             f"{минуты(свойства['duration'])}")
    говорить(f"  analysis folder: {project}")

    if script_path is not None:
        положить_сценарий(project, Path(script_path), meta, говорить)
        write_meta(project, meta)

    # Профиль субтитров этого видео — КОПИЯ, и она делается сразу,
    # а не при первой правке стиля.
    #
    # Пока копии нет, видео читало бы личный образец напрямую — и тогда
    # правка «моего стиля» устаревала бы собранные ролики ЧУЖИХ видео:
    # отпечаток профиля входит в штамп сборки. Копия отвечает на это
    # раз и навсегда.
    путь, откуда = subs.завести(project)
    if откуда != subs.СВОЙ:
        говорить(f"  subtitle style: copy ({откуда}) → {путь.name}")

    return project, meta


def run(source: Path, *, script_path: Path | None = None,
        заново: bool = False, говорить=report.скажи) -> dict:
    """Разобрать видео. Возвращает `meta.json` как он лёг на диск.

    **У разбора есть хозяин, и он берётся здесь, внутри стадии.**
    Поставь его снаружи — в веб-слое, — и разбор из терминала прошёл бы
    поверх идущего с экрана, молча: два ffmpeg пишут один `audio.wav`,
    и что в нём окажется, не знает никто. Механизм тот же, что
    у очереди сборки; второго такого не заводится.

    **Ход работы пишется на диск, а не держится в памяти.** Иначе
    закрытая вкладка не отличалась бы от закрытой программы: экрану
    неоткуда узнать, на какой стадии стоит разбор, кроме как прочитав
    это с диска.
    """
    project, meta = принять(source, script_path=script_path, заново=заново,
                            говорить=говорить)
    source = Path(meta["source"])
    работа = layout.work(project)
    works.взять(работа, f"analysis of “{project.name}”")

    осталось = [с for с in СТАДИИ
                if заново or not сделана(meta, с, project)]
    works.отметить(работа, слаг=project.name, что="разбор",
                   длина=float(meta.get("duration") or 0),
                   очередь=осталось, идёт=None, беда=None,
                   остановлен=False,
                   начато=datetime.now().astimezone().isoformat(
                       timespec="seconds"))
    try:
        for стадия in СТАДИИ:
            if not заново and сделана(meta, стадия, project):
                говорить(f"  ✓ {ИМЕНА[стадия]} — already done, skipping")
                continue
            # Стадия с отпечатком может быть «сделана» и всё равно
            # устареть: сменился текст или правила нарезки фраз. Сказать
            # об этом надо словами — иначе пересчёт выглядит как работа
            # сервиса зря.
            if not заново and meta.get("stages", {}).get(стадия):
                говорить(f"  … {ИМЕНА[стадия]} — redoing: the text or "
                         "the phrase rules changed")
            else:
                говорить(f"  … {ИМЕНА[стадия]}")
            works.отметить(работа, идёт=стадия, сделано=None, всего=None,
                           единица=None,
                           начало=datetime.now().astimezone().isoformat(
                               timespec="seconds"))
            начало = time.monotonic()
            ДЕЛА[стадия](source, project, meta, говорить,
                         _ход(работа, стадия))
            потрачено = time.monotonic() - начало
            штамп(meta, стадия, потрачено, project)
            write_meta(project, meta)
            говорить(f"  ✓ {ИМЕНА[стадия]} — {потрачено:.1f} s")
        works.отметить(работа, идёт=None, сделано=None, всего=None,
                       очередь=[])
    except KeyboardInterrupt:
        # Человек нажал «остановить» на экране или Ctrl+C в терминале.
        # Дорога у обеих одна: экран посылает SIGTERM, а тот превращён
        # в то же самое прерывание. Пометка нужна, чтобы в файле
        # не осталось «идёт распознавание» у работы, которой нет.
        works.отметить(работа, идёт=None, остановлен=True)
        raise
    except VertcutError as беда:
        # Беда остаётся на диске: экран прочитает её и скажет словами.
        # Стереть её вместе с работой значило бы, что человек, вернувшийся
        # через час, видит только «разбор не доделан» и ни слова о том,
        # почему.
        works.отметить(работа, идёт=None, беда=беда.message,
                       подсказка=беда.hint)
        raise
    finally:
        # Отпускается при ЛЮБОЙ беде, а не только при своей. Работа,
        # занятая мёртвым хозяином, — это кнопка, которая твердит
        # «уже идёт», когда никто не идёт.
        works.отпустить(работа)

    return meta


def _ход(работа: Path, стадия: str):
    """Отчёт стадии о том, сколько она уже сделала.

    Пишется на диск, потому что читает это другой процесс — экран.
    Стадий, у которых процент известен по-настоящему, всего две:
    распознавание (услышанные секунды звука) и рамки (посчитанные
    планы). Остальным полосу рисовать нечем, и они её не рисуют:
    правило пакета дизайна — прогресс только там, где процент правда
    известен.
    """
    def отметить(сделано, всего, единица) -> None:
        works.отметить(работа, идёт=стадия, сделано=round(float(сделано), 1),
                       всего=round(float(всего), 1), единица=единица)
    return отметить


def минуты(секунд: float) -> str:
    м, с = divmod(int(секунд), 60)
    return f"{м} min {с:02d} s"


def положить_сценарий(project: Path, script_path: Path, meta: dict,
                      говорить) -> None:
    """Скопировать сценарий в папку разбора очищенным.

    **Копией, а не ссылкой на файл человека.** Файл он переименует,
    перепишет или унесёт на другой диск, а укладка на звук и поиск
    вставленного текста опираются ровно на тот текст, по которому
    считались времена. Разъедутся они молча.
    """
    текст, выброшено = сценарий.read(script_path)
    layout.script(project).write_text(текст, encoding="utf-8")
    meta["script_source"] = str(Path(script_path).expanduser().resolve())
    meta["script_dropped"] = выброшено
    if выброшено:
        говорить(f"  left out of the script as not spoken: {len(выброшено)}")
        for строка in выброшено[:10]:
            говорить(f"      {строка}")
        if len(выброшено) > 10:
            говорить(f"      … and {len(выброшено) - 10} more")


def взять_текст(project: Path, услышано: str, говорить) -> tuple[str, str]:
    """Текст, который ляжет на звук, и откуда он взялся.

    **Два входа, а не два режима сервиса.** Есть сценарий — берётся он,
    и всё работает с прежней точностью: при расхождении правильным
    считается человек, а не машина. Нет сценария — текстом становится
    расшифровка, и дальше по дороге разницы нет ни для одной стадии.

    Расшифровка кладётся в папку разбора СВОИМ файлом. Не в
    `script.txt`: сценарий — то, что принёс человек, и подменять его
    машинным текстом значит через месяц не суметь ответить, чей это
    текст.
    """
    свой = layout.script(project)
    if свой.exists():
        return свой.read_text(encoding="utf-8"), speech.СЦЕНАРИЙ

    layout.transcript(project).write_text(услышано + "\n", encoding="utf-8")
    говорить("  no script — the transcript becomes the text")
    говорить(f"  saved as: {layout.transcript(project).name}")
    return услышано, speech.РАСШИФРОВКА


def _extract(source: Path, project: Path, meta: dict, говорить, ход) -> None:
    media.extract(source, layout.audio(project), layout.proxy(project))
    for файл in (layout.audio(project), layout.proxy(project)):
        if not файл.exists() or not файл.stat().st_size:
            raise VertcutError(
                f"ffmpeg finished, but the file is missing: {файл}",
                hint="the disk is probably full",
            )


