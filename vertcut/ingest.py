"""Разбор видео: дорогая однократная работа.

**Главное решение проекта перенесено целиком: видео разбирается один
раз, ролики из него режутся много раз.** Разбор дорогой (девять
с половиной минут на двадцатиминутное видео), нарезка дешёвая. Отсюда
всё устройство: стадии читают диск, пишут диск и завершаются. Общего
процесса, который держит состояние, нет. Базы нет — всё состояние файлы.

**Стадии переступаются, а не переделываются.** Каждая ставит штамп
в `meta.json`. Распознавание — минуты, и переделывать его ради
пересчёта склеек нельзя. `--again` заставляет пересчитать всё.

**`meta.json` пишется сразу, как только видео опознано**, а не после
первой стадии. Пока его нет, разбора не видно в списке — и первые
минуты человеку было бы негде посмотреть, что работа вообще идёт.

**Отпечаток исходника сверяется на входе.** Подменили файл под тем же
именем — разбор падает, а не режет по старым временам.
"""

from __future__ import annotations

import json
import time
from datetime import datetime
from pathlib import Path

from . import (layout, media, report, script as сценарий, shots as планы,
               slug, speech, works)
