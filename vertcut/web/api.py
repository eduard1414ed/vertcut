@ручка("POST", "найти-текст")
def найти_текст(просьба: Просьба) -> dict:
    """Вставленный кусок сценария — найти его в видео.

    Не нашлось — ДИАГНОЗ, а не «ничего не найдено»: сколько слов
    совпало и на каком слове текст разошёлся. Это правило проекта,
    и здесь оно достаётся даром: `pick.by_text` уже так и отказывает.
    """
    from .. import ingest, pick, speech

    _, meta, laid = ingest.открыть(просьба.слово("слаг"))
    раскладки = pick.by_text(laid, просьба.слово("текст"))
    вышло = []
    for раскладка in раскладки:
        фразы_ = [speech.фразы_слов(laid, a, b) for a, b in раскладка]
        вышло.append({"диапазоны": фразы_,
                      "слова": [[a, b] for a, b in раскладка]})
    return {"нашлось": вышло}



