@ручка("GET", "настройки")
def настройки(просьба: Просьба) -> dict:
    """Что у человека где лежит и чем занято.

    **Без блока ключа и без «формата и качества».** Ключ — пятая
    сессия. Формата и качества в сервисе нет вовсе: кадр вертикалки
    это геометрия площадки, а не настройка, и рисовать поле, которое
    ни на что не влияет, хуже, чем не рисовать его.
    """
    import shutil

    from .. import config, fonts, ingest, layout, subs
    from . import intake as приём

    разборы = []
    for это in ingest.список():
        папка = layout.project(это["слаг"])
        разборы.append({**это, "занято": ingest.занято(папка),
                        "папка": str(папка)})
    корень = layout.root()
    корень.mkdir(parents=True, exist_ok=True)

    личный = layout.my_subs()
    # Личный образец старого образца (до английских ключей) не должен
    # ронять экран настроек: на нём же стоит кнопка «убрать мой стиль»,
    # которой такой файл и убирают. Чисел тогда нет, отказ — словами.
    числа_личного, беда_личного = None, None
    if личный.exists():
        try:
            числа_личного = subs.плоско(subs.из_файла(личный))
        except VertcutError as беда:
            беда_личного = беда.message
    return {
        "корень": str(корень),
        "входящие": str(layout.inbox()),
        "настройки": str(layout.settings_dir()),
        "свободно": shutil.disk_usage(корень).free,
        "занято": sum(р["занято"] for р in разборы),
        "разборы": разборы,
        "входящих": приём.входящие(),
        "личный_стиль": {
            "есть": личный.exists(),
            "путь": str(личный),
            "числа": числа_личного,
            "беда": беда_личного,
        },
        "поставляемый": str(layout.subs_yaml()),
        "шрифты": [{"файл": ш["файл"], "какой": ш["какой"], "есть": ш["есть"]}
                   for ш in fonts.набор()],
        "свои_шрифты": sorted(п.name for п in layout.my_fonts().glob("*")
                              if п.suffix.lower() in (".ttf", ".otf", ".ttc")),
        "диалог_умеем": приём.диалог_умеем(),
        "новые_без_субтитров": config.новые_без_субтитров(),
    }


