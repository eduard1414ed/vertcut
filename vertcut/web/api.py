"""Ручки экрана: просьба страницы → вызов стадии → json.

**Здесь не считается ничего.** Каждая ручка короткая нарочно: взять
слова из просьбы, позвать функцию, которая уже есть, отдать её ответ.
Как только ручка становится длиннее пятнадцати строк, это почти всегда
значит, что в неё заползла логика — и её место не тут, а в стадии,
рядом с остальной такой же, где её позовёт и команда.

**Имена ручек русские, как и слова в терминале.** Это адреса, которые
видит только своя же страница; переводить их на английский значило бы
завести второй словарь для того же самого.
"""

from __future__ import annotations

import json
import os
from dataclasses import dataclass, field
from pathlib import Path

from ..errors import VertcutError


@dataclass
class Просьба:
    """Что пришло со страницы."""

    запрос: dict = field(default_factory=dict)
    тело: dict = field(default_factory=dict)
    сервер: object = None

    def слово(self, имя: str, надо: bool = True) -> str | None:
        """Слово из адреса или из тела — всё равно откуда.

        Одинаково нарочно: `слаг` приезжает то в адресе картинки, то
        в теле правки, и две разные функции для одного и того же
        однажды разошлись бы в отказах.

        **Имени поля в отказе нет, и это не забывчивость.** Имена полей
        русские (`слаг`, `ключ`) — это договор страницы с сервером,
        и человек его не видит. Отказ «чего-то не хватает» случается
        только тогда, когда сломана сама страница, — и до 24-й сессии
        он показывал человеку «The request is missing: слаг». Найдено
        прочёсом (`tools/cyrillic-sweep.py`): по коду этого не видно,
        слово едет переменной. Какое поле не пришло, разработчик видит
        в инструментах браузера, в самой просьбе.
        """
        было = self.запрос.get(имя)
        значение = было[0] if было else self.тело.get(имя)
        if значение is None or значение == "":
            if надо:
                raise VertcutError(_НЕПОЛНАЯ, hint=_НЕПОЛНАЯ_СОВЕТ)
            return None
        return str(значение)

    def число(self, имя: str, надо: bool = True) -> int | None:
        сырое = self.слово(имя, надо)
        if сырое is None:
            return None
        try:
            return int(сырое)
        except ValueError:
            raise VertcutError(f"The page sent “{сырое}” where a number "
                               "should be", hint=_НЕПОЛНАЯ_СОВЕТ) from None

    def дробь(self, имя: str, надо: bool = True) -> float | None:
        сырое = self.слово(имя, надо)
        if сырое is None:
            return None
        try:
            return float(сырое)
        except ValueError:
            raise VertcutError(f"The page sent “{сырое}” where a number "
                               "should be", hint=_НЕПОЛНАЯ_СОВЕТ) from None


_НЕПОЛНАЯ = "The page sent an incomplete request"
_НЕПОЛНАЯ_СОВЕТ = ("reload the page. If it happens again, it's a bug in "
                   "Vertcut — tell the author what you clicked")


@dataclass
class Файл:
    """Ответ файлом с диска: кадр, ролик, лист."""

    путь: Path
    скачать: str | None = None


@dataclass
class Готовое:
    """Ответ тем, чего на диске нет: картинкой, нарисованной сейчас,
    куском звука, вырезанным сейчас, или файлом субтитров."""

    байты: bytes
    тип: str = "image/png"
    скачать: str | None = None


РУЧКИ: dict[tuple[str, str], callable] = {}


def ручка(способ: str, имя: str):
    def взять(дело):
        РУЧКИ[(способ, имя)] = дело
        return дело
    return взять


