@ручка("GET", "вертикалка")
def вертикалка(просьба: Просьба) -> dict:
    """Всё про один ролик: планы, субтитры, состояние файла."""
    from .. import chain, layout, pick, plans, plate, render, subs, tuning
    from . import mark as отметка

    project, meta, всё = _открыть_ролик(просьба)
    cut, ряды, prof = всё["cut"], всё["ряды"], всё["prof"]
    файл = layout.out(project, cut)
    ш, в = int(meta["width"]), int(meta["height"])
    return {
        "слаг": project.name, "id": cut["id"], "зовут": pick.зовут(cut),
        "название": cut["название"], "своё_название": cut.get("своё_название"),
        "файл": cut.get("файл"),
        "duration": cut["duration"], "фразы": cut["phrases"],
        "куски": pick.ranges(cut),
        "планы": [{**ряд,
                   "окно": _окно_долей(chain, ш, в, ряд),
                   "имя_режима": plans.ИМЯ_РЕЖИМА[ряд["mode"]]}
                  for ряд in ряды],
        "огрызки": [р["idx"] for р in plans.stubs(ряды)],
        "субтитры": {
            "строк": len(всё["раскл"]["фразы"]),
            "шрифт": subs.про_шрифт(prof),
            "жалобы": всё["раскл"]["жалобы"],
            "частями": всё["раскл"]["частями"],
            "в_файле": subs.в_файле(project, cut),
        },
        "собирается": _собирается_ли(project, cut["id"]),
        "оценка_сборки": round(cut["duration"] * tuning.ЦЕНА_СБОРКИ, 1),
        "есть_файл": файл.exists(),
        "мегабайт": round(файл.stat().st_size / 1048576, 1)
                    if файл.exists() else None,
        # Байты — для подписи: «MB» на экране пишет общая функция
        # (`слова.мегабайт`), одна на все экраны.
        "байт": файл.stat().st_size if файл.exists() else None,
        "почему_устарел": render.почему_устарел(project, cut),
        "отметка": отметка.снять(layout.cut_json(project, cut["id"])),
        # Плашка в конце — чтобы черновой просмотр знал, что последние
        # секунды ролика идут ею. Планы под ней погашены, и без этого
        # он обрывался бы на три секунды раньше конца.
        #
        # Зовётся ПЛАШКОЙ, а не «хвостом»: слово «хвост» в ответах ручек
        # уже занято — это последние строки журнала работы. Одно слово
        # на две вещи однажды прочитают не тем.
        "плашка": {
            "показывать": plate.включена(plate.сырые(project, cut["id"])),
            "секунды": plate.секунд_у(project, cut["id"]),
            # Секунда РОЛИКА, на которой её показать. Считает раскладка
            # — та же, что считает её для сборки; экран своей арифметики
            # времени не заводит.
            "при": round(всё["раскл"]["плашка_с"]
                         + plate.секунд_у(project, cut["id"]) / 2, 3),
        },
    }


def _собирается_ли(project, ключ: str) -> bool:
    """Стоит ли этот ролик в очереди прямо сейчас.

    Спрашивается у очереди, а не у себя: она и есть состояние сборки,
    и лежит она файлом на диске. Экран, который помнил бы это сам,
    врал бы всякой второй вкладке.
    """
    from . import runner as работа

    что = работа.идёт(project, работа.СБОРКА)
    if что.get("запускается"):
        # Сборку пустили, а хозяина у неё ещё нет. Сказать «не
        # собирается» значит показать человеку, что кнопка не сработала.
        return True
    if not что.get("идёт_сейчас"):
        return False
    return any(д.get("id") == ключ and д.get("состояние") in ("ждёт", "идёт")
               for д in что.get("дела", []))


def _окно_долей(chain, ширина: int, высота: int, ряд: dict) -> dict:
    """Окно колонки — долями кадра, чтобы браузер нарисовал рамку там же.

    Геометрия своя тут не считается: коробка берётся у цепочки, той же
    самой, которой её вырежет сборка. Разойдись они — человек ставил бы
    рамку не туда, где она окажется в файле.
    """
    левый, верх, правый, низ = chain.коробка_окна(ширина, высота, ряд.get("cx"))
    return {"левый": левый / ширина, "ширина": (правый - левый) / ширина,
            "верх": верх / высота, "высота": (низ - верх) / высота}


