@ручка("POST", "стиль-откуда")
def стиль_откуда(просьба: Просьба) -> dict:
    """Взять мой стиль, сделать этот моим, вернуть поставляемый.

    **«Вернуть поставляемый» обязана работать тогда, когда всё
    остальное показать нечем.** Испорченный профиль — это ровно тот
    случай: страница не рисуется, а кнопка нужна именно сейчас.
    Поэтому старый файл здесь не читается вовсе, а просто заменяется.
    """
    import shutil

    from .. import ingest, layout, subs

    project, _, _ = ingest.открыть(просьба.слово("слаг"))
    ключ = просьба.слово("ключ")
    откуда = просьба.слово("откуда")
    починено = []
    if откуда == "поставляемый":
        # Сперва — то, что не читается: оно и привело человека сюда.
        # Ничего не сломано — обычная дорога: свой стиль вертикалке.
        починено = subs.починить(project, ключ, layout.subs_yaml())
        if not починено:
            shutil.copyfile(layout.subs_yaml(),
                            subs.завести_свой(project, ключ))
    elif откуда == "мой":
        if not layout.my_subs().exists():
            raise VertcutError(
                "You haven't saved a style of your own yet",
                hint="click Save as my style, and it will be here")
        # Старый образец не копируется — копия не читалась бы.
        subs.из_файла(layout.my_subs())
        починено = subs.починить(project, ключ, layout.my_subs())
        if not починено:
            shutil.copyfile(layout.my_subs(),
                            subs.завести_свой(project, ключ))
    elif откуда == "сделать-моим":
        layout.my_subs().parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(subs.файл(project, ключ), layout.my_subs())
    elif откуда == "видео":
        # «Взять стиль видео»: свой у вертикалки убирается, и она
        # снова читает общий.
        свой = layout.cut_subs(project, ключ)
        if свой.exists():
            свой.unlink()
            subs.сбросить_кэш()
    else:
        raise VertcutError(f"Unknown style source: {откуда}")
    return {**_после_стиля(просьба), "починено": починено}


