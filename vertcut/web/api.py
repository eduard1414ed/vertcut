@ручка("POST", "собрать")
def собрать(просьба: Просьба) -> dict:
    """Поставить ролик в очередь и пустить сборку своим процессом."""
    from .. import layout, queue as очередь
    from . import runner as работа

    слаг = просьба.слово("слаг")
    project = layout.project(слаг)
    ключ = просьба.слово("ключ", надо=False)
    заново = просьба.слово("заново", надо=False) == "1"
    # Слово «заново» — только когда собирают ВСЁ видео.
    #
    # У очереди «заново» значит «затереть недоделанное и сложить план
    # сначала», то есть по всем роликам. Сказанное вместе с одним
    # ключом оно и превращало «Собрать» у одной вертикалки в сборку
    # всех: ключ ставил в очередь одного, а команда тут же складывала
    # её заново — по всем.
    слова = ["queue", слаг, "--export"]
    if ключ:
        # Один ролик — это та же очередь из одного дела: второго
        # механизма сборки не заводится. Остальных в очереди не трогаем
        # И НЕ ЗАПУСКАЕМ: они остаются ждать.
        #
        # Второе — правка по слову автора. Он нажал «Собрать» у одной
        # вертикалки и получил сборку всех пяти: в очереди ждали
        # остатки прошлой, оборванной сборки, и запуск честно взял их
        # вместе со своим. Ждать им можно, а собираться без просьбы —
        # нет.
        очередь.поставить_один(project, ключ)
        слова += ["--only", ключ]
    elif заново:
        слова.append("--again")
    return работа.запустить(project, работа.СБОРКА, слова)


@ручка("GET", "скачать")
def скачать(просьба: Просьба) -> Файл:
    """Готовый файл. Имя — то, что записано в ролике."""
