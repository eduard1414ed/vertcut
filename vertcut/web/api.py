    """Свой шрифт в общий набор — без всякой вертикалки.

    **Не то же, что «выбрать-шрифт».** Та ручка живёт в редакторе
    субтитров: она ставит шрифт И НАЗНАЧАЕТ его этой вертикалке —
    там человек выбирает шрифт для того, что видит перед собой.
    Здесь вертикалки нет вовсе: шрифт просто кладётся к себе, чтобы
    потом появиться в списке у любой.

    Работа при этом одна и та же и живёт она в `fonts.поставить`:
    второе место, знающее, куда класть шрифты, разъехалось бы
    с первым молча.
    """
    from .. import fonts
    from . import intake as приём

    путь = приём.выбрать_на_диске("Choose a font file",
                                  тип="public.font")
    if путь is None:
        return {"передумал": True, **настройки(просьба)}
    свой = fonts.поставить(Path(путь))
    return {"поставлен": свой.name, **настройки(просьба)}


