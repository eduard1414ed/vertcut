def принять_файл(путь: str) -> dict:
    """Опознать видео и завести ему папку. Стадий не трогает.

    Не ручка, а общее для трёх дорог: системный диалог, путь руками
    и брошенный в окно файл. Три копии этого кода разошлись бы в том,
    что именно возвращается странице.
    """
    from .. import ingest

    project, meta = ingest.принять(Path(путь))
    return {"слаг": project.name, "источник": Path(meta["source"]).name,
            "duration": meta.get("duration"), "разобрано": False}


@ручка("GET", "обложка")
def обложка(просьба: Просьба) -> Файл:
    """Кадр, которым видео показано в списке.

    Отказывает словами, если кадра ещё нет: страница ставит на это
    место полосатую заглушку из пакета дизайна — то есть честно
    показывает, что кадра нет, а не рисует чёрный прямоугольник.
    """
    from .. import ingest, layout

    project = layout.project(просьба.слово("слаг"))
    if not project.exists():
        raise VertcutError(f"No such video: {просьба.слово('слаг')}")
    return Файл(ingest.обложка(project))


