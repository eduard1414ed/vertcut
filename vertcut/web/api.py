@ручка("GET", "куски")
def куски(просьба: Просьба) -> dict:
    """Что уже выбрано у этого видео."""
    from .. import ingest, layout, notes, pick, render

    project = layout.project(просьба.слово("слаг"))

    # Устаревшая — не то же, что собранная: колонка звала её «exported»,
    # а маршрут рядом — «out of date». Спрашивается только у собранных:
    # у несобранной ответ известен и без счёта.
    #
    # Стиль вертикалки не читается (испорчен или старого образца) —
    # неизвестность значит «устарел», как и у штампа. Раньше отказ
    # ронял всю колонку на каждом экране, и до редактора, где стиль
    # чинится, было не дойти.
    def устарел(c) -> bool:
        try:
            return render.почему_устарел(project, c) is not None
        except VertcutError:
            return True

    вышло = []
    for c in pick.listing(project):
        собрано = ingest.собран(project, c)
        вышло.append({"id": c["id"], "зовут": pick.зовут(c),
                      "duration": c["duration"],
                      "фразы": c["phrases"], "файл": c.get("файл"),
                      "собрано": собрано,
                      "устарел": собрано and устарел(c),
                      "описание": notes.прочитать(c)["текст"]})
    return {"куски": вышло}


@ручка("POST", "прикинуть")
def прикинуть(просьба: Просьба) -> dict:
    """Что выйдет из этого выбора — БЕЗ записи на диск.

    Отдельно от «создать» нарочно: полоса «выбрано» показывает длину,
    таймкоды и то, на чём стоят края, ещё до того, как человек решил.
    Слишком короткий кусок здесь не отказ, а предупреждение словами:
    отказывать надо в момент создания, а не мешать выбирать.
    """
    return _описать(просьба, записывать=False)


@ручка("POST", "выбрать-кусок")
def выбрать_кусок(просьба: Просьба) -> dict:
    """Создать вертикалку из выбранных фраз."""
    return _описать(просьба, записывать=True)


def _описать(просьба: Просьба, записывать: bool) -> dict:
    """Общее для «прикинуть» и «создать»: одна дорога к паре номеров слов.

    Две копии разошлись бы в том, что именно человек видит в полосе,
    и в том, что из этого получится.
    """
    from .. import ingest, pick, plate, speech
    from ..errors import VertcutError as Беда

    project, meta, laid = ingest.открыть(просьба.слово("слаг"))
    пары = [(int(a), int(b)) for a, b in (просьба.тело.get("диапазоны") or [])]
    if not пары:
        raise Беда("No phrases selected")
    куски_ = pick.by_ranges(laid, пары)
    как = "phrases " + ",".join(f"{a}-{b}" for a, b in пары)
    описание = pick.describe(laid, куски_, как, float(meta["duration"]))

    первое = pick.pieces(описание)[0]["words"]["first"]
    # Порог длины растёт вместе с плашкой в конце: сколько секунд она
    # заберёт, знает `plate`, а сравнивает по-прежнему `pick`.
    хвост = plate.секунд_у(project)
    если = {**описание,
            "не_хватает": pick.не_хватает_длины(описание, хвост),
            "порог": pick.порог_длины(хвост),
            "хвост": хвост,
            "с_начала_фразы": speech.с_начала_фразы(laid, первое)}
    if not записывать:
        return если

    pick.check_length(описание, хвост)
    pick.save(project, описание)
    return {**если, **pick.load(project, описание["id"])}



