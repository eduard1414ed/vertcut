@ручка("GET", "здоровье")
def здоровье(просьба: Просьба) -> dict:
    """Жив ли экран и где он — для того, кто спрашивает СНАРУЖИ.

    **Единственная ручка без пропуска**, и причина в том, кто
    спрашивает. Не страница: у неё пропуск есть. Спрашивает чужая
    программа — значок в строке меню, скрипт, следующий двойной
    щелчок, — и пропуска она не знает и знать не может. Ровно за этим
    ручка и заведена.

    **Ответ ничего нового не открывает.** Всё, что здесь есть, и так
    лежит в `~/.vertcut/app.json` рядом с настройками — файл этот
    писан для того же вопроса. А чужая страница в браузере ответа
    не прочтёт: имя хозяина проверено выше, и на просьбу с чужим
    `Origin` сервер отвечает отказом ещё до всяких ручек.

    **Пропуск едет в адресе нарочно.** Спрашивают эту ручку затем,
    чтобы открыть вкладку; адрес без пропуска открыл бы человеку
    отказ «нужен пропуск этого запуска» — то есть ответ был бы верен
    и бесполезен.

    Что в очереди — считает `queue.идущие`, здесь только передача.
    """
    from .. import queue as очередь
    from . import server

    return {"сервис": "vertcut", "pid": os.getpid(),
            "адрес": server.адрес(просьба.сервер),
            "собирается": очередь.идущие()}


