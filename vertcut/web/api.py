@ручка("GET", "окружение")
def окружение(просьба: Просьба) -> dict:
    """Чего не хватает, чтобы сервис работал.

    Ручка ОТДЕЛЬНАЯ и тяжёлая: она поднимает каждую библиотеку по имени
    — иначе «стоит ли она» узнать нельзя. Страница просит её после того,
    как нарисовалась, и говорит полосой, только если чего-то нет.
    """
    from .. import deps

    return {
        "всё_на_месте": deps.всё_на_месте(),
        "питон": deps.python_line(),
        "ffmpeg": {k: str(v) for k, v in deps.ffmpeg().items()},
        "библиотеки": [{"пакет": б["пакет"], "стоит": б["стоит"],
                        "версия": б["версия"], "зачем": б["зачем"],
                        "лежит_но_не_грузится": б["лежит_но_не_грузится"],
                        "почему": б["почему"]}
                       for б in deps.libs()],
        # Чего не хватает — СЛОВАМИ и по одной беде на строку. Собирает
        # это `deps`, а не экран: полоса на экране раньше выбирала
        # строки отчёта по буквам «НЕ» в них и теряла всякую беду,
        # которая назвалась иначе.
        "не_хватает": deps.чего_не_хватает(),
        "строки": deps.отчёт(),
    }


@ручка("GET", "помощь")
def помощь(просьба: Просьба) -> dict:
    """Факты про ЭТУ машину — то, чем страница помощи отличается
    от инструкции.

    Инструкция говорит «посмотрите в журнал»; здесь написан путь
    к нему и лежат последние строки последнего запуска. Человек,
    у которого что-то сломалось, не должен ещё и искать, где смотреть.

    **Тяжёлого тут нет:** пути и чтение одного файла. Состояние
    окружения просится отдельной ручкой и приезжает потом — по той же
    причине, по которой оно отделено от начала.
    """
    from .. import layout

    журнал = layout.журнал()
    логи = layout.журналы_запуска()
    хвост = []
    if логи:
        хвост = логи[-1].read_text(encoding="utf-8",
                                   errors="replace").splitlines()[-30:]
    программа = layout.программа()
    версия = (json.loads((программа / layout.МЕТКА_ПРОГРАММЫ).read_text(
        encoding="utf-8")) if программа else {})
    return {
        "пути": {
            "разборы": str(layout.root()),
            "входящие": str(layout.inbox()),
            "настройки": str(layout.settings_dir()),
            "журнал": str(журнал),
            "программа": str(программа) if программа else "",
        },
        "версия": версия,
        "лог": {"файл": str(логи[-1]) if логи else "",
                "строки": хвост, "сколько": len(логи)},
    }


