ПОРТ = 7864
ПОРТОВ_ПОДРЯД = 20

# Как зовётся то, чем страница доказывает, что она своя.
#
# **ПРОПУСК, а не «ключ», и это не украшение.** Слово «ключ» в проекте
# уже занято: ключ ролика — это номера его слов (`0040-0097`), он стоит
# в адресе почти каждой картинки и почти каждой правки. Пока оба звались
# одинаково, они затирали друг друга в одном и том же адресе: сервис
# видел ключ ролика на месте пропуска и отвечал «не тот ключ» — то есть
# отказывал в кадрах и превью на экранах вертикалки и субтитров.
#
# Поймано пробой, которая гоняет экраны как браузер. Два разных смысла
# под одним именем однажды сходятся в одной строке — тут они сошлись
# в адресе.
#
# Имя заголовка латиницей: имена заголовков в HTTP обязаны быть видимой
# латиницей, и русское браузер просто откажется отправлять.
ПРОПУСК = "pass"
ЗАГОЛОВОК_ПРОПУСКА = "X-Vertcut-Pass"

