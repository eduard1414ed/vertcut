def _следить_за_ярлыком(родитель: int, сервер: Экран) -> None:
    """Умер ярлык — уходит и сервер.

    **Ради этого всё и заведено.** Иконку снимают силой, машина
    засыпает, человек жмёт «завершить принудительно» — и сервер,
    запущенный из неё, остаётся жить сиротой. Он держит порт, а
    следующий двойной щелчок не поднимается, и человек не понимает
    почему: окна нет, а «занято».

    Смотрим НА ЖИЗНЬ РОДИТЕЛЯ, а не на `getppid`: после смерти
    родителя его номер достаётся кому-то другому, и сравнение
    с единицей врёт на Windows.

    Работает только под ярлыком: из терминала сервис так себя
    не ведёт — там родитель это оболочка человека, и закрытая вкладка
    терминала не повод уносить с собой чужую работу.

    **Единица — это НЕ живой родитель, хотя `works.жив` говорит
    обратное.** Там она права: чужой процесс, на который нет прав,
    считается живым. Здесь единица значит другое — ярлыка уже нет,
    нас усыновила система. Поймано на проверке: сторож ждал вечно
    ровно в том случае, ради которого он и заведён.
    """
    while True:
        time.sleep(2)
        if not works.жив(родитель):
            сервер.shutdown()
            return


def что_идёт_прямо_сейчас() -> list[str]:
    """Какая долгая работа переживёт закрытый экран.

    **Она НЕ обрывается, и это решение шестой сессии.** Разбор и сборка
    идут своими процессами именно затем, чтобы пережить закрытую
    вкладку; оборвать девять минут работы за то, что человек закрыл
    окно, значит наказать его за закрытое окно. Поэтому при выходе
    сервис говорит, что осталось идти, — а не спрашивает и не гасит.
    """
    идут = []
    корень = layout.root()
    if not корень.exists():
        return идут
    for папка in sorted(корень.iterdir()):
        if not папка.is_dir():
            continue
        for что, файл in (("analysis", layout.work(папка)),
                          ("export", layout.queue(папка))):
            состояние = works.прочитать(файл)
            хозяин = состояние.get("хозяин") or {}
            if хозяин and works.жив(int(хозяин.get("pid") or 0)):
                идут.append(f"{что} of “{папка.name}”")
    return идут


# ─── остановить без выхода из системы ────────────────────────────────
#
# До 27-й сессии экран гасился тремя способами, и ни одного человеку
# с иконкой: Ctrl+C в терминале, смерть ярлыка (сторож выше) и номер
# процесса — им пользуется внешний значок в строке меню. Запущенный
# двойным щелчком сервис жил до выхода из системы: у иконки нет окна
# и нет места в Dock (`LSUIElement`), а экран помощи советовал «Quit
# Vertcut» — не говоря, чем.
#
# Теперь способ один на двоих: кнопка на экране и `vertcut stop` зовут
# ОДНУ функцию — `выключить`, внутри самого сервера. Команда стучится
# к нему той же ручкой, что и страница. Грубая сила (сигнал) — только
# запасом, если сервер не ответил: так он успевает отпустить `app.json`
# и сказать, что продолжает идти.

# Через сколько после ответа гасить сервер. Ответ должен успеть уйти
# странице: погаси раньше — и кнопка получит обрыв вместо «остановлен»
# и покажет «Vertcut is not responding». Не замер — запас: ответ
# в несколько сотен байт уходит за миллисекунды.
ПАУЗА_ПЕРЕД_УХОДОМ = 0.3

# Сколько `vertcut stop` ждёт, пока сервер уйдёт сам, прежде чем
# слать сигнал. Сервер проверяет «пора ли уходить» раз в полсекунды
# (`serve_forever`), плюс пауза выше и закрытие — уходит он за
# секунду. Пять — с запасом на занятую машину.
ЖДАТЬ_УХОДА = 5.0


def выключить(сервер: Экран) -> dict:
    """Погасить ЭТОТ экран. Отвечает сразу, гасится чуть позже.

    **Долгая работа не обрывается** — то же решение шестой сессии, что
    у закрытой вкладки (`что_идёт_прямо_сейчас`): разбор и сборка идут
    своими процессами. Ответ называет то, что пойдёт дальше, — страница
    показывает это человеку ДО нажатия (ручка `что-идёт`) и после.

    `shutdown` зовётся из своей нити: из нити просьбы он ждал бы
    `serve_forever`, а тот — конца этой самой просьбы.
    """
    идут = что_идёт_прямо_сейчас()
    threading.Timer(ПАУЗА_ПЕРЕД_УХОДОМ, сервер.shutdown).start()
    return {"остановлен": True, "идёт": идут}


def _попросить_уйти(состояние: dict) -> bool:
    """Постучаться к работающему экрану его же ручкой `выключить`.

    Путь ручки — русскими буквами, и в просьбу он едет закодированным
    (`quote`): `http.client` берёт строку запроса только латиницей.
    Пропуск — заголовком, как у страницы; имя хозяина `http.client`
    ставит сам — `127.0.0.1:порт`, то, что сервер и ждёт.
    """
    import http.client
    from urllib.parse import quote

    связь = http.client.HTTPConnection("127.0.0.1", int(состояние["порт"]),
                                       timeout=ЖДАТЬ_УХОДА)
    try:
        связь.request("POST", quote("/апи/выключить"), body=b"{}",
                      headers={ЗАГОЛОВОК_ПРОПУСКА: состояние["пропуск"],
                               "Content-Type": "application/json"})
        return связь.getresponse().status == 200
    except OSError:
        return False
    finally:
        связь.close()


def _дождаться_ухода(сколько: float) -> bool:
    срок = time.monotonic() + сколько
    while time.monotonic() < срок:
        if живой_хозяин() is None:
            return True
        time.sleep(0.1)
    return живой_хозяин() is None


def остановить_работающий(говорить=report.скажи) -> None:
    """`vertcut stop`: погасить работающий экран, где бы он ни был поднят
    — из терминала, иконкой или с экрана.

    **Не работает — не отказ, а ответ, и код выхода ноль.** Просьба
    «пусть сервис не работает» уже исполнена; отказом на неё упал бы
    всякий сценарий, который гасит сервис «на всякий случай» перед
    обновлением, — а ровно так его и зовут (INSTALL.md, «Updating»).

    Сигнал — только запасом, если сервер не ответил на просьбу.
    На Windows `os.kill` с любым сигналом — это `TerminateProcess`,
    то есть смерть без уборки: `app.json` останется с мёртвым хозяином,
    и это не беда — живой ли хозяин, спрашивается по номеру процесса
    и порту (`живой_хозяин`), а не по записи.
    """
    import signal

    состояние = живой_хозяин()
    if состояние is None:
        говорить("Vertcut isn't running.")
        return
    pid = int((состояние.get("хозяин") or {}).get("pid") or 0)
    if not (_попросить_уйти(состояние) and _дождаться_ухода(ЖДАТЬ_УХОДА)):
        try:
            os.kill(pid, signal.SIGTERM)
        except OSError:
            pass
        if not _дождаться_ухода(ЖДАТЬ_УХОДА):
            raise VertcutError(
                f"Vertcut didn't stop (process {pid})",
                hint="end that process yourself: Activity Monitor on a Mac, "
                     "Task Manager on Windows")
    говорить("Vertcut has stopped.")
    идут = что_идёт_прямо_сейчас()
    if идут:
        говорить("\nThis keeps going on its own:")
        for строка in идут:
            говорить(f"  {строка}")
        говорить("Open Vertcut again to see how it's doing.")


def run(порт: int | None = None, открывать: bool = True,
        уйти_с_ярлыком: bool = False, говорить=report.скажи) -> None:
    """Запустить экран и держать его, пока не остановят.

    **Второй запуск при живом первом не поднимает второго сервера.**
    Он открывает ту же вкладку — то же правило одного хозяина, что
    у разбора и сборки, и заведено оно тем же механизмом.
    """
    # Родитель спрашивается ПЕРВЫМ ДЕЛОМ, до всякой работы: пока
    # поднимается сервер, ярлык может успеть умереть, и тогда мы
    # запомним единицу вместо него.
    родитель = os.getppid()
    if уйти_с_ярлыком and родитель <= 1:
        говорить("The process that started me has already exited — "
                 "not starting.")
        return

    уже = живой_хозяин()
    if уже:
        куда = адрес_хозяина(уже)
        говорить("Vertcut is already running — opening the same tab.")
        говорить(f"\n    {куда}\n")
        if открывать:
            открыть_в_браузере(куда)
        return

    подчистить_журнал()
    сервер = завести(порт, говорить=говорить)
    куда = адрес(сервер)
    файл = layout.экран_хозяин()
    файл.parent.mkdir(parents=True, exist_ok=True)
    works.взять(файл, "экран")  # не для человека: имя хозяина в app.json
    works.отметить(файл, порт=сервер.server_address[1], пропуск=сервер.пропуск)

    говорить("Vertcut is running. Open it in the browser:")
    говорить(f"\n    {куда}\n")
    говорить("The pass in the address is new on every start: without it,\n"
             "another page in the same browser could knock here and do "
             "something.")
    говорить("\nStop — Ctrl+C here, Quit Vertcut on the page, or vertcut stop.\n"
             "Analysis and export run as processes of their own and keep "
             "going\neven if you stop this.")
    if открывать and not открыть_в_браузере(куда):
        говорить("\nCouldn't open the browser — open the address above "
                 "yourself.")
    if уйти_с_ярлыком and родитель > 1:
        threading.Thread(target=_следить_за_ярлыком,
                         args=(родитель, сервер), daemon=True).start()
    try:
        сервер.serve_forever()
        # Сюда приходят без Ctrl+C: кнопка «Quit Vertcut», `vertcut stop`
        # или ушедший ярлык. Код выхода — ноль: ярлык считает это
        # обычным концом, а не «Vertcut didn't start».
        говорить("\nStopped.")
    except KeyboardInterrupt:
        говорить("\nStopped.")
    finally:
        сервер.server_close()
        works.отпустить(файл)
        идут = что_идёт_прямо_сейчас()
        if идут:
            говорить("\nThis keeps going on its own:")
            for строка in идут:
                говорить(f"  {строка}")
            говорить("Open Vertcut again to see how it's doing.")
