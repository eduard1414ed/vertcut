def живой_хозяин() -> dict | None:
    """Кто держит экран прямо сейчас — или ничего.

    Спрашивается ДВАЖДЫ, и это не перестраховка. Номер процесса
    отвечает «жив ли тот, кто записался»; но после грубого убийства
    номер достаётся кому-то другому, и живым окажется чужой процесс.
    Поэтому вторым делом стучимся на порт: отвечает — значит это
    и правда наш экран.
    """
    состояние = works.прочитать(layout.экран_хозяин())
    хозяин = состояние.get("хозяин") or {}
    порт = состояние.get("порт")
    if not (хозяин and порт and works.жив(int(хозяин.get("pid") or 0))):
        return None
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as гнездо:
        гнездо.settimeout(1.0)
        try:
            гнездо.connect(("127.0.0.1", int(порт)))
        except OSError:
            return None
    return состояние


def адрес_хозяина(состояние: dict) -> str:
    return (f"http://127.0.0.1:{состояние['порт']}/"
            f"?{ПРОПУСК}={состояние['пропуск']}")


def открыть_в_браузере(куда: str) -> bool:
    """Открыть вкладку. Адрес уходит АРГУМЕНТОМ, а не строкой скрипта.

    **Это замер, и он стоил сломанного первого запуска.** Стандартный
    `webbrowser` на macOS не зовёт программу с адресом — он собирает
    кусочек AppleScript (`open location "…"`) и пишет его `osascript`
    в стандартный ВВОД. А `osascript` читает ввод не как utf-8, и слово
    «пропуск» по дороге рассыпается. Замер на подставном сервере::

        зовём:   http://127.0.0.1:7899/?пропуск=ЗАМЕР123
        доехало: GET /?%C3%94%EF%A3%BF%C3%93%C3%94%C3%9B%C3%92%C3%8D=…

    `%EF%A3%BF` — яблоко Apple: примета того, что utf-8 прочли как
    MacRoman. Сервер честно смотрел, пропуска не находил и отвечал
    отказом — то есть КАЖДЫЙ запуск из терминала открывал белую
    страницу «нужен пропуск этого запуска».

    Через аргумент те же байты доезжают целыми::

        доехало: GET /?%D0%BF%D1%80%D0%BE%D0%BF%D1%83%D1%81%D0%BA=…

    **Это ДЕСЯТОЕ место проекта, где русские буквы не проходят**,
    и той же породы, что уже записанные девять. Ярлык (`launcher.sh`)
    и системный диалог (`web/intake.py`) им не болели никогда ровно
    потому, что оба зовут программу аргументом; здесь просто
    не заметили, что стандартная библиотека так не делает.

    **С 22-й сессии адрес латинский** (`?pass=`), и беде здесь больше
    не на чем случиться. Дорога аргументом остаётся: она верна сама
    по себе, а адрес однажды снова может понести чужие буквы.

    Не открылось — не беда и не отказ: адрес напечатан, человек
    откроет сам. Поэтому здесь `bool`, а не исключение.
    """
    import subprocess

    if sys.platform == "darwin":
        зов = ["open", куда]
    elif sys.platform.startswith("linux"):
        зов = ["xdg-open", куда]
    else:
        # Windows: там стандартная библиотека зовёт `os.startfile`,
        # который берёт адрес строкой питона и кодировкой его не портит.
        # Своей ветки ради этого заводить не надо — она была бы копией
        # того, что уже сделано верно.
        зов = None

    if зов is not None:
        try:
            return subprocess.run(зов, capture_output=True).returncode == 0
        except (OSError, subprocess.SubprocessError):
            pass          # программы нет — пробуем общим способом

    import webbrowser
    try:
        return bool(webbrowser.open(куда))
    except Exception:
        return False


