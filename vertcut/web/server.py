# исключение из главного заслона должно быть видно в одном месте
# и целиком — иначе через год их окажется пять, и узнается это
# перебором файла.
#
# Здесь она одна. `здоровье` спрашивает не страница, а чужая программа
# (значок в строке меню), которая пропуска не знает и знать не может;
