"""Сервер экрана: раздача страницы и перевод её просьб в вызовы.

## Почему стандартная библиотека, а не фреймворк

Ни одной новой зависимости. Причина та же, по которой разбор
аргументов сделан на `argparse`, а не на `click`: человек ставит
окружение руками на своей машине, и каждая строчка в списке — это
шанс, что установка не соберётся. Сервис здесь местный, одностраничный
и односмотрительный: запросов в секунду единицы, и `http.server`
покрывает это с запасом.

Работы у сервера ровно три: отдать файл, позвать функцию, перевести
отказ в json. Всё остальное — в стадиях.

## Слушает только себя

`127.0.0.1`, а не `0.0.0.0`. Разница не косметическая: во втором
случае сервис виден всей сети вокруг — в кафе это чужие люди,
а у сервиса есть кнопка «удалить» и доступ ко всем видео на диске.

**Плюс ПРОПУСК в адресе.** Одного `127.0.0.1` мало: любая страница,
открытая в том же браузере, может постучаться на `127.0.0.1` и
приказать сервису что-нибудь сделать — браузер послушно приложит
запрос. Поэтому у каждого запуска свой случайный пропуск: страница
получает его в адресе и прикладывает к каждой просьбе заголовком.
Чужая страница пропуска не знает и знать не может.

Зовётся он ПРОПУСКОМ, а не ключом, потому что слово «ключ» в проекте
занято: ключ ролика — это номера его слов. Пока оба звались одинаково,
они затирали друг друга в одном адресе.

**И проверка имени хозяина.** Браузер можно заманить на адрес, который
выглядит чужим, а разрешается в `127.0.0.1`. Поэтому сервер смотрит,
на какое имя к нему пришли, и чужое имя не обслуживает.

## Что он НЕ делает

Не держит состояние. Всё, что экран показывает, читается с диска
в момент запроса; всё, что экран меняет, ложится на диск сразу. Убили
сервер посреди работы — потеряется ровно ничего, потому что терять
нечего: разбор и сборка идут своими процессами и пишут своё состояние
сами.
"""

