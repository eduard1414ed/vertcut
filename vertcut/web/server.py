class Отказ(Exception):
    """Отказ самого сервера: не туда постучались, не тот пропуск.

    Отдельно от `VertcutError` нарочно. Та — про работу сервиса
    и показывается человеку полосой на экране. Эта — про сам запрос,
    и человеку показывать её незачем: он её не вызывал и починить
    не может.
    """

    def __init__(self, код: int, что: str):
        super().__init__(что)
        self.код = код
        self.что = что


class Экран(ThreadingHTTPServer):
    daemon_threads = True
    allow_reuse_address = True

    def __init__(self, адрес, пропуск: str):
        super().__init__(адрес, Ручка)
        self.пропуск = пропуск

    def server_bind(self) -> None:
        """Сесть на порт, не спрашивая сеть.

        Стандартный `HTTPServer.server_bind` зовёт `socket.getfqdn` —
        обратный запрос имени для адреса. Ответ нам не нужен: адрес
        всегда 127.0.0.1, а имя стандартный сервер больше ни для чего
        не берёт. На машине macOS у GitHub ответ не приходил дольше
        30 секунд, и экран не поднимался вовсе.
        """
        socketserver.TCPServer.server_bind(self)
        self.server_name, self.server_port = self.server_address[:2]

    @property
    def имена(self) -> set[str]:
        порт = self.server_address[1]
        return {f"127.0.0.1:{порт}", f"localhost:{порт}"}


class Ручка(BaseHTTPRequestHandler):
    protocol_version = "HTTP/1.1"
    server_version = "vertcut"
    sys_version = ""

    # ── то, ради чего всё ────────────────────────────────────────────

    def handle(self) -> None:
        """Браузер закрыл простаивающее соединение — не падение.

        Вкладку закрыли, браузер ушёл: соединение, которое ждало
        следующей просьбы, рвётся сбросом ещё ДО наших ручек, и
        стандартный сервер печатал это в журнал трассировкой «Exception
        occurred during processing». Человек, открывший журнал после
        беды, видел пять таких на ровном месте. Найдено прочёсом
        (`tools/cyrillic-sweep.py`), 24-я сессия.
        """
        try:
            super().handle()
        except (BrokenPipeError, ConnectionResetError, ConnectionAbortedError):
            pass

    def do_GET(self) -> None:
        self._обслужить("GET")

    def do_POST(self) -> None:
        self._обслужить("POST")

    def _обслужить(self, способ: str) -> None:
        разбор = urlparse(_адрес_как_текст(self.path))
        путь = unquote(разбор.path)
        запрос = parse_qs(разбор.query)
        try:
            self._свой_ли_дом()
            if путь == "/" or путь == "/index.html":
                self._страница(запрос)
            elif путь.startswith("/файлы/"):
                self._обвес(путь[len("/файлы/"):])
            elif путь.startswith("/шрифты/"):
                self._шрифт(путь[len("/шрифты/"):])
            elif путь == "/апи/бросить" and способ == "POST":
                self._бросить(запрос)
            elif путь.startswith("/апи/"):
                self._ручка(способ, путь[len("/апи/"):], запрос)
            else:
                raise Отказ(404, "no such address")
        except Отказ as о:
            self._просто(о.код, о.что)
        except VertcutError as б:
            # Отказ сервиса — не поломка сервера. Он доезжает до
            # страницы своим видом: что случилось и что делать.
            #
            # **Вид отказа едет отдельным словом, а не угадывается
            # по тексту.** «Дорого» — это вопрос, а не поломка: экран
            # обязан показать его полосой с кнопкой «да, спросить»,
            # а не красной бедой. Разбирать для этого сообщение
            # значило бы завести в браузере знание о том, как оно
            # написано, — и потерять его от первой же правки слов.
            это = {"беда": б.message, "подсказка": б.hint,
                   "вид": getattr(б, "вид", "беда")}
            # «слаг» и «ключ» — у отказа «стиль не читается»: страница
            # ставит под ним кнопку в редактор этой вертикалки.
            for лишнее in ("сколько", "порог", "слаг", "ключ"):
                if hasattr(б, лишнее):
                    это[лишнее] = getattr(б, лишнее)
            self._json(это, код=400)
        except (BrokenPipeError, ConnectionResetError, ConnectionAbortedError):
            # Человек ушёл со страницы посреди ответа. Это не беда.
            # Обрыв бывает трёх видов, и браузер, бросивший скачивание
            # ролика, рвёт соединение сбросом, а не трубой: до 24-й
            # сессии это печаталось в журнал как падение сервиса.
            pass
        except Exception:
            # Заглушек, молча возвращающих пустоту, здесь нет. Незнакомая
            # поломка едет на страницу словами и печатается в терминал
            # целиком — иначе её негде будет искать.
            след = traceback.format_exc()
            print(f"\nCrash on {способ} {путь}:\n{след}",
                  file=sys.stderr, flush=True)
            self._json({"беда": "Vertcut crashed on this request.",
                        "подсказка": "the details are printed in the terminal "
                                     "running vertcut screen, or in the log"},
                       код=500)

    # ── кто стучится ─────────────────────────────────────────────────

    def _свой_ли_дом(self) -> None:
        """На чьё имя пришли. Чужое имя не обслуживаем."""
        дом = (self.headers.get("Host") or "").lower()
        if дом not in self.server.имена:
            raise Отказ(421, "Vertcut only answers on 127.0.0.1")
        откуда = self.headers.get("Origin")
        if откуда and urlparse(откуда).netloc.lower() not in self.server.имена:
            raise Отказ(403, "the request came from another page")

    def _пропуск_верный(self, пропуск: str | None) -> bool:
        # Сравнение постоянного времени: обычное `==` отвечает тем
        # быстрее, чем раньше строки разошлись, и по этому времени
        # пропуск подбирается.
        #
        # Сравниваются БАЙТЫ, а не строки. На строках с нерусскими
        # буквами `compare_digest` не сравнивает, а падает — то есть
        # подсунутый пропуск «нетакой» роняет сервер вместо отказа.
        # Поймано проверкой на первом же запуске.
        if not пропуск:
            return False
        return secrets.compare_digest(пропуск.encode("utf-8"),
                                      self.server.пропуск.encode("utf-8"))

    # ── страница и обвес ─────────────────────────────────────────────

    def _страница(self, запрос: dict) -> None:
        if not self._пропуск_верный((запрос.get(ПРОПУСК) or [None])[0]):
            raise Отказ(403,
                        "this needs the pass for this run — it is in the "
                        "address that vertcut screen printed")
        self._файл(layout.web() / "index.html")

    def _обвес(self, имя: str) -> None:
        """Стили и скрипты. Без пропуска: секрета в них нет, а чужая
        страница до них всё равно не дотянется — имя хозяина проверено."""
        self._файл(_внутри(layout.web(), имя))

    def _шрифт(self, имя: str) -> None:
        """Шрифт интерфейса. Ищется в двух местах, и порядок важен.

        Сперва папка шрифтов ЭКРАНА, потом поставляемые шрифты
        субтитров: Golos Text и Literata нужны и там и там, и второй
        копии на диске заводить незачем.
        """
        for папка in (layout.web_fonts(), layout.fonts()):
            путь = папка / Path(имя).name
            if путь.exists():
                return self._файл(путь)
        raise Отказ(404, f"no such font: {имя}")

    # ── ручки ────────────────────────────────────────────────────────

    def _ручка(self, способ: str, имя: str, запрос: dict) -> None:
        from . import api

        if имя not in БЕЗ_ПРОПУСКА \
                and not self._пропуск_верный(self.headers.get(ЗАГОЛОВОК_ПРОПУСКА)):
            # Пропуск принимается и из адреса — не поблажка, а
            # необходимость. `<img>`, `<a download>` и `<audio>`
            # заголовков не носят вовсе: браузер их просто не даёт
            # приложить. А кадры, превью, звук и готовые ролики
            # приезжают именно ими.
            #
            # Поймано глазами автора на первом же экране: список видео
            # показывал значки битых картинок, потому что каждая
            # картинка получала отказ.
            if not self._пропуск_верный((запрос.get(ПРОПУСК) or [None])[0]):
                raise Отказ(403, "wrong pass")
        дело = api.РУЧКИ.get((способ, имя))
        if дело is None:
            raise Отказ(404, f"no such endpoint: {способ} {имя}")
        просьба = api.Просьба(запрос=запрос, тело=self._тело(),
                              сервер=self.server)
        ответ = дело(просьба)
        if isinstance(ответ, api.Файл):
            self._файл(ответ.путь, имя_для_скачивания=ответ.скачать)
        elif isinstance(ответ, api.Готовое):
            self._байты(ответ.байты, ответ.тип, имя=ответ.скачать)
        else:
            self._json(ответ)

    def _бросить(self, запрос: dict) -> None:
        """Файл, брошенный в окно браузера, — прямо на диск.

        **Своя дорога, мимо ручек, и вот почему.** Все остальные
        просьбы — это json в память: они короткие. Здесь в теле лежит
        само видео, и прочитать его в память нельзя — трёхгигабайтный
        подкаст положил бы сервис на машине, где памяти четыре
        гигабайта. Байты переливаются на диск куском за куском.

        Дальше начинается работа сервиса, и она уже не здесь: имя,
        место, времянка с переименованием — в `приём`, опознание —
        в разборе.
        """
        from . import api
        from . import intake as приём

        if not self._пропуск_верный(self.headers.get(ЗАГОЛОВОК_ПРОПУСКА)):
            raise Отказ(403, "wrong pass")
        имя = (запрос.get("имя") or [""])[0]
        сколько = int(self.headers.get("Content-Length") or 0)
        if сколько <= 0:
            raise Отказ(400, "no file in the request body")
        путь = приём.положить(имя, self.rfile.read, сколько)
        self._json(api.принять_файл(str(путь)))

    def _тело(self) -> dict:
        сколько = int(self.headers.get("Content-Length") or 0)
        if not сколько:
            return {}
        сырое = self.rfile.read(сколько)
        try:
            это = json.loads(сырое.decode("utf-8"))
        except (UnicodeDecodeError, json.JSONDecodeError):
            raise Отказ(400, "the request body is not JSON") from None
        if not isinstance(это, dict):
            raise Отказ(400, "the request body is not an object")
        return это

    # ── ответы ───────────────────────────────────────────────────────

    def _json(self, что: dict, код: int = 200) -> None:
        тело = json.dumps(что, ensure_ascii=False,
                          default=_в_простое).encode("utf-8")
        self._байты(тело, "application/json; charset=utf-8", код)

    def _просто(self, код: int, что: str) -> None:
        self._байты(что.encode("utf-8"), "text/plain; charset=utf-8", код)

    def _байты(self, тело: bytes, тип: str, код: int = 200,
               имя: str | None = None) -> None:
        self.send_response(код)
        self.send_header("Content-Type", тип)
        self.send_header("Content-Length", str(len(тело)))
        self.send_header("Cache-Control", "no-store")
        if имя:
            self.send_header("Content-Disposition", _как_скачать(имя))
        self.end_headers()
        if self.command != "HEAD":
            self.wfile.write(тело)

    def _файл(self, путь: Path, имя_для_скачивания: str | None = None) -> None:
        путь = Path(путь)
        if not путь.exists() or not путь.is_file():
            raise Отказ(404, f"no such file: {путь.name}")
        размер = путь.stat().st_size
        с, по, просили = self._кусок_файла(размер)

        # Ответ 206 даётся на ЛЮБУЮ просьбу о куске, а не только
        # на просьбу о куске не с начала. Пока решение принималось
        # по началу куска, `bytes=0-1` — а это первое, о чём
        # проигрыватель спрашивает, — получал ответ «200, длина 2»,
        # то есть «весь ваш ролик состоит из двух байт». Ролик
        # не играл вовсе.
        self.send_response(206 if просили else 200)
        self.send_header("Content-Type",
                         ТИПЫ.get(путь.suffix.lower(),
                                  "application/octet-stream"))
        self.send_header("Content-Length", str(по - с + 1))
        self.send_header("Accept-Ranges", "bytes")
        if просили:
            self.send_header("Content-Range", f"bytes {с}-{по}/{размер}")
        self.send_header("Cache-Control", "no-store")
        if имя_для_скачивания:
            self.send_header("Content-Disposition",
                             _как_скачать(имя_для_скачивания))
        self.end_headers()
        if self.command == "HEAD":
            return
        with путь.open("rb") as поток:
            поток.seek(с)
            осталось = по - с + 1
            while осталось > 0:
                кусок = поток.read(min(КУСОК, осталось))
                if not кусок:
                    break
                self.wfile.write(кусок)
                осталось -= len(кусок)

    def _кусок_файла(self, размер: int) -> tuple[int, int, bool]:
        """Какой кусок файла просят и просили ли кусок вообще.

        **Заведено ради просмотра ролика прямо на экране.** Видео
        в браузере не читается подряд от начала: чтобы перемотать
        на середину, проигрыватель просит байты с середины. Сервер,
        который отдаёт только целиком, показывает ролик один раз
        и без перемотки — а посмотреть свои сорок секунд человек
        захочет с любого места.
        """
        сырое = (self.headers.get("Range") or "").strip()
        if not сырое.startswith("bytes="):
            return 0, размер - 1, False
        куски = сырое[len("bytes="):].split(",")[0].split("-")
        try:
            с = int(куски[0]) if куски[0] else 0
            по = int(куски[1]) if len(куски) > 1 and куски[1] else размер - 1
        except ValueError:
            # Просьбы не понять — отдаём целиком и НЕ говорим 206:
            # обещать кусок, которого не разобрали, нельзя.
            return 0, размер - 1, False
        # Просьба за краем файла — это не беда, а обычное дело
        # у проигрывателя: он спрашивает наперёд.
        с = max(0, min(с, размер - 1))
        по = max(с, min(по, размер - 1))
        return с, по, True

    # ── тишина в терминале ───────────────────────────────────────────

    def log_message(self, формат, *аргументы) -> None:
        """Обычные запросы не печатаются, отказы печатаются.

        Терминал, где запущен экран, — это то место, куда сервис
        говорит про ход разбора и сборки. Забить его строчкой на каждую
        картинку значит потерять там всё остальное.
        """
        return

    def log_error(self, формат, *аргументы) -> None:
        print("screen: " + (формат % аргументы), file=sys.stderr, flush=True)


def _как_скачать(имя: str) -> str:
    """Заголовок «скачать под таким именем».

    Имя ролика русское и с пробелами. RFC 5987: голое имя в кавычках
    половина браузеров превратит в мусор, поэтому оно едет
    процентами.
    """
    из_байтов = имя.encode("utf-8")
    return ("attachment; filename*=UTF-8''"
            + "".join(f"%{б:02X}" for б in из_байтов))


def _в_простое(что):
    """Что делать с тем, чего в json не бывает.

    **Пути — строками, и решено это ЗДЕСЬ, а не у каждой ручки.**
    Путь приезжает из глубины сервиса — например, вместе со сведениями
    о шрифте, — и ручка про него не знает: она отдаёт словарь, который
    ей дали. Поймано на первой же такой ручке, и это ровно тот случай,
    когда чинить надо в одном месте: иначе следующий путь вылезет
    в следующей ручке через месяц.

    Всё остальное незнакомое — отказ, а не тихая строка. Молча
    превратить в текст объект, которого мы не ждали, значит отдать
    странице `<object at 0x…>` и заставить гадать, что это было.
    """
    if isinstance(что, Path):
        return str(что)
    if isinstance(что, set):
        return sorted(что)
    raise TypeError(
        f"The answer to the page holds something JSON cannot: "
        f"{type(что).__name__}")


def _адрес_как_текст(сырой: str) -> str:
    """Адрес запроса — в настоящих буквах, а не в мусоре.

    **Замер, а не осторожность.** `http.server` разбирает первую строку
    запроса как latin-1 — так велит стандарт, там могут лежать только
    байты. Русские слова в адресе (`/апи/начало`; до 22-й сессии и
    `?пропуск=`) приезжают
    после этого рассыпанными, и сравнение с русской строкой в коде
    не сходится никогда. Поймано на первом же запуске: ручки отвечали,
    а страница получала отказ.

    Байты собираются обратно и читаются как utf-8. Работает одинаково
    и когда браузер отправил слово в процентах (`%D0%BA…`), и когда
    кто-то постучался буквами напрямую — второе делают curl и соседний
    скрипт, и отказывать им было бы отказом непонятно за что.
    """
    байты = сырой.encode("latin-1", "replace")
    return байты.decode("utf-8", "replace")


def _внутри(папка: Path, имя: str) -> Path:
    """Путь внутри папки — и ни на шаг наружу.

    Без этого `/файлы/../../../etc/passwd` отдал бы что попросят.
    Проверяется РАЗРЕШЁННЫЙ путь, а не строка с именем: `..` бывает
    записано десятком способов, а разрешённый путь один.
    """
    цель = (папка / имя).resolve()
    корень = папка.resolve()
    if цель != корень and корень not in цель.parents:
        raise Отказ(403, "this path leads outside")
    return цель


def найти_порт(с: int = ПОРТ, говорить=report.скажи) -> int:
    """Первый свободный порт, начиная с постоянного.

    **Занятый порт называется словом, а не проглатывается.** Раньше
    сервис молча брал следующий, и человек, у которого в закладке стоял
    7864, попадал в пустоту — при живом сервисе на 7865. Молчание здесь
    хуже неудобства: беда невидима, а последствие выглядит поломкой.
    """
    for порт in range(с, с + ПОРТОВ_ПОДРЯД):
        with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as гнездо:
            гнездо.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
            try:
                гнездо.bind(("127.0.0.1", порт))
            except OSError:
                continue
            if порт != с and говорить:
                говорить(f"Port {с} is taken by something else — using {порт}.")
            return порт
    raise VertcutError(
        f"Ports {с} to {с + ПОРТОВ_ПОДРЯД - 1} are all taken",
        hint="Vertcut may be running already — look for it in another tab")


def завести(порт: int | None = None, говорить=report.скажи) -> Экран:
    """Сервер на своём порту со своим пропуском. Ещё не запущенный."""
