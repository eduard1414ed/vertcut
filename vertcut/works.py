"""Долгая работа: файл состояния, хозяин, подхват брошенного.

**Механизм заводится ОДИН раз, а не по разу на стадию.** Второй такой
же разъехался бы с первым молча — обе половины продолжали бы работать,
просто по-разному отвечая на вопрос «кто сейчас это делает».

Пользуются им очередь сборки и разбор. Слова у них разные нарочно:
очередь говорит про ролик «собирается», разбор про стадию «идёт». Это
подписи для человека, а не правило, и сводить их в один список значило
бы завести слово, которое ни там ни там не звучит.
"""

from __future__ import annotations

import json
import os
import signal
import sys
import time
import uuid
from datetime import datetime
from pathlib import Path

from .errors import VertcutError

ЖДЁТ, ИДЁТ, ГОТОВ, УПАЛ, ОТМЕНЁН = "ждёт", "идёт", "готов", "упал", "отменён"

# Как состояние дела называется человеку — словами словаря
# (`docs/glossary.md`, «Вертикалка и сборка»). Сами состояния остаются
# русскими: они лежат в `queue.json` и сравниваются страницей.
СОСТОЯНИЕ_СЛОВОМ = {ЖДЁТ: "waiting", ИДЁТ: "exporting", ГОТОВ: "exported",
                    УПАЛ: "failed", ОТМЕНЁН: "canceled"}


def жив(pid: int) -> bool:
    """Жив ли процесс с таким номером.

    **Единственное место, где это спрашивают.** Вторая такая же
    проверка однажды ответит иначе — например, забудет про то, что
    сигнал 0 на чужой процесс кидает `PermissionError`, а это значит
    «жив», а не «мёртв».

    **На Windows спрашивается СОВСЕМ ДРУГИМ СПОСОБОМ, и это не вкус.**
    Там `os.kill(pid, 0)` не спрашивает, а УБИВАЕТ: питон на этой
    системе шлёт сигнал через `TerminateProcess`, и нулевой сигнал
    становится кодом возврата убитого. То есть вопрос «жив ли ярлык»
    делал ярлык мёртвым.

    Стоило это того, что на Windows сервис не мог остаться работать
    вообще никогда: сторож спрашивал про ярлык каждые две секунды,
    первым же вопросом его убивал и следующим уходил сам. Нашла это
    сборочная машина — первая, кто вообще поднял сервис на живой
    Windows; ни один из семисот тестов такого увидеть не мог, потому
    что все они спрашивают нас, а не систему.

    Здесь система спрашивается сама: открыть процесс и посмотреть,
    дождался ли он конца. Отказ в правах значит «жив» — тот же смысл,
    что у `PermissionError` на остальных системах.
    """
    if not pid or pid <= 0:
        return False
    if sys.platform.startswith("win"):
        import ctypes

        SYNCHRONIZE = 0x00100000
        ОТКАЗАНО_В_ПРАВАХ = 5
        ЗАВЕРШИЛСЯ = 0          # WAIT_OBJECT_0: конца ждать уже не надо
        ядро = ctypes.windll.kernel32
        дескриптор = ядро.OpenProcess(SYNCHRONIZE, False, pid)
        if not дескриптор:
            return ядро.GetLastError() == ОТКАЗАНО_В_ПРАВАХ
        try:
            return ядро.WaitForSingleObject(дескриптор, 0) != ЗАВЕРШИЛСЯ
        finally:
            ядро.CloseHandle(дескриптор)
    try:
        os.kill(pid, 0)
    except ProcessLookupError:
        return False
    except PermissionError:
        return True     # чужой, но живой
    except OSError:
        return False
    return True


def прочитать(файл: Path) -> dict:
    if not файл.exists():
        return {}
    try:
        return json.loads(файл.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        raise VertcutError(
            f"The work state file is damaged: {файл}",
            hint="delete it — the work will start over") from None


def записать(файл: Path, состояние: dict, отступ: int = 1) -> None:
    """Через времянку с переименованием.

    Работа идёт минутами, и оборванная на записи запись оставила бы
    обрезанный json — то есть потерю всего состояния.

    **Времянка своя у каждого вызова** — правило проекта, и здесь оно
    нарушалось до 24-й сессии. Пишут файл работы двое: хозяин и тот,
    кто пришёл вторым и получил «уже идёт» (очередь он успевает
    сложить и записать до этого отказа). С общей времянкой
    `queue.json.part` второй переименовывал уже переименованное
    и падал трассировкой — а экран сборки показывает журнал человеку.
    Поймано прочёсом (`tools/cyrillic-sweep.py`).

    **Имя времянки не берётся из часов и номера процесса.** Экран
    многопоточный, а на Windows до питона 3.13 `time.monotonic` тикает
    раз в 15,6 мс: нити одного процесса получали одно имя. Проверка
    на Windows шла на 3.13 и этого не видела; показала еженедельная
    на 3.11.

    **На Windows замена повторяется.** Там `replace` отказывает
    («Access is denied»), пока ту же цель в это мгновение заменяет
    другой, — гонка, а не запрет. Число попыток — `tuning.ПОПЫТОК_ЗАМЕНЫ`.
    Не вышло и после них — времянка убирается, отказ уходит наверх.

    **Одна запись json на весь проект** (с 27-й сессии): `meta.json`,
    файлы стадий, `shots.json` и дневник расходов пишутся ею же. До того
    у каждого была своя запись с ОБЩЕЙ времянкой (`meta.json.tmp`), и два
    разбора, пущенные разом, роняли друг друга трассировкой — нашёл
    прочёс, когда впервые стал нажимать кнопки.
    """
    from . import tuning

    файл.parent.mkdir(parents=True, exist_ok=True)
    врем = файл.with_name(f"{файл.name}.{uuid.uuid4().hex}.part")
    врем.write_text(json.dumps(состояние, ensure_ascii=False, indent=отступ) + "\n",
                    encoding="utf-8")
    for попытка in range(tuning.ПОПЫТОК_ЗАМЕНЫ):
        try:
            врем.replace(файл)
            return
        except PermissionError:
            if попытка == tuning.ПОПЫТОК_ЗАМЕНЫ - 1:
                врем.unlink(missing_ok=True)
                raise
            time.sleep(tuning.ПАУЗА_ЗАМЕНЫ_С)


# Сколько ждать, пока пущенная работа возьмётся за дело.
#
# **Между «пустили» и «взялась» проходит время, и его надо пережить.**
# Процесс должен подняться (доли секунды), прочитать журнал и посчитать
# отпечаток исходника — а отпечаток трёхгигабайтного файла это около
# десяти секунд. Всё это время хозяина у работы ещё нет.
#
# Пока этого не было, экран смотрел сразу после нажатия, видел «никто
# не работает» и переставал следить. Человек нажимал «Продолжить
# разбор», разбор шёл, а экран показывал, что ничего не происходит.
# Найдено автором на живом сервисе.
#
# Полминуты — с запасом втрое к худшему замеру и вдесятеро к обычному.
# Оно нужно только для того, чтобы отличить «ещё не взялась»
# от «не запустилась вовсе».
ПУСК_ЖДЁМ = 30.0


def пуск(файл: Path, что: str) -> None:
    """Отметить, что работу ПУСТИЛИ. Хозяина при этом не ставим.

    Хозяин ставится внутри стадии, и это правило: поставь его снаружи,
    и работа из терминала прошла бы поверх идущей с экрана. А вот
    сказать «пущено» снаружи можно и нужно — иначе между нажатием
    и первой строчкой работы экран показывает пустоту.

    Пишется ДО запуска процесса, а не после: после — значит наперегонки
    с ним самим за один и тот же файл.
    """
    состояние = прочитать(файл)
    состояние["пущено"] = {
        "что": что,
        "когда": datetime.now().astimezone().isoformat(timespec="seconds"),
        "в": time.time(),
    }
    записать(файл, состояние)


def запускается(состояние: dict) -> bool:
    """Работу пустили, а хозяина у неё ещё нет.

    Долго висеть это не может: либо процесс возьмётся, либо он умер,
    не начав. Второе видно по времени и говорится человеку словами.
    """
    пущено = состояние.get("пущено") or {}
    if not пущено:
        return False
    return time.time() - float(пущено.get("в") or 0) < ПУСК_ЖДЁМ


def не_запустилась(состояние: dict) -> bool:
    """Пущена давно, а хозяина так и нет. Значит не поднялась."""
    пущено = состояние.get("пущено") or {}
    if not пущено:
        return False
    return time.time() - float(пущено.get("в") or 0) >= ПУСК_ЖДЁМ


def взять(файл: Path, что: str) -> dict:
    """Стать хозяином работы. Живой хозяин — отказ с номером процесса.

    **Хозяин ставится внутри стадии, а не в веб-слое.** Поставь его
    снаружи — и работа из терминала прошла бы поверх идущей с экрана,
    молча.
    """
    состояние = прочитать(файл)
    хозяин = состояние.get("хозяин") or {}
    if хозяин and жив(int(хозяин.get("pid") or 0)):
        raise VertcutError(
            f"Already running: {хозяин.get('что')} — process "
            f"{хозяин['pid']}, since {хозяин.get('когда')}",
            hint="wait for it to finish, or stop it")
    подхвачено = bool(хозяин)
    состояние["хозяин"] = {
        "pid": os.getpid(), "что": что,
        "когда": datetime.now().astimezone().isoformat(timespec="seconds")}
    состояние["подхвачено"] = подхвачено
    # Отметка «пущено» своё отработала: хозяин теперь настоящий.
    состояние.pop("пущено", None)
    записать(файл, состояние)
    return состояние


def отметить(файл: Path, **что) -> None:
    """Дописать в состояние работы, не трогая хозяина.

    **Пишет только сам хозяин, и это единственное правило записи.**
    Двое пишущих в один файл — это read-modify-write вдвоём, то есть
    потерянная запись; здесь она означала бы, что экран показывает
    ход не той стадии.

    Молча ничего не делает, если хозяин чужой: работа могла быть
    отобрана, пока стадия считала свои девять минут, и падать тут
    нельзя — она в этот момент делает настоящее дело.
    """
    состояние = прочитать(файл)
    if (состояние.get("хозяин") or {}).get("pid") != os.getpid():
        return
    состояние.update(что)
    записать(файл, состояние)


def остановить(файл: Path) -> dict:
    """Погасить работу, которая идёт. Возвращает, что вышло.

    **Сигналом процессу, а не флажком в файле.** Флажок стадия увидела
    бы только между шагами, а самый долгий шаг — распознавание — идёт
    минутами внутри чужой библиотеки: «остановить» означало бы «через
    пять минут», и человек нажал бы ещё три раза.

    **Гасится ГРУППА процессов, если работа своя.** Разбор запускает
    ffmpeg детьми, и сигнал одному питону оставил бы их дожёвывать
    трёхгигабайтный файл. Экран заводит работе свою группу как раз
    для этого.

    А вот работу, запущенную из терминала, гасить группой НЕЛЬЗЯ:
    её группа — это оболочка человека вместе со всем, что он там
    запустил. Поэтому группа проверяется, а не предполагается.
    """
    состояние = прочитать(файл)
    хозяин = состояние.get("хозяин") or {}
    pid = int(хозяин.get("pid") or 0)
    if not pid or not жив(pid):
        return {"сигнал_послан": False, "почему": "it is not running anymore"}
    if pid == os.getpid():
        return {"сигнал_послан": False,
                "почему": "this is the process that is asking"}

    группой = False
    try:
        группой = os.getpgid(pid) == pid
    except OSError:
        группой = False
    try:
        if группой:
            os.killpg(pid, signal.SIGTERM)
        else:
            os.kill(pid, signal.SIGTERM)
    except OSError as беда:
        raise VertcutError(
            f"Could not stop the work (process {pid})",
            hint=str(беда)) from None
    # «Сигнал послан», а не «остановлено», и это не придирка к слову.
    # Работа встаёт не мгновенно: самый долгий шаг идёт внутри чужой
    # библиотеки, и питон разберёт сигнал, только когда та вернёт ему
    # управление, — на распознавании это до нескольких секунд. Скажи
    # экрану «остановлено», и он покажет остановленной работу, которая
    # ещё идёт.
    return {"сигнал_послан": True, "pid": pid, "группой": группой,
            "что": хозяин.get("что")}


def отпустить(файл: Path) -> None:
    """Отпустить работу — при ЛЮБОЙ беде, а не только при своей.

    Оборванная сеть или упавший ffmpeg оставили бы работу занятой
    мёртвым хозяином, и кнопка твердила бы «уже идёт», когда никто
    не идёт.
    """
    состояние = прочитать(файл)
    if состояние.get("хозяин", {}).get("pid") == os.getpid():
        состояние.pop("хозяин", None)
        записать(файл, состояние)
