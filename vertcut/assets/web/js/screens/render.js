// Экран 09 · Сборка.
//
// **Очередь — состояние на диске, а не вкладка**, и экран говорит
// об этом одной строкой, а не раскрывашкой. Закрыли окно — сборка идёт
// дальше; убили процесс — очередь лежит, и следующий запуск продолжает
// с того места, где встали.
//
// У каждой строки видно, ПОЧЕМУ она здесь: сказано собрать, субтитры
// менялись, рамка правлена рукой. «Пересобираю семь» без объяснения
// читается как «сервис делает работу зря».
//
// Чего здесь нет: **«Скачать всё готовое»**. Готовые ролики уже лежат
// на диске этой самой машины, и «скачать» означало бы сложить рядом
// их вторую копию — тот же плохой сюрприз, что и с брошенным в окно
// файлом. Вместо неё «Показать в папке», как это названо в спеке.

import {
  нарисовать, лого, блок, маршрут, вертикалки, эл, моно, метка, растяжка,
  сказать, сказать_беду, убрать_полосы, подвал,
} from '../shell.js';
import * as связь from '../api.js';
import * as слова from '../words.js';
import * as адрес from '../route.js';

const ПЕРЕСПРАШИВАТЬ = 2000;

let это = null;
let часы = null;
let полоса_остановки = null;
let раскрыто = false;

export async function показать([слаг]) {
  if (!слаг) throw new связь.Беда('No video given to export', '');
  остановить_часы();
  await перечитать(слаг);
}

function остановить_часы() {
  if (часы) { clearInterval(часы); часы = null; }
}

async function перечитать(слаг) {
  это = await связь.взять('очередь', { слаг });
  это.куски = (await связь.взять('куски', { слаг })).куски;
  рисовать();
  // Следим, пока сборка идёт ИЛИ ПОДНИМАЕТСЯ: между нажатием
  // и первой строчкой работы проходит время, и всё это время экран
  // обязан показывать, что она пошла.
  остановить_часы();
  if (это.идёт_сейчас || это.запускается) {
    часы = setInterval(async () => {
      if (!адрес.на_экране('export')) return остановить_часы();
      try {
        const куски = это.куски;
        const было = итог_очереди(это);
        это = await связь.взять('очередь', { слаг });
        // Колонка вертикалок перечитывается, только когда в очереди
        // что-то КОНЧИЛОСЬ: собралась, упала, пропала. Раньше она
        // бралась раз при открытии и всю сборку показывала только что
        // собранную «устаревшей», а удалённую — живой.
        это.куски = итог_очереди(это) === было ? куски
          : (await связь.взять('куски', { слаг })).куски;
        рисовать();
        if (!это.идёт_сейчас && !это.запускается) {
          остановить_часы();
          if (полоса_остановки) {
            полоса_остановки.remove(); полоса_остановки = null;
            сказать({ вид: 'warn', что: 'Export stopped.',
                      делать: 'The clip that was exporting isn\'t counted as '
                              + 'exported: a clip counts only after its '
                              + 'checks pass. The rest wait in '
                              + 'the queue.' });
          } else {
            доложить();
          }
        }
      } catch (беда) { остановить_часы(); сказать_беду(беда); }
    }, ПЕРЕСПРАШИВАТЬ);
  }
}

function итог_очереди(о) {
  return `${о.готово}/${о.упало}/${о.удалено}`;
}

function доложить() {
  if (это.упало) {
    return сказать({
      вид: 'warn',
      что: `Export finished: ${это.готово} exported, ${это.упало} failed.`,
      делать: 'One failed clip doesn\'t stop the rest. Each row says why.',
    });
  }
  сказать({
    вид: 'good', что: 'Export finished — all clips exported.',
    делать: 'Show in folder opens the folder with the files.',
  });
}

// ── Рисование ─────────────────────────────────────────────────────────

function рисовать() {
  const строк = это.дела.length + это.ждут.length;
  нарисовать({
    колонка: колонка(),
    заголовок: эл('h1', { класс: 'vc-h1' }, ['Export']),
    лид: лид(),
    тело: [
      строк
        ? эл('div', { класс: 'в-очередь' }, [
            ...это.дела.map(строка_дела),
            ...это.ждут.map(строка_ждущего),
          ])
        : пусто(),
      эл('p', {
        класс: 'в-подпись',
        текст: 'The queue is saved next to the analysis. Close the tab ' +
               'and export keeps going, saving progress after each clip.',
      }),
      хвост(),
    ],
    футбар: футбар(),
  });
}

function лид() {
  if (это.запускается) {
    return 'Starting export…';
  }
  // Пусто — заголовок пустого блока говорит то же самое крупно;
  // повторять его строкой выше незачем.
  if (!это.дела.length && !это.ждут.length) return null;
  const части = [];
  if (это.готово) части.push(`${это.готово} exported`);
  const идёт = это.дела.filter((д) => д.состояние === 'идёт').length;
  if (идёт) части.push(`${идёт} exporting`);
  // «Ждёт» — только то, что стоит в очереди. Вертикалки вне очереди
  // названы так же, как их метка в строке: одно состояние — одно слово.
  const ждёт = это.дела.filter((д) => д.состояние === 'ждёт').length;
  if (ждёт) части.push(`${ждёт} waiting`);
  if (это.ждут.length) части.push(`${это.ждут.length} not queued`);
  if (это.упало) части.push(`${это.упало} failed`);
  if (это.удалено) части.push(`${это.удалено} deleted`);
  const хвост_ = (это.идёт_сейчас && это.оценка_очереди)
    ? ` · about ${слова.длина(это.оценка_очереди)} left` : '';
  if (!части.length) return 'Nothing to export.';
  return части.join(', ') + хвост_;
}

function пусто() {
  return эл('div', { класс: 'в-пусто' }, [
    эл('div', { класс: 'vc-empty__title', текст: 'The queue is empty — nothing to export' }),
    эл('p', {
      класс: 'vc-lede',
      текст: 'Clips show up here before their first export, and again ' +
             'when something changes after export: the segment, a crop, ' +
             'the subtitle text or style.',
    }),
  ]);
}

// ── Строка очереди ────────────────────────────────────────────────────

function строка_дела(д) {
  // Удалённая вертикалка ведёт в никуда, и щёлкать по ней нельзя:
  // экран открылся бы на отказе «нет такой». Строка при этом
  // остаётся — человек должен видеть, что стало с делом, которое
  // он ставил в очередь.
  if (д.удалён) return строка_удалённой(д);
  return эл('div', { класс: 'в-дело', 'data-как': д.состояние,
                     на: { click: (е) => к_вертикалке(е, д.id) } }, [
    обложка(д.id),
    эл('div', { класс: 'в-дело__что' }, [
      имя_дела(д.id, д.зовут),
      эл('span', { класс: 'в-дело__почему', текст: подпись_дела(д) }),
      итог_проверок(д),
      полоса_хода(д),
    ]),
    эл('div', { класс: 'в-дело__справа' }, [
      состояние_меткой(д),
      ...действия(д),
    ]),
  ]);
}

// Вертикалки больше нет: её удалили после того, как она попала
// в очередь.
//
// **Кадра здесь нет вовсе, а не битая картинка.** Обложка лежит
// в папке вертикалки, а папки нет — запрос за ней получает отказ,
// и на его месте оставался серый прочерк, который читается как
// «сервис сломался». Сломан он не был: показывать просто нечего,
// и сказать об этом надо словом.
function строка_удалённой(д) {
  return эл('div', { класс: 'в-дело', 'data-как': 'удалён' }, [
    эл('div', { класс: 'в-дело__кадр в-дело__кадр--нет' }),
    эл('div', { класс: 'в-дело__что' }, [
      эл('b', { класс: 'в-дело__зовут', текст: д.зовут, title: д.зовут }),
      эл('span', {
        класс: 'в-дело__почему',
        текст: 'the clip was deleted — nothing to export' +
               (д.состояние === 'готов'
                 ? '; its exported file went with it' : ''),
      }),
    ]),
    эл('div', { класс: 'в-дело__справа' }, [метка('deleted', 'bad')]),
  ]);
}

// Полоса ТОЛЬКО там, где процент известен по-настоящему. Правило
// пакета дизайна, и оно же честность: доля, посчитанная от ожидаемого
// времени сборки, показывала бы 90% у ролика, который режется вторую
// минуту сверх плана.
//
// Числа приходят настоящие: сколько секунд ролика закодировано,
// сколько кадров слоя записано, сколько точек сверено. У шагов,
// где считать нечего, — только имя шага; они и идут доли секунды.
function полоса_хода(д) {
  if (д.состояние !== 'идёт') return null;
  const ход = д.ход;
  if (!ход || !ход.всего) return эл('div', { класс: 'vc-progress' });
  const доля = Math.max(0, Math.min(1, (ход.сделано || 0) / ход.всего));
  return эл('div', {}, [
    эл('div', { класс: 'vc-progress' }, [
      эл('i', { стиль: { width: `${(доля * 100).toFixed(1)}%` } }),
    ]),
  ]);
}

function подпись_дела(д) {
  if (д.состояние === 'упал') {
    return (д.беда || 'failed without saying why') +
           (д.подсказка ? ` — ${д.подсказка}` : '');
  }
  // Идущее дело говорит, ЧТО делается прямо сейчас. Пока оно молчало,
  // сорок секунд сборки выглядели одинаково — «идёт» и пустая полоса,
  // — и человек видел только начало и конец.
  if (д.состояние === 'идёт') return ход_словами(д);
  if (д.состояние === 'готов' && д.отчёт) {
    const о = д.отчёт;
    return `export took ${слова.длина(о.секунд)} · ` +
           `${слова.мегабайт(д.байт)} · ${без_субтитров(д)}${д.файл}`;
  }
  // Причина попадания в очередь — не украшение: «пересобираю семь»
  // без объяснения читается как «сервис делает работу зря».
  const длина = д.duration ? `${слова.длина(д.duration)} · ` : '';
  return `${длина}${без_субтитров(д)}${д.почему} · export takes about ` +
         `${слова.длина(д.оценка)}`;
}

// Ролик без субтитров говорит это в своей строке: собранный файл без
// них — не поломка, но человек должен видеть это до того, как выложит.
function без_субтитров(д) {
  return д.без_субтитров ? 'without subtitles · ' : '';
}

// Пять проверок одной строкой, подробности — при наведении.
//
// Имена и подробности присылает сервер (`verify.итоги`) — те же, что
// в отказе сборки. Здесь только счёт и склейка в строку.
//
// **Пропущенная проверка не считается прошедшей.** Без плашки её
// проверять нечего, у стыков без смены рамки — тоже; «all 5 checks
// passed» там было бы неправдой, и пропущенные названы по именам.
function итог_проверок(д) {
  const все = д.проверки || (д.отчёт && д.отчёт.проверки);
  if (!все || !все.length) return null;
  const упали = все.filter((п) => п.как === 'failed');
  const прошли = все.filter((п) => п.как === 'passed');
  const пропущены = все.filter((п) => п.как === 'skipped');
  let текст;
  if (упали.length) {
    текст = `failed: ${упали.map((п) => п.имя).join(', ')} · ` +
            `passed: ${прошли.map((п) => п.имя).join(', ') || 'none'}`;
  } else if (!пропущены.length) {
    текст = `all ${все.length} checks passed`;
  } else {
    текст = `all ${слова.счёт(прошли.length, 'check', 'checks')} passed · ` +
            `skipped: ${пропущены.map((п) => п.имя).join(', ')}`;
  }
  return эл('span', {
    класс: 'в-дело__почему',
    текст,
    title: все.map((п) => `${п.имя}: ${п.как} — ${п.подробно}`).join('\n'),
  });
}

function ход_словами(д) {
  const ход = д.ход;
  if (!ход || !ход.шаг) return 'exporting';
  if (ход.всего === null || ход.всего === undefined || !ход.единица) {
    return ход.шаг;
  }
  return `${ход.шаг} · ${Math.round(ход.сделано)} of ` +
         `${Math.round(ход.всего)} ${ход.единица}`;
}

function состояние_меткой(д) {
  if (д.состояние === 'отменён') return метка('canceled', 'off');
  if (д.состояние === 'готов') return метка('exported', 'good');
  if (д.состояние === 'идёт') return метка('exporting', 'busy');
  if (д.состояние === 'упал') return метка('failed', 'bad');
  return метка('waiting', 'dim');
}

function действия(д) {
  if (д.состояние === 'готов' && д.есть_файл) {
    return [
      эл('a', {
        класс: 'vc-btn vc-btn--xs', текст: 'Download',
        download: '',
        href: связь.адрес('скачать', { слаг: это.слаг, ключ: д.id }),
      }),
      эл('button', {
        класс: 'vc-link vc-link--muted', текст: 'Show in folder',
        на: { click: () => в_папке(д.id) },
      }),
    ];
  }
  if (д.состояние === 'упал') {
    // Файл после не прошедшей проверки лежит, и отказ просит
    // посмотреть его глазами — значит, дорога к нему нужна здесь же.
    return [
      эл('button', {
        класс: 'vc-btn vc-btn--xs', текст: 'Try again',
        на: { click: () => собрать_один(д.id) },
      }),
      д.есть_файл ? эл('button', {
        класс: 'vc-link vc-link--muted', текст: 'Show in folder',
        на: { click: () => в_папке(д.id) },
      }) : null,
    ];
  }
  // Ссылки «открыть вертикалку» здесь больше нет: туда ведёт вся
  // строка. Две дороги в одно место — это вопрос «а они точно
  // в одно?», который человек задаёт себе на каждой строке.
  return [];
}

// Щелчок по строке ведёт на вертикалку.
//
// **Строка — не кнопка, и стать ею не может:** внутри у неё живут
// «Собрать», «Скачать» и «открыть», а кнопку в кнопку класть нельзя
// — браузер разбирает такую разметку как попало. Поэтому щелчок
// ловится на строке, а всё, что само по себе нажимается, из него
// исключается: иначе «Собрать» сперва собирал бы, а потом уводил
// с экрана, на котором человек хотел смотреть на сборку.
function к_вертикалке(е, ключ) {
  if (е.target.closest('button, a')) return;
  адрес.идти('clip', это.слаг, ключ);
}

// Название — единственное, что в строке нажимается с клавиатуры.
//
// Щелчок по строке мышью есть, а с клавиатуры до неё не добраться:
// `div` в обход клавиш. Раньше туда вела кнопка-ссылка «открыть
// вертикалку», и, убрав её, дорогу с клавиатуры мы бы просто
// потеряли. Кнопкой стало само название — оно и по смыслу главное
// в строке.
function имя_дела(ключ, зовут) {
  return эл('button', {
    класс: 'в-дело__зовут', текст: зовут, title: зовут,
    на: { click: () => { адрес.идти('clip', это.слаг, ключ); } },
  });
}

// Ролик, которого в очереди ещё нет, но собрать его надо. Показан
// в том же списке и той же строкой: разница только в том, что его
// пока никто не считает.
function строка_ждущего(ж) {
  return эл('div', { класс: 'в-дело', 'data-как': 'ждёт',
                     на: { click: (е) => к_вертикалке(е, ж.id) } }, [
    обложка(ж.id),
    эл('div', { класс: 'в-дело__что' }, [
      имя_дела(ж.id, ж.зовут),
      эл('span', {
        класс: 'в-дело__почему',
        текст: `${слова.длина(ж.duration)} · ${без_субтитров(ж)}${ж.почему} · ` +
               `export takes about ${слова.длина(ж.оценка)}`,
      }),
    ]),
    эл('div', { класс: 'в-дело__справа' }, [
      метка('not queued', 'off'),
      эл('button', {
        класс: 'vc-btn vc-btn--xs', текст: 'Export',
        на: { click: () => собрать_один(ж.id) },
      }),
    ]),
  ]);
}

// Кадр 9:16 — настоящий, с субтитром. Лежит готовым и пересчитывается
// сам, когда монтаж или стиль поменялись.
function обложка(ключ) {
  const кадр = эл('img', {
    класс: 'в-дело__кадр', alt: '',
    src: связь.адрес('обложка-ролика', { слаг: это.слаг, ключ }),
  });
  кадр.addEventListener('error', () => кадр.classList.add('vc-stripe'));
  return кадр;
}

function хвост() {
  const строки = это.хвост || [];
  if (!строки.length) return null;
  const узел = эл('details', { класс: 'в-раскрывашка', open: раскрыто }, [
    эл('summary', { текст: 'export log' }),
    эл('div', { класс: 'в-хвост', текст: строки.join('\n') }),
  ]);
  узел.addEventListener('toggle', () => { раскрыто = узел.open; });
  return узел;
}

// ── Колонка и футбар ──────────────────────────────────────────────────

function колонка() {
  const идёт = это.дела.filter((д) => д.состояние === 'идёт').length;
  return [
    лого(это.источник),
    блок('steps', маршрут({
      слаг: это.слаг, сейчас: 'export', идти: адрес.идти,
      разобрано: true, вертикалок: это.вертикалок,
      состояния: {
        // С числом — и слово: голое «1» у шага не говорило, одна чего.
        export: идёт ? `${идёт} exporting`
          : (это.готово ? `${это.готово} exported` : ''),
      },
    })),
    вертикалки({ слаг: это.слаг, куски: это.куски, идти: адрес.идти }),
    растяжка(),
    эл('p', {
      класс: 'в-подпись',
      текст: 'You can close this tab: the queue is saved and finishes on its own.',
    }),
    эл('button', {
      класс: 'vc-link vc-link--muted', текст: '← segments',
      на: { click: () => { адрес.идти('segments', это.слаг); } },
    }),
    подвал(адрес.идти),
  ];
}

function футбар() {
  // Упавшие тоже: «Export all» собирает их заново вместе с остальными.
  const надо = это.ждут.length
             + это.дела.filter((д) => д.состояние === 'ждёт').length
             + это.упало;
  const справа = [
    эл('button', {
      класс: 'vc-link vc-link--muted', текст: 'Show in folder',
      на: { click: () => в_папке(null) },
    }),
  ];
  if (это.идёт_сейчас || это.запускается) {
    справа.push(эл('button', {
      класс: 'vc-link vc-link--danger', текст: 'stop export',
      на: { click: остановить },
    }));
    return {
      главное: { зовут: 'Export all' },
      почему: это.запускается ? 'starting…' : 'exporting now',
      справа,
    };
  }
  if (!надо) {
    return {
      главное: { зовут: 'Export all' },
      // Смотрится на ВЕРТИКАЛКИ, а не на очередь: собранные из
      // терминала в очереди не стоят, и «no clips yet» рядом с тремя
      // собранными в колонке было неправдой.
      почему: это.вертикалок
        ? 'nothing to export: everything is up to date'
        : 'nothing to export: no clips yet',
      справа,
    };
  }
  return {
    главное: {
      зовут: 'Export all',
      подпись: `${слова.счёт(надо, 'clip', 'clips')} · ` +
               `about ${слова.длина(это.оценка)}`,
      делать: () => пустить(false),
    },
    справа,
  };
}

// ── Действия ──────────────────────────────────────────────────────────

async function пустить(заново) {
  убрать_полосы();
  try {
    await связь.послать('собрать-всё', { слаг: это.слаг,
                                         заново: заново ? '1' : '' });
    await перечитать(это.слаг);
  } catch (беда) { сказать_беду(беда); }
}

async function собрать_один(ключ) {
  убрать_полосы();
  try {
    await связь.послать('собрать', { слаг: это.слаг, ключ, заново: '1' });
    await перечитать(это.слаг);
  } catch (беда) { сказать_беду(беда); }
}

async function остановить() {
  убрать_полосы();
  try {
    const ответ = await связь.послать('остановить-сборку', { слаг: это.слаг });
    полоса_остановки = сказать({
      вид: 'warn',
      что: ответ.сигнал_послан ? 'Stopping…' : 'Nothing to stop.',
      делать: ответ.сигнал_послан
        ? 'The clip being exported will either finish or stop half-way. ' +
          'A broken file never counts as exported: a clip is exported ' +
          'only after its checks pass. The rest stay in the queue.'
        : (ответ.почему || ''),
    });
    if (!ответ.сигнал_послан) полоса_остановки = null;
    await перечитать(это.слаг);
  } catch (беда) { сказать_беду(беда); }
}

async function в_папке(ключ) {
  убрать_полосы();
  try {
    await связь.послать('показать-в-папке', { слаг: это.слаг, ключ: ключ || '' });
  } catch (беда) { сказать_беду(беда); }
}
