// Та же галочка стоит в редакторе субтитров — и это одна настройка
// вертикалки, не стиля (`subs.в_файле`).
function выключатель_субтитров() {
  const галочка = эл('input', { type: 'checkbox', checked: это.субтитры.в_файле });
  галочка.addEventListener('change', async () => {
    убрать_полосы();
    try {
      await связь.послать('субтитры-в-файле', {
        слаг: это.слаг, ключ: это.id, вкл: галочка.checked,
        отметка: это.отметка });
      await перечитать();
    } catch (беда) {
      сказать_беду(беда);
      await перечитать();
    }
  });
  return эл('label', { класс: 'в-выключатель' }, [
    галочка, эл('span', { текст: 'show subtitles in the clip' }),
  ]);
}

// Про файл говорится ТОЛЬКО когда про него есть что сказать.
//
// «Файла ещё нет» висело у каждой несобранной вертикалки — то есть
// почти всегда, — и не отвечало ни на один вопрос: какого файла,
// почему его нет, что с этим делать. Что вертикалка не собрана,
// и так написано в маршруте слева и на главной кнопке внизу.
function состояние_файла() {
  if (это.собирается) {
    return эл('div', { класс: 'vc-bar vc-bar--ask' }, [
      эл('div', { класс: 'vc-bar__what' }, [
        эл('b', { текст: 'Exporting…' }),
        эл('span', { текст: 'It runs on its own — you can close this tab.' }),
      ]),
    ]);
  }
  if (!это.есть_файл) return null;
  if (это.почему_устарел) {
    return эл('div', { класс: 'vc-bar vc-bar--warn' }, [
      эл('div', { класс: 'vc-bar__what' }, [
        эл('b', { текст: 'Out of date — export again' }),
        эл('span', { текст: это.почему_устарел }),
      ]),
    ]);
  }
  return эл('div', { класс: 'vc-bar vc-bar--ask' }, [
    эл('div', { класс: 'vc-bar__what' }, [
      эл('b', { текст: 'Exported · up to date' }),
      эл('span', { текст: `${это.файл} · ${слова.мегабайт(это.байт)}` }),
    ]),
  ]);
}

