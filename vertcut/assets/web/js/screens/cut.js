// Экран 07 · Вертикалка — довести один вертикальный клип.
//
// **Главная перестановка пакета дизайна:** справа всегда сама
// вертикалка в форме 9:16, и всё, что меняется слева, видно в ней.
//
// Превью рисует СЕРВЕР — той же функцией, которой рисуется лист «до
// и после», настоящим шрифтом. Браузер её показывает и ничего
// не набирает: наберись субтитр здесь, в проекте появилась бы вторая
// правда о том, как выглядит кадр — на экране красиво, в файле иначе,
// и ни один из четырёх заслонов этого не поймает.
//
// Чего здесь нет и почему:
//
//   · **«Сдвиг картинки»** — это сдвиг дорожки; его предел у предка
//     считается от длины плашки, а плашки здесь нет вовсе, и дыру
//     в конце закрывать нечем;
//   · **«Плашка в конце»** — решено в спеке: у чужого человека нет
//     ни обложки выпуска, ни канала, ни фона;
//   · **«Подменить кадром»** — механики нет: подмена рвёт равенство
//     «на секунде ролика стоит такая-то секунда исходника», на котором
//     держатся цепочка, шкала, предпросмотр и второй заслон. Записана
//     в отложенное вместе с тем, что для неё придётся завести;
//   · **«Разрезать» план** — то же самое плюс беда с номерами: планы
//     перенумеруются, а рамки рукой привязаны к номерам.

import {
  нарисовать, лого, блок, маршрут, вертикалки, кадр_с_ожиданием,
  эл, моно, метка, растяжка,
  сказать, сказать_беду, убрать_полосы, подвал,
} from '../shell.js';
import * as связь from '../api.js';
import * as слова from '../words.js';
import * as адрес from '../route.js';

let это = null;
let выбран = null;     // номер выбранного плана
let часы = null;       // пока идёт сборка, экран переспрашивает сам
let смотрим = null;      // 'preview' или 'frame'; null — как решит сервис
let плеер = null;        // тот самый <video>, чтобы его слушался пробел
let плеер_коробка = null; // что именно стоит в окне — вместе с обвесом
let плеер_из = null;     // из чего он сделан; поменялось — делаем заново
let плеер_на = null;     // на какой план он поставлен
let перемотать = null;   // встать на план; у двух плееров это разное
let гасить = null;       // как погасить слежение и отпустить видео

export async function показать([слаг, ключ]) {
  забыть_плеер();
  if (!слаг || !ключ) {
    throw new связь.Беда('No clip given to open', '');
  }
  это = await связь.взять('вертикалка', { слаг, ключ });
  это.куски = (await связь.взять('куски', { слаг })).куски;
  выбран = это.планы.length ? это.планы[0].idx : null;
  рисовать();
  if (это.собирается) следить();
}

async function перечитать() {
  const куски = это.куски;
  это = await связь.взять('вертикалка', { слаг: это.слаг, ключ: это.id });
  это.куски = куски;
  рисовать();
}

// Пока сборка идёт, экран переспрашивает сам — и останавливается,
// как только она кончилась. Опрашивать диск до скончания века незачем.
function следить() {
  if (часы) clearInterval(часы);
  часы = setInterval(async () => {
    if (!адрес.на_экране('clip')) {
      clearInterval(часы); часы = null; return;
    }
    try {
      await перечитать();
      if (!это.собирается) { clearInterval(часы); часы = null; }
    } catch (беда) {
      clearInterval(часы); часы = null; сказать_беду(беда);
    }
  }, 2000);
}

// ── Рисование ─────────────────────────────────────────────────────────

function рисовать() {
  нарисовать({
    колонка: колонка(),
    заголовок: заголовок(),
    // Ключа в мете нет: он нужен сервису, чтобы найти папку, а
    // человеку — ни разу. Занимает же он полстроки.
    мета: [
      моно(`phrases ${это.фразы.first}–${это.фразы.last}`),
      моно(слова.длина(это.duration)),
      моно(слова.счёт(это.планы.length, 'shot', 'shots')),
    ],
    тело: [
      огрызки(),
      эл('div', { класс: 'в-вертикалка' }, [
        эл('div', { класс: 'в-блок' }, [планы()]),
        правая_колонка(),
      ]),
    ],
    футбар: футбар(),
  });
}

// Заголовок без «переназвать»: название вертикалки — это первые
// слова, которые услышит зритель, и по ним же зовётся готовый файл.
// То, как человек её узнаёт в списке, делает описание — оно и стоит
// в колонке. Две кнопки на один вопрос путали бы, какая из них главнее.
function заголовок() {
  return эл('h1', { класс: 'vc-h1', стиль: { fontSize: 'var(--t-h1-sm)' },
                    текст: это.зовут });
}

// Огрызок — план, от которого в ролик попал хвост. Зритель увидит
// конец сцены, начала которой не было; сказать об этом надо.
function огрызки() {
  if (!это.огрызки.length) return null;
  return эл('div', { класс: 'vc-bar vc-bar--warn' }, [
    эл('div', { класс: 'vc-bar__what' }, [
      эл('b', { текст: `${слова.форма(это.огрызки.length, 'Partial shot',
                                     'Partial shots')}: ` +
                         `${это.огрызки.join(', ')}` }),
      эл('span', { текст: 'Viewers will see the end of a scene without ' +
                          'its start. That\'s not a fault — it\'s where ' +
                          'the segment begins or ends.' }),
    ]),
  ]);
}

// ── Планы ─────────────────────────────────────────────────────────────

function планы() {
  const план = это.планы.find((п) => п.idx === выбран);
  return эл('div', { класс: 'vc-card' }, [
    эл('div', { класс: 'в-ряд' }, [
      эл('b', { класс: 'vc-card__title', текст: 'Shots' }),
      моно(String(это.планы.length), 'в-подпись'),
      растяжка(),
    ]),
    план ? панель_плана(план) : null,
    план ? рамка_рукой(план) : null,
    эл('div', { класс: 'в-планы' }, это.планы.map(кадр_плана)),
    эл('p', {
      класс: 'в-подпись', стиль: { margin: '0' },
      текст: '← → move between shots · drag the crop on the big frame · ' +
             'it\'s saved for the selected shot',
    }),
  ]);
}

function панель_плана(план) {
  return эл('div', { класс: 'в-панель-плана' }, [
    эл('b', { текст: `Shot ${план.idx}` }),
    моно(`${слова.время(план.at)} → ${слова.время(план.till)}`, 'в-подпись'),
    эл('span', { класс: 'в-подпись', текст: чья_рамка(план) }),
    растяжка(),
    эл('div', { класс: 'vc-seg' }, [
      эл('button', {
        текст: 'Crop', 'aria-pressed': план.mode === 'crop' ? 'true' : 'false',
        на: { click: () => править(план.idx, { режим: 'crop' }) },
      }),
      эл('button', {
        текст: 'Full frame',
        'aria-pressed': план.mode === 'full' ? 'true' : 'false',
        на: { click: () => править(план.idx, { режим: 'full' }) },
      }),
    ]),
    // Место под «вернуть исходную» держится ВСЕГДА, даже пока
    // кнопки нет.
    //
    // **Это починка, а не запас.** Кнопка появляется в тот миг, когда
    // человек отпустил рамку, — и появлялась она третьей в ряду,
    // то есть переносила ряд на вторую строку. Панель становилась
    // выше, всё, что ниже, съезжало вниз, и крупный кадр уезжал
    // из-под курсора ровно после того движения мышью, ради которого
    // человек сюда и пришёл. Правило проекта прямое: ничто не должно
    // менять высоту от того, что человек делает.
    //
    // Мёртвой кнопки при этом не рисуется: место держит невидимая
    // распорка тех же размеров — её не видно, по ней не щёлкнуть
    // и её не читают с клавиатуры.
    план.hand
      ? эл('button', {
          класс: 'vc-btn vc-btn--xs', текст: 'Reset',
          на: { click: () => править(план.idx, { сбросить: '1' }) },
        })
      : эл('span', {
          класс: 'vc-btn vc-btn--xs в-распорка', 'aria-hidden': 'true',
          текст: 'Reset',
        }),
  ]);
}

function чья_рамка(план) {
  if (план.mode === 'full') return 'full frame, blurred sides';
  if (план.hand) return 'crop set by hand';
  if (план.by === 'face') return 'crop follows the face';
  return 'no face found — centered';
}

// Крупный кадр, на котором рамку двигают мышью. Это единственное,
// чего в командной строке сделать нельзя вовсе.
function рамка_рукой(план) {
  const окно = эл('div', { класс: 'в-окно' });
  const картинка = эл('img', {
    alt: '', src: связь.адрес('кадр-плана',
                              { слаг: это.слаг, план: план.idx }),
  });
  const кадр = эл('div', {
    класс: 'в-рамка-рукой',
    'data-рисуется': '',
    'data-полный': план.mode === 'full' ? '' : null,
  }, [
    картинка,
    эл('span', { класс: 'в-рисуется__слово', текст: 'loading frame…' }),
    план.mode === 'full' ? null : окно,
  ]);
  const готово = () => кадр.removeAttribute('data-рисуется');
  картинка.addEventListener('load', готово);
  картинка.addEventListener('error', готово);
  if (картинка.complete && картинка.naturalWidth) готово();
  поставить_окно(окно, план.окно);
  if (план.mode !== 'full') тащить(кадр, окно, план);
  return кадр;
}

function поставить_окно(окно, где) {
  окно.style.left = `${где.левый * 100}%`;
  окно.style.width = `${где.ширина * 100}%`;
}

// Пока тащат — двигается ТОЛЬКО прямоугольник, посчитанный сервером.
// Отпустили — сервер пересчитывает всё заново и присылает свою
// картинку. Браузер здесь двигает пиксели, а не рисует их.
function тащить(кадр, окно, план) {
  let ширина_окна = план.окно.ширина;
  let cx = план.окно.левый + ширина_окна / 2;
  let тащим = false;

  const где = (е) => {
    const коробка = кадр.getBoundingClientRect();
    const доля = (е.clientX - коробка.left) / коробка.width;
    // Окно не свисает за край — то же правило, что в цепочке:
    // лицо у самого края даёт окно, прижатое к краю.
    return Math.min(Math.max(доля, ширина_окна / 2), 1 - ширина_окна / 2);
  };

  кадр.addEventListener('pointerdown', (е) => {
    тащим = true;
    кадр.setPointerCapture(е.pointerId);
    cx = где(е);
    поставить_окно(окно, { левый: cx - ширина_окна / 2, ширина: ширина_окна });
  });
  кадр.addEventListener('pointermove', (е) => {
    if (!тащим) return;
    cx = где(е);
    поставить_окно(окно, { левый: cx - ширина_окна / 2, ширина: ширина_окна });
  });
  кадр.addEventListener('pointerup', async (е) => {
    if (!тащим) return;
    тащим = false;
    кадр.releasePointerCapture(е.pointerId);
    await править(план.idx, { рамка: cx });
  });
}

function кадр_плана(план) {
  const окно = эл('div', { класс: 'в-окно' });
  поставить_окно(окно, план.окно);
  return эл('button', {
    класс: 'в-план',
    'aria-selected': план.idx === выбран ? 'true' : 'false',
    на: { click: () => { выбран = план.idx; рисовать(); } },
  }, [
    эл('div', {
      класс: 'в-план__кадр',
      'data-полный': план.mode === 'full' ? '' : null,
    }, [
      эл('img', {
        alt: '', loading: 'lazy',
        src: связь.адрес('кадр-плана', { слаг: это.слаг, план: план.idx }),
      }),
      план.mode === 'full' ? null : окно,
    ]),
    // Чем поставлена рамка — лицом, рукой или по центру — сказано
    // словами в панели выбранного плана. Точкой у каждого кадра
    // это было тремя цветами, которые надо помнить.
    эл('div', { класс: 'в-план__низ' }, [
      `${план.idx} · ${слова.длина(план.duration)}`,
    ]),
  ]);
}

// ── Правая колонка ────────────────────────────────────────────────────

function правая_колонка() {
  return эл('div', { класс: 'в-правая' }, [
    эл('div', { класс: 'vc-card', стиль: { padding: '14px' } }, [
      эл('div', { класс: 'в-ряд' }, [
        эл('b', { класс: 'vc-card__title', текст: 'How it looks' }),
        растяжка(),
        переключатель_окна(),
      ]),
      превью(),
      эл('p', {
        класс: 'в-подпись', стиль: { margin: '0' },
        текст: подпись_окна(),
      }),
      // **Скачивание живёт на шаге «Сборка», и только там.**
      // Здесь человек правит вертикалку: рамку, текст, стиль.
      // Кнопка «Скачать» посреди этой работы уводит с экрана,
      // на который он как раз смотрит, а на сборке она стоит там,
      // где её и ищут — рядом с очередью и остальными файлами.
    ]),
    карточка_субтитров(),
    состояние_файла(),
  ]);
}

// Что показывать в окне «Как это выглядит»: кадр или просмотр.
//
// Вопроса два, и они разные. **Кадр** отвечает «как выглядит субтитр»
// — его рисует сервис тем же шрифтом, каким субтитр попадёт в файл.
// **Просмотр** отвечает «как это идёт»: движение, склейки, звук.
//
// Раньше окно решало за человека и у несобранной вертикалки не играло
// ничего: посмотреть свой фрагмент можно было, только заплатив
// за сборку. Теперь просмотр есть всегда — разного качества, и разница
// названа словами под окном.
function собран_свежим() {
  return это.есть_файл && !это.почему_устарел;
}

function смотрим_файл() {
  return смотрим === 'preview' || (смотрим === null && собран_свежим());
}

function переключатель_окна() {
  const кнопка = (имя, зовут) => эл('button', {
    текст: зовут,
    'aria-pressed': (смотрим_файл() === (имя === 'preview'))
      ? 'true' : 'false',
    на: { click: () => { смотрим = имя; рисовать(); } },
  });
  return эл('div', { класс: 'vc-seg vc-seg--xs' }, [
    кнопка('frame', 'Frame'), кнопка('preview', 'Preview'),
  ]);
}

// Плеер живёт МЕЖДУ перерисовками, и это не оптимизация.
//
// Экран рисуется заново на каждом щелчке и каждые две секунды, пока
// идёт сборка. Собери плеер заново — и он каждый раз начинал бы
// грузиться с нуля: щелчок по плану сбрасывал бы просмотр в начало.
// Узел DOM, переставленный на новое место, состояние проигрывания
// сохраняет; поэтому он и переставляется, а не пересоздаётся.
function забыть_плеер() {
  // **Слежение за кадрами обязано гаснуть вместе с плеером.**
  // Оно само себя перепланирует, и без гашения каждый заход на экран
  // оставлял бы за собой ещё один живой `<video>` с открытым потоком
  // и вечным кругом вызовов. Поймано живьём: у автора от этого
  // подвисал браузер, а следом и машина.
  if (гасить) гасить();
  гасить = null;
  плеер = плеер_коробка = плеер_из = плеер_на = перемотать = null;
}

function превью() {
  if (!смотрим_файл()) {
    забыть_плеер();
    // Метка времени в адресе — чтобы браузер не показал вчерашнюю
    // картинку из своего запаса: после каждой правки кадр другой.
    //
    // Кадр берётся на секунде ВЫБРАННОГО плана. Показывать первый,
    // какой бы план человек ни выбрал, — значит показывать не то,
    // что он сейчас правит.
    const план = это.планы.find((п) => п.idx === выбран);
    const при = план ? (план.at + план.till) / 2 : null;
    // Субтитры выключены — кадр без них: показывается то, что будет
    // в файле.
    const без = !это.субтитры.в_файле;
    return кадр_с_ожиданием({
      класс: 'в-превью', alt: без ? 'clip frame' : 'clip frame with subtitles',
      ждём: 'drawing frame…',
      src: связь.адрес('превью', { слаг: это.слаг, ключ: это.id,
                                   при: при === null ? '' : при.toFixed(2),
                                   ...(без ? { без_субтитра: '1' } : {}),
                                   когда: Date.now() }),
    });
  }

  const из = (собран_свежим() ? 'file:' : 'draft:') + это.слаг + ':' + это.id;
  if (плеер_коробка && плеер_из === из) {
    // Тот же плеер. Перематываем, только если человек ВЫБРАЛ другой
    // план: перерисовок много, и дёргать проигрывание на каждой
    // значило бы не дать ему доиграть ни разу.
    if (плеер_на !== выбран) встать_на_выбранный();
    return плеер_коробка;
  }
  плеер_из = из;
  плеер_коробка = собран_свежим() ? плеер_файла() : плеер_исходника();
  return плеер_коробка;
}

// Просмотр начинается с ВЫБРАННОГО плана, а не с начала ролика.
//
// Человек щёлкнул по плану, поправил ему рамку и хочет увидеть
// именно его — гонять для этого ролик с начала он не нанимался.
// Так же устроен предпросмотр у соседнего сервиса: пробел открывает
// тот план, на котором стоят.
function встать_на_выбранный() {
  const план = это.планы.find((п) => п.idx === выбран) || это.планы[0];
  if (!план || !перемотать) return;
  плеер_на = план.idx;
  перемотать(план);
}

// Собранный и свежий файл смотрится как есть: это ровно то, что
// человек скачает, и добавить к нему нечего.
function плеер_файла() {
  плеер = эл('video', {
    класс: 'в-превью', controls: true, preload: 'metadata',
    // Тот же довод, что у чернового просмотра: скачивание — работа
    // шага «Сборка», и второй дороги к нему не заводится.
    controlsList: 'nodownload',
    src: связь.адрес('скачать', { слаг: это.слаг, ключ: это.id,
                                  смотреть: '1' }),
  });
  // У готового файла время плана — это время самого ролика: файл
  // и есть ролик. Своей арифметики тут нет.
  перемотать = (план) => { плеер.currentTime = план.at; };
  плеер.addEventListener('loadedmetadata', встать_на_выбранный);
  return плеер;
}

// Перемотка встаёт на ближайший кадр, а он бывает чуть РАНЬШЕ
// запрошенного времени. Без допуска попадание в свой же план читалось
// бы как промах, и просмотр прыгал бы на ровном месте. Полкадра при
// 25 к/с — столько же, сколько стоит порог склейки в цепочке фильтров.
const ПОЛКАДРА = 0.02;

// Какой план стоит на этой секунде ИСХОДНИКА.
//
// **Ищется по времени, а не шагом «следующий».** Прежний просмотр
// двигал номер по одному за событие и только вперёд: перемотал
// человек ползунком — и окно осталось от плана, который давно
// доиграл. Отсюда «показывает не тот план, который выбран».
//
// Обход начинается с ТЕКУЩЕГО плана и идёт по кругу: у разрывной
// вертикалки куски лежат в исходнике не обязательно по возрастанию,
// и одна секунда исходника может отвечать двум кускам. Прав тот,
// который играет сейчас.
//
// Своей арифметики времени здесь нет — только сравнение с числами,
// которые посчитал `plans.timeline`.
export function план_на(планы, при, от = 0) {
  const внутри = (п) => (
    п && при >= п.видно.start - ПОЛКАДРА && при < п.видно.end);
  if (внутри(планы[от])) return { номер: от, дальше: -1 };
  for (let сдвиг = 1; сдвиг <= планы.length; сдвиг += 1) {
    const n = (от + сдвиг) % планы.length;
    if (внутри(планы[n])) return { номер: n, дальше: -1 };
  }
  return { номер: -1, дальше: от + 1 < планы.length ? от + 1 : -1 };
}

// Перевод времени: РОЛИК ↔ ИСХОДНИК.
//
// **Это единственная арифметика времени в браузере, и она повторяет
// серверную** — `preview.в_видео`: на секунде `at` ролика стоит
// секунда `видно.start` исходника, дальше секунда в секунду. Числа
// `at`, `till` и `видно` считает `plans.timeline` и присылает
// готовыми; своих здесь не заводится.
//
// **За последним планом — плашка в конце.** Планов под ней нет вовсе
// (они погашены в `plans`), и перевод там продолжается тем же счётом:
// звук под плашкой берётся из исходника дальше по времени, ровно как
// в готовом файле.
//
// Обе стороны проверяются пробой экрана: перевод туда и обратно
// обязан вернуть ту же секунду, а полученная секунда исходника —
// лечь в тот план, который назовёт `план_на`.
export function в_исходник(планы, при) {
  for (const п of планы) {
    if (при >= п.at - ПОЛКАДРА && при < п.till) {
      return п.видно.start + (при - п.at);
    }
  }
  const последний = планы[планы.length - 1];
  return последний ? последний.видно.end + (при - последний.till) : 0;
}

export function в_ролик(планы, секунда, от = 0) {
  const последний = планы[планы.length - 1];
  if (последний && секунда >= последний.видно.end - ПОЛКАДРА) {
    return последний.till + (секунда - последний.видно.end);
  }
  const где = план_на(планы, секунда, от);
  if (где.номер < 0) return null;
  const п = планы[где.номер];
  return п.at + (секунда - п.видно.start);
}

// ── Черновой просмотр ─────────────────────────────────────────────────
//
// Файла нет (или он от прежнего монтажа) — играет ИСХОДНИК, а экран
// делает над ним три вещи, и все три по числам сервера:
//
//   · держит окно колонки — то самое, что посчитал `chain.коробка_окна`
//     и по которому нарисована оранжевая рамка на кадре плана;
//   · перепрыгивает окно на склейках, потому что у каждого плана окно
//     своё;
//   · перескакивает разрывы: у разрывной вертикалки между кусками
//     выброшена речь, и играть её значило бы показать не тот ролик.
//
// **Субтитров тут нет, и это сказано словами.** Их рисует сборка
// настоящим шрифтом; набери их браузер — в проекте появилась бы
// вторая правда о том, как выглядит кадр, и ни один заслон её
// не поймал бы. Смотреть субтитр надо на кадре, он рядом одним щелчком.
function плеер_исходника() {
  const видео = эл('video', {
    класс: 'в-черновик__видео', preload: 'metadata',
    // **РОДНЫХ КНОПОК ЗДЕСЬ НЕТ, и это правка по слову автора:**
    // «предпросмотр нельзя перемотать или поставить с начала, только
    // кликая по кадрам».
    //
    // Причина была не в кнопках, а в том, ПО ЧЕМУ они размечены.
    // Играет исходник — всё видео на двадцать минут, — а вертикалка
    // занимает в нём секунды. Родной ползунок размечен по исходнику:
    // куда ни потяни, попадаешь мимо вертикалки, и слежение честно
    // уводило обратно на выбранный план. Перемотка выглядела
    // сломанной, потому что перематывать ею было некуда.
    //
    // Своя полоса ниже размечена ПО РОЛИКУ: ноль — его начало, конец
    // — его конец, разрывы и плашка на своих местах. То же самое,
    // что человек увидит в готовом файле.
    //
    // Заодно ушла и причина, по которой в родных кнопках приходилось
    // гасить «Скачать»: здесь играет исходник, и та кнопка предлагала
    // бы унести двухчасовое видео целиком, думая, что уносишь свою
    // вертикалку. Гасить больше нечего — кнопок нет.
    controlsList: 'nodownload',
    'data-нет': '',
    src: связь.адрес('исходник', { слаг: это.слаг }),
  });
  // Плашка в конце — картинкой ПОВЕРХ плеера, а звук идёт своим ходом.
  //
  // **Так это и в файле:** последние секунды там идут картинкой, а звук
  // доигрывает под ней целиком. Показывать вместо неё кадры исходника
  // значило бы завести вторую правду о том, как кончается ролик.
  //
  // Картинку рисует СЕРВЕР — та же `плашка.png`, что уйдёт в цепочку.
  // Браузер её не набирает: то же решение, по которому он не рисует
  // субтитр.
  const хвост_ = это.плашка || {};
  const плашка = эл('img', {
    класс: 'в-черновик__плашка', alt: 'end card', hidden: true,
    // Субтитра на ней нет: в черновом просмотре его нет нигде — его
    // рисует сборка настоящим шрифтом, и второй правды о кадре
    // в проекте не заводится.
    src: хвост_.показывать
      ? связь.адрес('превью', { слаг: это.слаг, ключ: это.id,
                                при: хвост_.при, без_субтитра: '1' })
      : '',
  });
  const коробка = эл('div', { класс: 'в-превью в-черновик' }, [
    видео, плашка,
    эл('span', { класс: 'в-рисуется__слово', текст: 'opening the original…' }),
  ]);
  const обёртка = эл('div', { класс: 'в-черновик__всё' }, [коробка]);

  const планы = это.планы.slice().sort((а, б) => а.at - б.at);
  let номер = 0;
  let слежу = true;

  // Где по ВРЕМЕНИ ИСХОДНИКА идёт плашка. Планы под ней погашены —
  // их там нет вовсе, — значит она начинается там, где кончился
  // последний план, и длится столько, сколько сказал сервер.
  const хвост = хвост_;
  const последний = планы.length ? планы[планы.length - 1] : null;
  const плашка_с = (хвост.показывать && последний)
    ? последний.видно.end : null;
  const плашка_по = плашка_с === null ? null : плашка_с + хвост.секунды;
  const конец = плашка_по !== null ? плашка_по
    : (последний ? последний.видно.end : 0);
  const показать_плашку = (надо) => { плашка.hidden = !надо; };

  // Отпустить поток и память: снятый `src` с `load()` — единственный
  // способ сказать браузеру, что это видео больше не нужно.
  const погасить = () => {
    слежу = false;
    видео.pause();
    видео.removeAttribute('src');
    видео.load();
  };
  гасить = погасить;

  // Ушли с экрана — плеер гаснет сам, даже если забыть его забыли.
  // Проверяется адрес, а не «есть ли узел в странице»: между
  // перерисовками узел на мгновение вынут, и по нему живой плеер
  // погас бы на ровном месте.
  const ушли = () => !адрес.на_экране('clip');

  // Окно двигается ТОЛЬКО долями, которые прислал сервер. Своей
  // геометрии здесь нет.
  //
  // Двигается при этом не сам плеер, а КАРТИНКА В НЁМ: `object-fit`
  // — тот самый случай, для которого он и заведён. Первым заходом
  // растягивался элемент целиком (втрое шире окна, сдвинут влево),
  // и вместе с картинкой уезжали кнопки плеера: полоса перемотки
  // висела за краем окна, играть и перематывать было нечем.
  const поставить = (план) => {
    if (план.mode === 'full') {
      видео.style.objectFit = 'contain';
      видео.style.objectPosition = 'center';
      return;
    }
    видео.style.objectFit = 'cover';
    // Доля «сколько мимо окна» — из тех же двух чисел, что рисуют
    // оранжевую рамку на кадре плана.
    const мимо = 1 - план.окно.ширина;
    видео.style.objectPosition =
      `${мимо > 0 ? (план.окно.левый / мимо) * 100 : 50}% 50%`;
  };

  перемотать = (план) => {
    номер = Math.max(0, планы.findIndex((п) => п.idx === план.idx));
    поставить(планы[номер]);
    видео.currentTime = планы[номер].видно.start;
  };

  видео.addEventListener('loadedmetadata', () => {
    коробка.removeAttribute('data-рисуется');
    видео.removeAttribute('data-нет');
    встать_на_выбранный();
    показать_время();
    следить();
  });
  коробка.setAttribute('data-рисуется', '');

  // ── Своя полоса, размеченная ПО РОЛИКУ ────────────────────────────
  //
  // Арифметика здесь ровно одна, и она повторяет серверную
  // (`preview.в_видео`): на секунде `at` ролика стоит секунда
  // `видно.start` исходника, дальше секунда в секунду. Числа `at`,
  // `till` и `видно` считает `plans.timeline` и присылает готовыми —
  // своих здесь не заводится.
  //
  // Под плашкой планов нет вовсе: она начинается там, где кончился
  // последний, и длится столько, сколько сказал сервер. Звук под ней
  // берётся из исходника дальше по времени — ровно как в файле.
  const длина = (последний ? последний.till : 0)
    + (хвост.показывать ? хвост.секунды : 0);

  let тащат = false;
  const полоса = эл('input', {
    класс: 'в-полоса', type: 'range', min: '0', max: String(длина),
    step: '0.04', value: '0', 'aria-label': 'position in the clip',
  });
  const отсчёт = моно('0:00.0 / ' + слова.время(длина), 'в-подпись');
  const играть = эл('button', {
    класс: 'vc-btn vc-btn--xs', текст: 'Play',
    на: { click: () => { if (видео.paused) видео.play(); else видео.pause(); } },
  });
  const звук = эл('button', {
    класс: 'vc-btn vc-btn--xs', текст: 'Mute',
    на: { click: () => { видео.muted = !видео.muted;
                         звук.textContent = видео.muted ? 'Unmute' : 'Mute'; } },
  });

  const показать_время = () => {
    const при = в_ролик(планы, видео.currentTime, номер);
    if (при === null) return;
    if (!тащат) полоса.value = String(Math.max(0, Math.min(длина, при)));
    отсчёт.textContent = `${слова.время(при)} / ${слова.время(длина)}`;
  };

  const встать_на = (при) => {
    const куда = Math.max(0, Math.min(длина - ПОЛКАДРА, при));
    видео.currentTime = в_исходник(планы, куда);
    отсчёт.textContent = `${слова.время(куда)} / ${слова.время(длина)}`;
    сверить_окно(в_исходник(планы, куда));
  };

  полоса.addEventListener('pointerdown', () => { тащат = true; });
  когда_отпустят(полоса, () => { тащат = false; });
  полоса.addEventListener('input', () => встать_на(+полоса.value));
  видео.addEventListener('play', () => { играть.textContent = 'Pause'; });
  видео.addEventListener('pause', () => { играть.textContent = 'Play'; });

  обёртка.append(эл('div', { класс: 'в-ряд в-полоса-ряд' }, [
    играть,
    эл('button', {
      класс: 'vc-btn vc-btn--xs', текст: 'Rewind',
      на: { click: () => встать_на(0) },
    }),
    полоса, отсчёт, звук,
  ]));
  обёртка.append(эл('p', {
    класс: 'в-подпись', стиль: { margin: '0' },
    // Про плашку — только когда она включена. Прежде подпись говорила
    // «последние секунды показывает плашкой» всякой вертикалке, в том
    // числе без плашки, то есть врала почти всегда.
    //
    // Про субтитры здесь не говорится: это сказано подписью окна
    // прямо ниже, и два раза подряд одно и то же читается как шум.
    текст: 'The bar runs from the start of the clip to its end and skips ' +
           'anything cut out between segments' +
           (хвост.показывать ? '; the last seconds show the end card' : '') +
           '.',
  }));

  // Где мы сейчас — и что с этим делать.
  //
  // **Время берётся у САМОГО КАДРА, а не у плеера.** `currentTime`
  // отвечает на вопрос «где плеер», и отвечает с запозданием: замер
  // на живом переходе — окно опаздывает до двух кадров, и это видно
  // глазом, потому что колонка на стыке прыгает сразу на десятую
  // ширины кадра. `requestVideoFrameCallback` вторым доводом отдаёт
  // время кадра, который показывается ПРЯМО СЕЙЧАС (`mediaTime`),
  // и по нему опоздание выходит 0.2 кадра — то есть его нет.
  const сверить_окно = (при) => {
    if (!планы.length) return;
    const т = при === undefined ? видео.currentTime : при;
    // Под плашкой картинки исходника нет — там плашка. Окно при этом
    // не трогается вовсе: двигать нечего.
    if (плашка_с !== null && т >= плашка_с - ПОЛКАДРА && т < плашка_по) {
      показать_плашку(true);
      показать_время();
      return;
    }
    показать_плашку(false);
    const где = план_на(планы, т, номер);
    if (где.номер >= 0) {
      if (где.номер !== номер) { номер = где.номер; поставить(планы[номер]); }
      показать_время();
      return;
    }
    // Ни один план этой секунде не отвечает: между кусками разрывной
    // вертикалки выброшена речь, и играть её значило бы показать
    // не тот ролик.
    if (где.дальше >= 0) {
      номер = где.дальше;
      поставить(планы[номер]);
      // Перемотка сама порождает событие, по которому нас зовут снова.
      // Без этой проверки два таких вызова гоняли бы плеер по кругу
      // и съели бы машину.
      const цель = планы[номер].видно.start;
      if (Math.abs(видео.currentTime - цель) > ПОЛКАДРА) {
        видео.currentTime = цель;
      }
      return;
    }
    // Доиграли до конца ролика — встаём обратно туда, откуда начали.
    видео.pause();
    показать_плашку(false);
    встать_на_выбранный();
  };

  // **Перемотка прижимается к ролику, а не выбрасывает из него.**
  //
  // Найдено автором: «предпросмотр нельзя перемотать, только кликая
  // по кадрам». Причина в том, что играет ИСХОДНИК — полное видео
  // на двадцать минут, — а ролик занимает в нём секунды. Куда ни
  // потяни ползунок, попадаешь мимо, и слежение честно уводило
  // обратно на выбранный план: перемотка выглядела сломанной.
  //
  // Теперь мимо ролика попасть нельзя: раньше начала — встаём
  // на начало, позже конца — на конец. Ползунок при этом всё ещё
  // родной и показывает длину ИСХОДНИКА: своей полосы, размеченной
  // по ролику, у чернового просмотра нет — это отдельная работа,
  // и она записана в `TODO.md`.
  видео.addEventListener('seeking', () => {
    if (!планы.length) return;
    const начало = планы[0].видно.start;
    if (видео.currentTime < начало - ПОЛКАДРА) видео.currentTime = начало;
    else if (видео.currentTime > конец) видео.currentTime = конец - ПОЛКАДРА;
  });

  // **Окно переключается на КАЖДОМ КАДРЕ, а не по `timeupdate`.**
  //
  // Это была настоящая беда, и её видел автор: `timeupdate` браузер
  // шлёт около четырёх раз в секунду — при 25 кадрах это до шести
  // кадров, которые новый план играет в окне ПРЕДЫДУЩЕГО. Выглядит
  // ровно как «в конце плана остаётся кусочек следующего», и списать
  // это легко на детектор склеек — там границы оказались точны все
  // сорок из сорока.
  //
  // `requestVideoFrameCallback` зовут на каждый показанный кадр видео
  // — ровно тогда, когда окну и надо переключиться, и ни разу
  // вхолостую на паузе. Знают его не все браузеры, и для остальных
  // ниже кадры экрана: они чаще кадров видео, то есть не хуже.
  function следить() {
    if (видео.requestVideoFrameCallback) {
      const на_кадре = (_, кадр) => {
        if (!слежу) return;
        if (ушли()) { погасить(); return; }
        сверить_окно(кадр ? кадр.mediaTime : undefined);
        видео.requestVideoFrameCallback(на_кадре);
      };
      видео.requestVideoFrameCallback(на_кадре);
      return;
    }
    // Запасная дорога: времени кадра тут взять негде, и окно опять
    // поедет за `currentTime`. Это хуже, и сказано об этом здесь.
    const тик = () => {
      if (!слежу) return;
      if (ушли()) { погасить(); return; }
      сверить_окно();
      if (!видео.paused) requestAnimationFrame(тик);
    };
    видео.addEventListener('play', тик);
    // Перемотка на паузе кадр меняет, а `play` при этом не приходит.
    видео.addEventListener('seeked', () => сверить_окно());
    тик();
  }

  // Не открылось — говорится ПОЧЕМУ, а не «не получилось».
  //
  // Причин ровно две, и они разные: сервер отказал (исходник переехал,
  // подменён) или браузер не умеет играть такой контейнер. Первую
  // сервер называет словами — их и надо показать; вторая видна по
  // тому, что сервер отдал файл честно. Чёрный прямоугольник без
  // объяснения человек прочтёт как поломку сервиса.
  видео.addEventListener('error', async () => {
    let беда = 'This browser can\'t play this video format. Export the ' +
               'clip — the exported file will play.';
    try {
      await связь.взять('исходник', { слаг: это.слаг });
    } catch (отказ) {
      беда = отказ.message || String(отказ);
    }
    коробка.removeAttribute('data-рисуется');
    коробка.replaceChildren(эл('p', {
      класс: 'в-подпись', стиль: { padding: '16px', margin: '0' },
      текст: 'The preview didn\'t open. ' + беда,
    }));
  });

  плеер = видео;
  return обёртка;
}

// Ползунок отпущен — где угодно, хоть за краем окна. Ловится и мышь,
// и палец, и клавиатура: `change` приходит после всех трёх.
function когда_отпустят(полоса, дело) {
  for (const имя of ['pointerup', 'pointercancel', 'change']) {
    полоса.addEventListener(имя, дело);
  }
}

// Чем этот просмотр отличается от готового файла — говорится прямо
// под ним. Промолчать значит дать человеку принять черновик
// за результат.
function подпись_окна() {
  if (!смотрим_файл()) {
    return 'A frame from the selected shot, drawn by Vertcut with the ' +
           'same font the exported file will use.';
  }
  if (собран_свежим()) {
    return 'This is the exported file — the one you\'ll download. ' +
           'Space plays and pauses.';
  }
  return 'Preview: the original picture and sound, cropped exactly as ' +
         'in the export. No subtitles here — they\'re added on export; see ' +
         'them on Frame. Space plays and pauses.' +
         // Только когда файл ЛЕЖИТ: у несобранной причина «устарела»
         // тоже есть («not exported yet»), и подпись обещала ей файл,
         // которого никогда не было. Так было и по-русски.
         (это.есть_файл && это.почему_устарел
           ? ' The previous export is still there, on the Export step.'
           : '');
}

function карточка_субтитров() {
  const с = это.субтитры;
  const галочка = выключатель_субтитров();
  if (!с.в_файле) {
    // Выключены: ни шрифта, ни длинных фраз — в файле их не будет.
    // Текст и стиль при этом целы, и это сказано.
    return эл('div', { класс: 'vc-card', стиль: { padding: '14px' } }, [
      эл('div', { класс: 'в-ряд' }, [
        эл('b', { класс: 'vc-card__title', текст: 'Subtitles' }),
        растяжка(),
        метка('off', 'off'),
      ]),
      галочка,
      эл('p', {
        класс: 'в-подпись', стиль: { margin: '0' },
        текст: 'This clip exports without subtitles. Its text and style ' +
               'are kept — tick the box to bring them back.',
      }),
      кнопка_редактора(),
    ]);
  }
  return эл('div', { класс: 'vc-card', стиль: { padding: '14px' } }, [
    эл('div', { класс: 'в-ряд' }, [
      эл('b', { класс: 'vc-card__title', текст: 'Subtitles' }),
      растяжка(),
      // Считаются ФРАЗЫ, а не строки: `строк` в ответе — это фразы
      // раскладки. Прежде подпись звала их «строками» и врала.
      моно(слова.счёт(с.строк, 'phrase', 'phrases'), 'в-подпись'),
    ]),
    галочка,
    эл('div', { класс: 'в-ряд' }, [
      моно(`${с.шрифт.гарнитура} ${с.шрифт.вес}`, 'в-подпись'),
      с.шрифт.вес_выставлен ? null
        : метка('weight didn\'t apply: the font has no weight axis', 'warn'),
    ]),
    // Длинные фразы — сведение, а не беда: серым, без метки. Жёлтая
    // метка «don't fit» читалась как «субтитр обрежется», а он
    // просто перелистывается, и все слова в кадре.
    ...[с.частями, ...с.жалобы].filter(Boolean).map((ж) => эл('p', {
      класс: 'в-подпись', стиль: { margin: '0' }, текст: ж })),
    кнопка_редактора(),
  ]);
}

