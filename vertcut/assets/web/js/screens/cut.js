// ← → ходят по планам. Правило пакета дизайна, и на длинной ленте
// это единственный способ пройти её подряд, не целясь мышью.
document.addEventListener('keydown', (е) => {
  if (!адрес.на_экране('clip') || !это) return;
  if (е.target.matches('input, textarea')) return;
  // Пробел играет и ставит на паузу. Свой обработчик нужен потому,
  // что своим пробелом плеер слушается ТОЛЬКО когда на нём фокус,
  // а человек до того щёлкал по планам, — и пробел уезжал странице,
  // которая на него листает.
  if (е.key === ' ' || е.key === 'Spacebar') {
    е.preventDefault();
    // Стоим на кадре — пробел переводит на просмотр и играет.
    // Играть на кадре нечего, а идти за этим мышью человек
    // не должен: пробел и значит «покажи, как это идёт».
    // Стоим на кадре — пробел переводит на просмотр и играет
    // ВЫБРАННЫЙ план: встать на него плеер успеет сам, как только
    // прочтёт длину.
    if (!плеер) { смотрим = 'preview'; рисовать(); играть(); return; }
    if (плеер.paused) играть(); else плеер.pause();
    return;
  }
  if (е.key !== 'ArrowLeft' && е.key !== 'ArrowRight') return;
  const номера = это.планы.map((п) => п.idx);
  const где = номера.indexOf(выбран);
  const куда = е.key === 'ArrowLeft' ? где - 1 : где + 1;
  if (куда < 0 || куда >= номера.length) return;
  е.preventDefault();
  выбран = номера[куда];
  рисовать();
});
