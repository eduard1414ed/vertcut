async function править(план, что) {
  убрать_полосы();
  try {
    // Отметка едет вместе с правкой: тронули файл из терминала или
    // из другой вкладки — отказ словами, а не тихая перезапись.
    const куски = это.куски;
    это = await связь.послать('рамка', {
      слаг: это.слаг, ключ: это.id, план, отметка: это.отметка, ...что,
    });
    это.куски = куски;
    выбран = план;
    рисовать();
  } catch (беда) { сказать_беду(беда); }
}

