// Экран 08 · Редактор субтитров.
//
// **Браузер здесь не рисует субтитр — и это главное решение экрана.**
// Наберись он тут своими шрифтами, в проекте появилась бы вторая правда
// о том, как выглядит кадр: на экране красиво, в файле иначе. Ни один
// из четырёх заслонов этого не поймает — они сверяют файл с монтажом,
// а не с экраном.
//
// Поэтому в середине лежат ДВЕ картинки с сервера: кадр без субтитра
// и прозрачный слой с одним субтитром, нарисованный тем же шрифтом,
// каким он попадёт в файл. Перетаскивание двигает слой; отпускание
// пересчитывает положение и просит новые картинки. Браузер двигает
// пиксели, а не рисует их.
//
// Чем это проверено, что не разошлось: `vertcut proof {слаг} {ключ}` —
// пятая сверка, кадр из готового файла против кадра из предпросмотра,
// с контролем.
//
// Уровней стиля четыре (`docs/decisions.md`, «Четыре уровня профиля»):
// поставляемый, мой, стиль видео и свой у вертикалки. Первая правка
// здесь заводит вертикалке свой; «Apply to all clips» раздаёт его
// остальным.
//
// Ключи стиля (`это.стиль['position.from_bottom']`) — имена профиля
// `subtitles.yaml`, и они английские: человек видит их, открыв файл.

import {
  нарисовать, лого, блок, маршрут, вертикалки, эл, моно, метка,
  растяжка,
  сказать, сказать_беду, убрать_полосы, положить, подвал,
} from '../shell.js';
import * as связь from '../api.js';
import * as слова from '../words.js';
import * as адрес from '../route.js';

let это = null;
// Вертикалки колонки живут ОТДЕЛЬНОЙ переменной, а не полем `это`.
//
// **Это починка живой беды, найденной автором.** Экран кладёт себе
// ответ ручки целиком (`это = await ...`), а в ответе ручки вертикалок
// нет вовсе — их спрашивают отдельно. Пока они лежали полем внутри
// `это`, каждое такое место обязано было помнить, что их надо
// перенести обратно, — девять мест помнили, а десятое, перетаскивание
// субтитра мышью, забыло. Оно рисует только кадр, поэтому колонка
// пропадала не сразу, а на следующей перерисовке: человек тащил
// субтитр, потом делал что угодно ещё — и список вертикалок исчезал.
//
// Правило проекта записано ровно про это: «ответ ручки, который экран
// кладёт себе целиком, обязан содержать всё, что экран рисует». Здесь
// оно сделано невозможным нарушить: терять нечего, потому что класть
// обратно нечего.
let куски = [];
// Набранная, но ещё не записанная надпись плашки.
//
// Панель перерисовывается на каждую правку — двинули ползунок кегля,
// и поле собралось заново. Набранное в нём при этом пропало бы: то же
// самое, на чём в седьмой сессии сбрасывался поиск по фразам. Здесь
// оно живёт до записи, а после — забывается.
let набрана = null;
// Набранный, но ещё НЕ сохранённый текст выбранной строки.
//
// **Без неё текст субтитра нельзя было исправить вовсе**, и это та же
// беда, на которой в седьмой сессии сбрасывался поиск по фразам.
// Экран рисуется заново на каждом щелчке — двинули ползунок кегля,
// потащили субтитр мышью, — и поле собиралось из того текста, который
// лежит на диске. Набранное пропадало молча, а со стороны это
// выглядело так, будто сервис сам стирает исправление и уходит рисовать
// кадр.
//
// Живёт ровно до записи, а после забывается: сохранённый текст
// приезжает с сервера, и вторая его копия здесь разошлась бы с ним.
let набран = null;
let выбрана = null;      // номер первого слова выбранной строки
// Правка модели, открытая в поле («Edit»), — номер первого слова её
// фразы, и набранное в этом поле. Живёт до Save или Cancel по той же
// причине, что и `набран`: экран перерисовывается на каждый щелчок.
let правлю = null;
let набрана_правка = null;
let проверяю = false;    // вычитка моделью идёт
let при = null;          // на какой секунде показан кадр

export async function показать([слаг, ключ]) {
  if (!слаг || !ключ) {
    throw new связь.Беда('No clip was given to edit subtitles for', '');
  }
  try {
    это = await связь.взять('субтитры', { слаг, ключ });
    куски = (await связь.взять('куски', { слаг })).куски;
  } catch (беда) {
    // Профиль испорчен или старого образца — рисовать нечем. Но кнопка
    // «вернуть стиль» нужна именно в эту минуту, и она рисуется даже
    // тогда, когда всё остальное показать нечем.
    return спасение(слаг, ключ, беда);
  }
  набрана = null;
  набран = null;
  правлю = null;
  набрана_правка = null;
  выбрана = это.строки.length ? это.строки[0].с : null;
  при = где_стоит();
  рисовать();
}

async function перечитать() {
  это = await связь.взять('субтитры', { слаг: это.слаг, ключ: это.ключ });
  рисовать();
}

function где_стоит() {
  const строка = это.строки.find((с) => с.с === выбрана) || это.строки[0];
  return строка ? (строка.at + строка.till) / 2 : 0;
}

// ── Испорченный профиль ───────────────────────────────────────────────

function спасение(слаг, ключ, беда) {
  нарисовать({
    колонка: [лого(), растяжка()],
    заголовок: эл('h1', { класс: 'vc-h1' }, ['Subtitles']),
    тело: [
      эл('div', { класс: 'vc-bar vc-bar--bad' }, [
        эл('div', { класс: 'vc-bar__what' }, [
          эл('b', { текст: беда.что || "The subtitle style can't be read." }),
          эл('span', { текст: беда.подсказка || '' }),
        ]),
      ]),
      эл('div', { класс: 'vc-card' }, [
        эл('b', { класс: 'vc-card__title', текст: 'Fix the style' }),
        эл('p', {
          класс: 'в-подпись', стиль: { margin: '0' },
          текст: "These buttons don't read the file that's broken — they " +
                 "replace it. So they work even when nothing else here " +
                 'can. Only the style is replaced; your clips, text edits ' +
                 'and exported files stay as they are.',
        }),
        эл('div', { класс: 'в-ряд' }, [
          эл('button', {
            класс: 'vc-btn vc-btn--sm vc-btn--primary',
            текст: 'Reset to default style',
            на: { click: () => спасти(слаг, ключ, 'поставляемый') },  // значение для сервера, не для человека
          }),
          эл('button', {
            класс: 'vc-btn vc-btn--sm', текст: 'Use my style',
            на: { click: () => спасти(слаг, ключ, 'мой') },  // значение для сервера, не для человека
          }),
        ]),
      ]),
    ],
  });
}

async function спасти(слаг, ключ, откуда) {
  убрать_полосы();
  try {
    const ответ = await связь.послать('стиль-откуда', { слаг, ключ, откуда });
    await показать([слаг, ключ]);
    // Сказать, ЧТО заменено: файлов на пути у вертикалки два, и человек
    // должен знать, что поменялся стиль всего видео, а не только её.
    if (ответ.починено && ответ.починено.length) {
      сказать({
        вид: 'good',
        что: `Replaced: ${ответ.починено.join(' and ')}.`,
        делать: откуда === 'мой' ? 'It now uses my style.'
                                 : 'It now uses the default style.',
      });
    }
  } catch (беда) { сказать_беду(беда); }
}

// ── Рисование ─────────────────────────────────────────────────────────

