function кадр() {
  if (!это.в_файле) return кадр_без_субтитров();
  const слой = эл('img', {
    класс: 'в-кадр__слой', alt: 'subtitle', draggable: 'false',
    src: связь.адрес('слой-субтитра',
                     { слаг: это.слаг, ключ: это.ключ, при, когда: Date.now() }),
  });
  const подложка = эл('img', {
    alt: 'clip frame', draggable: 'false',
    src: связь.адрес('превью', { слаг: это.слаг, ключ: это.ключ, при,
                                 без_субтитра: '1', когда: Date.now() }),
  });
  const коробка = эл('div', { класс: 'в-кадр', 'data-рисуется': '' }, [
    подложка, слой,
    эл('span', { класс: 'в-рисуется__слово', текст: 'drawing frame…' }),
    ...зоны(), база(),
  ]);
  // Кадр и слой приезжают порознь; слово уходит, когда приехали оба.
  // Ждать одного значило бы показать субтитр над пустотой или пустоту
  // под субтитром.
  let осталось = 2;
  const готово = () => {
    осталось -= 1;
    if (осталось <= 0) коробка.removeAttribute('data-рисуется');
  };
  for (const к of [подложка, слой]) {
    к.addEventListener('load', готово);
    к.addEventListener('error', готово);
    if (к.complete && к.naturalWidth) готово();
  }
  тащить(коробка, слой);
  return эл('div', { класс: 'в-кадр-обёртка' }, [
    эл('div', { класс: 'в-ряд' }, [
      моно(`frame ${слова.время(при)}`, 'в-подпись'),
      растяжка(),
      эл('span', { класс: 'в-подпись', текст: `${это.кадр.ширина}×${это.кадр.высота}` }),
    ]),
    коробка,
    эл('p', {
      класс: 'в-подпись', стиль: { margin: '0' },
      текст: 'Dashed lines mark the safe zones: outside them, platforms ' +
             'show the account name (top), buttons (bottom) and icons ' +
             '(sides). Drag the subtitle right in the frame. Vertcut draws ' +
             'the frame and subtitle with the same font the file will use.',
    }),
  ]);
}

