async function разделить(с) {
  // Делится посередине слов: точное место человек уточнит текстом,
  // а сервису надо знать номер слова, после которого резать.
  const посередине = с.с + Math.max(0, Math.floor((с.по - с.с) / 2));
  await правка_швом('разделить-строку', { после: посередине });  // имя ручки, не для человека
}

