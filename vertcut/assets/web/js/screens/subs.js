// Тащим ТОЛЬКО прозрачный слой, нарисованный сервером.
//
// **Отпустили — субтитр остаётся там, куда его положили, и никуда
// не мигает.** Так было не сразу: раньше отпускание перерисовывало
// весь экран, кадр и слой уезжали на пересчёт, а на их месте
// секунду-две висело «рисую кадр…». Со стороны это выглядело так,
// будто субтитр отпрыгнул назад и тащить его нельзя.
//
// Теперь после отпускания сдвиг ОСТАЁТСЯ на слое, сервер считает
// новые картинки в стороне, и когда они готовы — подменяются молча,
// а сдвиг снимается. Человек всё это время видит то, что сделал.
function тащить(коробка, слой) {
  let начало = null;
  let сдвиг = 0;

  const где = (е) => (е.touches ? е.touches[0].clientY : е.clientY);

  коробка.addEventListener('pointerdown', (е) => {
    начало = где(е);
    коробка.dataset.тащим = '1';
    коробка.setPointerCapture(е.pointerId);
  });
  коробка.addEventListener('pointermove', (е) => {
    if (начало === null) return;
    е.preventDefault();
    // Субтитр не уезжает за кадр: тащить его туда, где его никто
    // не увидит, — не свобода, а ловушка.
    const высота = коробка.getBoundingClientRect().height;
    const от_низа = это.стиль['position.from_bottom'];
    сдвиг = Math.min(Math.max(где(е) - начало,
                              (от_низа - 0.9) * высота), от_низа * высота);
    слой.style.transform = `translateY(${сдвиг}px)`;
    // Черта базы едет вместе со слоем: она показывает, где субтитр
    // стоит, и отстать от него не имеет права.
    подвинуть_базу(коробка, сдвиг);
  });
  const отпустили = async (е) => {
    if (начало === null) return;
    try { коробка.releasePointerCapture(е.pointerId); } catch (_) { /* уже */ }
    delete коробка.dataset.тащим;
    начало = null;
    if (Math.abs(сдвиг) < 2) { сдвиг = 0; return; }  // щелчок, не перетаскивание
    const высота = коробка.getBoundingClientRect().height;
    // Тащили вниз — субтитр стоит НИЖЕ, то есть «от низа» уменьшилось.
    const стало = Math.min(Math.max(
      это.стиль['position.from_bottom'] - сдвиг / высота, 0), 0.9);
    сдвиг = 0;
    await подвинуть(стало);
  };
  коробка.addEventListener('pointerup', отпустили);
  коробка.addEventListener('pointercancel', отпустили);
}

function подвинуть_базу(коробка, сдвиг) {
  const база_ = коробка.querySelector('.в-база');
  if (база_) база_.style.transform = `translateY(${сдвиг}px)`;
}

// Правка положения БЕЗ мигания: экран не перерисовывается, пока
// новые картинки не готовы. Всё остальное на панели меняется редко
// и мгновенно — там перерисовка не мешает.
async function подвинуть(от_низа) {
  убрать_полосы();
  try {
    это = await связь.послать('стиль', {
      слаг: это.слаг, ключ: это.ключ,
      правки: { 'position.from_bottom': окр(от_низа, 4) },
      отметка_стиля: это.отметка_стиля,
    });
    await обновить_кадр();
  } catch (беда) {
    сказать_беду(беда);
    рисовать();
  }
}

// Подменить кадр и слой на свежие, показав старые до последнего.
//
// Картинки грузятся В СТОРОНЕ и встают на место только готовыми:
// поставь адрес прямо в `src`, и браузер сперва очистит картинку,
// а потом секунду будет рисовать новую — то самое мигание.
async function обновить_кадр() {
  const коробка = document.querySelector('.в-кадр');
  if (!коробка || !это.в_файле) return рисовать();
  const [подложка, слой] = коробка.querySelectorAll('img');
  const адреса = [
    связь.адрес('превью', { слаг: это.слаг, ключ: это.ключ, при,
                            без_субтитра: '1', когда: Date.now() }),
    связь.адрес('слой-субтитра', { слаг: это.слаг, ключ: это.ключ, при,
                                   когда: Date.now() }),
  ];
  await Promise.all(адреса.map((адрес) => new Promise((готово) => {
    const про = new Image();
    про.addEventListener('load', готово);
    про.addEventListener('error', готово);
    про.src = адрес;
  })));
  подложка.src = адреса[0];
  слой.src = адреса[1];
  слой.style.transform = '';
  подвинуть_базу(коробка, 0);
  const база_ = коробка.querySelector('.в-база');
  if (база_) {
    база_.style.bottom = `${это.стиль['position.from_bottom'] * 100}%`;
    const подпись = база_.querySelector('span');
    if (подпись) {
      подпись.textContent =
        `${(это.стиль['position.from_bottom'] * 100).toFixed(1)}% from bottom`;
    }
  }
}

