function окр(число, знаков) {
  return Number(Number(число).toFixed(знаков));
}

// Знаков после точки — по единице: пиксели целые («45.004 px» —
// это доля кадра, переведённая в пиксели, и тысячные пикселя ничего
// не говорят), проценты и секунды — до десятой, доли — как есть.
function знаков_для(единица) {
  if (единица === 'px') return 0;
  if (единица) return 1;
  return 3;
}

function ползунок(зовут, значение, от, до, шаг, вчисла, единица = '') {
  const как = (з) => `${окр(з, знаков_для(единица))}${единица ? ' ' + единица : ''}`;
  const цифра = моно(как(значение));
  const вход = эл('input', {
    type: 'range', min: от, max: до, step: шаг, value: значение,
    на: {
      input: (е) => { цифра.textContent = как(+е.target.value); },
      // Пишется на ОТПУСКАНИИ, а не на каждом движении: каждая правка
      // — это запись файла на диск и пересчёт кадра сервером.
      change: (е) => задать(вчисла(+е.target.value)),
    },
  });
  return эл('div', { класс: 'в-настройка' }, [
    эл('span', { класс: 'в-подпись', текст: зовут }),
    эл('div', { класс: 'в-ползунок' }, [вход, цифра]),
  ]);
}

