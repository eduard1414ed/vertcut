// У каждого вида записана ЦЕНА — доля фраз, которые перестают влезать
// в одну страницу. Печатается ДО того, как человек вид возьмёт:
// иначе он узнает об этом на своём первом видео (`docs/decisions.md`,
// «Готовые виды»).
//
// **Цена вернулась на экран в двадцатой сессии.** Её убирали отсюда
// с доводом «последствия видны тут же, в кадре и в списке строк» —
// но видны они ПОСЛЕ того, как вид взят и стиль переписан. Пишется
// разбросом по трём видео замера, а не одним числом: на интервью
// и на эссе цена разная втрое, и одно число обещало бы неправду.
function виды() {
  const кнопка = (зовут, дело, цена) => эл('button', {
    класс: 'в-вид', на: { click: дело },
  }, [эл('b', { текст: зовут }), цена ? эл('span', { текст: цена }) : null]);

  const цена_вида = (вид) => {
    const доли = Object.values(вид.цена || {}).map((д) => Math.round(д * 100));
    if (!доли.length) return null;
    const от = Math.min(...доли), до = Math.max(...доли);
    return `${от === до ? от : `${от}–${до}`}% of phrases need two pages`;
  };

  const готовые = Object.entries(это.виды).map(
    ([имя, вид]) => кнопка(вид.зовут || имя, () => взять_вид(имя, вид.зовут || имя),
                           цена_вида(вид)));

  return [
    // Свой стиль стоит ПЕРВЫМ, как только он есть: человек, однажды
    // настроивший вид под себя, возвращается к нему чаще, чем
    // к любому поставляемому.
    это.чей.личный_есть ? кнопка('My style', () => откуда('мой')) : null,  // значение для сервера, не для человека
    ...готовые,
    эл('button', {
      класс: 'vc-btn vc-btn--xs', текст: 'Save as my style',
      title: 'New videos will start with this style',
      на: { click: () => откуда('сделать-моим') },  // значение для сервера, не для человека
    }),
    // Уровней стиля четыре, и четвёртый заводится сам — первой же
    // правкой ЭТОЙ вертикалки. Вернуть её к общему и раздать её стиль
    // всем — две разные кнопки, и обе появляются только когда есть
    // что возвращать и кому раздавать.
    это.свой_стиль && это.вертикалок > 1
      ? эл('button', {
          класс: 'vc-btn vc-btn--xs vc-btn--primary',
          текст: 'Apply to all clips',
          на: { click: применить_всем },
        })
      : null,
    это.свой_стиль
      ? эл('button', {
          класс: 'vc-link vc-link--muted', текст: "Use this video's style",
          title: "Drop this clip's own style; it will use the video's again",
          на: { click: () => откуда('видео') },  // значение для сервера, не для человека
        })
      : null,
    эл('span', {
      класс: 'в-подпись',
      // Сравнивается стиль ВИДЕО (так считает сервер), поэтому у
      // вертикалки со своим стилем сравнения нет — она просто своя.
      текст: это.свой_стиль ? "now: this clip's own style"
        : это.чей.как_поставляемый ? 'now: the default style'
          : это.чей.как_личный ? 'now: my style'
            : "now: this video's style, changed",
    }),
  ];
}

