"""Предпросмотр: кадр видео с субтитром, до и после.

Здесь настройка стиля превращается в картинку, которую можно
посмотреть глазами. Без этого стиль настраивать нельзя вовсе:
«кегль 0.05» ничего не значит, пока не видно, как это выглядит
на настоящем кадре настоящего видео.

## Зачем на настоящем кадре, а не на сером фоне

Серый лист (`subs.лист`) отвечает на вопрос «как разложился текст».
Он не отвечает на вопрос «читается ли это»: субтитр стоит поверх
картинки, и белая плашка на светлом кадре, тонкая обводка на пёстром
фоне, текст, попавший на лицо, — всё это видно только на кадре.

## Геометрия здесь не своя

Колонка кадра берётся тем же окном, каким её вырежет сборка
(`chain.коробка_окна`), поля полного кадра размываются тем же
радиусом (`chain.размытие_долей_кадра`). Своей арифметики нет
и быть не должно: предпросмотр, который показывает не то, что
соберётся, хуже, чем никакого.

**Точного совпадения с готовым файлом при этом не обещается.**
Сборка режет и растягивает средствами ffmpeg, здесь это делает
Pillow, и на границах букв разница в один-два уровня яркости есть.
Заслон сверяет ФАЙЛ, а не предпросмотр; предпросмотр — для глаз.

## Кому это пригодится дальше

Экран четвёртой сессии рисует ровно это в середине редактора
субтитров. Он позовёт эти же функции, а не напишет свои.
"""

from __future__ import annotations

import shutil
import tempfile
from pathlib import Path

from . import chain, media, subs, tuning
from .errors import VertcutError

# Фон листа и поле между кадрами. Тёмный нарочно: кадры вертикальные,
# и на светлом фоне их края теряются.
ФОН = (20, 20, 24)
ПОЛЕ = 12


def колонка(картинка, cx, width: int, height: int):
    """Вертикальная колонка из кадра исходника — как её вырежет сборка."""
    from PIL import Image

    ш, _ = картинка.size
    коробка = chain.коробка_окна(width, height, cx, ш / width)
    return картинка.crop(коробка).resize(
        (tuning.VERTICAL_W, tuning.VERTICAL_H), Image.LANCZOS)


def полный_кадр(картинка):
    """Кадр целиком, вписанный по ширине, на размытом фоне.

    Так сборка показывает планы, оставленные горизонтальными: колонка
    из того же кадра размывается и служит фоном, а сам кадр ложится
    поверх по центру. Радиус размытия берётся у цепочки — там он
    заведён долей высоты как раз для того, чтобы предпросмотр
    не завёл второй.
    """
    from PIL import Image, ImageFilter

    ш, в = картинка.size
    новая_в = max(2, round(в / ш * tuning.VERTICAL_W))
    лента = картинка.resize((tuning.VERTICAL_W, новая_в), Image.LANCZOS)

    мал_в = tuning.BLUR_HEIGHT
    мал_ш = max(2, round(tuning.VERTICAL_W * мал_в / tuning.VERTICAL_H))
    фон = (картинка.resize((мал_ш, мал_в), Image.BILINEAR)
           .filter(ImageFilter.GaussianBlur(tuning.BLUR_SIGMA))
           .resize((tuning.VERTICAL_W, tuning.VERTICAL_H), Image.BILINEAR))
    фон.paste(лента, (0, (tuning.VERTICAL_H - новая_в) // 2))
    return фон


def кадр_ролика(картинка, ряд: dict, width: int, height: int):
    """Кадр ролика без субтитра: колонка или полный кадр — по монтажу."""
    if ряд.get("mode") == "full":
        return полный_кадр(картинка)
    return колонка(картинка, ряд.get("cx"), width, height)


def ряд_на(ряды: list[dict], при: float) -> dict:
    """Какой план стоит на этой секунде ролика."""
    for ряд in ряды:
        if ряд["at"] - 1e-6 <= при < ряд["till"] + 1e-6:
            return ряд
    return ряды[-1]


def в_видео(ряд: dict, при: float) -> float:
    """Секунда ИСХОДНИКА, на которой стоит эта секунда ролика.

    Считается тем же способом, что и на сверке: на секунде `t0` ролика
    стоит секунда `essay0` исходника. Своей арифметики времени
    в проекте больше нигде нет, и здесь её тоже нет.
    """
    return float(ряд["essay0"]) + (при - float(ряд["t0"]))


def секунды_показов(раскл: dict, сколько: int = 5) -> list[dict]:
    """Какие состояния субтитра показать и на какой секунде.

    Берутся не подряд и не наугад, а по представителю каждой породы —
    первое, двухстрочное, нижнее, перелистывание, последнее. Лист нужен
    затем, чтобы увидеть РЕДКОЕ.
    """
    вышло = []
    for показ in subs.выбрать_показы(раскл, сколько):
        # Середина состояния, а не его начало: на самом начале субтитр
        # только-только сменился, и на кадре легко принять его
        # за предыдущий.
        вышло.append({"показ": показ,
                      "при": round((показ["at"] + показ["till"]) / 2, 3)})
    return вышло


def вынуть_кадры(source: Path, ряды: list[dict], точки: list[dict],
                 куда: Path, ширина: int) -> list[Path]:
    """Кадры исходника на секунды показов. По кадру на точку."""
    времена = [в_видео(ряд_на(ряды, т["при"]), т["при"]) for т in точки]
    return media.grab_frames(source, времена, куда, ширина)


def собрать_состояние(кадр: Path, ряд: dict, meta: dict, показ: dict,
                      prof: dict, шрифт, зоны: bool = False):
    """Один кадр ролика с наложенным субтитром."""
    from PIL import Image

    with Image.open(кадр) as сырое:
        основа = кадр_ролика(сырое.convert("RGB"), ряд,
                             int(meta["width"]), int(meta["height"]))
    слой = subs.нарисовать(показ["страница"], показ["сказано"],
                           показ["низ"], prof, шрифт)
    вышло = Image.alpha_composite(основа.convert("RGBA"), слой)
    if зоны:
        вышло = Image.alpha_composite(вышло, нарисовать_зоны(prof))
    return вышло.convert("RGB")


# Красная полупрозрачная плёнка поверх опасных зон. Ровно та мысль,
# что и в дизайне: полупрозрачные поля объясняют это без единого слова
# инструкции.
ПЛЁНКА = (170, 40, 40, 70)
ЧЕРТА = (230, 90, 80, 200)


def нарисовать_зоны(prof: dict):
    """Опасные зоны площадок плёнкой поверх кадра.

    Рисуется ВСЕГДА по числам зон, даже если галочка снята: человек,
    который её снял, тем более должен видеть, куда он лезет.
    """
    from PIL import Image, ImageDraw

    ш, в = prof["width"], prof["height"]
    слой = Image.new("RGBA", (ш, в), (0, 0, 0, 0))
    перо = ImageDraw.Draw(слой)
    сбоку, снизу, сверху = (prof["зона_сбоку"], prof["зона_снизу"],
                            prof["зона_сверху"])
    for коробка in ([0, 0, сбоку, в], [ш - сбоку, 0, ш, в],
                    [0, 0, ш, сверху], [0, в - снизу, ш, в]):
        перо.rectangle(коробка, fill=ПЛЁНКА)
    for линия in ([сбоку, 0, сбоку, в], [ш - сбоку, 0, ш - сбоку, в],
                  [0, сверху, ш, сверху], [0, в - снизу, ш, в - снизу]):
        перо.line(линия, fill=ЧЕРТА, width=3)
    return слой


