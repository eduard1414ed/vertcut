def _подпись(картинка, текст: str, снизу: int = 44):
    """Полоска с подписью под кадром. Подпись обязательна на листе
    «до и после»: два столбца без имён — это загадка, а не ответ."""
    from PIL import Image, ImageDraw

    from . import shots as планы

    ш, в = картинка.size
    холст = Image.new("RGB", (ш, в + снизу), ФОН)
    холст.paste(картинка, (0, 0))
    перо = ImageDraw.Draw(холст)
    перо.text((8, в + снизу // 2), текст, fill=(235, 235, 240),
              font=планы.шрифт_подписей(24), anchor="lm")
    return холст


def _столбец(картинки: list, ширина_столбца: int):
    """Кадры одного столбца, ужатые до общей ширины."""
    from PIL import Image

    ужатые = []
    for кадр in картинки:
        k = ширина_столбца / кадр.width
        ужатые.append(кадр.resize(
            (ширина_столбца, max(2, round(кадр.height * k))), Image.LANCZOS))
    высота = sum(к.height + ПОЛЕ for к in ужатые) - ПОЛЕ
    столбец = Image.new("RGB", (ширина_столбца, max(1, высота)), ФОН)
    y = 0
    for к in ужатые:
        столбец.paste(к, (0, y))
        y += к.height + ПОЛЕ
    return столбец


def лист(project: Path, meta: dict, cut: dict, ряды: list[dict],
         source: Path, куда: Path, столбцы: list[dict],
         ширина_кадра: int = 320) -> Path:
    """Лист «до и после» на настоящих кадрах видео.

    `столбцы` — по словарю на столбец: `имя`, `раскл`, `prof`, `шрифт`.
    Один столбец — просто лист; два — «до и после». Больше двух
    не запрещено, но и не нужно: сравнивать глазами три вида разом
    человек не станет.

    Кадры исходника вынимаются ОДИН РАЗ на все столбцы: секунды у них
    одни и те же, а выемка кадра из трёхгигабайтного файла стоит
    четверть секунды.
    """
    from PIL import Image

    if not столбцы:
        raise VertcutError("Nothing to show: no presets given")
    точки = секунды_показов(столбцы[0]["раскл"])
    if not точки:
        raise VertcutError(
            "Nothing to show: this clip has no subtitles")

    работа = Path(tempfile.mkdtemp(prefix="vertcut-preview-"))
    try:
        кадры = вынуть_кадры(source, ряды, точки, работа, int(meta["width"]))
        собранные = []
        for столбец in столбцы:
            свои_точки = секунды_показов(столбец["раскл"])
            картинки = []
            for n, точка in enumerate(точки):
                # Состояния берутся СВОИ у каждого столбца: другой кегль
                # разложит фразу на другое число страниц, и показывать
                # чужое состояние значило бы врать про то, что увидит
                # зритель. Кадр при этом тот же самый.
                показ = (свои_точки[n]["показ"] if n < len(свои_точки)
                         else точка["показ"])
                ряд = ряд_на(ряды, точка["при"])
                картинки.append(собрать_состояние(
                    кадры[n], ряд, meta, показ, столбец["prof"],
                    столбец["шрифт"], столбец.get("зоны", False)))
            собранные.append(_подпись(_столбец(картинки, ширина_кадра),
                                      столбец["имя"]))

        общая_высота = max(с.height for с in собранные)
        итог = Image.new("RGB",
                         (sum(с.width + ПОЛЕ for с in собранные) - ПОЛЕ,
                          общая_высота), ФОН)
        x = 0
        for с in собранные:
            итог.paste(с, (x, 0))
            x += с.width + ПОЛЕ
        куда.parent.mkdir(parents=True, exist_ok=True)
        итог.save(куда, quality=92)
    finally:
        shutil.rmtree(работа, ignore_errors=True)
    return куда


# ─────────────────────────────────────────────────────────────────────
# Один кадр — для экрана
# ─────────────────────────────────────────────────────────────────────

def кадр(project: Path, meta: dict, cut: dict, ряды: list[dict],
         раскл: dict, prof: dict, шрифт, при: float | None = None,
         зоны: bool = False, без_субтитра: bool = False):
    """Кадр ролика с субтитром на нужной секунде. Готовая картинка.

    **Это ТА ЖЕ функция, которой рисуется лист «до и после».** Экран
    показывает её и ничего не набирает своими шрифтами — и в этом всё
    дело. Наберись субтитр браузером, в проекте появилась бы вторая
    правда о том, как выглядит кадр: на экране красиво, в файле иначе,
    и ни один из четырёх заслонов этого не поймает — они сверяют файл
    с монтажом, а не с экраном.

    `при` — секунда РОЛИКА, не исходника. Не сказана — берётся первое
    состояние субтитра: на нём видно и кадр, и текст.

    **Под плашкой в конце подложкой становится сама плашка.** Это
    не украшение экрана, а то же правило: предпросмотр показывает то,
    что попадёт в файл, а в файле там плашка. Показывать вместо неё
    кадр видео значило бы завести вторую правду о том, как кончается
    ролик, — и ни один заслон её бы не поймал.
    """
    from . import plans, plate

    точки = секунды_показов(раскл, сколько=1)
    if при is None:
        if not точки:
            raise VertcutError(
                "Nothing to show: this clip has no subtitles")
        при = точки[0]["при"]
    # `без_субтитра` — для редактора: там субтитр приезжает отдельным
    # прозрачным слоем, и его тащат мышью поверх этой подложки.
    показ = None if без_субтитра else _показ_на(раскл, при)

    это_хвост = plate.сырые(project, cut["id"])
    плашка_с = plate.начало(
        plans.total_of(cut, float(meta["duration"])), это_хвост)
    if при >= плашка_с - 1e-6:
        return _на_плашке(project, cut, prof, шрифт, показ, зоны)

    ряд = ряд_на(ряды, при)

    работа = Path(tempfile.mkdtemp(prefix="vertcut-frame-"))
    try:
        кадры = media.grab_frames(
            _исходник(meta), [в_видео(ряд, при)], работа, int(meta["width"]))
        if not кадры:
            raise VertcutError("ffmpeg didn't give a frame at this second")
        if показ is None:
            # Секунда, на которой субтитра нет вовсе, — законный случай:
            # между фразами он и не должен стоять. Показывается голый
            # кадр, а не пустая картинка.
            from PIL import Image
            with Image.open(кадры[0]) as сырое:
                вышло = кадр_ролика(сырое.convert("RGB"), ряд,
                                    int(meta["width"]), int(meta["height"]))
            if зоны:
                вышло = Image.alpha_composite(
                    вышло.convert("RGBA"), нарисовать_зоны(prof)).convert("RGB")
            return вышло
        return собрать_состояние(кадры[0], ряд, meta, показ, prof, шрифт, зоны)
    finally:
        shutil.rmtree(работа, ignore_errors=True)


def _на_плашке(project: Path, cut: dict, prof: dict, шрифт,
               показ: dict | None, зоны: bool):
    """Кадр под плашкой: сама плашка, а поверх неё субтитр.

    **Плашка собирается КАЖДЫЙ РАЗ, а не когда файла нет.** Это урок
    предка: она зависит от обложки и от надписи, а их правят прямо
    на этом экране — и проверка «не устарела ли» была бы вторым
    местом, где это знают. Стоит она доли секунды.
    """
    from PIL import Image

    from . import plate

    сделано = plate.собрать_у(project, cut, prof)
    основа = Image.open(сделано["файл"]).convert("RGBA")
    if показ is not None:
        основа = Image.alpha_composite(
            основа, subs.нарисовать(показ["страница"], показ["сказано"],
                                    показ["низ"], prof, шрифт))
    if зоны:
        основа = Image.alpha_composite(основа, нарисовать_зоны(prof))
    return основа.convert("RGB")


def _показ_на(раскл: dict, при: float) -> dict | None:
    """Какое состояние субтитра стоит на этой секунде ролика."""
    for показ in раскл["показы"]:
        if показ["at"] - 1e-6 <= при < показ["till"] + 1e-6:
            return показ
    return None


def _исходник(meta: dict) -> Path:
    from . import render
    return render.проверить_исходник(meta)


def в_байты(картинка, качество: int = 88) -> bytes:
    """Картинку — в байты, без временного файла на диске.

    Экран просит кадры десятками: на каждый чих класть файл в папку
    разбора значит через неделю оставить там мусор, который никто
    не уберёт.
    """
    import io

    поток = io.BytesIO()
    картинка.save(поток, format="JPEG", quality=качество)
    return поток.getvalue()


# Ширина обложки для списков. Не подобранное число, а размер картинки:
# строка очереди показывает кадр 28×50, карточка — побольше, и 270
# покрывает и то и другое с запасом даже на плотном экране.
ОБЛОЖКА_Ш = 270


def обложка_ролика(project: Path, meta: dict, ident: str,
                   говорить=None) -> Path:
    """Кадр 9:16 с субтитром для списков. Считается один раз и лежит.

    У ролика без субтитров — без субтитра: обложка показывает то, что
    будет в файле.

    **Считать её на каждый показ нельзя.** Один такой кадр — это выемка
    кадра из исходника плюс рисование субтитра, почти секунда; в списке
    сборки их бывает двадцать. Двадцать секунд ожидания на экран,
    который просто показывает очередь, — это не экран.

    **Устаревает она сама, и правило у неё то же, что у штампа
    сборки**: обложка старше `cut.json` или профиля субтитров —
    значит показывает не тот монтаж или не тот стиль. Считать заново
    дешевле, чем врать картинкой.
    """
    from . import layout, render, subs

    готовая = layout.cut_preview(project, ident)
    # Свой стиль вертикалки — тоже: без него обложка ролика, которому
    # поправили стиль, оставалась бы старой.
    зависит = [layout.cut_json(project, ident),
               layout.project_subs(project),
               layout.cut_subs(project, ident)]
    свежая = (готовая.exists()
              and all(not з.exists()
                      or з.stat().st_mtime <= готовая.stat().st_mtime
                      for з in зависит))
    if свежая:
        return готовая

    всё = render.открыть_ролик(project, meta, ident,
                               говорить=говорить or (lambda *_: None))
    картинка = кадр(project, meta, всё["cut"], всё["ряды"], всё["раскл"],
                    всё["prof"], всё["шрифт"],
                    без_субтитра=not subs.в_файле(project, всё["cut"]))
    высота = round(ОБЛОЖКА_Ш * картинка.height / картинка.width)
    from PIL import Image
    готовая.parent.mkdir(parents=True, exist_ok=True)
    картинка.resize((ОБЛОЖКА_Ш, высота), Image.LANCZOS).save(
        готовая, quality=86)
    return готовая


def слой_субтитра(раскл: dict, prof: dict, шрифт, при: float | None = None):
    """Только субтитр, прозрачным слоем. Для перетаскивания на экране.

    **Ради этого слоя браузер и не набирает субтитр сам.** Пока человек
    тащит субтитр по кадру, двигать надо что-то видимое — и двигается
    ЭТА картинка, нарисованная сервером тем же шрифтом, каким субтитр
    попадёт в файл. Отпустил — сервер пересчитал положение и прислал
    новый кадр целиком.

    То есть браузер двигает пиксели, а не рисует их. Второй правды
    о том, как выглядит кадр, в проекте не заводится.
    """
    точки = секунды_показов(раскл, сколько=1)
    if при is None:
        if not точки:
            raise VertcutError(
                "Nothing to move: this clip has no subtitles")
        при = точки[0]["при"]
    показ = _показ_на(раскл, при)
    if показ is None:
        from PIL import Image
        return Image.new("RGBA", (prof["width"], prof["height"]), (0, 0, 0, 0))
    return subs.нарисовать(показ["страница"], показ["сказано"],
                           показ["низ"], prof, шрифт)


def в_байты_png(картинка) -> bytes:
    """Прозрачную картинку — байтами. JPEG прозрачности не умеет."""
    import io

    поток = io.BytesIO()
    картинка.save(поток, format="PNG")
    return поток.getvalue()
