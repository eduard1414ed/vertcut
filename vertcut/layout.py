"""Все пути в одном месте.

Правило перенесено вместе с причиной: литералов вроде `project / "cuts"`
в остальном коде нет. Раскладка переживёт не одну правку, а найти через
полгода все места, где имя папки написано руками, невозможно.

    ~/vertcut/Inbox/           ← видео, бро́шенные в окно браузера
    ~/vertcut/{слаг}/          ← папка разбора, одна на видео
      meta.json      источник, длительность, отпечаток файла, штампы стадий
      script.txt     сценарий как есть (если он есть)
      subtitles.yaml профиль субтитров этого видео — копия личного
      audio.wav      дорожка, снятая с видео: моно 16 кГц
      proxy.mp4      уменьшенная копия, 640 пикселей в ширину
      align.json     пословные времена, предложения, фразы
      shots.json     склейки и предложенная рамка на каждый план
      queue.json     очередь сборки — всё её состояние
      analysis-job.json  долгая работа: разбор
      ai-job.json    хозяин обращения к модели
      suggestions.json, suggestions.answer.txt, descriptions.answer.txt
                     ответы модели: разобранный и как приехали
      thumbnail.jpg  обложка выпуска для плашки в конце
      analysis.log, export.log  вывод работы, пущенной с экрана
      frames/        кадр на план, контактные листы, cover.jpg
      cuts/{ключ}/   один вертикальный ролик; ключ — номера слов
        cut.json     границы, монтаж кадра, название, штампы
        cover.jpg    кадр 9:16 для списков; end-card.png — плашка
        {название}.mp4  готовый ролик; имя из cut.json

    ~/.vertcut/
      config.json    настройки; app.json — кто держит экран
      subtitles.yaml личный образец профиля субтитров
      fonts/ backgrounds/  свои шрифты и фоны плашки
      logs/          журнал запусков: launch-{когда}.log
      install/       страница хода установки
      spending.json  дневник расходов; samples.txt — эталонные описания
      models/        веса детектора лиц

    vertcut/assets/            ← обвес: он ЧАСТЬ пакета, а не сосед
      subtitles.yaml профиль субтитров, поставляемый
      looks.yaml      готовые виды
      fonts/         четыре шрифта СУБТИТРОВ, у каждого лицензия рядом
      models/        веса детектора лиц
      web/           страница: разметка, стили, скрипты
        fonts/       шрифты ИНТЕРФЕЙСА, отдельно от шрифтов субтитров

**Все имена на диске — английские, без исключений** (22-я сессия).
Раньше по-русски оставались `работа.json`, «Входящие», журнал и ещё
полтора десятка имён — с доводом «их читает человек в проводнике».
Довод перевернулся, когда экран стал английским: человек, который
видит на экране *Inbox*, ищет на диске `Inbox`. А русская буква
в пути, уезжающем в ffmpeg, архиватор или чужой разборщик, — это
та же порода бед, что записана в `docs/decisions.md` тринадцать раз.

Переезда старых имён внутри программы нет — решение автора; для
своих папок есть разовый `private/tools/rename-disk-names.py`.

**Корень можно перебить переменной окружения `VERTCUT_HOME`.**
Не прихоть: у Нарезатора проверки гонялись на живой папке автора,
и однажды в ней пропала поставленная рукой рамка — виновника найти
не удалось. Проверка обязана уметь работать в песочнице, и способ
для этого нужен один, а не «ну я аккуратно».
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

from .errors import VertcutError


def root() -> Path:
    """Корень всех разборов."""
    подмена = os.environ.get("VERTCUT_HOME")
    return Path(подмена).expanduser() if подмена else Path.home() / "vertcut"


def settings_dir() -> Path:
    """Настройки и веса. Рядом с корнем, но не внутри него: разборы
    человек чистит руками, а настройки при этом терять не должен."""
    подмена = os.environ.get("VERTCUT_HOME")
    if подмена:
        return Path(подмена).expanduser() / ".settings"
    return Path.home() / ".vertcut"


def config_file() -> Path:
    return settings_dir() / "config.json"


def программа() -> Path | None:
    """Папка установленной программы — или ничего, если сервис запущен
    не из неё.

    Узнаётся по метке `version.json`, которую кладёт установка, а ищется
    вверх от того питона, которым сервис работает. Своего пути здесь
    не записано ни одного: у человека программа лежит в одном месте,
    у автора — в другом, а из репозитория её нет вовсе, и это законно.
    """
    свой = Path(sys.executable).resolve()
    for вверх in свой.parents:
        if (вверх / МЕТКА_ПРОГРАММЫ).exists():
            return вверх
    return None


# Метка установленной программы. Пишет её установка
# (`install/installer.py`), ищут ярлыки (`launcher.sh`, `launcher.ps1`)
# и экран помощи. У установки и ярлыков своя копия строки — они
# работают без пакета; что копии совпадают, сторожит проверка.
МЕТКА_ПРОГРАММЫ = "version.json"


def журнал() -> Path:
    """Куда сервис пишет, что с ним было.

    **Рядом с настройками, а не внутри программы, и это не мелочь.**
    Переустанавливают сервис ровно тогда, когда он сломался, — а лог
    и есть единственное свидетельство того, почему. Лежи он внутри
    программы, переустановка стирала бы улику вместе с бедой.

    Заведено вместе с ярлыком: у человека, запускающего сервис двойным
    щелчком, терминала нет вовсе, и после падения ему должно остаться
    что почитать и что переслать.
    """
    return settings_dir() / "logs"


# Журнал одного запуска: `launch-2026-10-08-120000.log`. Пишет его
# ярлык (`launcher.sh`, `launcher.ps1`), читают экран помощи и уборка
# старых. Начало имени — здесь, одно на всех.
ЖУРНАЛ_ЗАПУСКА = "launch-"


def журналы_запуска() -> list[Path]:
    """Журналы запусков по порядку, последний — в конце.

    Имя несёт дату с секундами, поэтому порядок по имени и есть
    порядок по времени."""
    папка = журнал()
    if not папка.exists():
        return []
    return sorted(папка.glob(f"{ЖУРНАЛ_ЗАПУСКА}*.log"), key=lambda п: п.name)


def экран_хозяин() -> Path:
    """Кто сейчас держит экран: номер процесса, порт и пропуск.

    **Тот же механизм, что у разбора и сборки** (`works.py`), и заведён
    он по той же причине: второй сервер на второй порт — это два
    сервиса, спорящих за одни файлы, и человек, который не понимает,
    почему в одной вкладке пусто, а в другой нет.

    Отсюда же берётся ответ на «второй щелчок по иконке»: если хозяин
    жив и отвечает, открывается ЕГО вкладка, а не поднимается второй.
    """
    return settings_dir() / "app.json"


def spend_file() -> Path:
    """Дневник расходов на модель: сколько ушло в какой день.

    **Отдельным файлом от настроек, и это не аккуратность.** Настройки
    человек правит руками и может испортить; дневник пишет только
    сервис, и терять его вместе с чужой опечаткой нельзя — на нём
    держится суточный стоп.
    """
    return settings_dir() / "spending.json"


# Имя файла инструкции — латиницей, а слово внутри сервиса русское
# («фрагменты», «описания», «вычитка»). Перевод один и лежит здесь,
# рядом с остальными путями: русское имя файла не переживает чужого
# распаковщика, а инструкция уезжает в раздаче.
ИМЯ_ИНСТРУКЦИИ = {"фрагменты": "prompt-suggest", "описания": "prompt-notes",
                  "вычитка": "prompt-proofread"}


def prompt(какая: str) -> Path:
    """Инструкция для модели, поправленная человеком.

    Уровня два, а не три: поставляемая в репозитории и своя здесь.
    Копии в видео нет нарочно — инструкция не попадает в готовый файл
    ни одним пикселем, и заводить её на каждое видео значило бы
    двадцать копий одного текста, расходящихся молча.
    """
    return settings_dir() / f"{ИМЯ_ИНСТРУКЦИИ[какая]}.txt"


def samples() -> Path:
    """Эталонные подписи: десять настоящих описаний человека.

    По ним модель пишет его голосом, а не с нуля. Их может не быть
    вовсе — у чужого человека эталона нет, и это законный случай,
    а не недостача.
    """
    return settings_dir() / "samples.txt"


def models() -> Path:
    """Веса детектора лиц. Качаются один раз при первом запуске."""
    return settings_dir() / "models"


def assets() -> Path:
    """Обвес: шрифты, профили, веса детектора, страница экрана.

    **Рядом с кодом, а не в домашней папке:** профиль субтитров —
    часть поставки, он обязан работать сразу после установки, а не
    после настройки.

    **И ВНУТРИ пакета, а не папкой выше.** Это замер шестой сессии,
    и он стоил бы дорого. Пока обвес лежал рядом с кодом, а не внутри
    него, собранная поставка состояла из одного кода: 51 файл, и ни
    единого шрифта, профиля, веса или страницы. У автора это
    не всплывало никогда — у него сервис поставлен «на месте», прямо
    из папки, где обвес лежит рядом. Чужой человек так его не ставит,
    и получил бы программу, которая не рисует субтитров и не открывает
    экрана.

    Путь считается ОДНОЙ строкой отсюда — той же самой, по которой все
    остальные пути собирает этот файл. Именно поэтому переезд стоил
    одной строки: литералов `"assets"` в остальном коде нет.
    """
    return Path(__file__).resolve().parent / "assets"


def web() -> Path:
    """Страница: разметка, стили, скрипты и шрифты интерфейса.

    Рядом с остальным обвесом и внутри репозитория — по той же
    причине, по которой там лежит поставляемый профиль субтитров:
    страница обязана работать сразу после скачивания, а не после
    настройки. Здесь же лежат `tokens.css` и `components.css`,
    взятые из пакета передачи дизайна как есть.
    """
    return assets() / "web"


def web_fonts() -> Path:
    """Шрифты ИНТЕРФЕЙСА, а не субтитров.

    Отдельно от `fonts()` нарочно. Тот набор — это выбор человека для
    его ролика; положи в него моноширинный шрифт экрана, и он появится
    в списке `vertcut fonts`, где не нужен никому. Разделение стоит
    одной папки и снимает вопрос навсегда.
    """
    return web() / "fonts"


def inbox() -> Path:
    """«Входящие» — куда ложатся видео, бро́шенные в окно браузера.

    **Заведена потому, что браузер не отдаёт путь к файлу, а только
    содержимое.** Спека говорит об этом прямо: настоящая загрузка
    двухчасового подкаста пошла бы через сеть на саму себя. Значит
    у экрана два входа, и они стоят разного: системный диалог сервис
    открывает сам и берёт файл на месте, а бро́шенный в окно ложится
    сюда копией — то есть занимает на диске второй раз.

    Внутри корня, а не рядом: человек чистит разборы руками, и видео,
    которое он сам сюда положил, должно чиститься вместе с ними,
    а не пережидать уборку в незнакомом месте.
    """
    return root() / "Inbox"


def subs_yaml() -> Path:
    """ПОСТАВЛЯЕМЫЙ образец профиля субтитров. Уровень первый.

    Лежит в репозитории и НЕ ПРАВИТСЯ: обновление сервиса приезжает
    вместе с ним, и правка отсюда пропала бы молча. Всё, что человек
    меняет, ложится в два других уровня.
    """
    return assets() / "subtitles.yaml"


def looks() -> Path:
    """Готовые виды субтитров: несколько чисел поверх профиля.

    В поставке и не правятся — как и сам образец профиля. Свой вид
    человек делает иначе: правит стиль видео и говорит «сделать этот
    стиль моим».
    """
    return assets() / "looks.yaml"


def shipped_prompt(какая: str) -> Path:
    """ПОСТАВЛЯЕМАЯ инструкция для модели. Уровень первый.

    Лежит в репозитории рядом с профилем субтитров и по той же
    причине: она часть поставки и должна работать сразу после
    скачивания, а не после настройки. Не правится — правка отсюда
    пропала бы при обновлении сервиса молча.
    """
    return assets() / f"{ИМЯ_ИНСТРУКЦИИ[какая]}.txt"


def my_subs() -> Path:
    """ЛИЧНЫЙ образец профиля субтитров. Уровень второй.

    Снаружи репозитория, рядом с настройками — по той же причине, по
    которой снаружи лежит ключ к модели: папка репозитория стирается
    и перекачивается, а «мой стиль» человек настраивал однажды и
    терять его при обновлении не должен.
    """
    return settings_dir() / "subtitles.yaml"


def project_subs(p: Path) -> Path:
    """КОПИЯ профиля в папке видео. Уровень третий.

    Пачка из одного видео выходит единообразной: разные шрифты внутри
    одной пачки читаются не как почерк, а как неаккуратность.

    **Копия, а не ссылка на личный образец,** и это главное здесь.
    Отпечаток профиля входит в штамп сборки: правка профиля устаревает
    собранные ролики. Если бы видео читало личный образец напрямую,
    правка «моего стиля» устаревала бы ролики ЧУЖИХ видео — тех,
    к которым она не имеет никакого отношения.
    """
    return p / "subtitles.yaml"


def fonts() -> Path:
    """Поставляемые шрифты. Рядом с ними лежат их лицензии."""
    return assets() / "fonts"


def my_fonts() -> Path:
    """Свои шрифты человека. Снаружи репозитория — по той же причине,
    по которой снаружи лежит личный профиль: обновление сервиса
    не должно их сносить."""
    return settings_dir() / "fonts"


def фоны() -> Path:
    """Фоны плашки в конце ролика. Только свои — поставляемых нет.

    **Рядом со своими шрифтами и по той же причине.** Фон — картинка
    канала: чужая, авторская, в репозиторий её не положить. Человек
    приносит её файлом, сервис копирует к себе, а в профиле стоит имя
    — ровно как со шрифтом.

    Отдельной папкой от шрифтов, а не вместе: положи фон в `fonts/`,
    и он появится в списке `vertcut fonts`, где не нужен никому.
    """
    return settings_dir() / "backgrounds"


# Функции «какой шрифт взят» здесь НЕТ, и это решение.
#
# Имя файла шрифта лежит в одном месте — в самом профиле субтитров
# (ключ «шрифт»), потому что человек его меняет. Заведи это имя вторым
# числом здесь — и однажды профиль будет говорить одно, а код брать
# другое, причём молча. Здесь только ПАПКИ, в которых он ищется.


def project(slug: str) -> Path:
    """Папка разбора по имени. Имя — ОДНА часть пути и ничего больше.

    **Проверяется здесь, а не у каждого, кто спрашивает.** Слаг
    приезжает снаружи: из команды, из адреса страницы. `../../etc`
    в нём выводит за корень — и `layout.project` честно отдаёт `/etc`,
    потому что складывать пути её и просили. Поймано на экране: ручка
    обложки отвечала отказом только потому, что в `/etc` не нашлось
    кадра, — то есть по счастливой случайности, а не по правилу.

    Место у проверки одно, и оно тут: второе такое же однажды
    разойдётся с первым, а мимо `layout` слаг в путь не превращается
    нигде.
    """
    имя = str(slug or "").strip()
    if not имя or имя in (".", ".."):
        raise VertcutError("No video given to open",
                           hint="to see your videos, run: vertcut videos")
    if имя != Path(имя).name or "/" in имя or "\\" in имя:
        raise VertcutError(
            f"“{имя}” is a path, not a video id",
            hint="a video id is one word with no slashes; "
                 "to see your videos, run: vertcut videos")
    return root() / имя


