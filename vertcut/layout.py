def cut_subs(p: Path, ident: str) -> Path:
    """Профиль субтитров ОДНОЙ вертикалки. Уровень четвёртый.

    **Заводится не всегда, и в этом весь смысл.** Пока файла нет,
    вертикалка читает профиль видео — и пачка из одного видео выходит
    единообразной, как и записано в спеке. Файл появляется ровно
    тогда, когда человек поправил стиль ЭТОЙ вертикалки: значит
    он захотел ей своего, и дальше она живёт своей жизнью.

    Кнопка «применить ко всем» делает обратное: кладёт этот стиль
    профилем видео и убирает все четвёртые уровни — то есть возвращает
    пачку к единообразию, но уже по новому образцу.
    """
    return cut(p, ident) / "subtitles.yaml"


def обложка_выпуска(p: Path) -> Path:
    """Обложка выпуска для плашки в конце. ОДНА на видео.

    **У видео, а не у ролика:** обложка одна на выпуск и наследуется
    всеми вертикалками из него. Класть её каждой отдельно значило бы
    двадцать копий одной картинки, расходящихся молча.

    **Не путать с `cover`** — та лежит в `frames/` и это кадр, которым
    видео показано в списке на экране; её вынимает разбор. Эту приносит
    человек, и разбор про неё не знает вовсе.

    Ставится ОТДЕЛЬНО и разбора не пересчитывает. Это урок предка:
    у него обложка по спеке ставилась стадией разбора, а разбор стоит
    двадцать две минуты — менять картинку такой ценой невозможно.
    """
    return p / "thumbnail.jpg"


