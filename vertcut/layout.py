def transcript(p: Path) -> Path:
    """Текст, услышанный распознаванием, — для тех, у кого сценария нет.

    **Отдельный файл, а не запись в `script.txt`.** Сценарий — то, что
    принёс человек; расшифровка — то, что расслышала машина. Сложи их
    в один файл, и через месяц уже не сказать, чей это текст: сервис
    решит, что сценарий есть, а точность у него будет как у машины.
    """
    return p / "transcript.txt"


