"""Сборка одного ролика: команда ffmpeg, заслоны, штамп.

**Одна цепочка, одно кодирование.** Склейки двух проходов нет: каждое
кодирование добавляет артефакты, а ролик и без того пересжимается
площадкой.

**Звук берётся из ИСХОДНИКА, а не из снятой дорожки.** Та сделана моно
16 кГц под распознавание, и слушать её нельзя.

**Отпечаток исходника сверяется на входе** — один раз на команду,
а не на каждый ролик: на трёхгигабайтном файле это десять секунд,
и платить их шесть раз подряд незачем.

**Штамп «готово» пишется ТОЛЬКО ПОСЛЕ сверки.** Написать раньше
значит: сверка упала, а на диске отметка «готово», и следующий запуск
переступает битый файл молча.
"""

