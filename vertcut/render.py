# Причины «почему устарел» названы здесь именами, а не строками в двух
# местах. «Стиль поменялся» печатает и команда стиля, чтобы сказать,
# сколько роликов придётся пересобрать; «ещё не собран» сборка
# отличает от остальных. Разъедутся две строки — команда замолчит,
# и притом молча. Проверки сверяются с именем, а не с текстом.
НЕ_СОБРАН = "not exported yet"
ФАЙЛА_НЕТ = "the exported file is missing"
ГРАНИЦЫ_УЕХАЛИ = "segment boundaries changed"
ПЛАШКА_ВКЛЮЧЕНА = "end card turned on"
ПЛАШКА_ВЫКЛЮЧЕНА = "end card turned off"
ПЛАШКА_ПОМЕНЯЛАСЬ = "end card changed"
СУБТИТРЫ_ВЫКЛЮЧЕНЫ = "subtitles turned off"
СУБТИТРЫ_ВКЛЮЧЕНЫ = "subtitles turned on"
РАМКА_РУКОЙ = "crop changed by hand"
ПЛАНЫ_ПЕРЕСЧИТАНЫ = "shots were detected again"
ПЛАНЫ_И_РАМКИ = ("shots were detected again — crops you set by hand "
                 "may now sit on other shots")
ПРОФИЛЬ_ПОМЕНЯЛСЯ = "subtitle style changed"
ТЕКСТ_НЕИЗВЕСТЕН = "exported before Vertcut kept track of subtitle text"
ТЕКСТ_ПОМЕНЯЛСЯ = "subtitle text or phrases changed"
СВЕРКА_НЕ_СОШЛАСЬ = "failed a check last time"


def исходник(meta: dict) -> Path:
    путь = Path(meta["source"])
    if not путь.exists():
        raise VertcutError(
            f"The source video isn't where it was: {путь}",
            hint="if you moved it, add it again from the new place "
                 "and analyze it")
    return путь


def проверить_исходник(meta: dict) -> Path:
    """Тот ли файл лежит. Подменили под тем же именем — падаем.

    Иначе ролик соберётся по старым временам из нового материала:
    файл откроется, длина сойдётся, а внутри чужие секунды.
    """
    путь = исходник(meta)
    отпечаток = media.fingerprint(путь)
    if отпечаток != meta.get("fingerprint"):
        raise VertcutError(
            f"The file has changed since it was analyzed: {путь.name}",
            hint="analyze again: vertcut ingest … --again")
    return путь


def почему_устарел(project: Path, cut: dict) -> str | None:
    """ПОЧЕМУ надо пересобрать. None — не надо, всё на месте.

    Причина называется словами, а не «да/нет». «Пересобираю семь»
    без объяснения читается как «сервис делает работу зря»; причина
    превращает это в «поправили рамку — вот эти семь».
    """
    штамп = cut.get("render")
    if not штамп:
        return НЕ_СОБРАН
    файл = layout.out(project, cut)
    if not файл.exists():
        return ФАЙЛА_НЕТ
    if штамп.get("куски") != pick.ranges(cut):
        return ГРАНИЦЫ_УЕХАЛИ
    # Плашка в конце. Спрашивается ПЕРВОЙ из всего, что
    # ниже, и это не порядок ради порядка. От плашки зависит всё
    # остальное: планы под ней гасятся, и монтаж кадра честно
    # становится другим, а профиль ловит её числа своим отпечатком.
    # Спроси её позже — и человек, включивший плашку, прочтёт
    # «планы видео пересчитаны» или «профиль субтитров поменялся».
    # Причина, названная не своим именем, читается как «сервис делает
    # работу зря».
    #
    # **Штамп без плашки значит «плашки не было», а не «неизвестно».**
    # Ролики, собранные до того, как она завелась, устаревать
    # не должны: включение возможности не имеет права трогать тех,
    # кто ею не пользуется.
    сейчас = plate.штамп_сейчас(project, cut, plate.сырые(project, cut["id"]))
    было_хвоста = штамп.get("хвост") or {"показывать": False}
    if было_хвоста != сейчас:
        if не_было(было_хвоста) and сейчас["показывать"]:
            return ПЛАШКА_ВКЛЮЧЕНА
        if было_хвоста.get("показывать") and not сейчас["показывать"]:
            return ПЛАШКА_ВЫКЛЮЧЕНА
        return ПЛАШКА_ПОМЕНЯЛАСЬ
    # Субтитры в файле. Штамп без ключа — «были»: так собирались все
    # ролики до того, как их стало можно выключить, и устаревать им
    # не за что.
    с_субтитрами = subs.в_файле(project, cut)
    if штамп.get("субтитры", True) != с_субтитрами:
        return СУБТИТРЫ_ВКЛЮЧЕНЫ if с_субтитрами else СУБТИТРЫ_ВЫКЛЮЧЕНЫ
    if штамп.get("montage", {}).get("hand") != plans.hand_of(cut):
        return РАМКА_РУКОЙ
    # Планы видео пересчитаны — например, поменяли порог склеек.
    #
    # ЭТО НЕ ПРИДУМАННЫЙ СЛУЧАЙ: во второй сессии порог менялся,
    # и планов на том же видео стало 425 вместо 382. Номера планов
    # при этом переехали ВСЕ, а рамки, поставленные рукой, привязаны
    # именно к номерам. Молчать тут нельзя вдвойне: и файл собран
    # по старым планам, и правки рукой теперь показывают на другие.
    было = штамп.get("montage", {}).get("digest")
    if было is not None:
        from . import shots as планы
        стало = plans.digest(plans.montage(project, _журнал(project), cut,
                                           планы.read(project)))
        if было != стало:
            if plans.frames_of(cut):
                return ПЛАНЫ_И_РАМКИ
            return ПЛАНЫ_ПЕРЕСЧИТАНЫ
    # Отпечаток — тоже по стилю ЭТОЙ вертикалки: иначе «применить
    # ко всем» не устарело бы ни одного ролика, чей стиль оно поменяло.
    профиль = subs.отпечаток(project=project, ident=cut["id"])
    # Без субтитров стиль в файле не виден — кроме плашки: полоса под
    # субтитр на ней считается по стилю и без самих субтитров.
    if штамп.get("subs", {}).get("профиль") != профиль and (
            с_субтитрами or сейчас["показывать"]):
        return ПРОФИЛЬ_ПОМЕНЯЛСЯ
    if not с_субтитрами:
        # Текста в файле нет — его правки файлу ничем не грозят.
        if not штамп.get("сверка", {}).get("сошлось", True):
            return СВЕРКА_НЕ_СОШЛАСЬ
        return None
    было = штамп.get("subs", {}).get("фразы")
    if было is None:
        # Штамп старше самого отпечатка фраз: из какого текста собран
        # лежащий рядом файл, неизвестно.
        #
        # **Неизвестность значит «устарел», а не «свеж».** Поймано
        # на живом ролике: он собран до того, как правила нарезки фраз
        # поменялись, субтитры в нём от старой нарезки — а сервис
        # объявлял его готовым и молчал.
        return ТЕКСТ_НЕИЗВЕСТЕН
    from . import speech
    if было != subs.отпечаток_фраз(speech.read(project),
                                   pick.ranges(cut), edits.список(cut)):
        return ТЕКСТ_ПОМЕНЯЛСЯ
    if not штамп.get("сверка", {}).get("сошлось", True):
        return СВЕРКА_НЕ_СОШЛАСЬ
    return None


def не_было(штамп_хвоста: dict) -> bool:
    """Плашки у лежащего рядом файла не было вовсе."""
    return not штамп_хвоста.get("показывать")


def _журнал(project: Path) -> dict:
    """`meta.json` разбора. Читается голым json: сверка «устарел ли»
    зовётся по ролику в цикле, и тянуть сюда стадии разбора незачем."""
    import json

    файл = layout.meta(project)
    return json.loads(файл.read_text(encoding="utf-8")) if файл.exists() else {}


def открыть_ролик(project: Path, meta: dict, ident, *,
                  ряды: list[dict] | None = None,
                  prof: dict | None = None,
                  laid: dict | None = None,
                  ширина: int = tuning.VERTICAL_W,
                  высота: int = tuning.VERTICAL_H,
                  говорить=None) -> dict:
    """Всё про один ролик, собранное вместе: монтаж, стиль, субтитры.

    **Одно место на всех, кто это спрашивает.** Спрашивают четверо:
    сборка, предпросмотр, команда `subs` и экран. Каждый из них
    складывал это сам — пять вызовов в одном и том же порядке, — и
    разойтись им было проще простого: достаточно взять профиль
    не того размера или собрать раскладку до того, как досчитаны рамки.
    А расхождение здесь означает, что на экране одно, а в файле другое.

    `ident` — ключ ролика или уже прочитанный `cut.json`.

    `prof` подсовывается снаружи ровно в одном случае: лист «до и
    после» рисует один и тот же ролик ДВУМЯ профилями, и второго
    на диске нет — он ещё только обдумывается человеком. Всё остальное
    при этом считается тем же порядком.
    """
    from . import shots as планы, speech

    cut = ident if isinstance(ident, dict) else pick.load(project, ident)
    if ряды is None:
        ряды = plans.montage(project, meta, cut, планы.read(project),
                             говорить)
    if prof is None:
        # Профиль берётся У ЭТОЙ ВЕРТИКАЛКИ, а не только у видео.
        # Своего у неё может и не быть — тогда читается профиль видео,
        # и пачка выходит единообразной. Но если человек поправил стиль
        # именно ей, собраться она обязана по своему.
        prof = subs.profile(project, ширина, высота, ident=cut["id"])
    шрифт = subs.font_of(prof)
    if laid is None:
        laid = speech.read(project)
    раскл = subs.раскладка_ролика(project, meta, laid, cut, ряды, prof, шрифт)
    return {"cut": cut, "ряды": ряды, "prof": prof, "шрифт": шрифт,
            "laid": laid, "раскл": раскл}


def one(project: Path, meta: dict, cut: dict, source: Path,
        rows: list[dict], говорить=report.скажи, ход=None) -> dict:
    """Собрать один ролик. Возвращает то, что ляжет в `cut.json`.

    `ход` — кому рассказывать, что делается прямо сейчас и сколько
    из этого уже сделано. Зовут его отсюда, а не снаружи: снаружи
    видно только «собирается», а сборка — это пять разных работ, и
    самая долгая из них идёт двенадцать секунд молча.
    """
    ход = ход or (lambda *_а, **_к: None)
    duration = float(meta["duration"])
    fps = float(meta.get("fps") or 25)
    таблица = plans.карта(cut, duration, fps)
    куски = таблица["куски"]
    всего = таблица["всего"]

    голые = plans.needed(rows)
    if голые:
        raise VertcutError(
            f"No crop yet for shots {', '.join(map(str, голые))}, so "
            "there's nothing to export.",
            hint=f"work them out: vertcut crop {meta['slug']}")

    куда = layout.out(project, cut)
    куда.parent.mkdir(parents=True, exist_ok=True)

    # Слой субтитров. Своя временная папка на каждую сборку: два счёта
    # разом — обычное дело, а общая стирается из-под соседа.
    работа = Path(tempfile.mkdtemp(prefix="vertcut-layer-"))
    ход("Laying out subtitles")
    всё = открыть_ролик(project, meta, cut, ряды=rows, говорить=говорить)
    prof, шрифт, раскл, laid = (всё["prof"], всё["шрифт"], всё["раскл"],
                                всё["laid"])
    # Без субтитров раскладка всё равно считается: от неё зависят начало
    # плашки и штамп. Не собирается только слой — и в цепочку не идёт.
    с_субтитрами = subs.в_файле(project, cut)
    if not с_субтитрами:
        говорить("  subtitles are off: exporting without them")
    elif раскл["частями"]:
        говорить(f"  {раскл['частями']}")
    for жалоба in раскл["жалобы"] if с_субтитрами else []:
        говорить(f"  ! {жалоба}")
    for строка in раскл["подрезано"] if с_субтитрами else []:
        говорить(f"  {строка}")

    # ЗНАКИ, КОТОРЫХ ШРИФТ НЕ ЗНАЕТ, — это отказ, а не предупреждение.
    #
    # Здесь единственное место, где отказ ещё дёшев: файла нет, ffmpeg
    # не звали. Собери сервис ролик — и все четыре заслона его
    # пропустят: субтитр ЕСТЬ и стоит на месте, квадратик тоже краска.
    # Узнал бы человек о беде из комментариев под опубликованным
    # роликом.
    if с_субтитрами and раскл.get("нет_знаков"):
        raise VertcutError(
            "The subtitle font is missing some characters this clip "
            f"uses.\n  {subs.перечислить_знаки(раскл['нет_знаков'], prof)}\n"
            "  They would come out as empty boxes, and the checks "
            "wouldn't catch it.",
            hint="choose another font or change the text in the subtitle "
                 f"editor (terminal: vertcut style {meta['slug']} "
                 "--font Literata.ttf)")

    слой = (layer.собрать(раскл, prof, шрифт, fps, работа, ход)
            if с_субтитрами else None)

    # Плашка в конце. Собирается КАРТИНКОЙ до кодирования и остаётся
    # лежать рядом: по ней видно, что уехало, ещё до сборки.
    ход("Making the end card")
    это_хвост = plate.сырые(project, cut["id"])
    плашка = None
    плашка_с = plate.начало(всего, это_хвост)
    if plate.включена(это_хвост):
        плашка = plate.собрать_у(project, cut, prof)
        for жалоба in плашка["жалобы"]:
            говорить(f"  ! end card: {жалоба}")
        говорить(f"  end card from {плашка_с:.1f} s to the end "
                 f"({plate.секунды(это_хвост):.1f} s), text size "
                 f"{плашка['надпись']['кегль']}")

    кадров = [к["видео"]["кадров"] for к in куски]
    вход_плашки = len(куски) if плашка is not None else None
    # Нет слоя — нет и входа: цепочка тогда та же, что была бы
    # у сборки без субтитров вовсе (`chain.video` умеет это с начала).
    вход_субтитров = (len(куски) + (1 if плашка is not None else 0)
                      if слой is not None else None)
    цепь = chain.video(rows, int(meta["width"]), int(meta["height"]),
                       вход_субтитров, fps,
                       кадров if len(куски) > 1 else None,
                       вход_плашки, плашка_с)
    звук_звенья, звук_метка = chain.audio(таблица)
    цепь = ";".join([цепь, *звук_звенья])

    # ВНИМАНИЕ на порядок слов. `-t` — настройка того, что стоит ПОСЛЕ
    # него: перед входом это «читать столько», перед выходом — «писать
    # столько». У предка перестановка одного слова превратила `-t`
    # из настройки длины ролика в настройку картинки, и файлы вышли
    # по девятнадцать минут вместо восемнадцати секунд.
    команда = [FFMPEG, "-v", "error", "-y"]
    for n, кусок in enumerate(куски):
        команда += ["-ss", f"{кусок['звук']['essay0']:.3f}"]
        if len(куски) > 1:
            # Читать ровно столько, сколько нужно этому куску: без
            # предела каждый вход разбирал бы видео до самого конца.
            надо = round(max(кусок["звук"]["длина"], кадров[n] / fps) + 0.5, 3)
            команда += ["-t", f"{надо:.3f}"]
        команда += ["-i", str(source)]
    # Плашка — картинкой, без `-ss` и `-t`. Она неподвижна, и `-t`
    # у неё стоял бы ровно тем словом, которым предок получил файлы
    # по девятнадцать минут вместо восемнадцати секунд: `-t` перед
    # ВХОДОМ значит «читать столько», и добавленный вход перетягивает
    # его на себя. Здесь `-t` стоит у выхода, ниже, и только там.
    if плашка is not None:
        команда += ["-i", str(плашка["файл"])]
    # Слой субтитров — последним входом, без `-ss` и `-t`: он собран
    # ровно под этот ролик и начинается с его нуля.
    if слой is not None:
        команда += ["-i", str(слой)]
    команда += [
        "-filter_complex", цепь,
        "-map", "[video]", "-map", f"[{звук_метка}]",
        "-t", f"{всего:.3f}",
        "-c:v", "libx264", "-crf", str(tuning.RENDER_CRF),
        "-preset", tuning.RENDER_PRESET, "-pix_fmt", "yuv420p",
        "-c:a", "aac", "-b:a", tuning.AUDIO_BITRATE,
        "-ar", str(tuning.AUDIO_RATE),
        "-movflags", "+faststart", str(куда),
    ]

    начало = time.time()
    try:
        run_с_ходом(команда, всего,
                    lambda с, в: ход("Encoding", с, в, "s"))
    finally:
        shutil.rmtree(работа, ignore_errors=True)
    потрачено = time.time() - начало

    if not куда.exists() or not куда.stat().st_size:
        raise VertcutError(f"ffmpeg didn't produce a file: {куда}")
    вышло = media.probe(куда)

    # ЗАСЛОН ПЕРВЫЙ: длина.
    #
    # Ролик не той длины — это не «чуть-чуть не так»: он открывается
    # и выглядит целым, а внутри чужие минуты.
    допуск = max(tuning.LENGTH_TOLERANCE_FRAMES / fps, 0.1)
    if abs(вышло["duration"] - всего) > допуск:
        raise VertcutError(
            f"Failed the Length check: the clip should be {всего:.2f} s, "
            f"but came out {вышло['duration']:.2f} s.\n  File: {куда}",
            hint="this isn't a setting — ffmpeg went wrong. Export again; "
                 "if it repeats, see Not working?")

    return {
        "at": datetime.now().astimezone().isoformat(timespec="seconds"),
        "took": round(потрачено, 1),
        "words": cut["words"],
        # Куски видео, из которых собран лежащий рядом файл. Отдельно
        # от `words`: у разрывного ролика верхние `words` говорят про
        # весь размах, а внутри него дыры.
        "куски": pick.ranges(cut),
        "стыков": len(куски) - 1,
        "file": str(куда),
        "asked": всего,
        "duration": вышло["duration"],
        "frame": f"{вышло['width']}×{вышло['height']}",
        "montage": {
            "digest": plans.digest(rows),
            # КОПИЯ, а не сам блок правок: положенный ссылкой штамп
            # менялся бы вместе с правками, и «из чего собран лежащий
            # рядом файл» переставало бы значить что-либо.
            "hand": deepcopy(plans.hand_of(cut)),
            "plans": [{"idx": r["idx"], "at": r["at"], "till": r["till"],
                       "cx": r["cx"], "mode": r["mode"],
                       "hand": bool(r.get("hand")),
                       "x": chain.окно_для(int(meta["width"]),
                                           int(meta["height"]),
                                           0.5 if r["cx"] is None
                                           else r["cx"])["x"]}
                      for r in rows],
        },
        "subs": {"профиль": subs.отпечаток(prof),
                 # Из какого ТЕКСТА собран лежащий рядом файл. Профиль
                 # отвечает за то, как субтитр выглядит; это — за то,
                 # что в нём написано и когда оно стоит.
                 "фразы": subs.отпечаток_фраз(laid, pick.ranges(cut),
                                             edits.список(cut)),
                 "фраз": len(раскл["фразы"]),
                 "состояний": len(раскл["показы"])},
        # Из чего собрана ПЛАШКА лежащего рядом файла. Отдельно
        # от отпечатка профиля, и это не дубль: числа плашки лежат
        # в профиле и в его отпечаток входят сами, а обложка — файл
        # в папке разбора, и надпись может быть своя у вертикалки.
        # Ни того ни другого профиль не видит вовсе, и заменённая
        # обложка доехала бы не до всех роликов — молча.
        "хвост": plate.штамп_сейчас(project, cut, это_хвост),
        # Есть ли в лежащем рядом файле субтитры. Нет ключа — были.
        "субтитры": с_субтитрами,
        "megabytes": round(куда.stat().st_size / 1024 / 1024, 1),
        # Место под отчёт сверки: он ложится сюда ПОСЛЕ проверки.
        "сверка": None,
    }, раскл, prof, шрифт, {"плашка": плашка, "с": плашка_с,
                            "всего": всего}


def собрать_один(project: Path, meta: dict, cut: dict, source: Path,
                 shots: list[dict], говорить=report.скажи, ход=None) -> dict:
    """Собрать ролик и пройти по нему всеми заслонами.

    Порядок здесь — часть смысла: сначала сборка, потом заслоны, и
    только потом штамп. Штамп, поставленный раньше сверки, означает,
    что упавшая сверка оставляет на диске отметку «готово», и следующий
    запуск переступает битый файл молча.
    """
    ход = ход or (lambda *_а, **_к: None)
    ход("Laying out shots")
    ряды = plans.montage(project, meta, cut, shots, говорить)
    говорить(f"  {report.счёт(len(ряды), 'shot', 'shots')} in the clip")
    штамп, раскл, prof, шрифт, хвост = one(project, meta, cut, source,
                                           ряды, говорить, ход)
    говорить(f"  exported in {штамп['took']:.1f} s: {штамп['megabytes']} MB, "
             f"{штамп['duration']:.2f} s long")

    с_субтитрами = штамп["субтитры"]
    говорить("  checking picture and cuts…")
    # Без субтитров кадр сверяется целиком: прятать под маску нечего.
    отчёт = verify.по_планам(project, meta, cut, ряды, source,
                             раскл if с_субтитрами else None, prof, ход)
    говорить(f"    {отчёт['точек']} frames, worst match {отчёт['худшая']}, "
             f"needs {отчёт['порог']}")
    if отчёт["слабая"]:
        говорить(f"    the check has little margin ({отчёт['запас']}): "
                 "on a still, dark shot it would pass almost anything")

    if хвост["плашка"] is not None:
        ход("Checking end card")
        говорить("  checking end card…")
        отчёт_плашки = verify.плашка(
            project, meta, cut, раскл, prof, хвост["плашка"]["файл"],
            хвост["с"], хвост["всего"])
        говорить(f"    {отчёт_плашки['точек']} frames, worst match "
                 f"{отчёт_плашки['худшая']}, needs {отчёт_плашки['порог']}")
        говорить(f"    frame before the end card: "
                 f"{отчёт_плашки['до_плашки']['связь']} — it must still be "
                 "the video, not the card")
        if отчёт_плашки["слабая"]:
            говорить(f"    the check has little margin "
                     f"({отчёт_плашки['запас']}): the end card has little "
                     "to compare")
    else:
        отчёт_плашки = None

    отчёт_субтитров = None
    if с_субтитрами:
        ход("Checking subtitles")
        говорить("  checking subtitles…")
        отчёт_субтитров = verify.субтитры(project, meta, cut, раскл, prof,
                                          шрифт)
        говорить(f"    {отчёт_субтитров['точек']} frames, worst match "
                 f"{отчёт_субтитров['худшая']}, needs "
                 f"{отчёт_субтитров['порог']}")
        if отчёт_субтитров["слабая"]:
            говорить(f"    the check has little margin "
                     f"({отчёт_субтитров['запас']}): the subtitles are "
                     "small, so there's little to compare")
    else:
        говорить("  subtitles: skipped — they are off")

    штамп["сверка"] = {"сошлось": отчёт["сошлось"], "худшая": отчёт["худшая"],
                       "точек": отчёт["точек"], "запас": отчёт["запас"],
                       "порог": отчёт["порог"],
                       # Картинка и стыки — одна сверка, но два вопроса:
                       # «та ли картинка» и «с того ли кадра». Экран
                       # называет их отдельно, и данные для этого здесь.
                       "середины": отчёт["середины"],
                       "края": отчёт["края"]}
    if отчёт_плашки is not None:
        штамп["сверка_плашки"] = {
            "сошлось": отчёт_плашки["сошлось"],
            "худшая": отчёт_плашки["худшая"],
            "порог": отчёт_плашки["порог"],
            "запас": отчёт_плашки["запас"],
            "рано": отчёт_плашки["рано"],
            "точек": отчёт_плашки["точек"]}
    if отчёт_субтитров is not None:
        штамп["сверка_субтитров"] = {
            "сошлось": отчёт_субтитров["сошлось"],
            "худшая": отчёт_субтитров["худшая"],
            "порог": отчёт_субтитров["порог"],
            "запас": отчёт_субтитров["запас"],
            "точек": отчёт_субтитров["точек"]}

    плашка_не_сошлась = (отчёт_плашки is not None
                         and not отчёт_плашки["сошлось"])
    субтитры_не_сошлись = (отчёт_субтитров is not None
                           and not отчёт_субтитров["сошлось"])
    if not отчёт["сошлось"] or субтитры_не_сошлись or плашка_не_сошлась:
        # Штамп всё равно пишем — но с честным «не сошлось». Тогда
        # следующий запуск увидит причину и пересоберёт, а не переступит.
        cut["render"] = штамп
        pick.update(project, cut)
        беда = VertcutError(
            f"Exported, but failed a check: {verify.что_не_сошлось(штамп)}.\n"
            f"  The file is still there — have a look: "
            f"{layout.out(project, cut)}",
            hint="it doesn't count as exported; the next export will "
                 "make it again")
        # Итоги всех пяти едут вместе с отказом: экран сборки покажет,
        # какая проверка не прошла, а какие прошли рядом.
        беда.проверки = verify.итоги(штамп)
        raise беда

    cut["render"] = штамп
    pick.update(project, cut)
    from . import rename
    rename.развесить(project)
    return штамп


def run_all(project: Path, meta: dict, ident: str | None = None,
            заново: bool = False, только: list[str] | None = None,
            говорить=report.скажи) -> list[dict]:
    """Собрать один ролик или все выбранные и ещё не собранные."""
    from . import shots as планы

    ролики = pick.listing(project)
    if ident:
        ролики = [c for c in ролики if c["id"] == ident]
        if not ролики:
            raise VertcutError(f"No such clip: {ident}",
                               hint=f"see clips: vertcut cuts {meta['slug']}")
    elif только is not None:
        ролики = [c for c in ролики if c["id"] in set(только)]
    if not ролики:
        raise VertcutError("No clips yet",
                           hint=f"make one: vertcut pick {meta['slug']} "
                                "--range 12-16")

    источник = проверить_исходник(meta)
    найдено = планы.read(project)
    вышло = []
    for cut in ролики:
        причина = почему_устарел(project, cut)
        if причина is None and not заново:
            говорить(f"{pick.зовут(cut)} — already exported, skipping")
            continue
        говорить(f"\n{pick.зовут(cut)}  ({cut['id']})")
        if причина and причина != НЕ_СОБРАН:
            говорить(f"  exporting again: {причина}")
        штамп = собрать_один(project, meta, cut, источник, найдено, говорить)
        вышло.append(штамп)
    return вышло
