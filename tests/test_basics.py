def test_кодировка_с_русскими_буквами_не_спасает_от_знаков():
    """cp1251 русской Windows букву «я» умеет, а «×» — нет.

    **Разбор с экрана падал на второй строке хода** — «1920×1080».
    Прежняя проба спрашивала кодировку про русскую букву, cp1251
    отвечала «умею», и вывод оставался в ней. Проверка выше этого
    не видела: в cp1252 русских букв нет, и проба переключала вывод.
    Без починки этот запуск падает с `UnicodeEncodeError`.
    """
    import os
    import subprocess

    среда = dict(os.environ, PYTHONIOENCODING="cp1251")
    среда.pop("PYTHONUTF8", None)
    # Знаки — экранами: аргумент команды тоже проходит через чужую
    # кодировку, а проверяется здесь только вывод.
    код = ("from vertcut import report; report.по_русски(); "
           "report.скажи('1920\\u00d71080 \\u2192 \\u044f')")
    вышло = subprocess.run([sys.executable, "-c", код],
                           capture_output=True, env=среда, cwd=str(КОРЕНЬ))
    assert вышло.returncode == 0, (
        "вывод остался в cp1251: "
        + вышло.stderr.decode("utf-8", "replace")[-400:])
    assert "1920×1080 → я".encode() in вышло.stdout


