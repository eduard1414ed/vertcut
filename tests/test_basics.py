def _кэш_как_у(система: str, корень: Path) -> Path:
    """Папка модели в кэше huggingface — так, как её сложили на маке
    и на сборочной машине Windows (замер 27-й сессии)."""
    import os
    модель = корень / "models--Systran--faster-whisper-small"
    снимок = модель / "snapshots" / "536b"
    (модель / "blobs").mkdir(parents=True)
    снимок.mkdir(parents=True)
    if система == "mac":
        (модель / "blobs" / "3e30").write_bytes(b"m" * 5000)
    else:
        # Windows: blobs/<хэш> модели — сам ссылка на общий склад
        # `hub/blobs/42/…`, лежащий вне папки модели.
        склад = корень / "blobs" / "42"
        склад.mkdir(parents=True)
        (склад / "429f").write_bytes(b"m" * 5000)
        os.symlink(os.path.join("..", "..", "blobs", "42", "429f"),
                   модель / "blobs" / "3e30")
    (модель / "blobs" / "7818").write_bytes(b"t" * 300)
    os.symlink(os.path.join("..", "..", "blobs", "3e30"), снимок / "model.bin")
    os.symlink(os.path.join("..", "..", "blobs", "7818"), снимок / "tokenizer.json")
    return модель


@pytest.mark.parametrize("система", ["mac", "windows"])
def test_вес_модели_считает_файл_за_ссылкой_один_раз(tmp_path, система):
    """На Windows `check` писал «3 MB» вместо 486: настоящий model.bin
    лежал за ссылкой вне папки модели, а ссылки пропускались."""
    from vertcut import deps
    модель = _кэш_как_у(система, tmp_path)
    assert deps.вес_папки(модель) == 5300


