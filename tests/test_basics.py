def test_поставленная_но_негодная_библиотека_не_зовётся_отсутствующей(
        monkeypatch):
    """«Не поставлена» и «поставлена, но не грузится» — разные беды.

    Найдено автором на живом сервисе: экран сказал «НЕТ numpy 2.5.2 —
    ставятся, около 243 МБ» на машине, где numpy стоит и работает.
    Сервис был поднят иконкой, а та подняла питон под Rosetta —
    arm64-ные библиотеки в него не грузились вовсе. Совет «поставьте»
    в этом случае не просто бесполезен: человек полчаса ставит то,
    что у него есть.

    Отличается это по метаданным: версия читается файлом рядом
    с библиотекой, и если версия есть, а импорт упал — она поставлена.
    """
    import importlib

    настоящий = importlib.import_module

    def падать_на_numpy(имя, *д, **к):
        if имя == "numpy":
            raise ImportError(
                "dlopen(...): (mach-o file, but is an incompatible "
                "architecture (have 'arm64', need 'x86_64'))")
        return настоящий(имя, *д, **к)

    monkeypatch.setattr(deps.importlib, "import_module", падать_на_numpy)

    это = next(x for x in deps.libs() if x["пакет"] == "numpy")
    assert это["стоит"] is False
    assert это["лежит_но_не_грузится"] is True, (
        "версия читается из метаданных — значит библиотека поставлена")
    assert "architecture" in это["почему"]

    # И человеку это говорится словами — обеими дорогами, какими сервис
    # вообще про окружение говорит.
    отчёт = "\n".join(deps.отчёт())
    # Сказано: ПОСТАВЛЕНА, но не грузится — и что ставить заново не надо.
    assert "IS installed but does not load" in отчёт
    беды = "\n".join(deps.чего_не_хватает())
    assert "is installed but does not load" in беды
    assert "no need to reinstall" in беды
    assert "НЕ поставлена" not in беды, "совет ставить заново остался"


