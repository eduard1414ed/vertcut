def test_подсказки_называют_ключи_которые_команда_принимает():
    """Каждое «vertcut <команда> … --ключ» в тексте проекта — настоящее.

    **Заведено в 22-й сессии, когда ключи стали английскими.** Подсказки
    с ключами разбросаны по двадцати файлам — отказы стадий, печать
    команды, экран, инструкции, ярлыки. Переименуй ключ и забудь одну
    подсказку — и человек получит совет, на который команда ответит
    «unrecognized arguments». Тут сверяется каждая строка, где
    названа команда, с тем, что её разбор принимает на самом деле.
    """
    import re

    from vertcut import cli

    корень = Path(layout.__file__).parent.parent
    разбор = cli.парсер()
    команды = {}
    for действие in разбор._actions:
        if isinstance(действие, argparse._SubParsersAction):
            for имя, под in действие.choices.items():
                команды[имя] = {к for д in под._actions
                                for к in д.option_strings}
    assert команды, "команды перестали разбираться"

    где = [п for п in (корень / "vertcut").rglob("*")
           if п.suffix in (".py", ".js", ".yaml", ".txt", ".md", ".html")]
    где += [п for п in (корень / "install").iterdir()
            if п.suffix in (".py", ".sh", ".ps1", ".cs")]
    где += [корень / "README.md", корень / "docs" / "glossary.md"]
    вызов = re.compile(r"vertcut\s+([a-z]+)\b([^\n\"'`)]*)")
    плохо = []
    for путь in где:
        for номер, строка in enumerate(
                путь.read_text(encoding="utf-8").splitlines(), 1):
            for м in вызов.finditer(строка):
                команда, хвост = м.group(1), м.group(2)
                if команда not in команды:
                    continue
                for ключ in re.findall(r"(?<![\w-])--[\w-]+", хвост):
                    if ключ not in команды[команда]:
                        плохо.append(f"{путь.relative_to(корень)}:{номер}: "
                                     f"vertcut {команда} {ключ}")
    assert not плохо, "\n".join(плохо)


def test_check_краснеет_кодом_выхода_когда_чего_то_нет(monkeypatch, capsys):
    """Сборочная машина и агент по `INSTALL.md` судят по коду выхода.
    До 26-й сессии он был нулём всегда — проверка не могла покраснеть."""
    from vertcut import cli, deps
