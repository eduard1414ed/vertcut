def test_экран_берёт_у_каркаса_всё_что_зовёт():
    """Имя, которое модуль просит, но не берёт у соседа.

    **Найдено автором на живом экране, и это второй раз за проект.**
    В первый раз каркас не ОТДАВАЛ имя, которое просили, и браузер
    не выполнял ни одного модуля — экран был пуст. Тогда завели пробу
    экрана; она это ловит.

    Здесь наоборот: модуль зовёт `сказать`, а в списке взятого его нет.
    Проба такого не видит вовсе — она рисует экран, а `сказать`
    зовётся только по нажатию. Человек нажимает кнопку и получает
    «Страница сломалась: сказать is not defined» — то есть беда живёт
    ровно до первого щелчка и до него не показывается ничем.
    """
    import re

    каркас = (layout.web() / "js" / "shell.js").read_text(encoding="utf-8")
    даёт = set(re.findall(r"export function (\w+)", каркас))
    даёт |= {и.strip() for и in
             re.findall(r"export \{([^}]*)\}", каркас)[0].split(",")}

    виноватые = []
    for файл in sorted((layout.web() / "js" / "screens").glob("*.js")):
        текст = файл.read_text(encoding="utf-8")
        взято = set()
        что = re.search(r"import \{([^}]*)\} from '\.\./shell\.js'",
                        текст, re.S)
        if что:
            взято = {и.strip() for и in что.group(1).split(",") if и.strip()}
        # Примечания не в счёт: они называют функции по именам.
        голый = "\n".join(с for с in текст.splitlines()
                          if not с.strip().startswith("//"))
        for имя in даёт:
            зовёт = re.search(rf"(?<![\w.]){re.escape(имя)}\s*\(", голый)
            if зовёт and имя not in взято:
                виноватые.append(f"{файл.name}: зовёт {имя}, но не берёт")
    assert not виноватые, виноватые


