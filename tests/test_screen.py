def test_место_под_полосу_прокрутки_держится_всегда():
    """Ничто не должно менять ширину от того, что человек делает.

    Раскрыли свёрнутое — страница стала выше, появилась полоса
    прокрутки, и всё на экране сузилось на её ширину. Найдено автором
    на колонке предложений: щелчок по «3 предложения не годятся» менял
    ширину колонок.

    Это второй случай того же правила: в четвёртой сессии раскрытая
    объяснялка растягивала экран содержимым, здесь — прокруткой.
    """
    import re

    стили = (layout.web() / "screen.css").read_text(encoding="utf-8")
    # Ищется само ПРАВИЛО, а не слова где угодно: первый заход этой
    # проверки находил `scrollbar-gutter` в примечании над правилом
    # и не краснел, когда правило убрали.
    голый = re.sub(r"/\*.*?\*/", "", стили, flags=re.S)
    # Каркас ровно в окно и не прокручивается: тогда прокручивается
    # рабочая область, и полоса появляется ТАМ, где под неё держат
    # место. Два прошлых захода чинили следствие — резервировали место
    # то у рабочей области (а она не прокручивалась), то у документа
    # (а `scrollbar-gutter` держится не во всяком браузере).
    каркас = re.search(r"\.vc-shell\s*\{([^}]*)\}", голый)
    assert каркас and "height: 100vh" in каркас.group(1) \
        and "overflow: hidden" in каркас.group(1), \
        "каркас может вырасти выше окна — тогда прокрутится документ"
    тело_ = re.findall(r"\.vc-main__body\s*\{([^}]*)\}", голый)
    assert any("scrollbar-gutter: stable" in п for п in тело_)
    assert re.search(r"\.в-фрагменты\s*>\s*\*\s*\{[^}]*min-width:\s*0",
                     голый)


