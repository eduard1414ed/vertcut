def _завести_ролик(project, ключ: str, duration: float = 20.0) -> None:
    """Вертикалка на диске — ровно столько, сколько читает `pick.listing`.

    Нужна тут потому, что дело очереди без вертикалки на диске теперь
    значит УДАЛЁННУЮ вертикалку, а не «дело как дело». Раньше это было
    всё равно: обзор про вертикалку ничего не спрашивал.
    """
    import json as _json

    from vertcut import layout as раскладка

    раскладка.cut(project, ключ).mkdir(parents=True, exist_ok=True)
    раскладка.cut_json(project, ключ).write_text(
        _json.dumps({"id": ключ, "название": ключ, "duration": duration,
                     "файл": f"{ключ}.mp4",
                     "words": {"first": 1, "last": 10},
                     "phrases": {"first": 1, "last": 3}},
                    ensure_ascii=False), encoding="utf-8")


def test_обзор_очереди_ничего_не_перекладывает(песочница, monkeypatch):
    """Открытие экрана не должно менять очередь на диске.

    `сложить` её меняет — и правильно делает, её за этим и зовут.
    А `обзор` человек задаёт всякий раз, когда просто смотрит,
    и это разные вопросы.
    """
    from vertcut import layout as раскладка, queue as очередь, works

    project = раскладка.project("видео")
    project.mkdir(parents=True)
    раскладка.meta(project).write_text("{}", encoding="utf-8")
    _завести_ролик(project, "0001-0010")
    # Все дела ДОДЕЛАНЫ — именно тот случай, когда `сложить` считает
    # план заново и пишет его на диск. Если бы обзор звал её, старая
    # запись бы исчезла.
    очередь.записать(project, {"дела": [
        {"id": "0001-0010", "зовут": "проба", "почему": "сказано собрать",
         "состояние": works.ГОТОВ}]})
    было = раскладка.queue(project).read_bytes()

    это = очередь.обзор(project, {})
    assert раскладка.queue(project).read_bytes() == было, "обзор тронул очередь"
    assert это["идёт_сейчас"] is False
    assert это["дела"][0]["состояние"] == works.ГОТОВ
    assert это["готово"] == 1


