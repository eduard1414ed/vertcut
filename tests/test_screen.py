def test_замена_файла_работы_переживает_отказ_windows(песочница, monkeypatch):
    """Windows отказывает в замене, пока ту же цель заменяет другой
    (26-я сессия, сборочная машина). Отказ-гонка повторяется; вечный
    отказ уходит наверх, и времянка за собой не остаётся."""
    from pathlib import Path as P

    from vertcut import tuning, works

    файл = layout.root() / "q" / "queue.json"
    настоящая = P.replace
    отказов = {"осталось": 3}

    def капризная(сам, цель):
        if отказов["осталось"]:
            отказов["осталось"] -= 1
            raise PermissionError(13, "Access is denied")
        return настоящая(сам, цель)

    monkeypatch.setattr(P, "replace", капризная)
    monkeypatch.setattr(tuning, "ПАУЗА_ЗАМЕНЫ_С", 0)
    works.записать(файл, {"i": 1})
    assert json.loads(файл.read_text(encoding="utf-8")) == {"i": 1}

    отказов["осталось"] = 10 ** 6
    with pytest.raises(PermissionError):
        works.записать(файл, {"i": 2})
    assert not list(файл.parent.glob("*.part"))
