@pytest.fixture
def экран(песочница):
    """Настоящий сервер на случайном порту. Корень — песочница."""
    layout.root().mkdir(parents=True, exist_ok=True)
    сервер = server.завести(порт=0)
    поток = threading.Thread(target=сервер.serve_forever, daemon=True)
    поток.start()
    try:
        yield сервер
    finally:
        сервер.shutdown()
        сервер.server_close()
        поток.join(timeout=5)


def как_браузер(путь: str) -> str:
    """Русские буквы в адресе — в проценты.

    **Так делает браузер, и по-другому нельзя.** Питоновский клиент
    отказывается класть в первую строку запроса что-либо кроме
    латиницы, и это не его каприз: так велит стандарт. Проверка,
    которая шлёт сырые буквы, проверяла бы не сервис, а клиента.

    Что сервис понимает и то и другое — стережёт отдельная проверка
    ниже: ходить сюда будет не только браузер.
    """
    разбор = urllib.parse.urlsplit(путь)
    return urllib.parse.urlunsplit((
        "", "", urllib.parse.quote(разбор.path),
        urllib.parse.quote(разбор.query, safe="=&%"), ""))


def спросить(сервер, путь: str, ключ: str | None = "свой",
             дом: str | None = None, тело: dict | None = None):
    """Один запрос. Возвращает (код, тело как текст)."""
    порт = сервер.server_address[1]
    просьба = urllib.request.Request(
        f"http://127.0.0.1:{порт}{как_браузер(путь)}",
        data=json.dumps(тело).encode("utf-8") if тело is not None else None,
        method="POST" if тело is not None else "GET")
    if ключ is not None:
        просьба.add_header(server.ЗАГОЛОВОК_ПРОПУСКА,
                           сервер.пропуск if ключ == "свой" else ключ)
    if тело is not None:
        просьба.add_header("Content-Type", "application/json")
    if дом:
        просьба.add_header("Host", дом)
    try:
        with urllib.request.urlopen(просьба, timeout=10) as ответ:
            return ответ.status, ответ.read().decode("utf-8")
    except urllib.error.HTTPError as отказ:
        return отказ.code, отказ.read().decode("utf-8")


