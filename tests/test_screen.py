def test_русские_буквы_в_адресе_доезжают(экран):
    """Найдено руками на первом запуске.

    `http.server` разбирает первую строку запроса как latin-1 — так
    велит стандарт. Русские слова в адресе после этого рассыпаются,
    и `?пропуск=` не сходился со словом в коде никогда: ручки отвечали,
    а страница получала «не тот ключ».

    Пропуск в адресе с 22-й сессии латиницей (`?pass=`), а пути ручек
    остались русскими (`/апи/начало`) — на них проверка и стоит.
    """
    порт = экран.server_address[1]
    for как in (как_браузер(f"/апи/начало?pass={экран.пропуск}"),
                "/%D0%B0%D0%BF%D0%B8/%D0%BD%D0%B0%D1%87%D0%B0%D0%BB%D0%BE"
                f"?pass={экран.пропуск}"):
        with urllib.request.urlopen(
                f"http://127.0.0.1:{порт}{как}", timeout=10) as ответ:
            assert ответ.status == 200, как
            assert json.loads(ответ.read())


def test_сырые_русские_буквы_в_адресе_тоже_доезжают(экран):
    """Тот самый случай, на котором это и поймалось.

    Браузер русские буквы кодирует и до беды не доходит; сырые байты
    в адрес кладут `curl` и любой соседний скрипт. Проверка идёт голым
    гнездом, потому что питоновский клиент такой запрос не отправит
    вовсе — он требует латиницы в первой строке.

    Без починки сервер читает эти байты как latin-1, `/апи/начало`
    рассыпается в мусор и не сходится с русским словом в коде никогда.
    """
    порт = экран.server_address[1]
    просьба = (f"GET /апи/начало?pass={экран.пропуск} HTTP/1.1\r\n"
               f"Host: 127.0.0.1:{порт}\r\n"
               "Connection: close\r\n\r\n").encode("utf-8")
    with socket.create_connection(("127.0.0.1", порт), timeout=10) as гнездо:
        гнездо.sendall(просьба)
        ответ = b""
        while кусок := гнездо.recv(65536):
            ответ += кусок
    assert ответ.startswith(b"HTTP/1.1 200"), ответ[:120]
    assert json.loads(ответ.split(b"\r\n\r\n", 1)[1])


