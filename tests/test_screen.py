def test_отметка_ловит_чужую_правку(tmp_path):
    """Экран и терминал правят одни и те же файлы.

    Прочитал экран, минуту думал человек, тем временем из терминала
    в тот же файл легла правка — записать поверх значит потерять
    чужую молча. У предка это стоило потерянного монтажа.
    """
    файл = tmp_path / "cut.json"
    файл.write_text("было", encoding="utf-8")
    была = отм.снять(файл)
    отм.сверить(файл, была, "This clip")          # никто не трогал

    файл.write_text("стало другое", encoding="utf-8")
    with pytest.raises(VertcutError) as беда:
        отм.сверить(файл, была, "This clip")
    assert "This clip" in беда.value.message
    assert беда.value.hint


