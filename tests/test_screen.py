# ─── страница собирается целиком ─────────────────────────────────────

def _разобрать_модули() -> dict:
    """Что каждый модуль страницы отдаёт наружу и что просит у соседей."""
    import re

    from vertcut import layout as раскладка

    вышло = {}
    корень = раскладка.web() / "js"
    for файл in sorted(корень.rglob("*.js")):
        текст = файл.read_text(encoding="utf-8")
        отдаёт = set(re.findall(
            r"^export\s+(?:async\s+)?(?:function|const|let|class)\s+([^\s(=]+)",
            текст, re.M))
        for кусок in re.findall(r"^export\s*\{([^}]*)\}", текст, re.M | re.S):
            отдаёт |= {и.split(" as ")[-1].strip()
                       for и in кусок.split(",") if и.strip()}
        просит = []
        for имена, откуда in re.findall(
                r"import\s*\{([^}]*)\}\s*from\s*['\"]([^'\"]+)['\"]", текст,
                re.S):
            цель = (файл.parent / откуда).resolve()
            просит.append((цель, [и.split(" as ")[0].strip()
                                  for и in имена.split(",") if и.strip()]))
        вышло[файл.resolve()] = {"отдаёт": отдаёт, "просит": просит,
                                 "имя": файл.name}
    return вышло


def test_страница_собирается_целиком():
    """Каждое имя, которое модуль просит, сосед обязан отдавать.

    **Найдено на живом экране, и выглядело это страшнее, чем было.**
    `shell.js` не отдавал наружу `точка`, а `cut.js` её просил
    — и браузер не выполнил НИ ОДНОГО модуля вовсе. Человек увидел
    пустую страницу: ни заголовка, ни полосы с бедой, ничего.

    Проверка синтаксиса такого не ловит: каждый файл по отдельности
    разбирается прекрасно. Ломается связь между ними, и ломается она
    молча.
    """
    модули = _разобрать_модули()
    assert модули, "модули страницы не нашлись"
    беды = []
    for путь, это in модули.items():
        for цель, имена in это["просит"]:
            сосед = модули.get(цель)
            if сосед is None:
                беды.append(f"{это['имя']} просит у {цель.name}, а его нет")
                continue
            for имя in имена:
                if имя not in сосед["отдаёт"]:
                    беды.append(
                        f"{это['имя']} просит «{имя}» у {сосед['имя']}, "
                        "а тот его не отдаёт")
    assert not беды, беды


