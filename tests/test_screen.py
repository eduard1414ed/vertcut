"""Заслоны на экран.

Экран — единственная часть сервиса, у которой есть чужой собеседник:
браузер. Всё остальное зовут либо человек в терминале, либо сам сервис.
Поэтому проверки тут двух пород:

1. **кто стучится** — ключ, имя хозяина, путь наружу. Это не паранойя:
   на `127.0.0.1` может постучаться любая страница, открытая в том же
   браузере, и браузер послушно приложит её запрос;
2. **не завелась ли логика в веб-слое** — главное правило спеки. Оно
   не сторожится ничем, кроме проверки: расползётся однажды, и экран
   с терминалом соберут разное.

Отдельно стоят две проверки на промахи, найденные на первом же запуске:
русские буквы в адресе и русские буквы в подсунутом ключе. Оба раза
сервис вёл себя не так, как написано, и оба раза это нашлось руками,
а не тестом. Теперь сторожится.
"""

