    просьба = urllib.request.Request(
        f"http://127.0.0.1:{порт}"
        + как_браузер("/апи/бросить?имя=брошенное.mp4"),
        data=исходник.read_bytes(), method="POST")
    просьба.add_header(server.ЗАГОЛОВОК_ПРОПУСКА, экран.пропуск)
    with urllib.request.urlopen(просьба, timeout=30) as ответ:
        это = json.loads(ответ.read().decode("utf-8"))
    assert это["слаг"], это
    лежит = раскладка.inbox() / "брошенное.mp4"
    assert лежит.read_bytes() == исходник.read_bytes()
    meta = json.loads(раскладка.meta(раскладка.project(это["слаг"]))
                      .read_text(encoding="utf-8"))
