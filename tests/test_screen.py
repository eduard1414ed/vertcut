def test_на_просьбу_о_куске_отвечают_кодом_206(экран):
    """Ролик не играл в браузере, и причина была в одной букве кода.

    Проигрыватель начинает не с «дай файл», а с «дай первые два
    байта». Пока 206 давался только на кусок, начатый НЕ С НУЛЯ,
    такая просьба получала «200, длина 2» — то есть «весь ваш ролик
    состоит из двух байт». Браузер верил и не играл ничего.

    Проверяется на любом файле, который сервер отдаёт: отвечает
    им всем одно место.
    """
    адрес = "/файлы/screen.css"
    код, шапка, целиком = кусок(экран, адрес, None)
    assert код == 200
    assert шапка.get("Accept-Ranges") == "bytes"
    assert "Content-Range" not in шапка
    размер = len(целиком)
    assert размер > 1000

    for диапазон, ждём in (
        ("bytes=0-1", (0, 1)),
        ("bytes=0-", (0, размер - 1)),
        ("bytes=100-199", (100, 199)),
        # Проигрыватель спрашивает наперёд, за край файла. Это
        # обычное дело, а не беда.
        (f"bytes={размер + 10_000}-", (размер - 1, размер - 1)),
    ):
        код, шапка, тело = кусок(экран, адрес, диапазон)
        с, по = ждём
        assert код == 206, диапазон
        assert шапка["Content-Range"] == f"bytes {с}-{по}/{размер}", диапазон
        assert тело == целиком[с:по + 1], диапазон

    # Просьбы, которой не разобрать, обещать нельзя: отдаём целиком
    # и честно говорим 200.
    код, шапка, тело = кусок(экран, адрес, "bytes=abc-def")
    assert код == 200
    assert "Content-Range" not in шапка
    assert тело == целиком


