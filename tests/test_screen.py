def test_адрес_уходит_аргументом(monkeypatch):
    """Главное свойство: адрес — ОТДЕЛЬНОЕ слово в вызове программы.

    Аргументы уезжают байтами utf-8 и по дороге не перекодируются.
    Строка скрипта, скормленная чужой программе в стандартный ввод,
    — перекодируется, и это замерено.
    """
    import subprocess

    from vertcut.web import server

    было = {}

    def подставной(зов, **прочее):
        было["зов"] = зов
        class Ответ:
            returncode = 0
        return Ответ()

    monkeypatch.setattr(subprocess, "run", подставной)
    monkeypatch.setattr(server.sys, "platform", "darwin")

    куда = server.адрес_хозяина({"порт": 7864, "пропуск": "abc"})
    assert server.открыть_в_браузере(куда) is True
    зов = было["зов"]
    assert isinstance(зов, list), "адрес ушёл строкой — её разбирает оболочка"
    assert куда in зов, зов
    assert зов[0] == "open"


