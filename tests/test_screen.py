def test_в_веб_слое_нет_логики():
    """Главное правило спеки, и сторожить его больше нечем.

    Проверяются слова, которых в переводчике json быть не может:
    арифметика времени, пороги, коэффициенты. Расползётся логика —
    экран и терминал соберут разное, и увидит это зритель.
    """
    папка = Path(server.__file__).parent
    виноватые = []
    for файл in папка.glob("*.py"):
        текст = файл.read_text(encoding="utf-8")
        for номер, строка in enumerate(текст.splitlines(), 1):
            голая = строка.strip()
            if голая.startswith("#") or голая.startswith('"'):
                continue
            for чужое in ("/ fps", "* fps", "tuning.", "0.5 *",
                          "PTS-STARTPTS", "import numpy", "from numpy"):
                if чужое in голая:
                    виноватые.append(f"{файл.name}:{номер}  {голая}")
    assert not виноватые, виноватые


def test_ручки_короткие():
    """Ручка длиннее двадцати строк — это почти всегда логика.

    Число не замерено и не претендует: это черта, за которой стоит
    остановиться и спросить себя, где место этой работе. Место у неё
    рядом с остальной такой же — там, где её позовёт и команда.
    """
    текст = Path(api.__file__).read_text(encoding="utf-8").splitlines()
    длинные, начало, зовут = [], None, None
    for номер, строка in enumerate(текст):
        if строка.startswith("def ") or строка.startswith("@ручка"):
            if начало is not None and номер - начало > 30:
                длинные.append(f"{зовут}: {номер - начало} строк")
            if строка.startswith("@ручка"):
                начало, зовут = номер, строка.strip()
            else:
                начало = None
    assert not длинные, длинные


